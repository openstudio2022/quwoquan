import 'dart:io';

class GoRuntimeErrorGenerator {
  const GoRuntimeErrorGenerator();

  void generate() {
    final output = _outputFile(Directory.current);
    output.parent.createSync(recursive: true);
    output.writeAsStringSync(render(Directory.current));
  }

  bool isCurrent(Directory repoRoot) {
    final output = _outputFile(repoRoot);
    return output.existsSync() && output.readAsStringSync() == render(repoRoot);
  }

  String render(Directory repoRoot) {
    final buffer = StringBuffer()
      ..writeln('// Code generated by runtime_error_codegen. DO NOT EDIT.')
      ..writeln()
      ..writeln('package failures')
      ..writeln();
    for (final code in _readCodes(repoRoot)) {
      buffer.writeln('const RuntimeFailureCode${_identifier(code)} = "$code"');
    }
    return buffer.toString();
  }

  List<String> _readCodes(Directory repoRoot) {
    final source = File(
      '${repoRoot.path}/quwoquan_service/contracts/runtime_errors/errors/runtime_failure_codes.yaml',
    );
    final pattern = RegExp(r'^\s*-\s*code:\s*([A-Z]+\.[A-Z]+\.[a-z0-9_]+)\s*$');
    return <String>[
      for (final line in source.readAsLinesSync())
        if (pattern.firstMatch(line)?.group(1) case final String code) code,
    ];
  }

  File _outputFile(Directory repoRoot) => File(
    '${repoRoot.path}/quwoquan_service/runtime/failures/'
    'runtime_failure_codes_generated.go',
  );

  String _identifier(String code) {
    return code
        .toLowerCase()
        .split(RegExp(r'[._-]+'))
        .map((part) => part[0].toUpperCase() + part.substring(1))
        .join();
  }
}
