#!/usr/bin/env python3
"""从 .claude/agents/*.md 生成 .codex/agents/*.toml。

子代理定义在三家 harness 上的格式不可共用：Claude Code 与 Cursor 读 Markdown +
YAML frontmatter，Codex 读 TOML（必填 name / description / developer_instructions）。
所以真相源只保留 Markdown 一份，TOML 由本脚本生成。

用法：
    python3 quwoquan_ops/tools/generate_codex_agents.py           # 生成
    python3 quwoquan_ops/tools/generate_codex_agents.py --check   # 只校验是否最新
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = REPO_ROOT / ".claude" / "agents"
TARGET_DIR = REPO_ROOT / ".codex" / "agents"

GENERATED_HEADER = (
    "# Generated by quwoquan_ops/tools/generate_codex_agents.py "
    "from {source}. DO NOT EDIT."
)

# Cursor 用 readonly 布尔，Codex 用 sandbox_mode 字符串；两者语义对应关系固定。
SANDBOX_FOR_READONLY = {True: "read-only", False: "workspace-write"}

FRONTMATTER_RE = re.compile(r"\A---\n(?P<fm>.*?)\n---\n(?P<body>.*)\Z", re.S)


def _parse_front_matter(text: str, rel: str) -> tuple[dict[str, str], str]:
    match = FRONTMATTER_RE.match(text)
    if match is None:
        raise ValueError(f"{rel}: 缺少 YAML frontmatter")
    # 必须用真正的 YAML 解析器：手写的按行 partition 会把 `description: A: B`
    # 读成合法值，生成出的 TOML 看着正常，而 Claude Code 与 Cursor 侧整份解析失败。
    try:
        parsed = yaml.safe_load(match.group("fm"))
    except yaml.YAMLError as error:
        reason = str(error).splitlines()[0]
        raise ValueError(
            f"{rel}: frontmatter 不是合法 YAML（{reason}）；"
            "值里含「冒号+空格」时必须加引号"
        ) from error
    if not isinstance(parsed, dict):
        raise ValueError(f"{rel}: frontmatter 不是键值映射")
    return {str(k): "" if v is None else str(v) for k, v in parsed.items()}, match.group(
        "body"
    ).strip()


def _toml_basic_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _toml_multiline_string(value: str) -> str:
    # TOML 多行基本字符串：只需转义反斜杠与三连引号，换行保持原样便于人读 diff。
    escaped = value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""\n{escaped}\n"""'


def render(source: Path) -> str:
    rel = source.relative_to(REPO_ROOT).as_posix()
    fields, body = _parse_front_matter(source.read_text(encoding="utf-8"), rel)

    for required in ("name", "description"):
        if not fields.get(required):
            raise ValueError(f"{rel}: frontmatter 缺 {required}")
    if not body:
        raise ValueError(f"{rel}: 正文为空，无法生成 developer_instructions")

    readonly = fields.get("readonly", "false").lower() == "true"

    lines = [
        GENERATED_HEADER.format(source=rel),
        "",
        f"name = {_toml_basic_string(fields['name'])}",
        f"description = {_toml_basic_string(fields['description'])}",
        f"sandbox_mode = {_toml_basic_string(SANDBOX_FOR_READONLY[readonly])}",
        "",
        f"developer_instructions = {_toml_multiline_string(body)}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="只校验生成物是否与真相源一致，不写盘",
    )
    args = parser.parse_args()

    sources = sorted(SOURCE_DIR.glob("*.md"))
    if not sources:
        print(f"[generate-codex-agents] FAIL: {SOURCE_DIR} 下没有子代理定义", file=sys.stderr)
        return 1

    stale: list[str] = []
    for source in sources:
        target = TARGET_DIR / f"{source.stem}.toml"
        try:
            rendered = render(source)
        except ValueError as error:
            print(f"[generate-codex-agents] FAIL: {error}", file=sys.stderr)
            return 1

        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == rendered:
            continue
        if args.check:
            reason = "缺失" if current is None else "与真相源不一致"
            stale.append(f"{target.relative_to(REPO_ROOT).as_posix()}: {reason}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(rendered, encoding="utf-8")
        print(f"[generate-codex-agents] wrote {target.relative_to(REPO_ROOT).as_posix()}")

    # 真相源删除后，生成物不得残留
    expected = {f"{s.stem}.toml" for s in sources}
    for orphan in sorted(TARGET_DIR.glob("*.toml")) if TARGET_DIR.exists() else []:
        if orphan.name in expected:
            continue
        rel = orphan.relative_to(REPO_ROOT).as_posix()
        if args.check:
            stale.append(f"{rel}: 真相源已删除，生成物应随之删除")
        else:
            orphan.unlink()
            print(f"[generate-codex-agents] removed {rel}")

    if stale:
        print("[generate-codex-agents] FAIL: 生成物不是最新", file=sys.stderr)
        for item in stale:
            print(f"  - {item}", file=sys.stderr)
        print(
            "  修复：python3 quwoquan_ops/tools/generate_codex_agents.py",
            file=sys.stderr,
        )
        return 1

    print(f"[generate-codex-agents] OK: {len(sources)} 个子代理定义已同步")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
