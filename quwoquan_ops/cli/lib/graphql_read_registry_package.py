"""Candidate-bound signed GraphQL persisted-query registry packaging.

The canonical Go generator is the only AST/cost-model implementation.  This
module invokes it for the immutable candidate, signs the exact generated bytes,
embeds only public verification material, and re-runs the generator whenever a
candidate is loaded for activation.  It never creates or serializes a signing
private key.
"""

