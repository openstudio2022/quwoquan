_DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
_KEY_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


def _sha256_bytes(encoded: bytes) -> str:
    return "sha256:" + hashlib.sha256(encoded).hexdigest()


def _sha256_file(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _canonical_json(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _go_cost_plan_json(value: object) -> bytes:
    if not isinstance(value, dict) or set(value) != {
        "baseComplexity",
        "listMultipliers",
        "maxOwnerCalls",
        "maxBatchKeys",
        "maxResponseBytes",
    }:
        raise ValueError("generated GraphQL cost plan fields mismatch")
    ordered = {
        "baseComplexity": value["baseComplexity"],
        "listMultipliers": value["listMultipliers"],
        "maxOwnerCalls": value["maxOwnerCalls"],
        "maxBatchKeys": value["maxBatchKeys"],
        "maxResponseBytes": value["maxResponseBytes"],
    }
    return json.dumps(
        ordered, ensure_ascii=True, separators=(",", ":")
    ).encode("utf-8")


def _regular_file(path: Path, *, label: str) -> os.stat_result:
    try:
        info = path.lstat()
    except OSError as exc:
        raise ValueError(f"{label} is unavailable: {exc}") from exc
    if path.is_symlink() or not stat.S_ISREG(info.st_mode):
        raise ValueError(f"{label} must be a regular non-symlink file")
    return info


def _generate_payload(
    repo_root: Path,
    candidate_digest: str,
    *,
    timeout_seconds: float = 120.0,
    scratch_root: Path | None = None,
) -> bytes:
    if _DIGEST.fullmatch(candidate_digest) is None:
        raise ValueError("GraphQL registry candidate digest must be canonical sha256")
    service_root = repo_root / "quwoquan_service"
    schema = repo_root / SCHEMA_SOURCE
    metadata = repo_root / METADATA_SOURCE
    _regular_file(schema, label="GraphQL schema source")
    _regular_file(metadata, label="GraphQL query metadata source")
    contract_view_cache = (
        Path(scratch_root)
        if scratch_root is not None
        else repo_root / ".qwq_output/env/repo/local/graphql-read-registry/cache"
    )
    contract_view_cache.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix="view-", dir=contract_view_cache
    ) as contract_view, tempfile.TemporaryDirectory(
        prefix="qwq-graphql-registry-"
    ) as temporary:
        view_argv = [
            "python3",
            "-B",
            "scripts/contracts/build_service_contract_view.py",
            "--output",
            contract_view,
        ]
        if scratch_root is not None:
            view_argv.extend(
                ["--external-output-root", str(contract_view_cache)]
            )
        view_result = subprocess.run(
            view_argv,
            cwd=service_root,
            text=True,
            capture_output=True,
            check=False,
            env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"},
            timeout=timeout_seconds,
        )
        if view_result.returncode != 0:
            detail = (view_result.stderr or view_result.stdout).strip()
            raise ValueError(
                "canonical GraphQL ContractGraph metadata view failed"
                + (f": {detail}" if detail else "")
            )
        output = Path(temporary) / "registry.json"
        argv = [
            "go",
            "run",
            "./tools/codegen_graphql_read_registry",
            "--schema",
            str(schema.relative_to(service_root)),
            "--metadata",
            str(metadata.relative_to(service_root)),
            "--metadata-dir",
            contract_view,
            "--candidate-digest",
            candidate_digest,
            "--output",
            str(output),
        ]
        result = subprocess.run(
            argv,
            cwd=service_root,
            text=True,
            capture_output=True,
            check=False,
            timeout=timeout_seconds,
        )
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise ValueError(
                "canonical GraphQL AST/cost generator failed"
                + (f": {detail}" if detail else "")
            )
        _regular_file(output, label="generated GraphQL registry payload")
        return output.read_bytes()


def _payload_identity(
    encoded: bytes,
    *,
    expected_candidate_digest: str,
) -> tuple[dict[str, Any], str, str, int]:
    try:
        payload = json.loads(encoded.decode("utf-8"))
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"generated GraphQL registry payload is invalid: {exc}") from exc
    if not isinstance(payload, dict) or set(payload) != {
        "candidateDigest",
        "schemaDigest",
        "entries",
    }:
        raise ValueError("generated GraphQL registry payload fields mismatch")
    if payload.get("candidateDigest") != expected_candidate_digest:
        raise ValueError("generated GraphQL registry candidate identity drifted")
    schema_digest = str(payload.get("schemaDigest") or "")
    if _DIGEST.fullmatch(schema_digest) is None:
        raise ValueError("generated GraphQL schema digest is invalid")
    entries = payload.get("entries")
    if not isinstance(entries, list) or not entries:
        raise ValueError("generated GraphQL registry entries are empty")
    aggregate_entries: list[dict[str, str]] = []
    versions: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError("generated GraphQL registry entry is invalid")
        query_hash = str(entry.get("sha256Hash") or "")
        plan_digest = str(entry.get("costPlanDigest") or "")
        version = str(entry.get("costModelVersion") or "")
        if re.fullmatch(r"[0-9a-f]{64}", query_hash) is None:
            raise ValueError("generated GraphQL query hash is invalid")
        if _DIGEST.fullmatch(plan_digest) is None:
            raise ValueError("generated GraphQL cost plan digest is invalid")
        plan = entry.get("costPlan")
        if _sha256_bytes(_go_cost_plan_json(plan)) != plan_digest:
            raise ValueError("generated GraphQL cost plan digest drifted")
        if version != COST_MODEL_VERSION:
            raise ValueError("generated GraphQL cost model version is unsupported")
        versions.add(version)
        aggregate_entries.append(
            {"sha256Hash": query_hash, "costPlanDigest": plan_digest}
        )
    if versions != {COST_MODEL_VERSION}:
        raise ValueError("generated GraphQL cost model versions are inconsistent")
    aggregate_entries.sort(key=lambda value: value["sha256Hash"])
    aggregate = {
        "costModelVersion": COST_MODEL_VERSION,
        "entries": aggregate_entries,
    }
    return (
        payload,
        schema_digest,
        _sha256_bytes(_canonical_json(aggregate)),
        len(entries),
    )


def _read_object(path: Path, *, label: str) -> dict[str, Any]:
    _regular_file(path, label=label)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} is unreadable: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be a JSON object")
    return value


def _write_bytes(path: Path, encoded: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    if temporary.exists():
        raise ValueError(f"GraphQL package temporary path is occupied: {temporary}")
    with temporary.open("xb") as handle:
        handle.write(encoded)
        handle.flush()
        os.fsync(handle.fileno())
    os.chmod(temporary, 0o600)
    os.replace(temporary, path)


def _candidate_root_without_links(candidate_root: Path) -> Path:
    root = Path(os.path.abspath(candidate_root))
    try:
        info = root.lstat()
    except OSError as exc:
        raise ValueError(f"GraphQL registry candidate root is unavailable: {exc}") from exc
    if root.is_symlink() or not stat.S_ISDIR(info.st_mode):
        raise ValueError("GraphQL registry candidate root is missing or unsafe")
    for current, directories, files in os.walk(root, followlinks=False):
        parent = Path(current)
        for name in (*directories, *files):
            entry = parent / name
            if entry.is_symlink():
                raise ValueError(
                    f"GraphQL registry candidate contains a symlink: {entry}"
                )
    return root


def _config_version(payload: Mapping[str, Any]) -> str:
    without_version = json.loads(json.dumps(payload))
    config = without_version.get("config")
    if isinstance(config, dict):
        config.pop("version", None)
        if not config:
            without_version.pop("config", None)
    encoded = yaml.safe_dump(
        without_version,
        allow_unicode=True,
        sort_keys=True,
        width=120,
    ).encode("utf-8")
    return _sha256_bytes(encoded)


def _patch_service_package(
    candidate_root: Path,
    *,
    candidate_digest: str,
    schema_digest: str,
    keyring: dict[str, str],
    schema_bytes: bytes,
    payload_bytes: bytes,
    envelope_bytes: bytes,
    keyring_bytes: bytes,
    descriptor: dict[str, Any],
) -> None:
    config_path = candidate_root / CONFIG_REF
    manifest_path = candidate_root / MANIFEST_REF
    provenance_path = candidate_root / PROVENANCE_REF
    _regular_file(config_path, label="api-edge package config")
    try:
        config = yaml.safe_load(config_path.read_text(encoding="utf-8")) or {}
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise ValueError(f"api-edge package config is unreadable: {exc}") from exc
    if not isinstance(config, dict):
        raise ValueError("api-edge package config must be a mapping")
    graph = config.get("graphql_read")
    if not isinstance(graph, dict) or graph.get("enabled") is not True:
        raise ValueError("GraphQL read is disabled in the runtime package")
    expected_source = {
        "registry_file": ENVELOPE_REF.name,
        "candidate_digest": "package-required",
        "schema_file": SCHEMA_REF.name,
        "schema_digest": "package-required",
        "trusted_public_keys_json": "package-required",
    }
    for field, expected in expected_source.items():
        if graph.get(field) != expected:
            raise ValueError(f"GraphQL package source {field} is not package-owned")
    timeout = graph.get("owner_timeout_ms")
    if not isinstance(timeout, int) or isinstance(timeout, bool) or not 100 <= timeout <= 5000:
        raise ValueError("GraphQL owner timeout is invalid")
    graph.update(
        {
            "registry_file": ENVELOPE_REF.name,
            "candidate_digest": candidate_digest,
            "schema_file": SCHEMA_REF.name,
            "schema_digest": schema_digest,
            "trusted_public_keys_json": json.dumps(
                keyring, ensure_ascii=True, separators=(",", ":"), sort_keys=True
            ),
        }
    )
    version = _config_version(config)
    config.setdefault("config", {})["version"] = version
    config_bytes = yaml.safe_dump(
        config, allow_unicode=True, sort_keys=False, width=120
    ).encode("utf-8")
    descriptor_bytes = (
        json.dumps(descriptor, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")
    for path, encoded in (
        (candidate_root / SCHEMA_REF, schema_bytes),
        (candidate_root / PAYLOAD_REF, payload_bytes),
        (candidate_root / ENVELOPE_REF, envelope_bytes),
        (candidate_root / KEYRING_REF, keyring_bytes),
        (candidate_root / PACKAGE_REF, descriptor_bytes),
        (config_path, config_bytes),
    ):
        _write_bytes(path, encoded)

    _regular_file(manifest_path, label="api-edge package manifest")
    try:
        documents = list(yaml.safe_load_all(manifest_path.read_text(encoding="utf-8")))
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise ValueError(f"api-edge package manifest is unreadable: {exc}") from exc
    config_maps = [
        item
        for item in documents
        if isinstance(item, dict)
        and item.get("kind") == "ConfigMap"
        and (item.get("metadata") or {}).get("name") == "api-edge-runtime-config"
    ]
    if len(config_maps) != 1:
        raise ValueError("api-edge runtime ConfigMap is not unique")
    config_map = config_maps[0]
    data = config_map.setdefault("data", {})
    if not isinstance(data, dict):
        raise ValueError("api-edge runtime ConfigMap data is invalid")
    data.update(
        {
            "api-edge.yaml": config_bytes.decode("utf-8"),
            SCHEMA_REF.name: schema_bytes.decode("utf-8"),
            ENVELOPE_REF.name: envelope_bytes.decode("utf-8"),
            KEYRING_REF.name: keyring_bytes.decode("utf-8"),
            PACKAGE_REF.name: descriptor_bytes.decode("utf-8"),
        }
    )
    manifest_bytes = yaml.safe_dump_all(
        documents, allow_unicode=True, sort_keys=False
    ).encode("utf-8")
    _write_bytes(manifest_path, manifest_bytes)

    provenance = _read_object(provenance_path, label="api-edge package provenance")
    if provenance.get("service") != "api-edge":
        raise ValueError("api-edge package provenance identity mismatch")
    digests = provenance.get("digests")
    if not isinstance(digests, dict):
        raise ValueError("api-edge package provenance digests are missing")
    provenance["configVersion"] = version
    digests["config"] = _sha256_bytes(config_bytes)
    digests["manifests"] = _sha256_bytes(manifest_bytes)
    provenance["graphqlReadRegistry"] = descriptor
    _write_bytes(
        provenance_path,
        (json.dumps(provenance, ensure_ascii=False, indent=2) + "\n").encode(
            "utf-8"
        ),
    )


def _validate_package_source_graphql_enabled(candidate_root: Path) -> None:
    config_path = candidate_root / CONFIG_REF
    _regular_file(config_path, label="api-edge package config")
    try:
        config = yaml.safe_load(config_path.read_text(encoding="utf-8")) or {}
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise ValueError(f"api-edge package config is unreadable: {exc}") from exc
    graph = config.get("graphql_read") if isinstance(config, dict) else None
    if not isinstance(graph, dict) or graph.get("enabled") is not True:
        raise ValueError("GraphQL read is disabled in the runtime package")


def _build_graphql_read_registry_artifacts(
    *,
    repo_root: Path,
    environment: str,
    target: str,
    candidate_digest: str,
    signing: SigningMaterial | None,
    scratch_root: Path | None = None,
) -> dict[str, Any]:
    if environment not in {"alpha", "beta", "gamma", "prod"}:
        raise ValueError("GraphQL registry package environment is invalid")
    expected_target = "prod-hosted" if environment == "prod" else f"{environment}-local"
    if target != expected_target:
        raise ValueError("GraphQL registry package target/environment mismatch")
    if _DIGEST.fullmatch(candidate_digest) is None:
        raise ValueError("GraphQL registry candidate digest must be canonical sha256")
    resolved_signing = signing or resolve_signing_material(repo_root)
    private_bytes, keyring_bytes, keyring = _validate_signing_material(
        repo_root, resolved_signing
    )
    payload_bytes = _generate_payload(
        repo_root,
        candidate_digest,
        scratch_root=scratch_root,
    )
    _payload, schema_digest, aggregate_digest, entry_count = _payload_identity(
        payload_bytes, expected_candidate_digest=candidate_digest
    )
    schema_bytes = (repo_root / SCHEMA_SOURCE).read_bytes()
    if _sha256_bytes(schema_bytes) != schema_digest:
        raise ValueError("GraphQL generator schema digest differs from source bytes")
    signature = _sign_payload(private_bytes, payload_bytes)
    envelope = {
        "keyId": resolved_signing.key_id,
        "payloadSha256": _sha256_bytes(payload_bytes),
        "payload": base64.b64encode(payload_bytes).decode("ascii"),
        "signature": base64.b64encode(signature).decode("ascii"),
    }
    envelope_bytes = (
        json.dumps(envelope, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")
    descriptor = {
        "schema": PACKAGE_SCHEMA,
        "environment": environment,
        "target": target,
        "candidateDigest": candidate_digest,
        "schemaRef": SCHEMA_REF.as_posix(),
        "schemaDigest": schema_digest,
        "payloadRef": PAYLOAD_REF.as_posix(),
        "payloadDigest": _sha256_bytes(payload_bytes),
        "envelopeRef": ENVELOPE_REF.as_posix(),
        "envelopeDigest": _sha256_bytes(envelope_bytes),
        "trustedPublicKeysRef": KEYRING_REF.as_posix(),
        "trustedPublicKeysDigest": _sha256_bytes(keyring_bytes),
        "signingKeyId": resolved_signing.key_id,
        "costModelVersion": COST_MODEL_VERSION,
        "costPlanAggregateDigest": aggregate_digest,
        "entryCount": entry_count,
    }
    return {
        "descriptor": descriptor,
        "schemaBytes": schema_bytes,
        "payloadBytes": payload_bytes,
        "envelopeBytes": envelope_bytes,
        "keyringBytes": keyring_bytes,
        "keyring": keyring,
    }


def materialize_graphql_read_runtime_config(
    *,
    repo_root: Path,
    runtime_config_path: Path,
    environment: str,
    target: str,
    candidate_digest: str,
    signing: SigningMaterial | None = None,
) -> dict[str, Any]:
    """Bind a signed current-worktree registry to one mutable runtime config."""

    _regular_file(runtime_config_path, label="api-edge mutable runtime config")
    try:
        config = yaml.safe_load(runtime_config_path.read_text(encoding="utf-8")) or {}
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise ValueError(f"api-edge mutable runtime config is unreadable: {exc}") from exc
    if not isinstance(config, dict):
        raise ValueError("api-edge mutable runtime config must be a mapping")
    graph = config.get("graphql_read")
    if not isinstance(graph, dict) or graph.get("enabled") is not True:
        raise ValueError("GraphQL read is disabled in the mutable runtime config")
    expected_source = {
        "registry_file": ENVELOPE_REF.name,
        "candidate_digest": "package-required",
        "schema_file": SCHEMA_REF.name,
        "schema_digest": "package-required",
        "trusted_public_keys_json": "package-required",
    }
    for field, expected in expected_source.items():
        if graph.get(field) != expected:
            raise ValueError(f"GraphQL mutable runtime source {field} is not package-owned")
    artifacts = _build_graphql_read_registry_artifacts(
        repo_root=repo_root,
        environment=environment,
        target=target,
        candidate_digest=candidate_digest,
        signing=signing,
    )
    descriptor = artifacts["descriptor"]
    graph.update(
        {
            "candidate_digest": candidate_digest,
            "schema_digest": descriptor["schemaDigest"],
            "trusted_public_keys_json": json.dumps(
                artifacts["keyring"],
                ensure_ascii=True,
                separators=(",", ":"),
                sort_keys=True,
            ),
        }
    )
    version = _config_version(config)
    config.setdefault("config", {})["version"] = version
    config_bytes = yaml.safe_dump(
        config, allow_unicode=True, sort_keys=False, width=120
    ).encode("utf-8")
    output_root = runtime_config_path.parent
    for path, encoded in (
        (output_root / SCHEMA_REF.name, artifacts["schemaBytes"]),
        (output_root / PAYLOAD_REF.name, artifacts["payloadBytes"]),
        (output_root / ENVELOPE_REF.name, artifacts["envelopeBytes"]),
        (output_root / KEYRING_REF.name, artifacts["keyringBytes"]),
        (runtime_config_path, config_bytes),
    ):
        _write_bytes(path, encoded)
    return {**descriptor, "configVersion": version}


def materialize_graphql_read_registry_package(
    *,
    repo_root: Path,
    candidate_root: Path,
    environment: str,
    target: str,
    candidate_digest: str,
    signing: SigningMaterial | None = None,
    scratch_root: Path | None = None,
) -> dict[str, Any]:
    """Generate, sign and bind one registry inside a fresh candidate package."""

    candidate_root = _candidate_root_without_links(candidate_root)
    _validate_package_source_graphql_enabled(candidate_root)
    artifacts = _build_graphql_read_registry_artifacts(
        repo_root=repo_root,
        environment=environment,
        target=target,
        candidate_digest=candidate_digest,
        signing=signing,
        scratch_root=scratch_root,
    )
    descriptor = artifacts["descriptor"]
    _patch_service_package(
        candidate_root,
        candidate_digest=candidate_digest,
        schema_digest=descriptor["schemaDigest"],
        keyring=artifacts["keyring"],
        schema_bytes=artifacts["schemaBytes"],
        payload_bytes=artifacts["payloadBytes"],
        envelope_bytes=artifacts["envelopeBytes"],
        keyring_bytes=artifacts["keyringBytes"],
        descriptor=descriptor,
    )
    return validate_packaged_graphql_read_registry(
        repo_root=repo_root,
        candidate_root=candidate_root,
        expected_environment=environment,
        expected_target=target,
        expected_candidate_digest=candidate_digest,
        expected_descriptor=descriptor,
    )


def _validate_descriptor(
    descriptor: object,
    *,
    environment: str,
    target: str,
    candidate_digest: str,
) -> dict[str, Any]:
    required = {
        "schema",
        "environment",
        "target",
        "candidateDigest",
        "schemaRef",
        "schemaDigest",
        "payloadRef",
        "payloadDigest",
        "envelopeRef",
        "envelopeDigest",
        "trustedPublicKeysRef",
        "trustedPublicKeysDigest",
        "signingKeyId",
        "costModelVersion",
        "costPlanAggregateDigest",
        "entryCount",
    }
    if not isinstance(descriptor, dict) or set(descriptor) != required:
        raise ValueError("GraphQL registry package descriptor fields mismatch")
    if (
        descriptor.get("schema") != PACKAGE_SCHEMA
        or descriptor.get("environment") != environment
        or descriptor.get("target") != target
        or descriptor.get("candidateDigest") != candidate_digest
    ):
        raise ValueError("GraphQL registry package candidate identity mismatch")
    expected_refs = {
        "schemaRef": SCHEMA_REF.as_posix(),
        "payloadRef": PAYLOAD_REF.as_posix(),
        "envelopeRef": ENVELOPE_REF.as_posix(),
        "trustedPublicKeysRef": KEYRING_REF.as_posix(),
    }
    for field, value in expected_refs.items():
        if descriptor.get(field) != value:
            raise ValueError(f"GraphQL registry package {field} mismatch")
    for field in (
        "schemaDigest",
        "payloadDigest",
        "envelopeDigest",
        "trustedPublicKeysDigest",
        "costPlanAggregateDigest",
    ):
        if _DIGEST.fullmatch(str(descriptor.get(field) or "")) is None:
            raise ValueError(f"GraphQL registry package {field} is invalid")
    if descriptor.get("costModelVersion") != COST_MODEL_VERSION:
        raise ValueError("GraphQL registry package cost model is invalid")
    if _KEY_ID.fullmatch(str(descriptor.get("signingKeyId") or "")) is None:
        raise ValueError("GraphQL registry package signing keyId is invalid")
    if not isinstance(descriptor.get("entryCount"), int) or isinstance(
        descriptor.get("entryCount"), bool
    ) or descriptor["entryCount"] < 1:
        raise ValueError("GraphQL registry package entryCount is invalid")
    return descriptor


def validate_packaged_graphql_read_registry(
    *,
    repo_root: Path,
    candidate_root: Path,
    expected_environment: str,
    expected_target: str,
    expected_candidate_digest: str,
    expected_descriptor: object | None = None,
    purpose: str = "self_verify",
    currentness_timeout_seconds: float = 120.0,
) -> dict[str, Any]:
    """Verify package bytes; only explicit currentness reruns source generators."""

    if _DIGEST.fullmatch(expected_candidate_digest) is None:
        raise ValueError("expected GraphQL candidate digest is invalid")
    if purpose not in {"self_verify", "currentness"}:
        raise ValueError("GraphQL registry validation purpose is invalid")
    candidate_root = _candidate_root_without_links(candidate_root)
    package_descriptor = _read_object(
        candidate_root / PACKAGE_REF,
        label="GraphQL registry package descriptor",
    )
    descriptor = _validate_descriptor(
        package_descriptor,
        environment=expected_environment,
        target=expected_target,
        candidate_digest=expected_candidate_digest,
    )
    if expected_descriptor is not None and descriptor != expected_descriptor:
        raise ValueError("GraphQL registry package descriptor drifted")
    paths = {
        "schema": candidate_root / SCHEMA_REF,
        "payload": candidate_root / PAYLOAD_REF,
        "envelope": candidate_root / ENVELOPE_REF,
        "keyring": candidate_root / KEYRING_REF,
    }
    for label, path in paths.items():
        _regular_file(path, label=f"GraphQL registry package {label}")
    digest_fields = {
        "schema": "schemaDigest",
        "payload": "payloadDigest",
        "envelope": "envelopeDigest",
        "keyring": "trustedPublicKeysDigest",
    }
    for label, field in digest_fields.items():
        if _sha256_file(paths[label]) != descriptor[field]:
            raise ValueError(f"GraphQL registry package {label} digest drifted")
    payload_bytes = paths["payload"].read_bytes()
    _payload, schema_digest, aggregate_digest, entry_count = _payload_identity(
        payload_bytes, expected_candidate_digest=expected_candidate_digest
    )
    if (
        schema_digest != descriptor["schemaDigest"]
        or aggregate_digest != descriptor["costPlanAggregateDigest"]
        or entry_count != descriptor["entryCount"]
    ):
        raise ValueError("GraphQL registry package cost/schema identity drifted")
    if purpose == "currentness":
        try:
            expected_payload = _generate_payload(
                repo_root,
                expected_candidate_digest,
                timeout_seconds=currentness_timeout_seconds,
            )
        except subprocess.TimeoutExpired as exc:
            raise ValueError("GraphQL currentness generation timed out") from exc
        if expected_payload != payload_bytes:
            raise ValueError("GraphQL registry payload differs from current AST cost plan")

    keyring = _decode_keyring(paths["keyring"].read_bytes())
    key_id = descriptor["signingKeyId"]
    if key_id not in keyring:
        raise ValueError("GraphQL registry signing key is absent from package keyring")
    envelope = _read_object(paths["envelope"], label="GraphQL registry envelope")
    if set(envelope) != {"keyId", "payloadSha256", "payload", "signature"}:
        raise ValueError("GraphQL registry envelope fields mismatch")
    if envelope.get("keyId") != key_id or envelope.get("payloadSha256") != descriptor[
        "payloadDigest"
    ]:
        raise ValueError("GraphQL registry envelope identity drifted")
    try:
        embedded_payload = base64.b64decode(str(envelope.get("payload") or ""), validate=True)
        signature = base64.b64decode(str(envelope.get("signature") or ""), validate=True)
    except ValueError as exc:
        raise ValueError("GraphQL registry envelope base64 is invalid") from exc
    if embedded_payload != payload_bytes:
        raise ValueError("GraphQL registry envelope payload drifted")
    _verify_signature(
        base64.b64decode(keyring[key_id], validate=True),
        payload_bytes,
        signature,
    )
    config = yaml.safe_load((candidate_root / CONFIG_REF).read_text(encoding="utf-8"))
    graph = config.get("graphql_read") if isinstance(config, dict) else None
    timeout = graph.get("owner_timeout_ms") if isinstance(graph, dict) else None
    if not isinstance(timeout, int) or isinstance(timeout, bool) or not 100 <= timeout <= 5000:
        raise ValueError("GraphQL registry runtime owner timeout is invalid")
    if not isinstance(graph, dict) or graph != {
        "enabled": True,
        "registry_file": ENVELOPE_REF.name,
        "candidate_digest": expected_candidate_digest,
        "schema_file": SCHEMA_REF.name,
        "schema_digest": descriptor["schemaDigest"],
        "trusted_public_keys_json": json.dumps(
            keyring, ensure_ascii=True, separators=(",", ":"), sort_keys=True
        ),
        "owner_timeout_ms": timeout,
    }:
        raise ValueError("GraphQL registry runtime config binding drifted")
    return descriptor
