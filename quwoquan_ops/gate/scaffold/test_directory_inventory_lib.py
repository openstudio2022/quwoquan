#!/usr/bin/env python3
"""Shared helpers for physical three-layer test governance."""

from __future__ import annotations

import re
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[3]
PAGE_INVENTORY_PATH = ROOT / "specs" / "gates" / "user_acceptance_page_inventory.yaml"

LAYERS = {"local_contract", "api_integration", "user_acceptance"}
APP_ROOT = ROOT / "quwoquan_app" / "test"
SERVICE_ROOT = ROOT / "quwoquan_service" / "services"
DATA_ROOT = ROOT / "quwoquan_data" / "tests"
OPS_TEST_ROOT = ROOT / "quwoquan_ops" / "tests"
OPS_ACCEPTANCE_ROOT = OPS_TEST_ROOT / "acceptance"

REQUIRED_PAGE_CASE_SUFFIXES = (
    "load_success",
    "empty_permission_error",
    "primary_cta",
    "trace_context",
)

GENERATED_BRIDGE_MARKERS = (
    "Code generated by generate_canonical_test_bridges.py",
    "Code generated by generate_app_canonical_test_wrappers.py",
    "Source legacy file:",
)

GO_TEST_RE = re.compile(
    r"^\s*func\s+(Test[A-Za-z0-9_]+)\s*\(\s*t\s+\*testing\.T\s*\)",
    re.MULTILINE,
)
GO_BENCH_RE = re.compile(
    r"^\s*func\s+(Benchmark[A-Za-z0-9_]+)\s*\(\s*b\s+\*testing\.B\s*\)",
    re.MULTILINE,
)
GO_TESTMAIN_RE = re.compile(
    r"^\s*func\s+TestMain\s*\(\s*m\s+\*testing\.M\s*\)",
    re.MULTILINE,
)


def snake_case_identifier(value: str) -> str:
    text = value.strip()
    if not text:
        return ""
    text = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", text)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"[^A-Za-z0-9]+", "_", text)
    return text.strip("_").lower()


def page_wrapper_target_path(owner: str, surface_id: str) -> str:
    surface_path = snake_case_identifier(surface_id)
    return (
        Path("quwoquan_app/test/user_acceptance/pages")
        / owner
        / surface_path
        / f"{surface_path}_page__user_acceptance_test.dart"
    ).as_posix()


def go_suite_names(path: Path) -> tuple[list[str], list[str]]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    tests = sorted(set(GO_TEST_RE.findall(text)))
    benches = sorted(set(GO_BENCH_RE.findall(text)))
    return tests, benches


def go_has_test_entrypoint(path: Path) -> bool:
    text = path.read_text(encoding="utf-8", errors="ignore")
    return bool(GO_TEST_RE.search(text) or GO_BENCH_RE.search(text) or GO_TESTMAIN_RE.search(text))


def iter_canonical_files() -> list[tuple[str, Path, str]]:
    files: list[tuple[str, Path, str]] = []
    for layer in LAYERS:
        for path in sorted((APP_ROOT / layer).rglob("*_test.dart")):
            files.append(("app", path, layer))
        for path in sorted((DATA_ROOT / layer).rglob("test_*.py")):
            files.append(("data", path, layer))
    for path in sorted((OPS_TEST_ROOT / "local_contract").rglob("test_*.py")):
        files.append(("quwoquan_ops", path, "local_contract"))
    for layer in ("api_integration", "user_acceptance"):
        for path in sorted((OPS_ACCEPTANCE_ROOT / layer).rglob("test_*.py")):
            files.append(("quwoquan_ops", path, layer))
    for service_tests_dir in SERVICE_ROOT.glob("*/tests"):
        for layer in ("local_contract", "api_integration"):
            for path in sorted((service_tests_dir / layer).rglob("*_test.go")):
                files.append(("service", path, layer))
            for path in sorted((service_tests_dir / layer).rglob("test_*.py")):
                files.append(("service", path, layer))
    for path in sorted(SERVICE_ROOT.glob("*/**/*_test.go")):
        rel = path.relative_to(SERVICE_ROOT).as_posix()
        if "/tests/local_contract/" in rel or "/tests/api_integration/" in rel:
            continue
        if path.name.endswith("__local_contract_test.go"):
            files.append(("service", path, "local_contract"))
    return files


def recorded_file_is_canonical(path_text: str) -> bool:
    if path_text.startswith(".qwq_output/env/repo/runs/tests/") and path_text.endswith("report.json"):
        return True
    if path_text.startswith("quwoquan_app/test/"):
        return any(path_text.startswith(f"quwoquan_app/test/{layer}/") for layer in LAYERS)
    if path_text.startswith("quwoquan_data/tests/"):
        return any(path_text.startswith(f"quwoquan_data/tests/{layer}/") for layer in LAYERS)
    if path_text.startswith("quwoquan_ops/tests/local_contract/"):
        return True
    if path_text.startswith("quwoquan_ops/tests/acceptance/"):
        return path_text.startswith(
            (
                "quwoquan_ops/tests/acceptance/api_integration/",
                "quwoquan_ops/tests/acceptance/user_acceptance/",
            )
        )
    if path_text.startswith("quwoquan_service/services/"):
        if "/tests/local_contract/" in path_text or "/tests/api_integration/" in path_text:
            return True
        return path_text.endswith("__local_contract_test.go")
    return False


def contains_generated_bridge_marker(path: Path) -> bool:
    if not path.is_file():
        return False
    text = path.read_text(encoding="utf-8", errors="ignore")
    return any(marker in text for marker in GENERATED_BRIDGE_MARKERS)


def load_page_inventory() -> dict:
    if not PAGE_INVENTORY_PATH.exists():
        return {}
    return yaml.safe_load(PAGE_INVENTORY_PATH.read_text(encoding="utf-8")) or {}
