#!/usr/bin/env python3
"""Shared helpers for three-layer test migration inventory and bridge generation."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Iterable

import yaml


ROOT = Path(__file__).resolve().parents[3]
INVENTORY_PATH = ROOT / "specs" / "gates" / "test_directory_inventory.yaml"
PAGE_INVENTORY_PATH = ROOT / "specs" / "gates" / "user_acceptance_page_inventory.yaml"
LEGACY_ALLOWLIST_PATH = ROOT / "specs" / "gates" / "test_legacy_source_allowlist.yaml"

LAYERS = {"local_contract", "api_integration", "user_acceptance"}
APP_ROOT = ROOT / "quwoquan_app" / "test"
SERVICE_ROOT = ROOT / "quwoquan_service" / "services"
DATA_ROOT = ROOT / "quwoquan_data" / "tests"
AGENT_OPS_TEST_ROOT = ROOT / "quwoquan_ops" / "tests"
AGENT_OPS_ACCEPTANCE_ROOT = ROOT / "quwoquan_ops" / "tests" / "acceptance"

APP_BRIDGE_HEADER = "// Code generated by generate_app_canonical_test_wrappers.py. DO NOT EDIT.\n"
GENERATED_BRIDGE_HEADER = "Code generated by generate_canonical_test_bridges.py. DO NOT EDIT."

GO_TEST_RE = re.compile(
    r"^\s*func\s+(Test[A-Za-z0-9_]+)\s*\(\s*t\s+\*testing\.T\s*\)",
    re.MULTILINE,
)
GO_BENCH_RE = re.compile(
    r"^\s*func\s+(Benchmark[A-Za-z0-9_]+)\s*\(\s*b\s+\*testing\.B\s*\)",
    re.MULTILINE,
)

APP_USER_ACCEPTANCE_HINTS = (
    ("patrol", "user_acceptance"),
    ("journey", "user_acceptance"),
    ("journeys", "user_acceptance"),
)

DATA_USER_ACCEPTANCE_PREFIXES = {"workflow"}
DATA_API_INTEGRATION_PREFIXES = {"integration", "ship"}
DATA_USER_ACCEPTANCE_STEMS = ("journey", "gwt", "pilot", "release_integrity", "scope_semantics")
DATA_API_INTEGRATION_STEMS = ("import", "ship", "release", "storage", "sampling")

AGENT_OPS_USER_ACCEPTANCE_STEMS = ("dev_up", "up_runtime")
AGENT_OPS_API_INTEGRATION_STEMS = (
    "prod_deploy",
    "prod_plane",
    "resolve_prod_release_state",
    "stackctl",
)

REQUIRED_PAGE_CASE_SUFFIXES = (
    "load_success",
    "empty_permission_error",
    "primary_cta",
    "trace_context",
)


def _strip_test_suffix(stem: str) -> str:
    stem = re.sub(r"__(local_contract|api_integration|user_acceptance)$", "", stem)
    if stem.endswith("_test"):
        return stem[: -len("_test")]
    return stem


def canonical_filename(path: Path, layer: str) -> str:
    return f"{_strip_test_suffix(path.stem)}__{layer}_test{path.suffix}"


def snake_case_identifier(value: str) -> str:
    text = value.strip()
    if not text:
        return ""
    text = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", text)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"[^A-Za-z0-9]+", "_", text)
    return text.strip("_").lower()


def _relative(path: Path, base: Path) -> str:
    return path.relative_to(base).as_posix()


def is_generated_bridge(path: Path) -> bool:
    if not path.exists() or not path.is_file():
        return False
    try:
        first_line = path.read_text(encoding="utf-8", errors="ignore").splitlines()[0]
    except IndexError:
        return False
    return first_line == APP_BRIDGE_HEADER.strip() or GENERATED_BRIDGE_HEADER in first_line


def is_app_canonical(rel: str) -> bool:
    return rel.startswith(("local_contract/", "api_integration/", "user_acceptance/"))


def is_service_canonical(rel: str) -> bool:
    return "/tests/local_contract/" in rel or "/tests/api_integration/" in rel


def is_data_canonical(rel: str) -> bool:
    return rel.startswith(("local_contract/", "api_integration/", "user_acceptance/"))


def is_quwoquan_ops_canonical(rel: str) -> bool:
    return rel.startswith("local_contract/")


def is_quwoquan_ops_acceptance_canonical(rel: str) -> bool:
    return rel.startswith(("api_integration/", "user_acceptance/"))


def app_layer(rel_path: Path) -> str:
    parts = rel_path.parts
    tokens = {token.lower() for token in parts[:-1]}
    stem = rel_path.stem.lower()
    first = parts[0].lower() if parts else ""
    if any(hint == first or hint in stem or hint in tokens for hint, _ in APP_USER_ACCEPTANCE_HINTS):
        return "user_acceptance"
    if first in {"beta", "gamma"}:
        return "api_integration"
    return "local_contract"


def app_target_path(rel_path: Path, layer: str) -> str:
    target = Path("quwoquan_app/test") / layer / Path(*rel_path.parts[:-1]) / canonical_filename(rel_path, layer)
    return target.as_posix()


def go_suite_names(path: Path) -> tuple[list[str], list[str]]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    tests = sorted(set(GO_TEST_RE.findall(text)))
    benches = sorted(set(GO_BENCH_RE.findall(text)))
    return tests, benches


def service_layer(rel_path: Path) -> str:
    parts = rel_path.parts
    if len(parts) >= 2 and parts[1] == "tests":
        return "api_integration"
    return "local_contract"


def service_target_path(rel_path: Path, layer: str) -> str:
    service_name = rel_path.parts[0]
    if layer == "api_integration" and len(rel_path.parts) >= 2 and rel_path.parts[1] == "tests":
        tail = rel_path.parts[2:-1]
    else:
        tail = rel_path.parts[1:-1]
    target = (
        Path("quwoquan_service/services")
        / service_name
        / "tests"
        / layer
        / Path(*tail)
        / canonical_filename(rel_path, layer)
    )
    return target.as_posix()


def data_layer(rel_path: Path) -> str:
    first = rel_path.parts[0].lower() if rel_path.parts else ""
    stem = rel_path.stem.lower()
    if first in DATA_USER_ACCEPTANCE_PREFIXES:
        return "user_acceptance"
    if first in DATA_API_INTEGRATION_PREFIXES:
        if "pilot" in stem or "gwt" in stem:
            return "user_acceptance"
        return "api_integration"
    if any(token in stem for token in DATA_USER_ACCEPTANCE_STEMS):
        return "user_acceptance"
    if any(token in stem for token in DATA_API_INTEGRATION_STEMS):
        return "api_integration"
    return "local_contract"


def data_target_path(rel_path: Path, layer: str) -> str:
    target = Path("quwoquan_data/tests") / layer / Path(*rel_path.parts[:-1]) / canonical_filename(rel_path, layer)
    return target.as_posix()


def quwoquan_ops_layer(rel_path: Path) -> str:
    stem = rel_path.stem.lower()
    if any(token in stem for token in AGENT_OPS_USER_ACCEPTANCE_STEMS):
        return "user_acceptance"
    if any(token in stem for token in AGENT_OPS_API_INTEGRATION_STEMS):
        return "api_integration"
    return "local_contract"


def quwoquan_ops_target_path(rel_path: Path, layer: str) -> str:
    if layer == "local_contract":
        target = Path("quwoquan_ops/tests") / layer / Path(*rel_path.parts[:-1]) / canonical_filename(rel_path, layer)
    else:
        target = Path("quwoquan_ops/tests/acceptance") / layer / Path(*rel_path.parts[:-1]) / canonical_filename(rel_path, layer)
    return target.as_posix()


def page_wrapper_target_path(owner: str, surface_id: str) -> str:
    surface_path = snake_case_identifier(surface_id)
    return (
        Path("quwoquan_app/test/user_acceptance/pages")
        / owner
        / surface_path
        / f"{surface_path}_page__user_acceptance_test.dart"
    ).as_posix()


def _legacy_page_wrapper_target_path(owner: str, surface_id: str) -> str:
    return (
        Path("quwoquan_app/test/user_acceptance/pages")
        / owner
        / surface_id
        / f"{surface_id}_page__user_acceptance_test.dart"
    ).as_posix()


def page_wrapper_path_mapping() -> dict[str, str]:
    if not PAGE_INVENTORY_PATH.is_file():
        return {}
    data = yaml.safe_load(PAGE_INVENTORY_PATH.read_text(encoding="utf-8")) or {}
    mapping: dict[str, str] = {}
    for surface in data.get("surfaces") or []:
        if not isinstance(surface, dict):
            continue
        owner = str(surface.get("owner") or "").strip()
        surface_id = str(surface.get("surface_id") or "").strip()
        if not owner or not surface_id:
            continue
        legacy = _legacy_page_wrapper_target_path(owner, surface_id)
        canonical = page_wrapper_target_path(owner, surface_id)
        if legacy != canonical:
            mapping[legacy] = canonical
    return mapping


def build_entry(
    *,
    current_path: str,
    layer: str,
    target_path: str,
    bridge_exists: bool,
    classification_basis: str,
) -> dict[str, object]:
    return {
        "current_path": current_path,
        "layer": layer,
        "target_path": target_path,
        "migration_status": "bridged" if bridge_exists else "pending",
        "classification_basis": classification_basis,
    }


def _app_entries() -> list[dict[str, object]]:
    entries: list[dict[str, object]] = []
    for path in sorted(APP_ROOT.rglob("*_test.dart")):
        test_rel = path.relative_to(APP_ROOT)
        if is_app_canonical(test_rel.as_posix()):
            continue
        layer = app_layer(test_rel)
        target_path = app_target_path(test_rel, layer)
        entries.append(
            build_entry(
                current_path=path.relative_to(ROOT).as_posix(),
                layer=layer,
                target_path=target_path,
                bridge_exists=(ROOT / target_path).exists(),
                classification_basis=f"app:{layer}:{test_rel.parts[0]}",
            )
        )
    return entries


def _service_entries() -> list[dict[str, object]]:
    entries: list[dict[str, object]] = []
    for path in sorted(SERVICE_ROOT.rglob("*_test.go")):
        rel = path.relative_to(SERVICE_ROOT)
        if is_service_canonical((Path("quwoquan_service/services") / rel).as_posix()):
            continue
        tests, benches = go_suite_names(path)
        if not tests and not benches:
            continue
        layer = service_layer(rel)
        target_path = service_target_path(rel, layer)
        entries.append(
            build_entry(
                current_path=path.relative_to(ROOT).as_posix(),
                layer=layer,
                target_path=target_path,
                bridge_exists=(ROOT / target_path).exists(),
                classification_basis=f"service:{layer}:{rel.parts[0]}/{rel.parts[1]}",
            )
        )
    return entries


def _data_entries() -> list[dict[str, object]]:
    entries: list[dict[str, object]] = []
    for path in sorted(DATA_ROOT.rglob("test_*.py")):
        test_rel = path.relative_to(DATA_ROOT)
        if is_data_canonical(test_rel.as_posix()):
            continue
        layer = data_layer(test_rel)
        target_path = data_target_path(test_rel, layer)
        entries.append(
            build_entry(
                current_path=path.relative_to(ROOT).as_posix(),
                layer=layer,
                target_path=target_path,
                bridge_exists=(ROOT / target_path).exists(),
                classification_basis=f"data:{layer}:{test_rel.parts[0]}",
            )
        )
    return entries


def _quwoquan_ops_entries() -> list[dict[str, object]]:
    entries: list[dict[str, object]] = []
    for path in sorted(AGENT_OPS_TEST_ROOT.rglob("test_*.py")):
        test_rel = path.relative_to(AGENT_OPS_TEST_ROOT)
        rel_text = test_rel.as_posix()
        if is_quwoquan_ops_canonical(rel_text):
            continue
        if rel_text.startswith("acceptance/"):
            acceptance_rel = test_rel.relative_to("acceptance").as_posix()
            if is_quwoquan_ops_acceptance_canonical(acceptance_rel):
                continue
        layer = quwoquan_ops_layer(test_rel)
        target_path = quwoquan_ops_target_path(test_rel, layer)
        entries.append(
            build_entry(
                current_path=path.relative_to(ROOT).as_posix(),
                layer=layer,
                target_path=target_path,
                bridge_exists=(ROOT / target_path).exists(),
                classification_basis=f"quwoquan_ops:{layer}:{test_rel.stem}",
            )
        )
    return entries


def _summarize_entries(entries: list[dict[str, object]]) -> dict[str, object]:
    pending = sum(1 for entry in entries if entry["migration_status"] == "pending")
    bridged = sum(1 for entry in entries if entry["migration_status"] == "bridged")
    return {
        "pending_count": pending,
        "bridged_count": bridged,
        "entries": entries,
    }


def build_inventory() -> dict[str, object]:
    app_entries = _app_entries()
    service_entries = _service_entries()
    data_entries = _data_entries()
    quwoquan_ops_entries = _quwoquan_ops_entries()
    return {
        "version": 2,
        "generated_by": "python3 quwoquan_ops/gate/scaffold/generate_test_directory_inventory.py",
        "areas": {
            "app": _summarize_entries(app_entries),
            "service": _summarize_entries(service_entries),
            "data": _summarize_entries(data_entries),
            "quwoquan_ops": _summarize_entries(quwoquan_ops_entries),
        },
    }


def build_path_mapping() -> dict[str, str]:
    mapping: dict[str, str] = {}
    inventory = build_inventory()
    for area in (inventory.get("areas") or {}).values():
        if not isinstance(area, dict):
            continue
        for entry in area.get("entries") or []:
            if isinstance(entry, dict):
                current_path = str(entry.get("current_path") or "").strip()
                target_path = str(entry.get("target_path") or "").strip()
                if current_path and target_path:
                    mapping[current_path] = target_path
    mapping.update(page_wrapper_path_mapping())
    return mapping


def iter_canonical_files() -> list[tuple[str, Path, str]]:
    files: list[tuple[str, Path, str]] = []
    for layer in LAYERS:
        for path in sorted((APP_ROOT / layer).rglob("*_test.dart")):
            files.append(("app", path, layer))
        for path in sorted((DATA_ROOT / layer).rglob("test_*.py")):
            files.append(("data", path, layer))
    if AGENT_OPS_TEST_ROOT.exists():
        for path in sorted((AGENT_OPS_TEST_ROOT / "local_contract").rglob("test_*.py")):
            files.append(("quwoquan_ops", path, "local_contract"))
    if AGENT_OPS_ACCEPTANCE_ROOT.exists():
        for layer in ("api_integration", "user_acceptance"):
            for path in sorted((AGENT_OPS_ACCEPTANCE_ROOT / layer).rglob("test_*.py")):
                files.append(("quwoquan_ops", path, layer))
    for service_tests_dir in SERVICE_ROOT.glob("*/tests"):
        for layer in ("local_contract", "api_integration"):
            layer_dir = service_tests_dir / layer
            if not layer_dir.exists():
                continue
            for path in sorted(layer_dir.rglob("*_test.go")):
                files.append(("service", path, layer))
    return files


def recorded_file_is_canonical(path_text: str) -> bool:
    if path_text.startswith(".qwq_output/runs/tests/") and path_text.endswith("report.json"):
        return True
    if path_text.startswith("quwoquan_app/test/"):
        return any(path_text.startswith(f"quwoquan_app/test/{layer}/") for layer in LAYERS)
    if path_text.startswith("quwoquan_data/tests/"):
        return any(path_text.startswith(f"quwoquan_data/tests/{layer}/") for layer in LAYERS)
    if path_text.startswith("quwoquan_ops/tests/local_contract/"):
        return True
    if path_text.startswith("quwoquan_ops/tests/acceptance/"):
        return path_text.startswith(("quwoquan_ops/tests/acceptance/api_integration/", "quwoquan_ops/tests/acceptance/user_acceptance/"))
    if path_text.startswith("quwoquan_service/services/"):
        return "/tests/local_contract/" in path_text or "/tests/api_integration/" in path_text
    return False


def iter_unbridged_entries() -> Iterable[tuple[str, dict[str, object]]]:
    inventory = build_inventory()
    for area_name, area in (inventory.get("areas") or {}).items():
        if not isinstance(area, dict):
            continue
        for entry in area.get("entries") or []:
            if isinstance(entry, dict) and entry.get("migration_status") != "bridged":
                yield str(area_name), entry
