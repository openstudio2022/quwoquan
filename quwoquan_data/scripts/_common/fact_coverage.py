def fact_covered(fact: str, article: str) -> bool:
    if fact in article:
        return True
    for alias in FACT_COVERAGE_ALIASES.get(fact, []):
        if alias in article:
            return True
    if len(fact) >= 2 and fact[:2] in article:
        return True
    return False


