def natural_fact_line(fact: str) -> str:
    if fact in FACT_NATURAL_LINES:
        return FACT_NATURAL_LINES[fact]
    return f"关于{fact}，我已写入上面动线与避坑段落，行前再对照官方公告复核。"


def append_fact_coverage_section(body: str, brief: dict, section_title: str | None = "行前核对") -> str:
    facts = [str(f) for f in (brief.get("mustIncludeFacts") or []) if f]
    missing = [f for f in facts if not fact_covered(f, body)]
    if not missing:
        return body
    lines = [natural_fact_line(f) for f in missing]
    if section_title:
        section = f"## {section_title}\n\n" + "\n\n".join(lines) + "\n\n"
        marker = "## 注意事项\n"
        if marker in body:
            return body.replace(marker, section + marker)
        return body + "\n\n" + section
    return body + "\n\n" + "\n\n".join(lines) + "\n"


