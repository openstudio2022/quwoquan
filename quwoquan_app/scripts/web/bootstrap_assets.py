"""Web bootstrap surface 产物生成（runtime-client-foundation DEC-005）。

Flutter 引擎启动前只允许一个平台实现的 bootstrap surface：loading 为
`role=status + aria-live=polite`，字体 404/首次离线为 `startupDependencyUnavailable`
全屏恢复态，唯一动作是重新加载。本 generator 从设计系统与 l10n ARB 真相源
生成 `web/qwq_bootstrap.css` 与 `web/qwq_bootstrap.js`，HTML 不复制品牌字面值。
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from _common.paths import APP_ROOT

_COLORS_PATH = APP_ROOT / "lib/design_system/colors/app_colors.dart"
_TYPOGRAPHY_PATH = APP_ROOT / "lib/design_system/typography/app_typography.dart"
_SPACING_PATH = APP_ROOT / "lib/design_system/spacing/app_spacing_values.dart"
_ARB_ZH_PATH = APP_ROOT / "lib/l10n/app_zh.arb"
_ARB_EN_PATH = APP_ROOT / "lib/l10n/app_en.arb"
CSS_OUTPUT = APP_ROOT / "web/qwq_bootstrap.css"
JS_OUTPUT = APP_ROOT / "web/qwq_bootstrap.js"

_L10N_KEYS = (
    "webBootstrapLoading",
    "webBootstrapUnavailableTitle",
    "webBootstrapUnavailableBody",
    "webBootstrapReload",
)

_GENERATED_HEADER = (
    "GENERATED by quwoquan_app/scripts/web/bootstrap_assets.py -- do not edit.\n"
    "Sources: lib/design_system (AppColors/AppTypography/AppSpacing) and lib/l10n ARB."
)


class WebBootstrapAssetsError(RuntimeError):
    pass


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise WebBootstrapAssetsError(f"cannot read source: {path}: {error}") from error


def _dart_color_to_css(value: str) -> str:
    match = re.fullmatch(r"0x([0-9A-Fa-f]{2})([0-9A-Fa-f]{6})", value)
    if match is None:
        raise WebBootstrapAssetsError(f"not a canonical Dart color literal: {value}")
    alpha = int(match.group(1), 16)
    rgb = match.group(2).lower()
    if alpha == 0xFF:
        return f"#{rgb}"
    return f"#{rgb}{match.group(1).lower()}"


def _named_color(source: str, name: str) -> str:
    match = re.search(
        rf"static const Color {re.escape(name)} = Color\((0x[0-9A-Fa-f]{{8}})\)", source
    )
    if match is None:
        raise WebBootstrapAssetsError(f"AppColors.{name} literal not found")
    return _dart_color_to_css(match.group(1))


def _theme_getter_colors(source: str, getter: str) -> tuple[str, str]:
    """返回 AppColorsTheme getter 的 (dark, light) CSS 颜色。"""

    match = re.search(
        rf"Color get {re.escape(getter)} =>\s*isDark\s*\?\s*const Color\((0x[0-9A-Fa-f]{{8}})\)"
        rf"\s*:\s*const Color\((0x[0-9A-Fa-f]{{8}})\);",
        source,
    )
    if match is None:
        raise WebBootstrapAssetsError(
            f"AppColorsTheme.{getter} does not expose two color literals"
        )
    return _dart_color_to_css(match.group(1)), _dart_color_to_css(match.group(2))


def _named_double(source: str, class_hint: str, name: str) -> float:
    match = re.search(
        rf"static const double (?:[A-Za-z0-9_]+ = [0-9.]+, )*{re.escape(name)} = ([0-9.]+)",
        source,
    )
    if match is None:
        raise WebBootstrapAssetsError(f"{class_hint}.{name} literal not found")
    return float(match.group(1))


def _l10n_messages(path: Path) -> dict[str, str]:
    try:
        payload = json.loads(_read(path))
    except json.JSONDecodeError as error:
        raise WebBootstrapAssetsError(f"invalid ARB {path}: {error}") from error
    messages: dict[str, str] = {}
    for key in _L10N_KEYS:
        value = payload.get(key)
        if not isinstance(value, str) or not value.strip():
            raise WebBootstrapAssetsError(f"ARB {path.name} is missing {key}")
        messages[key] = value
    return messages


def _tokens() -> dict[str, object]:
    colors = _read(_COLORS_PATH)
    typography = _read(_TYPOGRAPHY_PATH)
    spacing = _read(_SPACING_PATH)
    foreground_dark, foreground_light = _theme_getter_colors(colors, "foregroundPrimary")
    secondary_dark, secondary_light = _theme_getter_colors(colors, "foregroundSecondary")
    return {
        "backgroundLight": _named_color(colors, "iosGroupedBackgroundLight"),
        "backgroundDark": _named_color(colors, "iosGroupedBackgroundDark"),
        "foregroundLight": foreground_light,
        "foregroundDark": foreground_dark,
        "foregroundSecondaryLight": secondary_light,
        "foregroundSecondaryDark": secondary_dark,
        "accent": _named_color(colors, "brandBlue600"),
        "fontTitlePx": _named_double(typography, "AppTypography", "xl"),
        "fontBodyPx": _named_double(typography, "AppTypography", "base"),
        "spaceMdPx": _named_double(spacing, "AppSpacing", "md"),
        "spaceLgPx": _named_double(spacing, "AppSpacing", "lg"),
        "radiusPx": _named_double(spacing, "AppSpacing", "radiusTen"),
    }


def _px(value: object) -> str:
    number = float(value)  # type: ignore[arg-type]
    return f"{number:g}px"


