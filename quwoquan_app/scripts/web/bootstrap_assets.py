def render_js() -> str:
    zh = _l10n_messages(_ARB_ZH_PATH)
    en = _l10n_messages(_ARB_EN_PATH)
    header = "\n".join(f" * {line}" for line in _GENERATED_HEADER.splitlines())
    l10n_literal = json.dumps({"zh": zh, "en": en}, ensure_ascii=False, indent=2)
    return f"""/*
{header}
 */
(function () {{
  "use strict";
  var L10N = {l10n_literal};
  var CRITICAL_RESOURCE = /(flutter_bootstrap\\.js|flutter\\.js|main\\.dart\\.(js|mjs|wasm)|canvaskit|FontManifest\\.json|\\.ttf|\\.otf|\\.woff2?)([?#].*)?$/;
  var RECOVERY_DEADLINE_MS = 30000;

  function messages() {{
    var language = (navigator.language || "zh").toLowerCase();
    return language.indexOf("zh") === 0 ? L10N.zh : L10N.en;
  }}

  var surface = document.getElementById("qwq-bootstrap");
  var loading = document.getElementById("qwq-bootstrap-loading");
  var recovery = document.getElementById("qwq-bootstrap-recovery");
  if (!surface || !loading || !recovery) {{
    return;
  }}
  var text = messages();
  document.getElementById("qwq-bootstrap-loading-text").textContent =
    text.webBootstrapLoading;
  document.getElementById("qwq-bootstrap-recovery-title").textContent =
    text.webBootstrapUnavailableTitle;
  document.getElementById("qwq-bootstrap-recovery-body").textContent =
    text.webBootstrapUnavailableBody;
  var reload = document.getElementById("qwq-bootstrap-reload");
  reload.textContent = text.webBootstrapReload;
  reload.addEventListener("click", function () {{
    location.reload();
  }});

  var engineStarted = false;
  var dependencyFailed = false;

  // startupDependencyUnavailable：引擎首帧前关键资源失败或首次离线时的
  // 全屏恢复态，唯一动作是重新加载（DEC-005）。
  function showRecovery() {{
    if (engineStarted) {{
      return;
    }}
    loading.hidden = true;
    recovery.hidden = false;
    try {{
      window.__qwqRecordStartupEvent("web_bootstrap_dependency_unavailable");
    }} catch (_) {{}}
  }}

  function dismissSurface() {{
    engineStarted = true;
    surface.hidden = true;
  }}

  window.addEventListener("flutter-first-frame", dismissSurface);

  window.addEventListener(
    "error",
    function (event) {{
      var target = event.target;
      if (!target || target === window) {{
        return;
      }}
      var url = target.src || target.href || "";
      if (CRITICAL_RESOURCE.test(url)) {{
        dependencyFailed = true;
        showRecovery();
      }}
    }},
    true
  );

  setTimeout(function () {{
    if (!engineStarted && (dependencyFailed || navigator.onLine === false)) {{
      showRecovery();
    }}
  }}, RECOVERY_DEADLINE_MS);
}})();
"""


def generate() -> list[Path]:
    CSS_OUTPUT.write_text(render_css(), encoding="utf-8")
    JS_OUTPUT.write_text(render_js(), encoding="utf-8")
    return [CSS_OUTPUT, JS_OUTPUT]


def check() -> None:
    problems: list[str] = []
    for path, expected in ((CSS_OUTPUT, render_css()), (JS_OUTPUT, render_js())):
        if not path.is_file():
            problems.append(f"missing generated asset: {path.name}")
        elif path.read_text(encoding="utf-8") != expected:
            problems.append(f"generated asset is stale: {path.name}")
    if problems:
        raise WebBootstrapAssetsError(
            "web bootstrap assets are out of sync (run: "
            "python3 scripts/cli.py web generate-bootstrap): " + "; ".join(problems)
        )
