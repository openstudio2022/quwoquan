CircleImpactItem buildCircleImpactItemContract({
  required String helpType,
  required String action,
  required String intersectionDimension,
  required int count,
  required String primaryText,
  String source = 'test',
  String tagRef = '',
  String subtitleText = '',
  String? impactId,
  List<IntersectionTextSpan> primarySpans = const <IntersectionTextSpan>[],
  List<IntersectionVisual> sampleVisuals = const <IntersectionVisual>[],
  IntersectionRepresentativeActor? representativeActor,
  List<IntersectionActionHint> actionHints = const <IntersectionActionHint>[],
  IntersectionTarget? countTarget,
  String evidenceSnapshotId = '',
  String countObjectKind = 'user',
  IntersectionPropagationPath? propagationPath,
  String iconKey = 'relationship',
}) {
  return CircleImpactItem(
    helpType: helpType,
    action: action,
    intersectionDimension: intersectionDimension,
    tagRef: tagRef,
    source: source,
    count: count,
    primaryText: primaryText,
    subtitleText: subtitleText,
    impactId: impactId ?? '$helpType:$action',
    primarySpans: primarySpans,
    sampleVisuals: sampleVisuals,
    representativeActor: representativeActor,
    actionHints: actionHints,
    countTarget: countTarget,
    evidenceSnapshotId: evidenceSnapshotId,
    countObjectKind: countObjectKind,
    propagationPath: propagationPath,
    iconKey: iconKey,
  );
}

