/// Circle 领域 canonical 契约对象的 local_contract 构造器。
///
/// 唯一目的：让测试只声明它真正断言的字段，其余必填字段取契约中性默认值。
/// 这里不做任何 wire 解析、映射或业务判定，避免成为第二真相源。
/// 仅供测试树使用，禁止被 `lib/**` 或任何环境 App 装配引用。
library;

import 'package:quwoquan_cloud_contracts/quwoquan_cloud_contracts.dart';

final DateTime circleContractTestEpoch = DateTime.utc(2026, 1, 1);

Circle buildCircleContract({
  required String circleId,
  String name = '契约测试圈子',
  String ownerId = 'fixture_user_owner',
  String? description,
  String? coverUrl,
  String? iconUrl,
  String? ownerDisplayNameSnapshot,
  String? category,
  String? subCategory,
  String? domainId,
  List<String>? tags,
  int memberCount = 0,
  int postCount = 0,
  int weeklyActiveCount = 0,
  int version = 1,
  CircleStatus status = CircleStatus.active,
  CircleVisibility visibility = CircleVisibility.public,
  CircleJoinPolicy joinPolicy = CircleJoinPolicy.open,
  CircleKind kind = CircleKind.interest,
  CircleDisplaySubjectType displaySubjectType = CircleDisplaySubjectType.circle,
  bool followEnabled = true,
  bool autoSyncChat = true,
  String? defaultPublicGroupId,
  List<CircleSectionConfig>? sectionConfig,
  int storageUsedBytes = 0,
  int storageQuotaBytes = 0,
  String? linkedHomepageId,
  HomepageType? linkedHomepageType,
  String? linkedHomepageTitle,
  DateTime? createdAt,
  DateTime? updatedAt,
}) {
  return Circle(
    id: circleId,
    name: name,
    description: description,
    coverUrl: coverUrl,
    iconUrl: iconUrl,
    ownerId: ownerId,
    ownerDisplayNameSnapshot: ownerDisplayNameSnapshot,
    category: category,
    subCategory: subCategory,
    tags: tags,
    memberCount: memberCount,
    postCount: postCount,
    weeklyActiveCount: weeklyActiveCount,
    version: version,
    status: status,
    visibility: visibility,
    joinPolicy: joinPolicy,
    kind: kind,
    displaySubjectType: displaySubjectType,
    followEnabled: followEnabled,
    defaultPublicGroupId: defaultPublicGroupId,
    autoSyncChat: autoSyncChat,
    sectionConfig: sectionConfig,
    storageUsedBytes: storageUsedBytes,
    storageQuotaBytes: storageQuotaBytes,
    domainId: domainId,
    linkedHomepageId: linkedHomepageId,
    linkedHomepageType: linkedHomepageType,
    linkedHomepageTitle: linkedHomepageTitle,
    createdAt: createdAt ?? circleContractTestEpoch,
    updatedAt: updatedAt ?? createdAt ?? circleContractTestEpoch,
  );
}

