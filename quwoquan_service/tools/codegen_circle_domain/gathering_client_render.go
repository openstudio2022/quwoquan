func renderGatheringPathFunction(
	output *strings.Builder,
	operation ast.Operation,
) {
	name := gatheringOperationGoName(operation)
	pathBindings := operationPathBindings(operation)
	fmt.Fprintf(output, "func CircleGathering%sPath(", name)
	for index, binding := range pathBindings {
		if index != 0 {
			output.WriteString(", ")
		}
		fmt.Fprintf(output, "%s string", lowerGoName(binding.Field))
	}
	output.WriteString(") string {\n")
	fmt.Fprintf(
		output,
		"\tresult := CircleGathering%sPathTemplate\n",
		name,
	)
	for _, binding := range pathBindings {
		fmt.Fprintf(
			output,
			"\tresult = strings.ReplaceAll(result, %q, url.PathEscape(strings.TrimSpace(%s)))\n",
			"{"+binding.Name+"}",
			lowerGoName(binding.Field),
		)
	}
	output.WriteString("\treturn result\n}\n\n")
}

func renderGatheringClient(model gatheringClientModel) string {
	var output strings.Builder
	output.WriteString(
		"// Code generated by tools/codegen_circle_domain from " +
			model.Spec.FieldsPath + " and " + model.Spec.OperationsPath +
			". DO NOT EDIT.\n",
	)
	fmt.Fprintf(&output, "package %s\n\n", model.Spec.PublicPackage)
	output.WriteString(`import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"net/url"
	"strconv"
	"time"

	"quwoquan_service/generated/serviceclients"
)

`)
	for _, name := range model.EnumNames {
		fmt.Fprintf(
			&output,
			"// %s enumerates canonical %s wire values.\ntype %s string\n\nconst (\n",
			name,
			name,
			name,
		)
		for _, value := range model.Enums[name] {
			fmt.Fprintf(
				&output,
				"\t%s %s = %q\n",
				enumConstName(name, value),
				name,
				value,
			)
		}
		output.WriteString(")\n\n")
	}
	for _, name := range model.TypeNames {
		fmt.Fprintf(
			&output,
			"// %s is generated from Gathering fields.yaml.\ntype %s struct {\n",
			name,
			name,
		)
		for _, field := range model.Types[name].Fields {
			goType, err := circleServiceGoType(field, model)
			if err != nil {
				panic(err)
			}
			fmt.Fprintf(
				&output,
				"\t%s %s `json:%q`\n",
				goFieldName(field.Name),
				goType,
				gatheringJSONTag(field),
			)
		}
		output.WriteString("}\n\n")
	}
	output.WriteString(`// RequestPacket is the fully bound wire packet plus the canonical request
// bytes used by delegated grant requestDigest verification.
type RequestPacket struct {
	Operation        serviceclients.CircleGatheringOperationMetadata
	Path             string
	Query            url.Values
	Body             []byte
	CanonicalRequest []byte
}

type ResponsePacket struct {
	StatusCode int
	Body       []byte
}

type UnexpectedResponseError struct {
	OperationID string
	StatusCode  int
}

func (err UnexpectedResponseError) Error() string {
	return fmt.Sprintf(
		"circle gathering operation %s returned status %d",
		err.OperationID,
		err.StatusCode,
	)
}

// CanonicalRequestDigest hashes exactly the bytes emitted by a generated
// operation request encoder for delegated grant binding.
func CanonicalRequestDigest(canonicalRequest []byte) string {
	digest := sha256.Sum256(canonicalRequest)
	return "sha256:" + hex.EncodeToString(digest[:])
}

func operationMetadata(
	operationID string,
) (serviceclients.CircleGatheringOperationMetadata, error) {
	operation, found := serviceclients.LookupCircleGatheringOperation(operationID)
	if !found {
		return serviceclients.CircleGatheringOperationMetadata{}, fmt.Errorf(
			"unknown generated Circle Gathering operation %q",
			operationID,
		)
	}
	return operation, nil
}

func decodeResponse(
	operation serviceclients.CircleGatheringOperationMetadata,
	packet ResponsePacket,
	target any,
) error {
	if packet.StatusCode != operation.SuccessStatus {
		return UnexpectedResponseError{
			OperationID: operation.OperationID,
			StatusCode: packet.StatusCode,
		}
	}
	if err := json.Unmarshal(packet.Body, target); err != nil {
		return fmt.Errorf("decode %s response: %w", operation.OperationID, err)
	}
	return nil
}

`)
	for _, operation := range model.Operations {
		renderGatheringOperationEncoder(&output, operation, model)
	}
	output.WriteString("var _ = strconv.FormatInt\nvar _ = time.Time{}\n")
	return renderCircleServiceClientNames(output.String(), model.Spec)
}

func renderGatheringClientAlias(model gatheringClientModel) string {
	var output strings.Builder
	output.WriteString(
		"// Code generated by tools/codegen_circle_domain from " +
			model.Spec.FieldsPath + " and " + model.Spec.OperationsPath +
			". DO NOT EDIT.\n",
	)
	fmt.Fprintf(&output, "package %s\n\n", model.Spec.PrivatePackage)
	fmt.Fprintf(
		&output,
		"import shared %q\n\n",
		model.Spec.PublicImportPath,
	)
	for _, name := range model.EnumNames {
		fmt.Fprintf(&output, "type %s = shared.%s\n\n", name, name)
		output.WriteString("const (\n")
		for _, value := range model.Enums[name] {
			constantName := enumConstName(name, value)
			fmt.Fprintf(
				&output,
				"\t%s = shared.%s\n",
				constantName,
				constantName,
			)
		}
		output.WriteString(")\n\n")
	}
	for _, name := range model.TypeNames {
		fmt.Fprintf(&output, "type %s = shared.%s\n", name, name)
	}
	output.WriteString(`
type RequestPacket = shared.RequestPacket
type ResponsePacket = shared.ResponsePacket
type UnexpectedResponseError = shared.UnexpectedResponseError

func CanonicalRequestDigest(canonicalRequest []byte) string {
	return shared.CanonicalRequestDigest(canonicalRequest)
}

`)
	for _, operation := range model.Operations {
		name := gatheringOperationGoName(operation)
		fmt.Fprintf(
			&output,
			"func Encode%s(request %s) (RequestPacket, error) {\n"+
				"\treturn shared.Encode%s(request)\n"+
				"}\n",
			name,
			operation.RequestEntity,
			name,
		)
		fmt.Fprintf(
			&output,
			"func Decode%sResponse(packet ResponsePacket) (%s, error) {\n"+
				"\treturn shared.Decode%sResponse(packet)\n"+
				"}\n",
			name,
			operation.ResponseEntity,
			name,
		)
	}
	return renderCircleServiceClientNames(output.String(), model.Spec)
}
