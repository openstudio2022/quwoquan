func encodeEvaluation(
	operation OperationMetadata,
	request EvaluationQuery,
	pathBinding string,
) (RequestPacket, error) {
	canonicalRequest, err := json.Marshal(request)
	if err != nil {
		return RequestPacket{}, fmt.Errorf("encode %s canonical request: %w", operation.OperationID, err)
	}
	subjectID := strings.TrimSpace(request.HostSubjectID)
	if subjectID == "" {
		return RequestPacket{}, fmt.Errorf("encode %s canonical request: hostSubjectId is required", operation.OperationID)
	}
	path := strings.ReplaceAll(
		operation.PathTemplate,
		"{"+pathBinding+"}",
		url.PathEscape(subjectID),
	)
	return RequestPacket{
		Operation: operation,
		Path: path,
		Query: make(url.Values),
		CanonicalRequest: canonicalRequest,
	}, nil
}

