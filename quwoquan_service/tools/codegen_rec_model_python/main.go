func goExportedName(name string) string {
	if name == "" {
		return ""
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func goJSONOmitEmpty(constraints []string) string {
	if isRequired(constraints) {
		return ""
	}
	return ",omitempty"
}

func goTransportType(metaType string, required bool, entityNames map[string]bool) string {
	typeName := strings.TrimSpace(metaType)
	if strings.HasPrefix(typeName, "[]") {
		inner := strings.Trim(strings.TrimPrefix(typeName, "[]"), "[]\"'")
		return "[]" + goTransportType(inner, true, entityNames)
	}
	base := "map[string]any"
	switch typeName {
	case "string", "ObjectId":
		base = "string"
	case "float64", "number", "decimal":
		base = "float64"
	case "int64":
		base = "int64"
	case "int":
		base = "int"
	case "bool":
		base = "bool"
	case "timestamp":
		base = "time.Time"
	case "object":
		base = "map[string]any"
	default:
		if entityNames[typeName] {
			base = typeName
		}
	}
	if !required && !strings.HasPrefix(base, "[]") && base != "map[string]any" {
		return "*" + base
	}
	return base
}

func resolveContentBehaviors(source *contractcodegen.Source) string {
	p := filepath.Join("content", "content", "content_behavior_fact", "behaviors.yaml")
	if source.Has(p) {
		return p
	}
	return ""
}

// --- YAML structs ---

type fieldsFile struct {
	Entities map[string]entityDef `yaml:"entities"`
	Types    map[string]entityDef `yaml:"types"`
}

type entityDef struct {
	Description string     `yaml:"description"`
	Fields      []fieldDef `yaml:"fields"`
}

type fieldDef struct {
	Name        string   `yaml:"name"`
	Type        string   `yaml:"type"`
	Constraints []string `yaml:"constraints"`
	Description string   `yaml:"description"`
}

type operationsFile struct {
	APIRoutes []routeDef `yaml:"api_routes"`
}

type routeDef struct {
	Method          string          `yaml:"method"`
	Path            string          `yaml:"path"`
	Operation       string          `yaml:"operation"`
	RequestEntity   string          `yaml:"request_entity"`
	ResponseEntity  string          `yaml:"response_entity"`
	Description     string          `yaml:"description"`
	RequestBindings requestBindings `yaml:"request_bindings"`
}

type requestBindings struct {
	Injected []bindingDef `yaml:"injected"`
}

type bindingDef struct {
	Name  string `yaml:"name"`
	Field string `yaml:"field"`
}

type projectionFile struct {
	ReadModel   string      `yaml:"read_model"`
	Description string      `yaml:"description"`
	Collection  string      `yaml:"collection"`
	Fields      []projField `yaml:"fields"`
}

type projField struct {
	Name        string `yaml:"name"`
	Type        string `yaml:"type"`
	Description string `yaml:"description"`
	Nullable    bool   `yaml:"nullable"`
}

type projectionSpec struct {
	ReadModel  string
	Collection string
	Fields     []projField
}

func loadFields(source *contractcodegen.Source, path string) (*fieldsFile, error) {
	var f fieldsFile
	if err := source.Decode(path, &f); err != nil {
		return nil, err
	}
	if len(f.Entities) == 0 {
		f.Entities = f.Types
	}
	return &f, nil
}

func loadOperations(source *contractcodegen.Source, path string) (*operationsFile, error) {
	var s operationsFile
	if err := source.Decode(path, &s); err != nil {
		return nil, err
	}
	return &s, nil
}

// mergeProjectionEntities makes object-local named projections available to the
// generated internal transport without copying their wire fields into
// fields.yaml. The projection document remains the only schema truth source.
func mergeProjectionEntities(
	source *contractcodegen.Source,
	servicePath string,
	fields *fieldsFile,
) error {
	if fields.Entities == nil {
		fields.Entities = map[string]entityDef{}
	}
	prefix := filepath.Join(servicePath, "projections") + "/"
	for _, path := range source.Paths(prefix, ".yaml") {
		var projection projectionFile
		if err := source.Decode(path, &projection); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		name := strings.TrimSpace(projection.ReadModel)
		if name == "" {
			return fmt.Errorf("%s: read_model is required", path)
		}
		if _, exists := fields.Entities[name]; exists {
			return fmt.Errorf("%s: read_model %s duplicates fields entity", path, name)
		}
		entity := entityDef{Description: projection.Description}
		for _, field := range projection.Fields {
			constraints := []string{"NOT_NULL"}
			if field.Nullable {
				constraints = []string{"NULLABLE"}
			}
			entity.Fields = append(entity.Fields, fieldDef{
				Name: field.Name, Type: field.Type,
				Constraints: constraints, Description: field.Description,
			})
		}
		fields.Entities[name] = entity
	}
	return nil
}

func loadProjections(
	source *contractcodegen.Source,
	projectionsPath string,
) ([]projectionSpec, error) {
	names := []string{"learning_events.yaml", "training_samples.yaml", "model_registry.yaml"}
	var out []projectionSpec
	for _, n := range names {
		path := filepath.Join(projectionsPath, n)
		if !source.Has(path) {
			continue
		}
		var p projectionFile
		if err := source.Decode(path, &p); err != nil {
			return nil, fmt.Errorf("%s: %w", n, err)
		}
		out = append(out, projectionSpec{
			ReadModel:  p.ReadModel,
			Collection: p.Collection,
			Fields:     p.Fields,
		})
	}
	return out, nil
}

// --- Type mapping metadata -> Python ---

func pyType(metaType string, required bool, entityNames map[string]bool) string {
	t := strings.TrimSpace(metaType)
	optional := !required
	wrapOptional := func(s string) string {
		if optional {
			return s + " | None"
		}
		return s
	}
	switch {
	case t == "string":
		return wrapOptional("str")
	case t == "enum":
		return wrapOptional("str")
	case t == "float64" || t == "number" || t == "decimal":
		return wrapOptional("float")
	case t == "int64" || t == "int":
		return wrapOptional("int")
	case t == "bool":
		return wrapOptional("bool")
	case t == "object" || t == "json":
		return wrapOptional("dict[str, Any]")
	case t == "timestamp":
		return wrapOptional("float")
	case t == "ObjectId":
		return wrapOptional("str")
	case strings.HasPrefix(t, "[]"):
		inner := strings.TrimPrefix(t, "[]")
		inner = strings.Trim(inner, "[]\"'")
		innerPy := pyType(inner, true, entityNames)
		return wrapOptional("list[" + innerPy + "]")
	default:
		if entityNames[t] {
			return wrapOptional(t)
		}
		return wrapOptional("dict[str, Any]")
	}
}

func pyTransportType(metaType string, required bool, entityNames map[string]bool) string {
	t := strings.TrimSpace(metaType)
	optional := !required
	wrapOptional := func(s string) string {
		if optional {
			return s + " | None"
		}
		return s
	}
	if t == "timestamp" {
		return wrapOptional("datetime")
	}
	if strings.HasPrefix(t, "[]") {
		inner := strings.TrimPrefix(t, "[]")
		inner = strings.Trim(inner, "[]\"'")
		innerPy := pyTransportType(inner, true, entityNames)
		return wrapOptional("list[" + innerPy + "]")
	}
	return pyType(t, required, entityNames)
}

func isRequired(constraints []string) bool {
	for _, c := range constraints {
		if c == "NOT_NULL" || c == "NOT_BLANK" {
			return true
		}
	}
	return false
}

