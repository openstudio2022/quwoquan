// mergeProjectionEntities makes object-local named projections available to the
// generated internal transport without copying their wire fields into
// fields.yaml. The projection document remains the only schema truth source.
func mergeProjectionEntities(
	source *contractcodegen.Source,
	servicePath string,
	fields *fieldsFile,
	missingOnly ...bool,
) error {
	if fields.Entities == nil {
		fields.Entities = map[string]entityDef{}
	}
	prefix := filepath.Join(servicePath, "projections") + "/"
	for _, path := range source.Paths(prefix, ".yaml") {
		var projection projectionFile
		if err := source.Decode(path, &projection); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		name := strings.TrimSpace(projection.ReadModel)
		if name == "" {
			return fmt.Errorf("%s: read_model is required", path)
		}
		if _, exists := fields.Entities[name]; exists {
			// owning-event本地transport优先使用fields已有类型，只加载未声明的projection依赖。
			if len(missingOnly) > 0 && missingOnly[0] {
				continue
			}
			return fmt.Errorf("%s: read_model %s duplicates fields entity", path, name)
		}
		entity := entityDef{Description: projection.Description}
		for _, field := range projection.Fields {
			constraints := []string{"NOT_NULL"}
			if field.Nullable {
				constraints = []string{"NULLABLE"}
			}
			entity.Fields = append(entity.Fields, fieldDef{
				Name: field.Name, Type: field.Type, EnumRef: field.EnumRef, Values: field.Values,
				Constraints: constraints, Description: field.Description,
			})
		}
		fields.Entities[name] = entity
	}
	return nil
}

func loadProjections(
	source *contractcodegen.Source,
	projectionsPath string,
) ([]projectionSpec, error) {
	names := []string{"learning_events.yaml", "training_samples.yaml", "model_registry.yaml"}
	var out []projectionSpec
	for _, n := range names {
		path := filepath.Join(projectionsPath, n)
		if !source.Has(path) {
			continue
		}
		var p projectionFile
		if err := source.Decode(path, &p); err != nil {
			return nil, fmt.Errorf("%s: %w", n, err)
		}
		out = append(out, projectionSpec{
			ReadModel:  p.ReadModel,
			Collection: p.Collection,
			Fields:     p.Fields,
		})
	}
	return out, nil
}

// --- Type mapping metadata -> Python ---

func pyType(metaType string, required bool, entityNames map[string]bool) string {
	t := strings.TrimSpace(metaType)
	optional := !required
	wrapOptional := func(s string) string {
		if optional {
			return s + " | None"
		}
		return s
	}
	switch {
	case t == "string":
		return wrapOptional("str")
	case t == "enum":
		return wrapOptional("str")
	case t == "float" || t == "float64" || t == "number" || t == "decimal":
		return wrapOptional("float")
	case t == "int64" || t == "int":
		return wrapOptional("int")
	case t == "bool":
		return wrapOptional("bool")
	case t == "object" || t == "json" || t == "semantic_document":
		return wrapOptional("dict[str, Any]")
	case t == "timestamp":
		return wrapOptional("float")
	case t == "ObjectId":
		return wrapOptional("str")
	case strings.HasPrefix(t, "[]"):
		inner := strings.TrimPrefix(t, "[]")
		inner = strings.TrimSpace(inner)
		innerPy := pyType(inner, true, entityNames)
		return wrapOptional("list[" + innerPy + "]")
	default:
		if entityNames[t] {
			return wrapOptional(t)
		}
		return wrapOptional("dict[str, Any]")
	}
}

func pyTransportType(metaType string, required bool, entityNames map[string]bool) string {
	t := strings.TrimSpace(metaType)
	optional := !required
	wrapOptional := func(s string) string {
		if optional {
			return s + " | None"
		}
		return s
	}
	if t == "timestamp" {
		return wrapOptional("datetime")
	}
	if strings.HasPrefix(t, "[]") {
		inner := strings.TrimPrefix(t, "[]")
		inner = strings.TrimSpace(inner)
		innerPy := pyTransportType(inner, true, entityNames)
		return wrapOptional("list[" + innerPy + "]")
	}
	return pyType(t, required, entityNames)
}

func isRequired(constraints []string) bool {
	for _, c := range constraints {
		if c == "NOT_NULL" || c == "NOT_BLANK" {
			return true
		}
	}
	return false
}

