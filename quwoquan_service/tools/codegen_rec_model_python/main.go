func goExportedName(name string) string {
	if name == "" {
		return ""
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func goJSONOmitEmpty(constraints []string) string {
	if isRequired(constraints) {
		return ""
	}
	return ",omitempty"
}

func goTransportType(metaType string, required bool, entityNames map[string]bool) string {
	typeName := strings.TrimSpace(metaType)
	if strings.HasPrefix(typeName, "[]") {
		inner := strings.TrimSpace(strings.TrimPrefix(typeName, "[]"))
		result := "[]" + goTransportType(inner, true, entityNames)
		if !required {
			return "*" + result
		}
		return result
	}
	base := "map[string]any"
	switch typeName {
	case "string", "ObjectId", "enum":
		base = "string"
	case "float", "float64", "number", "decimal":
		base = "float64"
	case "int64":
		base = "int64"
	case "int":
		base = "int"
	case "bool":
		base = "bool"
	case "timestamp":
		base = "time.Time"
	case "object", "json", "semantic_document":
		base = "map[string]any"
	default:
		if entityNames[typeName] {
			base = typeName
		}
	}
	if !required && !strings.HasPrefix(base, "[]") && base != "map[string]any" {
		return "*" + base
	}
	return base
}

func resolveContentBehaviors(source *contractcodegen.Source) string {
	p := filepath.Join("content", "content", "content_behavior_fact", "behaviors.yaml")
	if source.Has(p) {
		return p
	}
	return ""
}

