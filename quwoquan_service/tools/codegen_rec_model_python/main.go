func generateModelsInitForNames(names []string, projections []projectionSpec) string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("\nfrom .request_response import (\n")
	for _, name := range names {
		b.WriteString(fmt.Sprintf("    %s,\n", name))
	}
	b.WriteString(")\n")
	if len(projections) == 0 {
		return b.String()
	}
	b.WriteString("from .projections import (\n")
	for _, projection := range projections {
		b.WriteString(fmt.Sprintf("    %s,\n", projectionClassName(projection.ReadModel)))
	}
	b.WriteString(")\n")
	return b.String()
}

func pythonOperationConstant(operation string) string {
	var b strings.Builder
	for i, r := range operation {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		if r >= 'a' && r <= 'z' {
			b.WriteRune(r - ('a' - 'A'))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func generateOperationsPy(s *operationsFile) string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("\n\"\"\"Operation descriptors generated from ContractGraph metadata.\"\"\"\n\n")
	for _, r := range s.APIRoutes {
		name := pythonOperationConstant(r.Operation)
		b.WriteString(fmt.Sprintf("%s_PATH = %q\n", name, r.Path))
		b.WriteString(fmt.Sprintf("%s_METHOD = %q\n", name, strings.ToUpper(r.Method)))
	}
	return b.String()
}

func generateSchemasPy(f *fieldsFile) string {
	return generateSchemasPyForNames(f, requestResponseOrder)
}

func generateSchemasPyForNames(f *fieldsFile, order []string) string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("\n\"\"\"Re-export request/response models for API use.\"\"\"\n\n")
	b.WriteString("from ..models.request_response import (\n")
	names := make([]string, 0, len(order))
	for _, name := range order {
		if _, ok := f.Entities[name]; ok {
			names = append(names, name)
		}
	}
	for _, n := range names {
		b.WriteString(fmt.Sprintf("    %s,\n", n))
	}
	b.WriteString(")\n")
	b.WriteString("\n__all__ = [\n")
	for _, n := range names {
		b.WriteString(fmt.Sprintf("    %q,\n", n))
	}
	b.WriteString("]\n")
	return b.String()
}

func generateObjectTransportPackage(
	source *contractcodegen.Source,
	servicePath string,
	outputDir string,
	order []string,
) error {
	fields, err := loadFields(source, filepath.Join(servicePath, "fields.yaml"))
	if err != nil {
		return fmt.Errorf("load fields: %w", err)
	}
	if err := mergeProjectionEntities(source, servicePath, fields); err != nil {
		return fmt.Errorf("load object projections: %w", err)
	}
	operations, err := loadOperations(source, filepath.Join(servicePath, "operations.yaml"))
	if err != nil {
		return fmt.Errorf("load operations: %w", err)
	}
	for _, directory := range []string{
		filepath.Join(outputDir, "models"),
		filepath.Join(outputDir, "api"),
	} {
		if err := os.MkdirAll(directory, 0755); err != nil {
			return err
		}
	}
	outputs := map[string]string{
		filepath.Join(outputDir, "api", "operations.py"):          generateOperationsPy(operations),
		filepath.Join(outputDir, "api", "schemas.py"):             generateSchemasPyForNames(fields, order),
		filepath.Join(outputDir, "api", "__init__.py"):            generateAPIInit(),
		filepath.Join(outputDir, "models", "request_response.py"): generateRequestResponsePyForNames(fields, order),
		filepath.Join(outputDir, "models", "__init__.py"):         generateModelsInitForNames(order, nil),
		filepath.Join(outputDir, "__init__.py"):                   generateRootInit(),
	}
	for path, content := range outputs {
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			return err
		}
	}
	return nil
}

