// Codegen for recommendation-service Python: reads ModelRelease metadata and projections,
// then generates pure operation descriptors and Pydantic contracts.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

const (
	genHeader = "# Code generated by tools/codegen_rec_model_python. DO NOT EDIT.\n"
)

func main() {
	metadataDir := flag.String("metadata-dir", "contracts/metadata", "metadata root directory")
	outputDir := flag.String("output-dir", "services/recommendation-service/internal/recommendation/recommendation_model_release/generated", "Python generated output directory")
	serviceDir := flag.String("service-dir", "recommendation/recommendation/recommendation_model_release", "service metadata directory")
	contentRankedWindowGoOutput := flag.String(
		"content-ranked-window-go-output",
		"services/content-service/generated/content/feed_delivery_page/recommendation_ranked_window.g.go",
		"generated Content-side Go transport derived from RankedRecommendationWindow",
	)
	contentFeatureProfileGoOutput := flag.String(
		"content-feature-profile-go-output",
		"services/content-service/generated/content/post/recommendation_feature_profile.g.go",
		"generated Content-side Go transport derived from RecommendationFeatureProfileView",
	)
	flag.Parse()

	if err := run(
		*metadataDir,
		*outputDir,
		*serviceDir,
		*contentRankedWindowGoOutput,
		*contentFeatureProfileGoOutput,
	); err != nil {
		fmt.Fprintf(os.Stderr, "codegen_rec_model_python: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("generated Python code at %s\n", *outputDir)
}

func run(
	metadataDir,
	outputDir,
	serviceDir,
	contentRankedWindowGoOutput,
	contentFeatureProfileGoOutput string,
) error {
	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		return fmt.Errorf("compile ContractGraph: %w", err)
	}
	servicePath := serviceDir
	projectionsPath := filepath.Join(servicePath, "projections")

	fields, err := loadFields(source, filepath.Join(servicePath, "fields.yaml"))
	if err != nil {
		return fmt.Errorf("load fields: %w", err)
	}
	operations, err := loadOperations(source, filepath.Join(servicePath, "operations.yaml"))
	if err != nil {
		return fmt.Errorf("load operations: %w", err)
	}

	projections, err := loadProjections(source, projectionsPath)
	if err != nil {
		return fmt.Errorf("load projections: %w", err)
	}

	if err := os.MkdirAll(filepath.Join(outputDir, "models"), 0755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(outputDir, "api"), 0755); err != nil {
		return err
	}
	operationsPy := generateOperationsPy(operations)
	if err := os.WriteFile(filepath.Join(outputDir, "api", "operations.py"), []byte(operationsPy), 0644); err != nil {
		return err
	}

	reqRespPy := generateRequestResponsePy(fields)
	if err := os.WriteFile(filepath.Join(outputDir, "models", "request_response.py"), []byte(reqRespPy), 0644); err != nil {
		return err
	}

	projPy := generateProjectionsPy(projections)
	if err := os.WriteFile(filepath.Join(outputDir, "models", "projections.py"), []byte(projPy), 0644); err != nil {
		return err
	}

	modelsInit := generateModelsInit(projections)
	if err := os.WriteFile(filepath.Join(outputDir, "models", "__init__.py"), []byte(modelsInit), 0644); err != nil {
		return err
	}

	if err := os.Remove(filepath.Join(outputDir, "api", "routes.py")); err != nil && !os.IsNotExist(err) {
		return err
	}

	schemasPy := generateSchemasPy(fields)
	if err := os.WriteFile(filepath.Join(outputDir, "api", "schemas.py"), []byte(schemasPy), 0644); err != nil {
		return err
	}

	apiInit := generateAPIInit()
	if err := os.WriteFile(filepath.Join(outputDir, "api", "__init__.py"), []byte(apiInit), 0644); err != nil {
		return err
	}

	rootInit := generateRootInit()
	if err := os.WriteFile(filepath.Join(outputDir, "__init__.py"), []byte(rootInit), 0644); err != nil {
		return err
	}

	rankedWindowPath := filepath.Join(filepath.Dir(servicePath), "ranked_recommendation_window")
	if source.Has(filepath.Join(rankedWindowPath, "fields.yaml")) {
		rankedOutputDir := filepath.Join(filepath.Dir(outputDir), "ranked_recommendation_window")
		if err := generateObjectTransportPackage(
			source,
			rankedWindowPath,
			rankedOutputDir,
			rankedWindowTransportOrder,
		); err != nil {
			return fmt.Errorf("generate ranked recommendation window: %w", err)
		}
		if strings.TrimSpace(contentRankedWindowGoOutput) != "" {
			rankedFields, err := loadFields(
				source,
				filepath.Join(rankedWindowPath, "fields.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load ranked recommendation window Go fields: %w", err)
			}
			rankedOperations, err := loadOperations(
				source,
				filepath.Join(rankedWindowPath, "operations.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load ranked recommendation window Go operations: %w", err)
			}
			if err := writeRankedWindowGoTransport(
				contentRankedWindowGoOutput,
				rankedFields,
				rankedOperations,
			); err != nil {
				return fmt.Errorf("generate Content ranked window Go transport: %w", err)
			}
		}
	}

	featureProfilePath := filepath.Join(filepath.Dir(servicePath), "recommendation_feature_profile_view")
	if source.Has(filepath.Join(featureProfilePath, "fields.yaml")) {
		featureProfileOutputDir := filepath.Join(
			filepath.Dir(outputDir),
			"recommendation_feature_profile_view",
		)
		if err := generateObjectTransportPackage(
			source,
			featureProfilePath,
			featureProfileOutputDir,
			featureProfileTransportOrder,
		); err != nil {
			return fmt.Errorf("generate recommendation feature profile view: %w", err)
		}
		if strings.TrimSpace(contentFeatureProfileGoOutput) != "" {
			featureFields, err := loadFields(
				source,
				filepath.Join(featureProfilePath, "fields.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load recommendation feature profile Go fields: %w", err)
			}
			if err := mergeProjectionEntities(source, featureProfilePath, featureFields); err != nil {
				return fmt.Errorf("load recommendation feature profile projections: %w", err)
			}
			featureOperations, err := loadOperations(
				source,
				filepath.Join(featureProfilePath, "operations.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load recommendation feature profile Go operations: %w", err)
			}
			if err := writeFeatureProfileGoTransport(
				contentFeatureProfileGoOutput,
				featureFields,
				featureOperations,
			); err != nil {
				return fmt.Errorf("generate Content feature profile Go transport: %w", err)
			}
		}
	}

	// Generate content features + training sample from
	// content/content/content_behavior_fact/behaviors.yaml
	behaviorsPath := resolveContentBehaviors(source)
	if behaviorsPath != "" {
		beh, err := loadBehaviors(source, behaviorsPath)
		if err == nil && beh != nil {
			if beh.RecommendFeatures.PythonClass != "" {
				featuresPy := generateContentFeaturesPy(beh)
				featsPath := filepath.Join(outputDir, "content_features.py")
				if err := os.WriteFile(featsPath, []byte(featuresPy), 0644); err != nil {
					return err
				}
				fmt.Printf("generated: %s\n", featsPath)
			}
			if beh.TrainingSample.PythonClass != "" {
				samplePy := generateTrainingSamplePy(beh)
				samplePath := filepath.Join(outputDir, "training_sample.py")
				if err := os.WriteFile(samplePath, []byte(samplePy), 0644); err != nil {
					return err
				}
				fmt.Printf("generated: %s\n", samplePath)
			}
		}
	}

	return nil
}

func writeRankedWindowGoTransport(
	outputPath string,
	fields *fieldsFile,
	operations *operationsFile,
) error {
	generated, err := format.Source([]byte(generateRankedWindowGoTransport(fields, operations)))
	if err != nil {
		return fmt.Errorf("format generated Go transport: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(outputPath), 0755); err != nil {
		return err
	}
	return os.WriteFile(outputPath, generated, 0644)
}

func generateRankedWindowGoTransport(
	fields *fieldsFile,
	operations *operationsFile,
) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_rec_model_python. DO NOT EDIT.\n")
	b.WriteString("// Source: recommendation-service/contracts/recommendation/ranked_recommendation_window.\n\n")
	b.WriteString("package feeddeliverypage\n\n")
	b.WriteString("import \"time\"\n\n")
	for _, route := range operations.APIRoutes {
		name := route.Operation
		b.WriteString(fmt.Sprintf("const %sPath = %q\n", name, route.Path))
		b.WriteString(fmt.Sprintf("const %sMethod = %q\n", name, strings.ToUpper(route.Method)))
	}
	entityNames := make(map[string]bool, len(fields.Entities))
	for name := range fields.Entities {
		entityNames[name] = true
	}
	for _, name := range rankedWindowTransportOrder {
		entity, ok := fields.Entities[name]
		if !ok {
			continue
		}
		b.WriteString(fmt.Sprintf("\ntype %s struct {\n", name))
		for _, field := range entity.Fields {
			b.WriteString(fmt.Sprintf(
				"\t%s %s `json:%q`\n",
				goExportedName(field.Name),
				goTransportType(field.Type, isRequired(field.Constraints), entityNames),
				field.Name+goJSONOmitEmpty(field.Constraints),
			))
		}
		b.WriteString("}\n")
	}
	for _, route := range operations.APIRoutes {
		if route.RequestEntity == "" || len(route.RequestBindings.Injected) == 0 {
			continue
		}
		entity, ok := fields.Entities[route.RequestEntity]
		if !ok {
			continue
		}
		injected := make(map[string]struct{}, len(route.RequestBindings.Injected))
		for _, binding := range route.RequestBindings.Injected {
			injected[strings.TrimSpace(binding.Field)] = struct{}{}
		}
		b.WriteString(fmt.Sprintf("\ntype %sRequestBody struct {\n", route.Operation))
		for _, field := range entity.Fields {
			if _, excluded := injected[field.Name]; excluded {
				continue
			}
			b.WriteString(fmt.Sprintf(
				"\t%s %s `json:%q`\n",
				goExportedName(field.Name),
				goTransportType(field.Type, isRequired(field.Constraints), entityNames),
				field.Name+goJSONOmitEmpty(field.Constraints),
			))
		}
		b.WriteString("}\n")
	}
	return b.String()
}

