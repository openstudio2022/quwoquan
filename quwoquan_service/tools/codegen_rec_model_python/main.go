func pythonOperationConstant(operation string) string {
	var b strings.Builder
	for i, r := range operation {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		if r >= 'a' && r <= 'z' {
			b.WriteRune(r - ('a' - 'A'))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

