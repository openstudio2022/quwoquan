func main() {
	metadataDir := flag.String("metadata-dir", "contracts/metadata", "metadata root directory")
	outputDir := flag.String("output-dir", "services/recommendation-service/internal/recommendation/recommendation_model_release/generated", "Python generated output directory")
	serviceDir := flag.String("service-dir", "recommendation/recommendation/recommendation_model_release", "service metadata directory")
	contentRankedWindowGoOutput := flag.String(
		"content-ranked-window-go-output",
		"services/content-service/generated/content/feed_delivery_page/recommendation_ranked_window.g.go",
		"generated Content-side Go transport derived from RankedRecommendationWindow",
	)
	contentFeatureProfileGoOutput := flag.String(
		"content-feature-profile-go-output",
		"services/content-service/generated/content/post/recommendation_feature_profile.g.go",
		"generated Content-side Go transport derived from RecommendationFeatureProfileView",
	)
	searchEvents := flag.String("search-events-go-output", "services/search-service/generated/search/search_index_view/events", "Search owning-event Go packages from declared lifecycle source events")
	consumedOwner := flag.String("consumed-event-owner", "", "generate only this canonical consumer owning-event closure")
	consumedOutput := flag.String("consumed-event-output", "", "output directory for explicit owning-event closure")
	consumedGo := flag.Bool("consumed-event-go", false, "emit Go packages instead of Python for explicit owning-event closure")
	operationOwner := flag.String("operation-owner", "", "owner metadata path for a generated Go operation closure")
	operationName := flag.String("operation-name", "", "exact operation root")
	additionalTypes := flag.String("owner-local-types", "", "comma-separated owner-local internal port roots")
	operationOutput := flag.String("operation-go-output", "", "owner-local generated Go file")
	operationPython := flag.String("operation-python-output", "", "owner-local generated Python file; reuses the exact operation/type DAG")
	manifestOutput := flag.String("manifest-output", "", "generated output provenance manifest")
	check := flag.Bool("check", false, "rebuild privately and reject stale canonical outputs")
	flag.Parse()
	if *operationOwner != "" {
		source, err := contractcodegen.NewSource(*metadataDir, validate.ProfileBaseline)
		if err == nil {
			if *operationPython != "" && *operationOutput != "" {
				err = fmt.Errorf("exactly one operation output language is required")
			} else {
				output := *operationOutput
				if *operationPython != "" {
					output = *operationPython
				}
				err = generateOperationTransport(source, *operationOwner, *operationName, output, *check, *operationPython != "", strings.Split(*additionalTypes, ",")...)
			}
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if *consumedOwner != "" {
		if *consumedOutput == "" {
			fmt.Fprintln(os.Stderr, "consumed-event-output required")
			os.Exit(1)
		}
		source, err := contractcodegen.NewSource(*metadataDir, validate.ProfileBaseline)
		if err == nil {
			err = generateOrCheckConsumedEvents(source, *consumedOwner, *consumedOutput, *consumedGo, *check)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if *check {
		if err := checkGenerated(*metadataDir, *outputDir, *serviceDir, *contentRankedWindowGoOutput, *contentFeatureProfileGoOutput, *searchEvents); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("recommendation generated outputs are current")
		return
	}

	if err := run(
		*metadataDir,
		*outputDir,
		*serviceDir,
		*contentRankedWindowGoOutput,
		*contentFeatureProfileGoOutput,
		*searchEvents,
	); err != nil {
		fmt.Fprintf(os.Stderr, "codegen_rec_model_python: %v\n", err)
		os.Exit(1)
	}
	if *manifestOutput != "" {
		roots := []string{
			*outputDir,
			filepath.Join(filepath.Dir(*outputDir), "ranked_recommendation_window"),
			filepath.Join(filepath.Dir(*outputDir), "recommendation_feature_profile_view"),
			filepath.Join(filepath.Dir(*outputDir), "recommendation_candidate_index_view"),
			*contentRankedWindowGoOutput, *contentFeatureProfileGoOutput, *searchEvents,
		}
		if err := writeProvenanceManifest(*manifestOutput, roots); err != nil {
			fmt.Fprintf(os.Stderr, "codegen_rec_model_python manifest: %v\n", err)
			os.Exit(1)
		}
	}
	fmt.Printf("generated Python code at %s\n", *outputDir)
}

type provenanceOutput struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Bytes  int    `json:"bytes"`
}

func writeProvenanceManifest(path string, roots []string) error {
	paths := map[string]struct{}{}
	for _, root := range roots {
		if strings.TrimSpace(root) == "" {
			continue
		}
		info, err := os.Stat(root)
		if err != nil {
			return err
		}
		if !info.IsDir() {
			paths[filepath.Clean(root)] = struct{}{}
			continue
		}
		err = filepath.WalkDir(root, func(current string, entry os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if !entry.IsDir() {
				paths[filepath.Clean(current)] = struct{}{}
			}
			return nil
		})
		if err != nil {
			return err
		}
	}
	ordered := make([]string, 0, len(paths))
	for current := range paths {
		ordered = append(ordered, current)
	}
	sort.Strings(ordered)
	outputs := make([]provenanceOutput, 0, len(ordered))
	for _, current := range ordered {
		body, err := os.ReadFile(current)
		if err != nil {
			return err
		}
		outputs = append(outputs, provenanceOutput{Path: filepath.ToSlash(current), SHA256: fmt.Sprintf("%x", sha256.Sum256(body)), Bytes: len(body)})
	}
	payload, err := json.MarshalIndent(struct {
		Generator string             `json:"generator"`
		Outputs   []provenanceOutput `json:"outputs"`
	}{
		Generator: "tools/codegen_rec_model_python", Outputs: outputs,
	}, "", "  ")
	if err != nil {
		return err
	}
	payload = append(payload, '\n')
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, payload, 0o644)
}

// checkGenerated重建到独立输出，逐字节核验，绝不修复或覆盖被检查文件。
func checkGenerated(metadataDir, outputDir, serviceDir, rankedGo, featureGo string, searchOutputs ...string) error {
	tmp, err := os.MkdirTemp("", "rec-codegen-check-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	privateOutput := filepath.Join(tmp, "python", filepath.Base(outputDir))
	privateRanked, privateFeature := "", ""
	if rankedGo != "" {
		privateRanked = filepath.Join(tmp, "go", "ranked.go")
	}
	if featureGo != "" {
		privateFeature = filepath.Join(tmp, "go", "feature.go")
	}
	privateSearch := ""
	if len(searchOutputs) > 0 && searchOutputs[0] != "" {
		privateSearch = filepath.Join(tmp, "search")
	}
	if err := run(metadataDir, privateOutput, serviceDir, privateRanked, privateFeature, privateSearch); err != nil {
		return err
	}
	compare := func(generated, current string) error {
		want, err := os.ReadFile(generated)
		if err != nil {
			return err
		}
		got, err := os.ReadFile(current)
		if err != nil {
			return err
		}
		if !bytes.Equal(want, got) {
			return fmt.Errorf("CONTRACT.CODEGEN.STALE_OUTPUT: %s", current)
		}
		return nil
	}
	if err := filepath.WalkDir(filepath.Join(tmp, "python"), func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(filepath.Join(tmp, "python"), path)
		if err != nil {
			return err
		}
		return compare(path, filepath.Join(filepath.Dir(outputDir), rel))
	}); err != nil {
		return err
	}
	if privateSearch != "" {
		if err := filepath.WalkDir(privateSearch, func(path string, entry os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() {
				return nil
			}
			rel, err := filepath.Rel(privateSearch, path)
			if err != nil {
				return err
			}
			return compare(path, filepath.Join(searchOutputs[0], rel))
		}); err != nil {
			return err
		}
	}
	for _, pair := range [][2]string{{privateRanked, rankedGo}, {privateFeature, featureGo}} {
		if pair[0] != "" {
			if err := compare(pair[0], pair[1]); err != nil {
				return err
			}
		}
	}
	return nil
}

func run(
	metadataDir,
	outputDir,
	serviceDir,
	contentRankedWindowGoOutput,
	contentFeatureProfileGoOutput string,
	searchOutputs ...string,
) error {
	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		return fmt.Errorf("compile ContractGraph: %w", err)
	}
	servicePath := serviceDir
	projectionsPath := filepath.Join(servicePath, "projections")

	fields, err := loadFields(source, filepath.Join(servicePath, "fields.yaml"))
	if err != nil {
		return fmt.Errorf("load fields: %w", err)
	}
	operations, err := loadOperations(source, filepath.Join(servicePath, "operations.yaml"))
	if err != nil {
		return fmt.Errorf("load operations: %w", err)
	}

	projections, err := loadProjections(source, projectionsPath)
	if err != nil {
		return fmt.Errorf("load projections: %w", err)
	}

	if err := os.MkdirAll(filepath.Join(outputDir, "models"), 0755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(outputDir, "api"), 0755); err != nil {
		return err
	}
	operationsPy := generateOperationsPy(operations)
	if err := os.WriteFile(filepath.Join(outputDir, "api", "operations.py"), []byte(operationsPy), 0644); err != nil {
		return err
	}

	if _, err := resolveNamedTransportClosure(fields, requestResponseOrder); err != nil {
		return err
	}
	reqRespPy := generateRequestResponsePyForNames(fields, transportOrder(fields))
	if err := os.WriteFile(filepath.Join(outputDir, "models", "request_response.py"), []byte(reqRespPy), 0644); err != nil {
		return err
	}

	projPy := generateProjectionsPy(projections)
	if err := os.WriteFile(filepath.Join(outputDir, "models", "projections.py"), []byte(projPy), 0644); err != nil {
		return err
	}

	modelsInit := generateModelsInit(projections)
	if err := os.WriteFile(filepath.Join(outputDir, "models", "__init__.py"), []byte(modelsInit), 0644); err != nil {
		return err
	}

	if err := os.Remove(filepath.Join(outputDir, "api", "routes.py")); err != nil && !os.IsNotExist(err) {
		return err
	}

	schemasPy := generateSchemasPy(fields)
	if err := os.WriteFile(filepath.Join(outputDir, "api", "schemas.py"), []byte(schemasPy), 0644); err != nil {
		return err
	}

	apiInit := generateAPIInit()
	if err := os.WriteFile(filepath.Join(outputDir, "api", "__init__.py"), []byte(apiInit), 0644); err != nil {
		return err
	}

	rootInit := generateRootInit()
	if err := os.WriteFile(filepath.Join(outputDir, "__init__.py"), []byte(rootInit), 0644); err != nil {
		return err
	}

	if err := generateRankedWindowArtifacts(source, servicePath, outputDir, contentRankedWindowGoOutput); err != nil {
		return err
	}

	featureProfilePath := filepath.Join(filepath.Dir(servicePath), "recommendation_feature_profile_view")
	if source.Has(filepath.Join(featureProfilePath, "fields.yaml")) {
		featureProfileOutputDir := filepath.Join(
			filepath.Dir(outputDir),
			"recommendation_feature_profile_view",
		)
		if err := generateObjectTransportPackage(
			source,
			featureProfilePath,
			featureProfileOutputDir,
			featureProfileTransportOrder,
		); err != nil {
			return fmt.Errorf("generate recommendation feature profile view: %w", err)
		}
		if err := generateConsumedEvents(source, featureProfilePath, filepath.Join(featureProfileOutputDir, "events")); err != nil {
			return err
		}
		if strings.TrimSpace(contentFeatureProfileGoOutput) != "" {
			featureFields, err := loadFields(
				source,
				filepath.Join(featureProfilePath, "fields.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load recommendation feature profile Go fields: %w", err)
			}
			if err := mergeProjectionEntities(source, featureProfilePath, featureFields); err != nil {
				return fmt.Errorf("load recommendation feature profile projections: %w", err)
			}
			featureOperations, err := loadOperations(
				source,
				filepath.Join(featureProfilePath, "operations.yaml"),
			)
			if err != nil {
				return fmt.Errorf("load recommendation feature profile Go operations: %w", err)
			}
			if err := writeFeatureProfileGoTransport(
				contentFeatureProfileGoOutput,
				featureFields,
				featureOperations,
			); err != nil {
				return fmt.Errorf("generate Content feature profile Go transport: %w", err)
			}
		}
	}

	if len(searchOutputs) > 0 && searchOutputs[0] != "" {
		if err := generateConsumedEvents(source, "search/search/search_index_view", searchOutputs[0], true); err != nil {
			return err
		}
	}
	candidatePath := filepath.Join(filepath.Dir(servicePath), "recommendation_candidate_index_view")
	if err := generateConsumedEvents(source, candidatePath, filepath.Join(filepath.Dir(outputDir), "recommendation_candidate_index_view", "events")); err != nil {
		return err
	}

	// Generate content features + training sample from
	// content/content/content_behavior_fact/behaviors.yaml
	behaviorsPath := resolveContentBehaviors(source)
	if behaviorsPath != "" {
		beh, err := loadBehaviors(source, behaviorsPath)
		if err == nil && beh != nil {
			if beh.RecommendFeatures.PythonClass != "" {
				featuresPy := generateContentFeaturesPy(beh)
				featsPath := filepath.Join(outputDir, "content_features.py")
				if err := os.WriteFile(featsPath, []byte(featuresPy), 0644); err != nil {
					return err
				}
				fmt.Printf("generated: %s\n", featsPath)
			}
			if beh.TrainingSample.PythonClass != "" {
				samplePy := generateTrainingSamplePy(beh)
				samplePath := filepath.Join(outputDir, "training_sample.py")
				if err := os.WriteFile(samplePath, []byte(samplePy), 0644); err != nil {
					return err
				}
				fmt.Printf("generated: %s\n", samplePath)
			}
		}
	}

	if err := writeContentTypeEncoding(source, servicePath, outputDir); err != nil {
		return err
	}

	return nil
}

