// operation根复用现役闭包；用于owner自身typed请求/响应，不建立新的类型源。
func generateOperationGo(source *contractcodegen.Source, owner, name, out string, check bool, localTypes ...string) error {
	return generateOperationTransport(source, owner, name, out, check, false, localTypes...)
}

func generateOperationTransport(source *contractcodegen.Source, owner, name, out string, check, python bool, localTypes ...string) error {
	if name == "" || out == "" {
		return fmt.Errorf("operation name/output required")
	}
	fields, err := loadFields(source, filepath.Join(owner, "fields.yaml"))
	if err != nil {
		return err
	}
	ops, err := loadOperations(source, filepath.Join(owner, "operations.yaml"))
	if err != nil {
		return err
	}
	roots := &operationsFile{}
	for _, op := range ops.APIRoutes {
		if op.Operation == name {
			roots.APIRoutes = append(roots.APIRoutes, op)
		}
	}
	if len(roots.APIRoutes) != 1 {
		return fmt.Errorf("exact operation root missing or ambiguous: %s", name)
	}
	for _, name := range localTypes {
		if name == "" {
			continue
		}
		if _, ok := fields.Entities[name]; !ok {
			return fmt.Errorf("owner-local type missing: %s", name)
		}
		roots.APIRoutes = append(roots.APIRoutes, routeDef{RequestEntity: name})
	}
	order, err := resolveTransportClosure(fields, fields.Shared, roots)
	if err != nil {
		return err
	}
	raw, err := renderConsumedEventGo(fields, order, filepath.Join(owner, "operations.yaml"), name)
	if err != nil {
		return err
	}
	raw = bytes.Replace(raw, []byte("event_ref: "), []byte("operation: "), 1)
	if python {
		raw = []byte("# Source: " + filepath.Join(owner, "operations.yaml") + "; operation: " + name + "; owner-local roots: " + strings.Join(localTypes, ",") + "\n" + generateRequestResponsePyForNames(fields, order, true))
	}
	if check {
		current, err := os.ReadFile(out)
		if err != nil {
			return err
		}
		if !bytes.Equal(raw, current) {
			return fmt.Errorf("CONTRACT.CODEGEN.STALE_OUTPUT: %s", out)
		}
		return nil
	}
	if err = os.MkdirAll(filepath.Dir(out), 0755); err != nil {
		return err
	}
	return os.WriteFile(out, raw, 0644)
}

// 单owner定向执行仍遍历其全部SourceEvents；不得按事件白名单绕过错误源。
func generateOrCheckConsumedEvents(source *contractcodegen.Source, owner, out string, goOutput, check bool) error {
	if !check {
		return generateConsumedEvents(source, owner, out, goOutput)
	}
	tmp, err := os.MkdirTemp("", "owning-event-check-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	if err = generateConsumedEvents(source, owner, tmp, goOutput); err != nil {
		return err
	}
	return filepath.WalkDir(tmp, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(tmp, path)
		if err != nil {
			return err
		}
		want, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		got, err := os.ReadFile(filepath.Join(out, rel))
		if err != nil {
			return err
		}
		if !bytes.Equal(want, got) {
			return fmt.Errorf("CONTRACT.CODEGEN.STALE_OUTPUT: %s", rel)
		}
		return nil
	})
}

// 复用已由源事件根解析的local/shared DAG和现役Go类型映射；不新增类型解析器。
// 每个event_ref独立包，裁剪相同payload类型的不同事件不会互相覆盖。
func renderConsumedEventGo(fields *fieldsFile, order []string, sourcePath, eventRef string) ([]byte, error) {
	if len(order) == 0 {
		return nil, fmt.Errorf("CONTRACT.CODEGEN.EVENT_PAYLOAD_EMPTY: %s", eventRef)
	}
	var body strings.Builder
	names := map[string]bool{}
	needsTime := false
	for _, name := range order {
		names[name] = true
	}
	for _, name := range transportEnums(fields, order) {
		names[name] = true
	}
	writeGoTransportEnums(&body, fields, order)
	for _, name := range order {
		entity := fields.Entities[name]
		if len(entity.Fields) == 0 {
			return nil, fmt.Errorf("CONTRACT.CODEGEN.EVENT_PAYLOAD_EMPTY: %s", name)
		}
		fmt.Fprintf(&body, "\ntype %s struct {\n", name)
		for _, field := range entity.Fields {
			typ := goTransportType(enumFieldType(field), isRequired(field.Constraints), names)
			if strings.Contains(typ, "time.Time") {
				needsTime = true
			}
			// 指针表达null，不加omitempty；presence及业务组合由严格raw decoder负责。
			fmt.Fprintf(&body, "%s %s `json:%q`\n", goExportedName(field.Name), typ, field.Name)
		}
		body.WriteString("}\n")
	}
	header := "// Code generated by tools/codegen_rec_model_python. DO NOT EDIT.\n// Source: " + sourcePath + "; event_ref: " + eventRef + "\n\npackage eventpayload\n"
	if needsTime {
		header += "\nimport \"time\"\n"
	}
	if len(transportEnums(fields, order)) > 0 {
		header += "\nimport (\"encoding/json\"; \"fmt\")\n"
	}
	return format.Source([]byte(header + body.String()))
}
