// Command codegen_chat_service generates chat-service HTTP route plumbing from
// object-owned operations.yaml contracts discovered below the service contracts
// directory.
//
// It emits the object-root generated transport route table. The handwritten
// inbound adapter owns handler dispatch. Duplicate operation or method/path
// ownership is a generator error rather than a last-wins rule.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

func main() {
	var metadataDir string
	var outputDir string
	var contractsDir string
	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&outputDir, "output-dir", "services/chat-service/generated", "chat-service generated root directory")
	flag.StringVar(&contractsDir, "contracts-dir", "services/chat-service/contracts", "chat-service contracts directory")
	flag.Parse()

	inputs, err := discoverContractInputs(contractsDir)
	if err != nil {
		exitErr(fmt.Errorf("discover contracts in %s: %w", contractsDir, err))
	}
	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		exitErr(fmt.Errorf("compile ContractGraph: %w", err))
	}

	totalRoutes := 0
	totalErrors := 0
	for _, input := range inputs.Objects {
		routes, err := collectRoutes(source, []string{input.OperationGraphPath})
		if err != nil {
			exitErr(err)
		}
		if len(routes) > 0 {
			if err := writeRouteFile(outputDir, input, routes); err != nil {
				exitErr(err)
			}
			totalRoutes += len(routes)
		}
		if input.ErrorsGraphPath != "" {
			count, err := writeErrorsFile(source, outputDir, input)
			if err != nil {
				exitErr(err)
			}
			totalErrors += count
		}
	}
	fmt.Printf("generated chat-service object routes=%d errors=%d\n", totalRoutes, totalErrors)
}

func writeRouteFile(outputDir string, input objectContractInput, routes []routeData) error {
	rendered, err := render(routeFileData{
		OperationSourcesRel: []string{input.OperationSourcePath},
		Routes:              routes,
	})
	if err != nil {
		return fmt.Errorf("render %s routes: %w", input.Object, err)
	}
	typeStart := bytes.Index(rendered, []byte("type routeEntry struct"))
	registerStart := bytes.Index(rendered, []byte("func RegisterGeneratedRoutes"))
	resolverStart := bytes.Index(rendered, []byte("func resolveGeneratedOperation"))
	if typeStart < 0 || registerStart <= typeStart || resolverStart <= registerStart {
		exitErr(fmt.Errorf("generated route sections are incomplete"))
	}
	var transportHeader strings.Builder
	transportHeader.WriteString("// Code generated by tools/codegen_chat_service from:\n")
	fmt.Fprintf(&transportHeader, "//   - %s\n", input.OperationSourcePath)
	transportHeader.WriteString("// DO NOT EDIT.\npackage transport\n\nimport \"strings\"\n\n")
	transport := []byte(transportHeader.String())
	transport = append(transport, rendered[typeStart:registerStart]...)
	transport = append(transport, rendered[resolverStart:]...)
	transport = bytes.Replace(transport, []byte("type routeEntry struct"), []byte("type RouteEntry struct"), 1)
	transport = bytes.Replace(transport, []byte("var generatedRouteTable = []routeEntry"), []byte("var RouteTable = []RouteEntry"), 1)
	transport = bytes.ReplaceAll(transport, []byte("generatedRouteTable"), []byte("RouteTable"))
	transport = bytes.Replace(transport, []byte("func resolveGeneratedOperation"), []byte("func ResolveOperation"), 1)
	transport = bytes.ReplaceAll(transport, []byte("matchTemplate("), []byte("MatchTemplate("))
	transport = bytes.Replace(transport, []byte("func extractPathParam"), []byte("func ExtractPathParam"), 1)
	if formatted, formatErr := format.Source(transport); formatErr == nil {
		transport = formatted
	}

	outPath := filepath.Join(outputDir, input.Context, input.Object, "transport", "routes.g.go")
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(outPath), err)
	}
	if err := os.WriteFile(outPath, transport, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outPath, err)
	}
	fmt.Printf("generated %s/%s routes (%d operations) at %s\n", input.Context, input.Object, len(routes), outPath)
	return nil
}

func writeErrorsFile(source *contractcodegen.Source, outputDir string, input objectContractInput) (int, error) {
	errorsFile, err := loadErrorsYAML(source, input.ErrorsGraphPath)
	if err != nil {
		return 0, fmt.Errorf("load errors.yaml %s: %w", input.ErrorsGraphPath, err)
	}
	errorsRendered := contractcodegen.RenderGoErrorsFile(errorsFile, contractcodegen.GoErrorsFileOptions{
		Generator:    "tools/codegen_chat_service",
		SourcePath:   input.ErrorsSourcePath,
		CommentLines: []string{"Chat error sentinels and helpers. user_message from errors.yaml user_message.zh."},
	})
	formattedErrors, err := format.Source([]byte(errorsRendered))
	if err != nil {
		return 0, fmt.Errorf("gofmt generated errors: %w", err)
	}
	errorsOutPath := filepath.Join(outputDir, input.Context, input.Object, "errors.go")
	if err := os.MkdirAll(filepath.Dir(errorsOutPath), 0o755); err != nil {
		return 0, fmt.Errorf("create %s: %w", filepath.Dir(errorsOutPath), err)
	}
	if err := os.WriteFile(errorsOutPath, formattedErrors, 0o644); err != nil {
		return 0, fmt.Errorf("write %s: %w", errorsOutPath, err)
	}
	fmt.Printf("generated %s/%s errors (%d codes) at %s\n", input.Context, input.Object, len(errorsFile.Errors), errorsOutPath)
	return len(errorsFile.Errors), nil
}

type contractInputs struct {
	Objects []objectContractInput
}

type objectContractInput struct {
	Context             string
	Object              string
	OperationGraphPath  string
	OperationSourcePath string
	ErrorsGraphPath     string
	ErrorsSourcePath    string
}

type domainYAML struct {
	Domain string `yaml:"domain"`
}

func discoverContractInputs(contractsDir string) (contractInputs, error) {
	var inputs contractInputs
	raw, err := os.ReadFile(filepath.Join(contractsDir, "domain.yaml"))
	if err != nil {
		return inputs, err
	}
	var domain domainYAML
	if err := yaml.Unmarshal(raw, &domain); err != nil {
		return inputs, err
	}
	if strings.TrimSpace(domain.Domain) == "" {
		return inputs, fmt.Errorf("domain.yaml missing domain")
	}
	objects := map[string]*objectContractInput{}
	err = filepath.WalkDir(contractsDir, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || (entry.Name() != "operations.yaml" && entry.Name() != "errors.yaml") {
			return nil
		}
		rel, err := filepath.Rel(contractsDir, path)
		if err != nil {
			return err
		}
		parts := strings.Split(filepath.ToSlash(rel), "/")
		if len(parts) != 3 {
			return fmt.Errorf("object contract must be <context>/<object>/<file>: %s", filepath.ToSlash(rel))
		}
		sourcePath := filepath.ToSlash(filepath.Join("contracts", rel))
		graphPath := filepath.ToSlash(filepath.Join(domain.Domain, rel))
		key := parts[0] + "/" + parts[1]
		input := objects[key]
		if input == nil {
			input = &objectContractInput{Context: parts[0], Object: parts[1]}
			objects[key] = input
		}
		switch entry.Name() {
		case "operations.yaml":
			input.OperationSourcePath = sourcePath
			input.OperationGraphPath = graphPath
		case "errors.yaml":
			// Generated headers carry the full domain/context/object owner so the
			// architecture gate can reverse-map the output without a registry.
			input.ErrorsSourcePath = graphPath
			input.ErrorsGraphPath = graphPath
		}
		return nil
	})
	if err != nil {
		return inputs, err
	}
	for _, input := range objects {
		if input.OperationGraphPath != "" {
			inputs.Objects = append(inputs.Objects, *input)
		}
	}
	if len(inputs.Objects) == 0 {
		return inputs, fmt.Errorf("no object operations.yaml found")
	}
	sort.Slice(inputs.Objects, func(i, j int) bool {
		left := inputs.Objects[i].Context + "/" + inputs.Objects[i].Object
		right := inputs.Objects[j].Context + "/" + inputs.Objects[j].Object
		return left < right
	})
	return inputs, nil
}

func loadErrorsYAML(
	source *contractcodegen.Source,
	path string,
) (*contractcodegen.ErrorsFile, error) {
	var file contractcodegen.ErrorsFile
	if err := source.Decode(path, &file); err != nil {
		return nil, err
	}
	return &file, nil
}

type operationsYAML struct {
	APIRoutes []serviceRouteYAML `yaml:"api_routes"`
}

type serviceRouteYAML struct {
	Method    string `yaml:"method"`
	Path      string `yaml:"path"`
	Operation string `yaml:"operation"`
}

func loadOperationsYAML(
	source *contractcodegen.Source,
	path string,
) (operationsYAML, error) {
	var s operationsYAML
	if err := source.Decode(path, &s); err != nil {
		return s, err
	}
	return s, nil
}

func collectRoutes(
	source *contractcodegen.Source,
	operationSources []string,
) ([]routeData, error) {
	routes := make([]routeData, 0)
	operationOwners := make(map[string]string)
	pathOwners := make(map[string]string)
	for _, operationsPath := range operationSources {
		svc, err := loadOperationsYAML(source, operationsPath)
		if err != nil {
			return nil, fmt.Errorf("load operations.yaml %s: %w", operationsPath, err)
		}
		for _, route := range svc.APIRoutes {
			if route.Operation == "" {
				continue
			}
			if owner, exists := operationOwners[route.Operation]; exists {
				return nil, fmt.Errorf("duplicate chat operation %q in %s and %s", route.Operation, owner, operationsPath)
			}
			pathKey := route.Method + " " + route.Path
			if owner, exists := pathOwners[pathKey]; exists {
				return nil, fmt.Errorf("duplicate chat route %q in %s and %s", pathKey, owner, operationsPath)
			}
			operationOwners[route.Operation] = operationsPath
			pathOwners[pathKey] = operationsPath
			routes = append(routes, routeData{
				Method:    route.Method,
				Template:  route.Path,
				Operation: route.Operation,
			})
		}
	}
	return routes, nil
}

type routeData struct {
	Method    string
	Template  string
	Operation string
}

type routeFileData struct {
	OperationSourcesRel []string
	Routes              []routeData
}

const routeTemplate = `// Code generated by tools/codegen_chat_service from:
{{- range .OperationSourcesRel}}
//   - {{.}}
{{- end}}
// DO NOT EDIT.
package http

import (
	"net/http"
	"strings"

	rterr "quwoquan_service/runtime/errors"
)

type routeEntry struct {
	Method    string
	Template  string
	Operation string
}

var generatedRouteTable = []routeEntry{
{{- range .Routes}}
	{"{{.Method}}", "{{.Template}}", "{{.Operation}}"},
{{- end}}
}

func RegisterGeneratedRoutes(mux *http.ServeMux, h *ChatHandler) {
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		op, ok := resolveGeneratedOperation(r.Method, r.URL.Path)
		if !ok {
			writeHTTPError(w, r, rterr.NewInvalidArgument(rterr.ModuleChat, "接口不存在", "route not found"))
			return
		}
		dispatchGeneratedOperation(h, op, w, r)
	})
}

func dispatchGeneratedOperation(h *ChatHandler, operation string, w http.ResponseWriter, r *http.Request) {
	switch operation {
{{- range .Routes}}
	case "{{.Operation}}":
		h.handle{{.Operation}}(w, r)
{{- end}}
	default:
		writeHTTPError(w, r, rterr.NewInvalidArgument(rterr.ModuleChat, "接口不存在", "operation not found"))
	}
}

func resolveGeneratedOperation(method, path string) (string, bool) {
	for _, r := range generatedRouteTable {
		if r.Method != method {
			continue
		}
		if matchTemplate(r.Template, path) {
			return r.Operation, true
		}
	}
	return "", false
}

func matchTemplate(template, path string) bool {
	tParts := strings.Split(strings.Trim(template, "/"), "/")
	pParts := strings.Split(strings.Trim(path, "/"), "/")
	if len(tParts) != len(pParts) {
		return false
	}
	for i, tp := range tParts {
		if strings.HasPrefix(tp, "{") && strings.HasSuffix(tp, "}") {
			continue
		}
		if tp != pParts[i] {
			return false
		}
	}
	return true
}

func extractPathParam(path, template, paramName string) string {
	tParts := strings.Split(strings.Trim(template, "/"), "/")
	pParts := strings.Split(strings.Trim(path, "/"), "/")
	target := "{" + paramName + "}"
	for i, tp := range tParts {
		if tp == target && i < len(pParts) {
			return pParts[i]
		}
	}
	return ""
}
`

func render(data routeFileData) ([]byte, error) {
	tmpl, err := template.New("routes").Parse(routeTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\n--- source ---\n%s", err, buf.String())
	}
	return formatted, nil
}

func exitErr(err error) {
	fmt.Fprintln(os.Stderr, "codegen_chat_service:", err)
	os.Exit(1)
}
