package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

type serviceRoutesFile struct {
	APIRoutes []struct {
		Method    string `yaml:"method"`
		Path      string `yaml:"path"`
		Operation string `yaml:"operation"`
	} `yaml:"api_routes"`
}

func main() {
	var metadataDir string
	var outputDir string
	var sharedDir string
	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&outputDir, "output-dir", "services/notification-service/generated/notification_delivery/notification", "notification-service generated object directory")
	flag.StringVar(&sharedDir, "shared-dir", "generated/serviceclients", "cross-service client constants output directory")
	flag.Parse()

	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		exitErr(fmt.Errorf("compile ContractGraph: %w", err))
	}
	var errorsFile contractcodegen.ErrorsFile
	const sourcePath = "notification/notification_delivery/notification/errors.yaml"
	if err := source.Decode(sourcePath, &errorsFile); err != nil {
		exitErr(fmt.Errorf("load %s: %w", sourcePath, err))
	}
	rendered := contractcodegen.RenderGoErrorsFile(&errorsFile, contractcodegen.GoErrorsFileOptions{
		Generator:    "tools/codegen_notification_service",
		SourcePath:   sourcePath,
		CommentLines: []string{"Notification error sentinels and helpers. Transport semantics come from errors.yaml."},
	})
	writeGoFile(filepath.Join(outputDir, "errors.go"), rendered)
	var deliveryJobErrors contractcodegen.ErrorsFile
	const deliveryJobErrorsSource = "notification/notification_delivery/notification_delivery_job/errors.yaml"
	if err := source.Decode(deliveryJobErrorsSource, &deliveryJobErrors); err != nil {
		exitErr(fmt.Errorf("load %s: %w", deliveryJobErrorsSource, err))
	}
	deliveryJobRendered := contractcodegen.RenderGoErrorsFile(
		&deliveryJobErrors,
		contractcodegen.GoErrorsFileOptions{
			Generator:    "tools/codegen_notification_service",
			SourcePath:   deliveryJobErrorsSource,
			CommentLines: []string{"NotificationDeliveryJob error sentinels and helpers. Transport semantics come from errors.yaml."},
		},
	)
	writeGoFile(
		filepath.Join(filepath.Dir(outputDir), "notification_delivery_job", "errors.go"),
		deliveryJobRendered,
	)

	var routes serviceRoutesFile
	const routesSource = "notification/notification_delivery/notification/operations.yaml"
	if err := source.Decode(routesSource, &routes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", routesSource, err))
	}
	createAppMessagePath := ""
	for _, route := range routes.APIRoutes {
		if strings.TrimSpace(route.Operation) == "CreateAppMessage" {
			createAppMessagePath = strings.TrimSpace(route.Path)
		}
	}
	if createAppMessagePath == "" {
		exitErr(fmt.Errorf("%s: operation CreateAppMessage missing api route path", routesSource))
	}
	var client strings.Builder
	client.WriteString("// Code generated by tools/codegen_notification_service from " + routesSource + ". DO NOT EDIT.\n")
	client.WriteString("package serviceclients\n\n")
	client.WriteString("// Notification transport paths for cross-service producers.\n")
	client.WriteString("const (\n")
	client.WriteString(fmt.Sprintf("\tNotificationCreateAppMessagePath = %q\n", createAppMessagePath))
	client.WriteString(")\n")
	writeGoFile(filepath.Join(sharedDir, "notification_paths.g.go"), client.String())

	var userRoutes serviceRoutesFile
	const userSource = "user/account/device_registration/operations.yaml"
	if err := source.Decode(userSource, &userRoutes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", userSource, err))
	}
	userPath := ""
	for _, route := range userRoutes.APIRoutes {
		if strings.TrimSpace(route.Operation) ==
			"ResolveIncomingCallPushDestinations" {
			userPath = strings.TrimSpace(route.Path)
			break
		}
	}
	if userPath == "" {
		exitErr(fmt.Errorf(
			"%s: operation ResolveIncomingCallPushDestinations missing api route path",
			userSource,
		))
	}
	var userSettingsRoutes serviceRoutesFile
	const userSettingsSource = "user/account/user_settings/operations.yaml"
	if err := source.Decode(userSettingsSource, &userSettingsRoutes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", userSettingsSource, err))
	}
	assistantDeliveryPolicyPath := ""
	for _, route := range userSettingsRoutes.APIRoutes {
		if strings.TrimSpace(route.Operation) == "ResolveAssistantDeliveryPolicy" {
			assistantDeliveryPolicyPath = strings.TrimSpace(route.Path)
			break
		}
	}
	if assistantDeliveryPolicyPath == "" {
		exitErr(fmt.Errorf(
			"%s: operation ResolveAssistantDeliveryPolicy missing api route path",
			userSettingsSource,
		))
	}
	var userClient strings.Builder
	userClient.WriteString(
		"// Code generated by tools/codegen_notification_service from " +
			userSource + " and " + userSettingsSource + ". DO NOT EDIT.\n",
	)
	userClient.WriteString("package serviceclients\n\n")
	userClient.WriteString("import (\n")
	userClient.WriteString("\t\"net/url\"\n")
	userClient.WriteString("\t\"strings\"\n")
	userClient.WriteString(")\n\n")
	userClient.WriteString("const (\n")
	userClient.WriteString(
		fmt.Sprintf(
			"\tUserResolveIncomingCallPushDestinationsPathTemplate = %q\n",
			userPath,
		),
	)
	userClient.WriteString(
		fmt.Sprintf(
			"\tUserResolveAssistantDeliveryPolicyPathTemplate = %q\n",
			assistantDeliveryPolicyPath,
		),
	)
	userClient.WriteString(")\n")
	userClient.WriteString(`
func UserResolveIncomingCallPushDestinationsPath(personaID string) string {
	return strings.ReplaceAll(
		UserResolveIncomingCallPushDestinationsPathTemplate,
		"{personaId}",
		url.PathEscape(strings.TrimSpace(personaID)),
	)
}

func UserResolveAssistantDeliveryPolicyPath(userID string) string {
	return strings.ReplaceAll(
		UserResolveAssistantDeliveryPolicyPathTemplate,
		"{userId}",
		url.PathEscape(strings.TrimSpace(userID)),
	)
}
`)
	writeGoFile(
		filepath.Join(sharedDir, "user_paths.g.go"),
		userClient.String(),
	)

	const chatMembershipSource = "chat/chat/conversation_membership/operations.yaml"
	var chatMembershipRoutes serviceRoutesFile
	if err := source.Decode(
		chatMembershipSource,
		&chatMembershipRoutes,
	); err != nil {
		exitErr(fmt.Errorf("load %s: %w", chatMembershipSource, err))
	}
	const chatMessageSource = "chat/chat/message/operations.yaml"
	var chatMessageRoutes serviceRoutesFile
	if err := source.Decode(chatMessageSource, &chatMessageRoutes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", chatMessageSource, err))
	}
	resolveMembershipPath := requiredOperationPath(
		chatMembershipSource,
		chatMembershipRoutes,
		"ResolveAssistantDeliveryMembership",
	)
	listGroundingMessagesPath := requiredOperationPath(
		chatMessageSource,
		chatMessageRoutes,
		"ListAssistantGroundingMessages",
	)
	sendDeliveryMessagePath := requiredOperationPath(
		chatMessageSource,
		chatMessageRoutes,
		"SendAssistantDeliveryMessage",
	)
	var chatClient strings.Builder
	chatClient.WriteString(
		"// Code generated by tools/codegen_notification_service from " +
			chatMembershipSource + " and " + chatMessageSource +
			". DO NOT EDIT.\n",
	)
	chatClient.WriteString("package serviceclients\n\n")
	chatClient.WriteString("import (\n")
	chatClient.WriteString("\t\"net/url\"\n")
	chatClient.WriteString("\t\"strings\"\n")
	chatClient.WriteString(")\n\n")
	chatClient.WriteString("const (\n")
	chatClient.WriteString(fmt.Sprintf(
		"\tChatResolveAssistantDeliveryMembershipPathTemplate = %q\n",
		resolveMembershipPath,
	))
	chatClient.WriteString(fmt.Sprintf(
		"\tChatListAssistantGroundingMessagesPathTemplate = %q\n",
		listGroundingMessagesPath,
	))
	chatClient.WriteString(fmt.Sprintf(
		"\tChatSendAssistantDeliveryMessagePathTemplate = %q\n",
		sendDeliveryMessagePath,
	))
	chatClient.WriteString(")\n")
	chatClient.WriteString(`
func ChatResolveAssistantDeliveryMembershipPath(conversationID string) string {
	return strings.ReplaceAll(
		ChatResolveAssistantDeliveryMembershipPathTemplate,
		"{conversationId}",
		url.PathEscape(strings.TrimSpace(conversationID)),
	)
}

func ChatListAssistantGroundingMessagesPath(conversationID string) string {
	return strings.ReplaceAll(
		ChatListAssistantGroundingMessagesPathTemplate,
		"{conversationId}",
		url.PathEscape(strings.TrimSpace(conversationID)),
	)
}

func ChatSendAssistantDeliveryMessagePath(conversationID string) string {
	return strings.ReplaceAll(
		ChatSendAssistantDeliveryMessagePathTemplate,
		"{conversationId}",
		url.PathEscape(strings.TrimSpace(conversationID)),
	)
}
`)
	writeGoFile(
		filepath.Join(sharedDir, "chat_paths.g.go"),
		chatClient.String(),
	)
}

func requiredOperationPath(
	sourcePath string,
	routes serviceRoutesFile,
	operation string,
) string {
	for _, route := range routes.APIRoutes {
		if strings.TrimSpace(route.Operation) == operation {
			if path := strings.TrimSpace(route.Path); path != "" {
				return path
			}
		}
	}
	exitErr(fmt.Errorf(
		"%s: operation %s missing api route path",
		sourcePath,
		operation,
	))
	return ""
}

func writeGoFile(path string, contents string) {
	formatted, err := format.Source([]byte(contents))
	if err != nil {
		exitErr(fmt.Errorf("gofmt %s: %w", path, err))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		exitErr(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		exitErr(err)
	}
	fmt.Printf("codegen_notification_service: wrote %s\n", path)
}

func exitErr(err error) {
	fmt.Fprintf(os.Stderr, "codegen_notification_service error: %v\n", err)
	os.Exit(1)
}
