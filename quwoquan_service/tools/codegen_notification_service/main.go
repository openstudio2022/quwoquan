package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

type serviceRoutesFile struct {
	APIRoutes []struct {
		Method    string `yaml:"method"`
		Path      string `yaml:"path"`
		Operation string `yaml:"operation"`
	} `yaml:"api_routes"`
}

func main() {
	var metadataDir string
	var outputDir string
	var sharedDir string
	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&outputDir, "output-dir", "services/notification-service/internal", "notification-service internal output directory")
	flag.StringVar(&sharedDir, "shared-dir", "generated/serviceclients", "cross-service client constants output directory")
	flag.Parse()

	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		exitErr(fmt.Errorf("compile ContractGraph: %w", err))
	}
	var errorsFile contractcodegen.ErrorsFile
	const sourcePath = "notification/notification/errors.yaml"
	if err := source.Decode(sourcePath, &errorsFile); err != nil {
		exitErr(fmt.Errorf("load %s: %w", sourcePath, err))
	}
	rendered := contractcodegen.RenderGoErrorsFile(&errorsFile, contractcodegen.GoErrorsFileOptions{
		Generator:    "tools/codegen_notification_service",
		SourcePath:   sourcePath,
		CommentLines: []string{"Notification error sentinels and helpers. Transport semantics come from errors.yaml."},
	})
	writeGoFile(filepath.Join(outputDir, "generated", "errors.go"), rendered)

	var routes serviceRoutesFile
	const routesSource = "notification/notification/service.yaml"
	if err := source.Decode(routesSource, &routes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", routesSource, err))
	}
	createAppMessagePath := ""
	for _, route := range routes.APIRoutes {
		if strings.TrimSpace(route.Operation) == "CreateAppMessage" {
			createAppMessagePath = strings.TrimSpace(route.Path)
		}
	}
	if createAppMessagePath == "" {
		exitErr(fmt.Errorf("%s: operation CreateAppMessage missing api route path", routesSource))
	}
	var client strings.Builder
	client.WriteString("// Code generated by tools/codegen_notification_service from " + routesSource + ". DO NOT EDIT.\n")
	client.WriteString("package serviceclients\n\n")
	client.WriteString("// Notification transport paths for cross-service producers.\n")
	client.WriteString("const (\n")
	client.WriteString(fmt.Sprintf("\tNotificationCreateAppMessagePath = %q\n", createAppMessagePath))
	client.WriteString(")\n")
	writeGoFile(filepath.Join(sharedDir, "notification_paths.g.go"), client.String())

	var userRoutes serviceRoutesFile
	const userSource = "user/device_registration/service.yaml"
	if err := source.Decode(userSource, &userRoutes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", userSource, err))
	}
	userPath := ""
	for _, route := range userRoutes.APIRoutes {
		if strings.TrimSpace(route.Operation) ==
			"ResolveIncomingCallPushDestinations" {
			userPath = strings.TrimSpace(route.Path)
			break
		}
	}
	if userPath == "" {
		exitErr(fmt.Errorf(
			"%s: operation ResolveIncomingCallPushDestinations missing api route path",
			userSource,
		))
	}
	var userClient strings.Builder
	userClient.WriteString(
		"// Code generated by tools/codegen_notification_service from " +
			userSource + ". DO NOT EDIT.\n",
	)
	userClient.WriteString("package serviceclients\n\n")
	userClient.WriteString(
		fmt.Sprintf(
			"const UserResolveIncomingCallPushDestinationsPathTemplate = %q\n",
			userPath,
		),
	)
	writeGoFile(
		filepath.Join(sharedDir, "user_paths.g.go"),
		userClient.String(),
	)
}

func writeGoFile(path string, contents string) {
	formatted, err := format.Source([]byte(contents))
	if err != nil {
		exitErr(fmt.Errorf("gofmt %s: %w", path, err))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		exitErr(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		exitErr(err)
	}
	fmt.Printf("codegen_notification_service: wrote %s\n", path)
}

func exitErr(err error) {
	fmt.Fprintf(os.Stderr, "codegen_notification_service error: %v\n", err)
	os.Exit(1)
}
