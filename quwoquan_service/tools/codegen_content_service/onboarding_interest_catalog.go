package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

// taxonomy 发布身份不在本 catalog 内：它是 tag-service 活跃发布的运行时事实，
// 由客户端回显 TagChild.releaseId、服务端转交 tag-service 判定。
type onboardingInterestCatalogYAML struct {
	MinSelectionCount int `yaml:"min_selection_count"`
	MaxSelectionCount int `yaml:"max_selection_count"`
	Dimensions        []struct {
		ID            string `yaml:"id"`
		TagRef        string `yaml:"tag_ref"`
		DisplayLabel  string `yaml:"display_label"`
		MinSelections int    `yaml:"min_selections"`
		MaxSelections int    `yaml:"max_selections"`
		Order         int    `yaml:"order"`
	} `yaml:"dimensions"`
}

type contentUIConfigYAML struct {
	OnboardingInterestCatalog onboardingInterestCatalogYAML `yaml:"onboarding_interest_catalog"`
}

func generateOnboardingInterestCatalog(
	source *contractcodegen.Source,
	outputDir string,
) error {
	var ui contentUIConfigYAML
	if err := source.Decode("content/content/post/ui_config.yaml", &ui); err != nil {
		return err
	}
	catalog := ui.OnboardingInterestCatalog
	if catalog.MinSelectionCount <= 0 ||
		catalog.MaxSelectionCount < catalog.MinSelectionCount ||
		len(catalog.Dimensions) == 0 {
		return fmt.Errorf("content/content/post/ui_config.yaml onboarding_interest_catalog is incomplete")
	}

	dimensions := append([]struct {
		ID            string `yaml:"id"`
		TagRef        string `yaml:"tag_ref"`
		DisplayLabel  string `yaml:"display_label"`
		MinSelections int    `yaml:"min_selections"`
		MaxSelections int    `yaml:"max_selections"`
		Order         int    `yaml:"order"`
	}(nil), catalog.Dimensions...)
	sort.Slice(dimensions, func(i, j int) bool {
		if dimensions[i].Order != dimensions[j].Order {
			return dimensions[i].Order < dimensions[j].Order
		}
		return dimensions[i].ID < dimensions[j].ID
	})

	dimensionIDs := make(map[string]struct{}, len(dimensions))
	for _, dimension := range dimensions {
		if dimension.ID == "" || dimension.TagRef == "" {
			return fmt.Errorf("onboarding_interest_catalog dimension requires id and tag_ref")
		}
		if _, exists := dimensionIDs[dimension.ID]; exists {
			return fmt.Errorf("onboarding_interest_catalog dimension id %q is duplicated", dimension.ID)
		}
		if dimension.MinSelections < 0 || dimension.MaxSelections < dimension.MinSelections {
			return fmt.Errorf(
				"onboarding_interest_catalog dimension %q has invalid selection bounds",
				dimension.ID,
			)
		}
		dimensionIDs[dimension.ID] = struct{}{}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/codegen_content_service from content/content/post/ui_config.yaml. DO NOT EDIT.\n\n")
	buf.WriteString("package generated\n\n")
	buf.WriteString("type OnboardingInterestCatalogPolicy struct {\n")
	buf.WriteString("\tMinSelectionCount        int\n")
	buf.WriteString("\tMaxSelectionCount        int\n")
	buf.WriteString("\tDimensionRoots           map[string]string\n")
	buf.WriteString("\tDimensionMinSelections   map[string]int\n")
	buf.WriteString("\tDimensionMaxSelections   map[string]int\n")
	buf.WriteString("}\n\n")
	buf.WriteString("func DefaultOnboardingInterestCatalogPolicy() OnboardingInterestCatalogPolicy {\n")
	buf.WriteString("\treturn OnboardingInterestCatalogPolicy{\n")
	fmt.Fprintf(&buf, "\t\tMinSelectionCount: %d,\n", catalog.MinSelectionCount)
	fmt.Fprintf(&buf, "\t\tMaxSelectionCount: %d,\n", catalog.MaxSelectionCount)
	buf.WriteString("\t\tDimensionRoots: map[string]string{\n")
	sortedIDs := make([]string, 0, len(dimensions))
	roots := make(map[string]string, len(dimensions))
	minSelections := make(map[string]int, len(dimensions))
	maxSelections := make(map[string]int, len(dimensions))
	for _, dimension := range dimensions {
		sortedIDs = append(sortedIDs, dimension.ID)
		roots[dimension.ID] = dimension.TagRef
		minSelections[dimension.ID] = dimension.MinSelections
		maxSelections[dimension.ID] = dimension.MaxSelections
	}
	sort.Strings(sortedIDs)
	for _, id := range sortedIDs {
		fmt.Fprintf(&buf, "\t\t\t%q: %q,\n", id, roots[id])
	}
	buf.WriteString("\t\t},\n")
	buf.WriteString("\t\tDimensionMinSelections: map[string]int{\n")
	for _, id := range sortedIDs {
		fmt.Fprintf(&buf, "\t\t\t%q: %d,\n", id, minSelections[id])
	}
	buf.WriteString("\t\t},\n")
	buf.WriteString("\t\tDimensionMaxSelections: map[string]int{\n")
	for _, id := range sortedIDs {
		fmt.Fprintf(&buf, "\t\t\t%q: %d,\n", id, maxSelections[id])
	}
	buf.WriteString("\t\t},\n")
	buf.WriteString("\t}\n")
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(
		filepath.Join(outputDir, "onboarding_interest_catalog.g.go"),
		out,
		0o644,
	)
}
