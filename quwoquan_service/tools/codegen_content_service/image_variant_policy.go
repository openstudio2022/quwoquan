package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

type contentImageVariantPolicyYAML struct {
	Schema                  string                                    `yaml:"schema"`
	DerivativePolicyVersion int                                       `yaml:"derivative_policy_version"`
	Profiles                map[string]contentImageVariantProfileYAML `yaml:"profiles"`
}

type contentImageVariantProfileYAML struct {
	Width      int    `yaml:"width"`
	Format     string `yaml:"format"`
	Quality    int    `yaml:"quality"`
	Scene      string `yaml:"scene"`
	Processing string `yaml:"processing"`
}

func generateContentImageVariantPolicy(
	source *contractcodegen.Source,
	outputDir string,
) error {
	var policy contentImageVariantPolicyYAML
	if err := source.Decode(
		"content/media_asset/image_variant_policy.yaml",
		&policy,
	); err != nil {
		return err
	}
	expected := map[string]struct {
		width      int
		format     string
		quality    int
		processing string
	}{
		"thumbnail": {320, "webp", 80, "image/resize,w_320/format,webp/quality,q_80"},
		"display":   {960, "webp", 82, "image/resize,w_960/format,webp/quality,q_82"},
		"cover":     {1280, "webp", 85, "image/resize,w_1280/format,webp/quality,q_85"},
		"full":      {2048, "webp", 90, "image/resize,w_2048/format,webp/quality,q_90"},
	}
	if policy.Schema != "content_image_variant_policy" ||
		policy.DerivativePolicyVersion <= 0 ||
		len(policy.Profiles) != len(expected) {
		return fmt.Errorf("content image variant policy is incomplete")
	}
	for name, want := range expected {
		profile, ok := policy.Profiles[name]
		if !ok ||
			profile.Width != want.width ||
			profile.Format != want.format ||
			profile.Quality != want.quality ||
			profile.Processing != want.processing ||
			profile.Scene == "" {
			return fmt.Errorf("content image variant profile %s is invalid", name)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/codegen_content_service from content/media_asset/image_variant_policy.yaml. DO NOT EDIT.\n\n")
	buf.WriteString("package generated\n\n")
	fmt.Fprintf(
		&buf,
		"const ContentImageDerivativePolicyVersion = %d\n\n",
		policy.DerivativePolicyVersion,
	)
	buf.WriteString("type ContentImageVariantProfile struct {\n")
	buf.WriteString("\tWidth      int\n")
	buf.WriteString("\tFormat     string\n")
	buf.WriteString("\tQuality    int\n")
	buf.WriteString("\tScene      string\n")
	buf.WriteString("\tProcessing string\n")
	buf.WriteString("}\n\n")
	buf.WriteString("var ContentImageVariantProfiles = map[string]ContentImageVariantProfile{\n")
	names := make([]string, 0, len(policy.Profiles))
	for name := range policy.Profiles {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		profile := policy.Profiles[name]
		fmt.Fprintf(&buf, "\t%q: {\n", name)
		fmt.Fprintf(&buf, "\t\tWidth: %d,\n", profile.Width)
		fmt.Fprintf(&buf, "\t\tFormat: %q,\n", profile.Format)
		fmt.Fprintf(&buf, "\t\tQuality: %d,\n", profile.Quality)
		fmt.Fprintf(&buf, "\t\tScene: %q,\n", profile.Scene)
		fmt.Fprintf(&buf, "\t\tProcessing: %q,\n", profile.Processing)
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	targetDir := filepath.Join(outputDir, "generated")
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(
		filepath.Join(targetDir, "content_image_variant_policy.go"),
		out,
		0o644,
	)
}
