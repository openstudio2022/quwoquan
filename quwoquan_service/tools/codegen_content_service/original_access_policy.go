package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

type contentMediaOriginalAccessPolicyYAML struct {
	Schema          string `yaml:"schema"`
	GrantTTLSeconds int    `yaml:"grant_ttl_seconds"`
	RateLimit       struct {
		MaxGrants     int `yaml:"max_grants"`
		WindowSeconds int `yaml:"window_seconds"`
	} `yaml:"rate_limit"`
}

func generateContentMediaOriginalAccessPolicy(
	source *contractcodegen.Source,
	outputDir string,
) error {
	var policy contentMediaOriginalAccessPolicyYAML
	if err := source.Decode(
		"content/media_original_access_fact/original_access_policy.yaml",
		&policy,
	); err != nil {
		return err
	}
	if policy.Schema != "content_media_original_access_policy" ||
		policy.GrantTTLSeconds <= 0 ||
		policy.RateLimit.MaxGrants <= 0 ||
		policy.RateLimit.WindowSeconds <= 0 {
		return fmt.Errorf("content media original access policy is invalid")
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/codegen_content_service from content/media_original_access_fact/original_access_policy.yaml. DO NOT EDIT.\n\n")
	buf.WriteString("package generated\n\n")
	fmt.Fprintf(&buf, "const ContentMediaOriginalAccessGrantTTLSeconds = %d\n", policy.GrantTTLSeconds)
	fmt.Fprintf(&buf, "const ContentMediaOriginalAccessRateLimitMaxGrants = %d\n", policy.RateLimit.MaxGrants)
	fmt.Fprintf(&buf, "const ContentMediaOriginalAccessRateLimitWindowSeconds = %d\n", policy.RateLimit.WindowSeconds)

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	targetDir := filepath.Join(outputDir, "generated")
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(
		filepath.Join(targetDir, "content_media_original_access_policy.go"),
		out,
		0o644,
	)
}
