package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

type contentMediaUploadPolicyYAML struct {
	Schema            string                                `yaml:"schema"`
	StreamingRequired bool                                  `yaml:"streaming_required"`
	MediaTypes        map[string]contentMediaUploadTypeYAML `yaml:"media_types"`
	Errors            struct {
		FileTooLarge    string `yaml:"file_too_large"`
		UnsupportedType string `yaml:"unsupported_type"`
	} `yaml:"errors"`
}

type contentMediaUploadTypeYAML struct {
	MaxFileSizeBytes    int64    `yaml:"max_file_size_bytes"`
	AllowedContentTypes []string `yaml:"allowed_content_types"`
}

func generateContentMediaUploadPolicy(
	source *contractcodegen.Source,
	outputDir string,
) error {
	var policy contentMediaUploadPolicyYAML
	if err := source.Decode(
		"content/media_upload_session/upload_policy.yaml",
		&policy,
	); err != nil {
		return err
	}
	if policy.Schema != "content_media_upload_policy" ||
		!policy.StreamingRequired ||
		policy.Errors.FileTooLarge == "" ||
		policy.Errors.UnsupportedType == "" {
		return fmt.Errorf("content media upload policy is incomplete")
	}
	for _, mediaType := range []string{"image", "video", "audio", "file"} {
		definition := policy.MediaTypes[mediaType]
		if definition.MaxFileSizeBytes <= 0 ||
			len(definition.AllowedContentTypes) == 0 {
			return fmt.Errorf("content media upload policy %s limits and types are required", mediaType)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/codegen_content_service from content/media_upload_session/upload_policy.yaml. DO NOT EDIT.\n\n")
	buf.WriteString("package generated\n\n")
	buf.WriteString("const (\n")
	fmt.Fprintf(&buf, "\tContentMediaUploadStreamingRequired = %t\n", policy.StreamingRequired)
	fmt.Fprintf(&buf, "\tContentMediaUploadFileTooLargeErrorCode = %q\n", policy.Errors.FileTooLarge)
	fmt.Fprintf(&buf, "\tContentMediaUploadUnsupportedTypeErrorCode = %q\n", policy.Errors.UnsupportedType)
	buf.WriteString(")\n\n")
	buf.WriteString("type ContentMediaUploadTypePolicy struct {\n")
	buf.WriteString("\tMaxFileSizeBytes int64\n")
	buf.WriteString("\tAllowedContentTypes map[string]struct{}\n")
	buf.WriteString("}\n\n")
	buf.WriteString("var ContentMediaUploadPolicies = map[string]ContentMediaUploadTypePolicy{\n")
	mediaTypes := make([]string, 0, len(policy.MediaTypes))
	for mediaType := range policy.MediaTypes {
		mediaTypes = append(mediaTypes, mediaType)
	}
	sort.Strings(mediaTypes)
	for _, mediaType := range mediaTypes {
		definition := policy.MediaTypes[mediaType]
		fmt.Fprintf(&buf, "\t%q: {\n", mediaType)
		fmt.Fprintf(&buf, "\t\tMaxFileSizeBytes: %d,\n", definition.MaxFileSizeBytes)
		buf.WriteString("\t\tAllowedContentTypes: map[string]struct{}{\n")
		for _, contentType := range definition.AllowedContentTypes {
			fmt.Fprintf(&buf, "\t\t%q: {},\n", contentType)
		}
		buf.WriteString("\t\t},\n")
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	targetDir := filepath.Join(outputDir, "generated")
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(
		filepath.Join(targetDir, "content_media_upload_policy.go"),
		out,
		0o644,
	)
}
