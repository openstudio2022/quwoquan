package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

// ── errors.yaml → Go errors.go ────────────────────────────────────────────────

type errorEntryYAML struct {
	Code                 string            `yaml:"code"`
	Reason               string            `yaml:"reason"`
	HTTPStatus           int               `yaml:"http_status"`
	GoConst              string            `yaml:"go_const"`
	RecoveryAction       string            `yaml:"recovery_action"`
	RecoveryAfterSeconds int               `yaml:"recovery_after_seconds"`
	DisruptionLevel      string            `yaml:"disruption_level"`
	UserMessage          map[string]string `yaml:"user_message"`
}

type errorsYAML struct {
	Domain string           `yaml:"domain"`
	Errors []errorEntryYAML `yaml:"errors"`
}

// contentDomainErrorsPaths 与 tools/codegen_app_metadata 的同名列表保持一致。
// 每份对象 errors.yaml 生成到自己的 generated/<context>/<object>/errors.go。
func contentDomainErrorsPaths() []string {
	return []string{
		"content/content/post/errors.yaml",
		"content/content/comment/errors.yaml",
		"content/content/content_reaction/errors.yaml",
		"content/content/deleted_post_tombstone/errors.yaml",
		"content/content/profile_interaction_activity_view/errors.yaml",
		"content/content/profile_interaction_read_fact/errors.yaml",
		"content/media/filter_catalog_release/errors.yaml",
		"content/media/media_asset/errors.yaml",
		"content/media/media_image_reprocess_run/errors.yaml",
		"content/media/original_access_quota/errors.yaml",
		"content/media/media_upload_session/errors.yaml",
		"content/content/outbound_share_fact/errors.yaml",
		"content/trust_safety/post_moderation_case/errors.yaml",
		"content/trust_safety/report/errors.yaml",
	}
}

func generateErrorConstants(
	source *contractcodegen.Source,
	outputRoot string,
) error {
	seen := map[string]string{}
	for _, errsPath := range contentDomainErrorsPaths() {
		if !source.Has(errsPath) {
			return fmt.Errorf("content errors metadata missing: %s", errsPath)
		}
		var part errorsYAML
		if err := source.Decode(errsPath, &part); err != nil {
			return fmt.Errorf("parse %s: %w", errsPath, err)
		}
		for _, entry := range part.Errors {
			if previous, exists := seen[entry.Code]; exists {
				return fmt.Errorf(
					"duplicate content error code %s in %s (already in %s)",
					entry.Code,
					errsPath,
					previous,
				)
			}
			seen[entry.Code] = errsPath
		}
		parts := strings.Split(errsPath, "/")
		if len(parts) != 4 || parts[0] != "content" || parts[3] != "errors.yaml" {
			return fmt.Errorf("unexpected content errors path %q", errsPath)
		}
		out, err := renderContentErrorConstants(errsPath, part)
		if err != nil {
			return err
		}
		targetDir := filepath.Join(outputRoot, parts[1], parts[2])
		if err := os.MkdirAll(targetDir, 0o755); err != nil {
			return err
		}
		outPath := filepath.Join(targetDir, "errors.go")
		if err := os.WriteFile(outPath, out, 0o644); err != nil {
			return err
		}
		fmt.Printf("generated: %s\n", outPath)
	}
	return nil
}

func renderContentErrorConstants(sourcePath string, spec errorsYAML) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(
		&buf,
		"// Code generated by tools/codegen_content_service from %s. DO NOT EDIT.\n",
		sourcePath,
	)
	buf.WriteString("package generated\n")
	if len(spec.Errors) == 0 {
		return format.Source(buf.Bytes())
	}
	buf.WriteString("\nimport (\n")
	buf.WriteString("\t\"errors\"\n\n")
	buf.WriteString("\trterr \"quwoquan_service/runtime/errors\"\n")
	buf.WriteString(")\n\n")
	buf.WriteString("// Content object error sentinels bound to runtime/errors conventions.\n")
	buf.WriteString("//\n//nolint:gochecknoglobals\n")
	buf.WriteString("var (\n")
	sort.Slice(spec.Errors, func(i, j int) bool { return spec.Errors[i].GoConst < spec.Errors[j].GoConst })
	for _, e := range spec.Errors {
		if e.GoConst == "" {
			continue
		}
		buf.WriteString(fmt.Sprintf("\t%s = errors.New(%q)\n", e.GoConst, e.Code))
	}
	buf.WriteString(")\n")
	for _, e := range spec.Errors {
		if e.GoConst == "" {
			continue
		}
		reason := errorReason(e)
		userMessage := strings.TrimSpace(e.UserMessage["zh"])
		if userMessage == "" {
			userMessage = "内容服务异常，请稍后重试"
		}
		funcName := "AppErrorFrom" + strings.TrimPrefix(e.GoConst, "Err")
		buf.WriteString(fmt.Sprintf("\n// %s returns *AppError for %s (user_message from errors.yaml).\n", funcName, e.Code))
		buf.WriteString(fmt.Sprintf("func %s(debugMessage string) *rterr.AppError {\n", funcName))
		buf.WriteString(fmt.Sprintf("\tcode, _ := rterr.ParseCode(%q)\n", e.Code))
		buf.WriteString(fmt.Sprintf("\treturn rterr.NewAppError(code, %q, debugMessage).WithMetadata(%q, %d)%s\n", userMessage, reason, e.HTTPStatus, goErrorRecoveryCall(e)))
		buf.WriteString("}\n")
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated errors from %s: %w", sourcePath, err)
	}
	return formatted, nil
}

// errorReason 取 errors.yaml 的 reason，缺失时回退到 code 第三段。
func errorReason(e errorEntryYAML) string {
	reason := strings.TrimSpace(e.Reason)
	if reason == "" {
		parts := strings.Split(strings.TrimSpace(e.Code), ".")
		if len(parts) == 3 {
			reason = parts[2]
		}
	}
	if reason == "" {
		reason = "internal_error"
	}
	return reason
}

func goErrorRecoveryCall(e errorEntryYAML) string {
	action := strings.TrimSpace(e.RecoveryAction)
	if action == "" {
		return ""
	}
	if disruption := strings.TrimSpace(e.DisruptionLevel); disruption != "" {
		return fmt.Sprintf(
			".WithRecoveryDirective(%q, %q, %d)",
			action,
			disruption,
			e.RecoveryAfterSeconds,
		)
	}
	return fmt.Sprintf(".WithRecovery(%q, %d)", action, e.RecoveryAfterSeconds)
}
