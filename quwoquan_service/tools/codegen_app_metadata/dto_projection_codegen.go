func renderStandaloneDtoDart(proj clientProjection, sourcePath string) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from %s. DO NOT EDIT.\n", sourcePath))
	b.WriteString("// ignore_for_file: prefer_const_constructors, unnecessary_null_in_if_null_operators\n\n")
	for _, imp := range proj.DartImports {
		b.WriteString(fmt.Sprintf("import '%s';\n", imp))
	}
	if len(proj.DartImports) > 0 {
		b.WriteString("\n")
	}

	className := proj.DartClass
	if className == "" {
		className = "Dto"
	}
	b.WriteString(fmt.Sprintf("class %s {\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if f.Nullable && !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("  final %s %s;\n", dartType, f.Name))
	}
	// 非 const：DateTime / 集合默认值等在 const 构造下非法。
	b.WriteString("\n  " + className + "({\n")
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		if f.Nullable {
			b.WriteString(fmt.Sprintf("    this.%s,\n", f.Name))
		} else if proj.Strict {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		} else if md := mapEmptyCtorDefaultFromYaml(f, dt); md != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, md))
		} else if cd := constSafeCtorDefaultFromYaml(f, dt); cd != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, cd))
		} else if ld := listCtorDefaultConst(dt); ld != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, ld))
		} else {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		}
	}
	b.WriteString("  });\n\n")
	b.WriteString(fmt.Sprintf("  factory %s.fromMap(Map<String, dynamic> m) {\n", className))
	if proj.Strict {
		b.WriteString(fmt.Sprintf("    _validate%sWire(m);\n", className))
	}
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		resolver := buildAliasResolver(f)
		if proj.Strict {
			resolver = buildStrictProjectionResolver(f)
		}
		b.WriteString(fmt.Sprintf("      %s: %s,\n", f.Name, resolver))
	}
	b.WriteString("    );\n  }\n\n")
	b.WriteString("  Map<String, dynamic> toMap() {\n    return <String, dynamic>{\n")
	for _, f := range proj.Fields {
		key := f.Name
		value := f.Name
		if proj.Strict {
			key = projectionWireKey(f)
			value = strictProjectionToWireValue(f)
		}
		b.WriteString(fmt.Sprintf("      '%s': %s,\n", key, value))
	}
	b.WriteString("    };\n  }\n\n")

	b.WriteString(fmt.Sprintf("  %s copyWith({\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("    %s %s,\n", dartType, f.Name))
	}
	b.WriteString("  }) {\n")
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      %s: %s ?? this.%s,\n", f.Name, f.Name, f.Name))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n")

	if len(proj.ComputedGetters) > 0 {
		b.WriteString("\n")
		for _, g := range proj.ComputedGetters {
			returnType := strings.TrimSpace(g.DartReturnType)
			body := strings.TrimSpace(g.Body)
			if g.Description != "" {
				b.WriteString(fmt.Sprintf("  /// %s\n", g.Description))
			}
			b.WriteString(fmt.Sprintf("  %s get %s {\n", returnType, g.Name))
			for _, line := range strings.Split(body, "\n") {
				b.WriteString(fmt.Sprintf("    %s\n", strings.TrimSpace(line)))
			}
			b.WriteString("  }\n")
		}
	}

	b.WriteString("}\n\n")
	if proj.Strict {
		writeStrictProjectionValidator(&b, className, proj.Fields)
	}
	needsStringKeyMap := false
	needsDateTime := false
	needsStringList := false
	needsMapList := false
	needsProjectionDtoList := false
	needsFirstNonEmptyMapList := false
	needsFirstNonEmptyWireString := false
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		switch dt {
		case "Map<String, dynamic>":
			needsStringKeyMap = true
		case "DateTime":
			needsDateTime = true
		case "List<String>":
			needsStringList = true
		case "List<Map<String, dynamic>>":
			needsMapList = true
			keys := projectionFieldAliasKeys(f)
			if len(keys) > 1 {
				needsFirstNonEmptyMapList = true
			}
		}
		if f.ListElementDartClass != "" && strings.HasPrefix(dt, "List<") && strings.HasSuffix(dt, ">") {
			needsProjectionDtoList = true
		}
		if f.MapFromStringKeyClass != "" {
			needsStringKeyMap = true
		}
		if dt == "String" && f.SkipEmptyStringAliases {
			needsFirstNonEmptyWireString = true
		}
	}
	if needsFirstNonEmptyWireString {
		b.WriteString("String? _firstNonEmptyWireString(Map<String, dynamic> m, List<String> keys) {\n")
		b.WriteString("  for (final k in keys) {\n")
		b.WriteString("    final v = m[k]?.toString();\n")
		b.WriteString("    if (v != null && v.isNotEmpty) return v;\n")
		b.WriteString("  }\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n\n")
	}
	if needsDateTime {
		b.WriteString("DateTime? _parseDateTime(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is DateTime) return v;\n")
		b.WriteString("  if (v is String) return DateTime.tryParse(v);\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n\n")
	}
	if needsStringList {
		b.WriteString("List<String>? _parseStringList(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is List) return v.map((e) => e?.toString() ?? '').toList();\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	if needsMapList {
		b.WriteString("List<Map<String, dynamic>> _parseMapList(Object? v) {\n")
		b.WriteString("  if (v == null) return const <Map<String, dynamic>>[];\n")
		b.WriteString("  if (v is! List) return const <Map<String, dynamic>>[];\n")
		b.WriteString("  final out = <Map<String, dynamic>>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map) {\n")
		b.WriteString("      out.add(Map<String, dynamic>.from(e));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n\n")
	}
	if needsProjectionDtoList {
		b.WriteString("List<T> _parseProjectionDtoList<T>(\n")
		b.WriteString("  Object? v,\n")
		b.WriteString("  T Function(Map<String, dynamic> m) fromMap,\n")
		b.WriteString(") {\n")
		b.WriteString("  if (v == null) return List<T>.empty(growable: false);\n")
		b.WriteString("  if (v is! List) return List<T>.empty(growable: false);\n")
		b.WriteString("  final out = <T>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map<String, dynamic>) {\n")
		b.WriteString("      out.add(fromMap(e));\n")
		b.WriteString("    } else if (e is Map) {\n")
		b.WriteString("      out.add(fromMap(Map<String, dynamic>.from(e)));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n\n")
	}
	if needsFirstNonEmptyMapList {
		b.WriteString("List<Map<String, dynamic>> _firstNonEmptyMapList(Map<String, dynamic> m, List<String> keys) {\n")
		b.WriteString("  for (final k in keys) {\n")
		b.WriteString("    final parsed = _parseMapList(m[k]);\n")
		b.WriteString("    if (parsed.isNotEmpty) return parsed;\n")
		b.WriteString("  }\n")
		b.WriteString("  return const <Map<String, dynamic>>[];\n")
		b.WriteString("}\n\n")
	}
	if needsStringKeyMap {
		b.WriteString("\nMap<String, dynamic>? _parseStringKeyMap(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is Map<String, dynamic>) return v;\n")
		b.WriteString("  if (v is Map) {\n")
		b.WriteString("    return Map<String, dynamic>.from(\n")
		b.WriteString("      v.map((k, val) => MapEntry(k.toString(), val)),\n")
		b.WriteString("    );\n")
		b.WriteString("  }\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func projectionWireKey(f projectionFieldDef) string {
	if key := strings.TrimSpace(f.Source); key != "" {
		return key
	}
	return strings.TrimSpace(f.Name)
}

func buildStrictProjectionResolver(f projectionFieldDef) string {
	key := projectionWireKey(f)
	dartType := normalizeDartType(f.DartType)
	nullableSuffix := ""
	if f.Nullable {
		nullableSuffix = "?"
	}
	switch dartType {
	case "String", "int", "double", "bool":
		return fmt.Sprintf("m['%s'] as %s%s", key, dartType, nullableSuffix)
	case "DateTime":
		return fmt.Sprintf("m['%s'] == null ? null : DateTime.parse(m['%s'] as String)", key, key)
	case "List<String>":
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : List<String>.unmodifiable(List<String>.from(m['%s'] as List))", key, key)
		}
		return fmt.Sprintf("List<String>.unmodifiable(List<String>.from(m['%s'] as List))", key)
	case "Map<String, dynamic>":
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : Map<String, dynamic>.unmodifiable(Map<String, dynamic>.from(m['%s'] as Map))", key, key)
		}
		return fmt.Sprintf("Map<String, dynamic>.unmodifiable(Map<String, dynamic>.from(m['%s'] as Map))", key)
	default:
		return buildAliasResolver(f)
	}
}

func strictProjectionToWireValue(f projectionFieldDef) string {
	if f.MapFromStringKeyClass != "" {
		if f.Nullable {
			return fmt.Sprintf("%s?.toMap()", f.Name)
		}
		return fmt.Sprintf("%s.toMap()", f.Name)
	}
	if f.ListElementDartClass != "" {
		if f.Nullable {
			return fmt.Sprintf("%s?.map((value) => value.toMap()).toList(growable: false)", f.Name)
		}
		return fmt.Sprintf("%s.map((value) => value.toMap()).toList(growable: false)", f.Name)
	}
	if normalizeDartType(f.DartType) != "DateTime" {
		return f.Name
	}
	if f.Nullable {
		return fmt.Sprintf("%s?.toIso8601String()", f.Name)
	}
	return fmt.Sprintf("%s.toIso8601String()", f.Name)
}

func writeStrictProjectionValidator(b *strings.Builder, className string, fields []projectionFieldDef) {
	b.WriteString(fmt.Sprintf("void _validate%sWire(Map<String, dynamic> m) {\n", className))
	b.WriteString("  const allowed = <String>{\n")
	seen := map[string]bool{}
	for _, f := range fields {
		key := projectionWireKey(f)
		if !seen[key] {
			b.WriteString(fmt.Sprintf("    '%s',\n", key))
			seen[key] = true
		}
	}
	b.WriteString("  };\n")
	b.WriteString("  final unknown = m.keys.where((key) => !allowed.contains(key)).toList(growable: false);\n")
	b.WriteString("  if (unknown.isNotEmpty) {\n")
	b.WriteString(fmt.Sprintf("    throw FormatException('%s contains unknown fields: ${unknown.join(',')}');\n", className))
	b.WriteString("  }\n")
	for _, f := range fields {
		key := projectionWireKey(f)
		condition := strictProjectionInvalidCondition(f, key)
		if condition == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("  if (%s) {\n", condition))
		b.WriteString(fmt.Sprintf("    throw FormatException('%s.%s has an invalid wire value');\n", className, key))
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\n")
}

func strictProjectionInvalidCondition(f projectionFieldDef, key string) string {
	dartType := normalizeDartType(f.DartType)
	presentValue := fmt.Sprintf("m['%s']", key)
	typeCheck := ""
	if f.MapFromStringKeyClass != "" {
		typeCheck = fmt.Sprintf("%s is! Map || (%s as Map).keys.any((key) => key is! String)", presentValue, presentValue)
	} else if f.ListElementDartClass != "" {
		typeCheck = fmt.Sprintf("%s is! List || (%s as List).any((value) => value is! Map || (value as Map).keys.any((key) => key is! String))", presentValue, presentValue)
	}
	if typeCheck != "" {
		if f.Nullable {
			return fmt.Sprintf("m.containsKey('%s') && %s != null && (%s)", key, presentValue, typeCheck)
		}
		return fmt.Sprintf("!m.containsKey('%s') || %s == null || (%s)", key, presentValue, typeCheck)
	}
	switch dartType {
	case "String", "int", "double", "bool":
		typeCheck = fmt.Sprintf("%s is! %s", presentValue, dartType)
	case "DateTime":
		typeCheck = fmt.Sprintf("%s is! String || DateTime.tryParse(%s as String) == null", presentValue, presentValue)
	case "List<String>":
		typeCheck = fmt.Sprintf("%s is! List || (%s as List).any((value) => value is! String)", presentValue, presentValue)
	case "Map<String, dynamic>":
		typeCheck = fmt.Sprintf("%s is! Map || (%s as Map).keys.any((key) => key is! String)", presentValue, presentValue)
	default:
		return ""
	}
	if f.Nullable {
		return fmt.Sprintf("m.containsKey('%s') && %s != null && (%s)", key, presentValue, typeCheck)
	}
	return fmt.Sprintf("!m.containsKey('%s') || %s == null || (%s)", key, presentValue, typeCheck)
}

