func renderStandaloneDtoDart(proj clientProjection, sourcePath string) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from %s. DO NOT EDIT.\n", sourcePath))
	b.WriteString("// ignore_for_file: prefer_const_constructors, unnecessary_null_in_if_null_operators\n\n")
	for _, imp := range proj.DartImports {
		b.WriteString(fmt.Sprintf("import '%s';\n", imp))
	}
	if len(proj.DartImports) > 0 {
		b.WriteString("\n")
	}

	className := proj.DartClass
	if className == "" {
		className = "Dto"
	}
	b.WriteString(fmt.Sprintf("class %s {\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if f.Nullable && !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("  final %s %s;\n", dartType, f.Name))
	}
	// 非 const：DateTime / 集合默认值等在 const 构造下非法。
	b.WriteString("\n  " + className + "({\n")
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		if f.Nullable {
			b.WriteString(fmt.Sprintf("    this.%s,\n", f.Name))
		} else if md := mapEmptyCtorDefaultFromYaml(f, dt); md != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, md))
		} else if cd := constSafeCtorDefaultFromYaml(f, dt); cd != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, cd))
		} else if ld := listCtorDefaultConst(dt); ld != "" {
			b.WriteString(fmt.Sprintf("    this.%s = %s,\n", f.Name, ld))
		} else if proj.Strict {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		} else {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		}
	}
	b.WriteString("  });\n\n")
	b.WriteString(fmt.Sprintf("  factory %s.fromMap(Map<String, dynamic> m) {\n", className))
	if proj.Strict {
		b.WriteString(fmt.Sprintf("    _validate%sWire(m);\n", className))
	}
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		resolver := buildAliasResolver(f)
		if proj.Strict {
			resolver = buildStrictProjectionResolver(f, className)
		}
		b.WriteString(fmt.Sprintf("      %s: %s,\n", f.Name, resolver))
	}
	b.WriteString("    );\n  }\n\n")
	writeProjectionSourceFactory(&b, className, proj.Fields)
	b.WriteString("  Map<String, dynamic> toMap() {\n    return <String, dynamic>{\n")
	for _, f := range proj.Fields {
		key := projectionWireKey(f)
		value := f.Name
		if proj.Strict {
			value = strictProjectionToWireValue(f)
		}
		b.WriteString(fmt.Sprintf("      '%s': %s,\n", key, value))
	}
	b.WriteString("    };\n  }\n\n")

	b.WriteString(fmt.Sprintf("  %s copyWith({\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("    %s %s,\n", dartType, f.Name))
	}
	b.WriteString("  }) {\n")
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      %s: %s ?? this.%s,\n", f.Name, f.Name, f.Name))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n")

	if len(proj.ComputedGetters) > 0 {
		b.WriteString("\n")
		for _, g := range proj.ComputedGetters {
			returnType := strings.TrimSpace(g.DartReturnType)
			body := strings.TrimSpace(g.Body)
			if g.Description != "" {
				b.WriteString(fmt.Sprintf("  /// %s\n", g.Description))
			}
			b.WriteString(fmt.Sprintf("  %s get %s {\n", returnType, g.Name))
			for _, line := range strings.Split(body, "\n") {
				b.WriteString(fmt.Sprintf("    %s\n", strings.TrimSpace(line)))
			}
			b.WriteString("  }\n")
		}
	}

	b.WriteString("}\n\n")
	if proj.Strict {
		writeStrictProjectionValidator(&b, className, proj.Fields)
	}
	needsStringKeyMap := false
	needsDateTime := false
	needsStringList := false
	needsMapList := false
	needsProjectionDtoList := false
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		switch dt {
		case "Map<String, dynamic>":
			needsStringKeyMap = true
		case "DateTime":
			needsDateTime = !proj.Strict
		case "List<String>":
			needsStringList = !proj.Strict
		case "List<Map<String, dynamic>>":
			needsMapList = true
		}
		if f.ListElementDartClass != "" && strings.HasPrefix(dt, "List<") && strings.HasSuffix(dt, ">") {
			needsProjectionDtoList = true
		}
		if f.MapFromStringKeyClass != "" {
			needsStringKeyMap = true
		}
	}
	if needsDateTime {
		b.WriteString("DateTime? _parseDateTime(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is DateTime) return v;\n")
		b.WriteString("  if (v is String) return DateTime.tryParse(v);\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n\n")
	}
	if needsStringList {
		b.WriteString("List<String>? _parseStringList(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is List) return v.map((e) => e?.toString() ?? '').toList();\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	if needsMapList {
		b.WriteString("List<Map<String, dynamic>> _parseMapList(Object? v) {\n")
		b.WriteString("  if (v == null) return const <Map<String, dynamic>>[];\n")
		b.WriteString("  if (v is! List) return const <Map<String, dynamic>>[];\n")
		b.WriteString("  final out = <Map<String, dynamic>>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map) {\n")
		b.WriteString("      out.add(Map<String, dynamic>.from(e));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n\n")
	}
	if needsProjectionDtoList {
		b.WriteString("List<T> _parseProjectionDtoList<T>(\n")
		b.WriteString("  Object? v,\n")
		b.WriteString("  T Function(Map<String, dynamic> m) fromMap,\n")
		b.WriteString(") {\n")
		b.WriteString("  if (v == null) return List<T>.empty(growable: false);\n")
		b.WriteString("  if (v is! List) return List<T>.empty(growable: false);\n")
		b.WriteString("  final out = <T>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map<String, dynamic>) {\n")
		b.WriteString("      out.add(fromMap(e));\n")
		b.WriteString("    } else if (e is Map) {\n")
		b.WriteString("      out.add(fromMap(Map<String, dynamic>.from(e)));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n\n")
	}
	if needsStringKeyMap {
		b.WriteString("\nMap<String, dynamic>? _parseStringKeyMap(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is Map<String, dynamic>) return v;\n")
		b.WriteString("  if (v is Map) {\n")
		b.WriteString("    return Map<String, dynamic>.from(\n")
		b.WriteString("      v.map((k, val) => MapEntry(k.toString(), val)),\n")
		b.WriteString("    );\n")
		b.WriteString("  }\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// projectionWireKey is the JSON wire key for client projections.
// Always use field name; source only describes the storage/projection origin
// (e.g. Mongo `_id`) and must never appear as a client wire key.
func projectionWireKey(f projectionFieldDef) string {
	if wireName := strings.TrimSpace(f.WireName); wireName != "" {
		return wireName
	}
	return strings.TrimSpace(f.Name)
}

func projectionUsesTypedEnum(f projectionFieldDef) bool {
	enumRef := strings.TrimSpace(f.EnumRef)
	dartType := strings.TrimSuffix(normalizeDartType(f.DartType), "?")
	return enumRef != "" && dartType == enumRef
}

func buildStrictProjectionResolver(f projectionFieldDef, className string) string {
	key := projectionWireKey(f)
	dartType := normalizeDartType(f.DartType)
	if enumRef := strings.TrimSpace(f.EnumRef); projectionUsesTypedEnum(f) {
		decode := fmt.Sprintf("%s.fromWire(m['%s'])", enumRef, key)
		if f.DartEnumDecoderWithPath {
			decode = fmt.Sprintf(
				"%s.fromWire(m['%s'], '%s.%s')",
				enumRef,
				key,
				className,
				key,
			)
		}
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : %s", key, decode)
		}
		return decode
	}
	nullableSuffix := ""
	if f.Nullable {
		nullableSuffix = "?"
	}
	switch dartType {
	case "String", "int", "bool":
		return fmt.Sprintf("m['%s'] as %s%s", key, dartType, nullableSuffix)
	case "double":
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : (m['%s'] as num).toDouble()", key, key)
		}
		return fmt.Sprintf("(m['%s'] as num).toDouble()", key)
	case "DateTime":
		if !f.Nullable {
			return fmt.Sprintf("DateTime.parse(m['%s'] as String)", key)
		}
		return fmt.Sprintf("m['%s'] == null ? null : DateTime.parse(m['%s'] as String)", key, key)
	case "List<String>":
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : List<String>.unmodifiable(List<String>.from(m['%s'] as List))", key, key)
		}
		return fmt.Sprintf("List<String>.unmodifiable(List<String>.from(m['%s'] as List))", key)
	case "Map<String, dynamic>":
		if f.Nullable {
			return fmt.Sprintf("m['%s'] == null ? null : Map<String, dynamic>.unmodifiable(Map<String, dynamic>.from(m['%s'] as Map))", key, key)
		}
		return fmt.Sprintf("Map<String, dynamic>.unmodifiable(Map<String, dynamic>.from(m['%s'] as Map))", key)
	default:
		return buildAliasResolver(f)
	}
}

func strictProjectionToWireValue(f projectionFieldDef) string {
	if projectionUsesTypedEnum(f) {
		getter := strings.TrimSpace(f.DartEnumWireGetter)
		if getter == "" {
			getter = "wireValue"
		}
		if f.Nullable {
			return fmt.Sprintf("%s?.%s", f.Name, getter)
		}
		return fmt.Sprintf("%s.%s", f.Name, getter)
	}
	if f.MapFromStringKeyClass != "" {
		if f.Nullable {
			return fmt.Sprintf("%s?.toMap()", f.Name)
		}
		return fmt.Sprintf("%s.toMap()", f.Name)
	}
	if f.ListElementDartClass != "" {
		if f.Nullable {
			return fmt.Sprintf("%s?.map((value) => value.toMap()).toList(growable: false)", f.Name)
		}
		return fmt.Sprintf("%s.map((value) => value.toMap()).toList(growable: false)", f.Name)
	}
	if normalizeDartType(f.DartType) != "DateTime" {
		return f.Name
	}
	if f.Nullable {
		return fmt.Sprintf("%s?.toIso8601String()", f.Name)
	}
	return fmt.Sprintf("%s.toIso8601String()", f.Name)
}

func writeStrictProjectionValidator(b *strings.Builder, className string, fields []projectionFieldDef) {
	b.WriteString(fmt.Sprintf("void _validate%sWire(Map<String, dynamic> m) {\n", className))
	b.WriteString("  const allowed = <String>{\n")
	seen := map[string]bool{}
	for _, f := range fields {
		key := projectionWireKey(f)
		if !seen[key] {
			b.WriteString(fmt.Sprintf("    '%s',\n", key))
			seen[key] = true
		}
	}
	b.WriteString("  };\n")
	b.WriteString("  final unknown = m.keys.where((key) => !allowed.contains(key)).toList(growable: false);\n")
	b.WriteString("  if (unknown.isNotEmpty) {\n")
	b.WriteString(fmt.Sprintf("    throw FormatException('%s contains unknown fields: ${unknown.join(',')}');\n", className))
	b.WriteString("  }\n")
	for _, f := range fields {
		key := projectionWireKey(f)
		condition := strictProjectionInvalidCondition(f, key)
		if condition == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("  if (%s) {\n", condition))
		b.WriteString(fmt.Sprintf("    throw FormatException('%s.%s has an invalid wire value');\n", className, key))
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\n")
}

func strictProjectionInvalidCondition(f projectionFieldDef, key string) string {
	dartType := normalizeDartType(f.DartType)
	presentValue := fmt.Sprintf("m['%s']", key)
	typeCheck := ""
	if strings.TrimSpace(f.EnumRef) != "" {
		typeCheck = fmt.Sprintf("%s is! String", presentValue)
	}
	if typeCheck != "" {
		// Canonical enum parsing is performed by Enum.fromWire in fromMap;
		// the validator owns only the JSON scalar shape.
	} else if f.MapFromStringKeyClass != "" {
		typeCheck = fmt.Sprintf("%s is! Map || (%s as Map).keys.any((key) => key is! String)", presentValue, presentValue)
	} else if f.ListElementDartClass != "" {
		typeCheck = fmt.Sprintf("%s is! List || (%s as List).any((value) => value is! Map || value.keys.any((key) => key is! String))", presentValue, presentValue)
	}
	if typeCheck != "" {
		if f.Nullable {
			return fmt.Sprintf("m.containsKey('%s') && %s != null && (%s)", key, presentValue, typeCheck)
		}
		return fmt.Sprintf("!m.containsKey('%s') || %s == null || (%s)", key, presentValue, typeCheck)
	}
	switch dartType {
	case "String", "int", "bool":
		typeCheck = fmt.Sprintf("%s is! %s", presentValue, dartType)
	case "double":
		typeCheck = fmt.Sprintf("%s is! num", presentValue)
	case "DateTime":
		typeCheck = fmt.Sprintf("%s is! String || DateTime.tryParse(%s as String) == null", presentValue, presentValue)
	case "List<String>":
		typeCheck = fmt.Sprintf("%s is! List || (%s as List).any((value) => value is! String)", presentValue, presentValue)
	case "Map<String, dynamic>":
		typeCheck = fmt.Sprintf("%s is! Map || (%s as Map).keys.any((key) => key is! String)", presentValue, presentValue)
	default:
		return ""
	}
	if f.Nullable {
		return fmt.Sprintf("m.containsKey('%s') && %s != null && (%s)", key, presentValue, typeCheck)
	}
	return fmt.Sprintf("!m.containsKey('%s') || %s == null || (%s)", key, presentValue, typeCheck)
}

func shouldAnnotateOverrideForComputedGetter(baseClass, getterName string) bool {
	if strings.TrimSpace(baseClass) != "ContentPostViewData" {
		return false
	}
	return postBaseDtoComputedGetters[strings.TrimSpace(getterName)]
}

// renderTypedPostDtoDart generates a typed DTO that extends a base class (e.g. ContentPostViewData).
func renderTypedPostDtoDart(proj clientProjection, sourceFile string) string {
	var b strings.Builder
	className := proj.DartClass
	baseClass := proj.BaseClass

	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from content/content/post/projections/%s. DO NOT EDIT.\n", sourceFile))
	b.WriteString("// ignore_for_file: prefer_const_constructors, unnecessary_null_in_if_null_operators\n\n")
	if baseClass != "" {
		b.WriteString("import 'package:quwoquan_app/service/content_service/content/post/application/public/content_post_view_data.dart';\n\n")
	}
	for _, imp := range proj.DartImports {
		b.WriteString(fmt.Sprintf("import '%s';\n", imp))
	}
	if len(proj.DartImports) > 0 {
		b.WriteString("\n")
	}

	// Class declaration with base class
	b.WriteString(fmt.Sprintf("class %s extends %s {\n", className, baseClass))

	// Fields
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if f.Nullable && !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		if postBaseDtoFields[f.Name] {
			b.WriteString(fmt.Sprintf("  @override final %s %s;\n", dartType, f.Name))
		} else {
			b.WriteString(fmt.Sprintf("  final %s %s;\n", dartType, f.Name))
		}
	}
	b.WriteString("\n")

	// Constructor
	b.WriteString(fmt.Sprintf("  const %s({\n", className))
	for _, f := range proj.Fields {
		if f.Nullable {
			b.WriteString(fmt.Sprintf("    this.%s,\n", f.Name))
		} else {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		}
	}
	b.WriteString("  });\n\n")

	// fromMap factory
	b.WriteString(fmt.Sprintf("  factory %s.fromMap(Map<String, dynamic> m) {\n", className))
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		resolver := buildAliasResolver(f)
		b.WriteString(fmt.Sprintf("      %s: %s,\n", f.Name, resolver))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n\n")
	writeProjectionSourceFactory(&b, className, proj.Fields)

	// toMap override
	b.WriteString("  @override\n")
	b.WriteString("  Map<String, dynamic> toMap() {\n")
	b.WriteString("    return <String, dynamic>{\n")
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      '%s': %s,\n", projectionWireKey(f), f.Name))
	}
	b.WriteString("    };\n")
	b.WriteString("  }\n\n")

	// copyWith
	b.WriteString(fmt.Sprintf("  %s copyWith({\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("    %s %s,\n", dartType, f.Name))
	}
	b.WriteString("  }) {\n")
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      %s: %s ?? this.%s,\n", f.Name, f.Name, f.Name))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n")

	// Computed getters
	if len(proj.ComputedGetters) > 0 {
		b.WriteString("\n")
		for _, g := range proj.ComputedGetters {
			returnType := strings.TrimSpace(g.DartReturnType)
			body := strings.TrimSpace(g.Body)
			if g.Description != "" {
				b.WriteString(fmt.Sprintf("  /// %s\n", g.Description))
			}
			if shouldAnnotateOverrideForComputedGetter(baseClass, g.Name) {
				b.WriteString("  @override\n")
			}
			b.WriteString(fmt.Sprintf("  %s get %s {\n", returnType, g.Name))
			for _, line := range strings.Split(body, "\n") {
				b.WriteString(fmt.Sprintf("    %s\n", strings.TrimSpace(line)))
			}
			b.WriteString("  }\n")
		}
	}

	b.WriteString("}\n\n")

	// Helper functions used by fromMap (only if needed)
	needsDateTime := false
	needsStringList := false
	needsStringKeyMap := false
	needsProjectionDtoList := false
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		if dt == "DateTime" {
			needsDateTime = true
		}
		if dt == "List<String>" {
			needsStringList = true
		}
		if dt == "Map<String, dynamic>" || f.MapFromStringKeyClass != "" {
			needsStringKeyMap = true
		}
		if f.ListElementDartClass != "" && strings.HasPrefix(dt, "List<") && strings.HasSuffix(dt, ">") {
			needsProjectionDtoList = true
		}
	}

	if needsDateTime {
		b.WriteString("DateTime? _parseDateTime(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is DateTime) return v;\n")
		b.WriteString("  if (v is String) return DateTime.tryParse(v);\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n\n")
	}
	if needsStringList {
		b.WriteString("List<String>? _parseStringList(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is List) return v.map((e) => e?.toString() ?? '').toList();\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	if needsStringKeyMap {
		b.WriteString("\nMap<String, dynamic>? _parseStringKeyMap(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is Map<String, dynamic>) return v;\n")
		b.WriteString("  if (v is Map) {\n")
		b.WriteString("    return Map<String, dynamic>.from(\n")
		b.WriteString("      v.map((k, val) => MapEntry(k.toString(), val)),\n")
		b.WriteString("    );\n")
		b.WriteString("  }\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	if needsProjectionDtoList {
		b.WriteString("\nList<T> _parseProjectionDtoList<T>(\n")
		b.WriteString("  Object? v,\n")
		b.WriteString("  T Function(Map<String, dynamic> m) fromMap,\n")
		b.WriteString(") {\n")
		b.WriteString("  if (v == null) return List<T>.empty(growable: false);\n")
		b.WriteString("  if (v is! List) return List<T>.empty(growable: false);\n")
		b.WriteString("  final out = <T>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map<String, dynamic>) {\n")
		b.WriteString("      out.add(fromMap(e));\n")
		b.WriteString("    } else if (e is Map) {\n")
		b.WriteString("      out.add(fromMap(Map<String, dynamic>.from(e)));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n")
	}

	return b.String()
}

// buildAliasResolver generates the fromMap expression for a single canonical wire key.
func buildAliasResolver(f projectionFieldDef) string {
	dartType := normalizeDartType(f.DartType)
	defaultVal := f.Default
	if defaultVal == "" {
		if f.Nullable {
			defaultVal = "null"
		} else {
			defaultVal = defaultForType(dartType)
		}
	}

	key := projectionWireKey(f)
	deduped := []string{}
	if key != "" {
		deduped = []string{key}
	}

	if f.ListElementDartClass != "" && strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
		if len(deduped) == 0 {
			return defaultVal
		}
		if f.Nullable {
			return fmt.Sprintf(
				"m['%s'] == null ? null : _parseProjectionDtoList(m['%s'], %s.fromMap)",
				key, key, f.ListElementDartClass,
			)
		}
		return fmt.Sprintf(
			"_parseProjectionDtoList(m['%s'], %s.fromMap)",
			key,
			f.ListElementDartClass,
		)
	}

	if f.MapFromStringKeyClass != "" {
		if len(deduped) == 0 {
			return defaultVal
		}
		cls := f.MapFromStringKeyClass
		if f.Nullable {
			return fmt.Sprintf(
				"m['%s'] == null ? null : %s.fromMap(_parseStringKeyMap(m['%s'])!)",
				key, cls, key,
			)
		}
		return fmt.Sprintf(
			"%s.fromMap(_parseStringKeyMap(m['%s']) ?? <String, dynamic>{})",
			cls, key,
		)
	}

	if enumRef := strings.TrimSpace(f.EnumRef); projectionUsesTypedEnum(f) {
		if len(deduped) == 0 {
			return defaultVal
		}
		if f.Nullable {
			return fmt.Sprintf(
				"m['%s'] == null ? null : %s.fromWire(m['%s'])",
				key,
				enumRef,
				key,
			)
		}
		return fmt.Sprintf("%s.fromWire(m['%s'])", enumRef, key)
	}

	switch dartType {
	case "String":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("m['%s']?.toString()", k)
		}
		if len(parts) == 0 {
			return defaultVal
		}
		return parts[0] + fmt.Sprintf(" ?? %s", defaultVal)

	case "int":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("(m['%s'] as num?)?.toInt()", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "double":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("(m['%s'] as num?)?.toDouble()", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "bool":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("m['%s'] as bool?", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "DateTime":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseDateTime(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "List<String>":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseStringList(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "List<Map<String, dynamic>>":
		if len(deduped) == 0 {
			return defaultVal
		}
		return fmt.Sprintf("_parseMapList(m['%s'])", deduped[0])

	case "Map<String, dynamic>":
		if len(deduped) == 0 {
			return defaultVal
		}
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseStringKeyMap(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	default:
		// fallback: raw cast
		if len(deduped) == 0 {
			return defaultVal
		}
		return fmt.Sprintf("m['%s'] as %s? ?? %s", deduped[0], dartType, defaultVal)
	}
}

// writeProjectionSourceFactory emits the metadata-owned read-model projection
// boundary. Public client wire continues to use field names; source names are
// accepted only by this explicit factory so fixtures and adapters do not copy
// field mappings into hand-written code.
func writeProjectionSourceFactory(
	b *strings.Builder,
	className string,
	fields []projectionFieldDef,
) {
	hasDistinctSource := false
	for _, field := range fields {
		source := strings.TrimSpace(field.Source)
		if source != "" && source != strings.TrimSpace(field.Name) {
			hasDistinctSource = true
			break
		}
	}
	if !hasDistinctSource {
		return
	}

	b.WriteString(fmt.Sprintf(
		"  factory %s.fromReadModelMap(Map<String, dynamic> source) {\n",
		className,
	))
	b.WriteString(fmt.Sprintf("    return %s.fromMap(<String, dynamic>{\n", className))
	for _, field := range fields {
		key := strings.TrimSpace(field.Name)
		source := strings.TrimSpace(field.Source)
		if source == "" {
			source = key
		}
		b.WriteString(fmt.Sprintf("      '%s': source['%s'],\n", key, source))
	}
	b.WriteString("    });\n")
	b.WriteString("  }\n\n")
}

func normalizeDartType(t string) string {
	t = strings.TrimSpace(t)
	t = strings.TrimSuffix(t, "?")
	return t
}

func defaultForType(dartType string) string {
	switch dartType {
	case "String":
		return "''"
	case "int":
		return "0"
	case "double":
		return "0.0"
	case "bool":
		return "false"
	case "List<String>":
		return "<String>[]"
	case "List<Map<String, dynamic>>":
		return "const <Map<String, dynamic>>[]"
	case "Map<String, dynamic>":
		return "<String, dynamic>{}"
	case "DateTime":
		return "DateTime(0)"
	default:
		if strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
			inner := strings.TrimSuffix(strings.TrimPrefix(dartType, "List<"), ">")
			return fmt.Sprintf("<%s>[]", inner)
		}
		return "null"
	}
}

// listCtorDefaultConst returns a const empty list default for non-nullable List<...> ctor params.
func mapEmptyCtorDefaultFromYaml(f projectionFieldDef, dt string) string {
	if dt != "Map<String, dynamic>" {
		return ""
	}
	d := strings.TrimSpace(f.Default)
	if d == "<String, dynamic>{}" || d == "{}" {
		return "const <String, dynamic>{}"
	}
	return ""
}

func listCtorDefaultConst(dartType string) string {
	switch dartType {
	case "List<String>":
		return "const <String>[]"
	case "List<Map<String, dynamic>>":
		return "const <Map<String, dynamic>>[]"
	default:
		if strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
			inner := strings.TrimSuffix(strings.TrimPrefix(dartType, "List<"), ">")
			return fmt.Sprintf("const <%s>[]", inner)
		}
	}
	return ""
}

// constSafeCtorDefaultFromYaml emits const-constructor-safe defaults from YAML `default`
// (int/double/bool/string literals only). Skips DateTime/Map/List — those use listCtorDefaultConst or required.
func constSafeCtorDefaultFromYaml(f projectionFieldDef, dt string) string {
	d := strings.TrimSpace(f.Default)
	if d == "" {
		return ""
	}
	switch dt {
	case "int":
		for _, r := range d {
			if r < '0' || r > '9' {
				return ""
			}
		}
		return d
	case "double":
		ok := true
		dot := false
		for i, r := range d {
			if i == 0 && r == '-' {
				continue
			}
			if r == '.' {
				if dot {
					ok = false
					break
				}
				dot = true
				continue
			}
			if r < '0' || r > '9' {
				ok = false
				break
			}
		}
		if !ok || d == "." || d == "-" {
			return ""
		}
		return d
	case "bool":
		if d == "true" || d == "false" {
			return d
		}
		return ""
	case "String":
		return d
	default:
		return ""
	}
}

