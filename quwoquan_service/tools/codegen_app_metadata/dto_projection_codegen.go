// renderTypedPostDtoDart generates a typed DTO that extends a base class (e.g. PostBaseDto).
func renderTypedPostDtoDart(proj clientProjection, sourceFile string) string {
	var b strings.Builder
	className := proj.DartClass
	baseClass := proj.BaseClass

	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from content/post/projections/%s. DO NOT EDIT.\n", sourceFile))
	b.WriteString("// ignore_for_file: prefer_const_constructors, unnecessary_null_in_if_null_operators\n\n")
	if baseClass != "" {
		b.WriteString("import 'package:quwoquan_app/cloud/runtime/generated/content/post_base_dto.dart';\n\n")
	}
	for _, imp := range proj.DartImports {
		b.WriteString(fmt.Sprintf("import '%s';\n", imp))
	}
	if len(proj.DartImports) > 0 {
		b.WriteString("\n")
	}

	// Class declaration with base class
	b.WriteString(fmt.Sprintf("class %s extends %s {\n", className, baseClass))

	// Fields
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if f.Nullable && !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		if postBaseDtoFields[f.Name] {
			b.WriteString(fmt.Sprintf("  @override final %s %s;\n", dartType, f.Name))
		} else {
			b.WriteString(fmt.Sprintf("  final %s %s;\n", dartType, f.Name))
		}
	}
	b.WriteString("\n")

	// Constructor
	b.WriteString(fmt.Sprintf("  const %s({\n", className))
	for _, f := range proj.Fields {
		if f.Nullable {
			b.WriteString(fmt.Sprintf("    this.%s,\n", f.Name))
		} else {
			b.WriteString(fmt.Sprintf("    required this.%s,\n", f.Name))
		}
	}
	b.WriteString("  });\n\n")

	// fromMap factory
	b.WriteString(fmt.Sprintf("  factory %s.fromMap(Map<String, dynamic> m) {\n", className))
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		resolver := buildAliasResolver(f)
		b.WriteString(fmt.Sprintf("      %s: %s,\n", f.Name, resolver))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n\n")

	// toMap override
	b.WriteString("  @override\n")
	b.WriteString("  Map<String, dynamic> toMap() {\n")
	b.WriteString("    return <String, dynamic>{\n")
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      '%s': %s,\n", f.Name, f.Name))
	}
	b.WriteString("    };\n")
	b.WriteString("  }\n\n")

	// copyWith
	b.WriteString(fmt.Sprintf("  %s copyWith({\n", className))
	for _, f := range proj.Fields {
		dartType := normalizeDartType(f.DartType)
		if !strings.HasSuffix(dartType, "?") {
			dartType += "?"
		}
		b.WriteString(fmt.Sprintf("    %s %s,\n", dartType, f.Name))
	}
	b.WriteString("  }) {\n")
	b.WriteString(fmt.Sprintf("    return %s(\n", className))
	for _, f := range proj.Fields {
		b.WriteString(fmt.Sprintf("      %s: %s ?? this.%s,\n", f.Name, f.Name, f.Name))
	}
	b.WriteString("    );\n")
	b.WriteString("  }\n")

	// Computed getters
	if len(proj.ComputedGetters) > 0 {
		b.WriteString("\n")
		for _, g := range proj.ComputedGetters {
			returnType := strings.TrimSpace(g.DartReturnType)
			body := strings.TrimSpace(g.Body)
			if g.Description != "" {
				b.WriteString(fmt.Sprintf("  /// %s\n", g.Description))
			}
			if shouldAnnotateOverrideForComputedGetter(baseClass, g.Name) {
				b.WriteString("  @override\n")
			}
			b.WriteString(fmt.Sprintf("  %s get %s {\n", returnType, g.Name))
			for _, line := range strings.Split(body, "\n") {
				b.WriteString(fmt.Sprintf("    %s\n", strings.TrimSpace(line)))
			}
			b.WriteString("  }\n")
		}
	}

	b.WriteString("}\n\n")

	// Helper functions used by fromMap (only if needed)
	needsDateTime := false
	needsStringList := false
	needsProjectionDtoList := false
	for _, f := range proj.Fields {
		dt := normalizeDartType(f.DartType)
		if dt == "DateTime" {
			needsDateTime = true
		}
		if dt == "List<String>" {
			needsStringList = true
		}
		if f.ListElementDartClass != "" && strings.HasPrefix(dt, "List<") && strings.HasSuffix(dt, ">") {
			needsProjectionDtoList = true
		}
	}

	if needsDateTime {
		b.WriteString("DateTime? _parseDateTime(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is DateTime) return v;\n")
		b.WriteString("  if (v is String) return DateTime.tryParse(v);\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n\n")
	}
	if needsStringList {
		b.WriteString("List<String>? _parseStringList(dynamic v) {\n")
		b.WriteString("  if (v == null) return null;\n")
		b.WriteString("  if (v is List) return v.map((e) => e?.toString() ?? '').toList();\n")
		b.WriteString("  return null;\n")
		b.WriteString("}\n")
	}
	if needsProjectionDtoList {
		b.WriteString("\nList<T> _parseProjectionDtoList<T>(\n")
		b.WriteString("  Object? v,\n")
		b.WriteString("  T Function(Map<String, dynamic> m) fromMap,\n")
		b.WriteString(") {\n")
		b.WriteString("  if (v == null) return List<T>.empty(growable: false);\n")
		b.WriteString("  if (v is! List) return List<T>.empty(growable: false);\n")
		b.WriteString("  final out = <T>[];\n")
		b.WriteString("  for (final e in v) {\n")
		b.WriteString("    if (e is Map<String, dynamic>) {\n")
		b.WriteString("      out.add(fromMap(e));\n")
		b.WriteString("    } else if (e is Map) {\n")
		b.WriteString("      out.add(fromMap(Map<String, dynamic>.from(e)));\n")
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("  return out;\n")
		b.WriteString("}\n")
	}

	return b.String()
}

// projectionFieldAliasKeys returns source + aliases for a field, deduplicated.
func projectionFieldAliasKeys(f projectionFieldDef) []string {
	allKeys := []string{f.Source}
	for _, a := range f.Aliases {
		if a != f.Source {
			allKeys = append(allKeys, a)
		}
	}
	seen := map[string]bool{}
	deduped := []string{}
	for _, k := range allKeys {
		if !seen[k] {
			seen[k] = true
			deduped = append(deduped, k)
		}
	}
	return deduped
}

// buildAliasResolver generates the fromMap expression for a single field,
// trying each alias key in order until a non-null value is found.
func buildAliasResolver(f projectionFieldDef) string {
	dartType := normalizeDartType(f.DartType)
	defaultVal := f.Default
	if defaultVal == "" {
		if f.Nullable {
			defaultVal = "null"
		} else {
			defaultVal = defaultForType(dartType)
		}
	}

	deduped := projectionFieldAliasKeys(f)

	if f.ListElementDartClass != "" && strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
		if len(deduped) == 0 {
			return defaultVal
		}
		key := deduped[0]
		if f.Nullable {
			return fmt.Sprintf(
				"m['%s'] == null ? null : _parseProjectionDtoList(m['%s'], %s.fromMap)",
				key, key, f.ListElementDartClass,
			)
		}
		return fmt.Sprintf(
			"_parseProjectionDtoList(m['%s'], %s.fromMap)",
			key,
			f.ListElementDartClass,
		)
	}

	if f.MapFromStringKeyClass != "" {
		if len(deduped) == 0 {
			return defaultVal
		}
		key := deduped[0]
		cls := f.MapFromStringKeyClass
		if f.Nullable {
			return fmt.Sprintf(
				"m['%s'] == null ? null : %s.fromMap(_parseStringKeyMap(m['%s'])!)",
				key, cls, key,
			)
		}
		return fmt.Sprintf(
			"%s.fromMap(_parseStringKeyMap(m['%s']) ?? <String, dynamic>{})",
			cls, key,
		)
	}

	switch dartType {
	case "String":
		if f.SkipEmptyStringAliases && len(deduped) > 0 {
			quoted := make([]string, len(deduped))
			for i, k := range deduped {
				quoted[i] = fmt.Sprintf("'%s'", k)
			}
			return fmt.Sprintf(
				"_firstNonEmptyWireString(m, <String>[%s]) ?? %s",
				strings.Join(quoted, ", "),
				defaultVal,
			)
		}
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("m['%s']?.toString()", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "int":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("(m['%s'] as num?)?.toInt()", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "double":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("(m['%s'] as num?)?.toDouble()", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "bool":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("m['%s'] as bool?", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "DateTime":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseDateTime(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "List<String>":
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseStringList(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	case "List<Map<String, dynamic>>":
		if len(deduped) == 0 {
			return defaultVal
		}
		if len(deduped) == 1 {
			return fmt.Sprintf("_parseMapList(m['%s'])", deduped[0])
		}
		quoted := make([]string, len(deduped))
		for i, k := range deduped {
			quoted[i] = fmt.Sprintf("'%s'", k)
		}
		return fmt.Sprintf("_firstNonEmptyMapList(m, <String>[%s])", strings.Join(quoted, ", "))

	case "Map<String, dynamic>":
		if len(deduped) == 0 {
			return defaultVal
		}
		parts := make([]string, len(deduped))
		for i, k := range deduped {
			parts[i] = fmt.Sprintf("_parseStringKeyMap(m['%s'])", k)
		}
		return strings.Join(parts, " ?? ") + fmt.Sprintf(" ?? %s", defaultVal)

	default:
		// fallback: raw cast
		if len(deduped) == 0 {
			return defaultVal
		}
		return fmt.Sprintf("m['%s'] as %s? ?? %s", deduped[0], dartType, defaultVal)
	}
}

func normalizeDartType(t string) string {
	t = strings.TrimSpace(t)
	t = strings.TrimSuffix(t, "?")
	return t
}

func defaultForType(dartType string) string {
	switch dartType {
	case "String":
		return "''"
	case "int":
		return "0"
	case "double":
		return "0.0"
	case "bool":
		return "false"
	case "List<String>":
		return "<String>[]"
	case "List<Map<String, dynamic>>":
		return "const <Map<String, dynamic>>[]"
	case "DateTime":
		return "DateTime(0)"
	default:
		if strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
			inner := strings.TrimSuffix(strings.TrimPrefix(dartType, "List<"), ">")
			return fmt.Sprintf("<%s>[]", inner)
		}
		return "null"
	}
}

// listCtorDefaultConst returns a const empty list default for non-nullable List<...> ctor params.
func mapEmptyCtorDefaultFromYaml(f projectionFieldDef, dt string) string {
	if dt != "Map<String, dynamic>" {
		return ""
	}
	d := strings.TrimSpace(f.Default)
	if d == "<String, dynamic>{}" || d == "{}" {
		return "const <String, dynamic>{}"
	}
	return ""
}

func listCtorDefaultConst(dartType string) string {
	switch dartType {
	case "List<String>":
		return "const <String>[]"
	case "List<Map<String, dynamic>>":
		return "const <Map<String, dynamic>>[]"
	default:
		if strings.HasPrefix(dartType, "List<") && strings.HasSuffix(dartType, ">") {
			inner := strings.TrimSuffix(strings.TrimPrefix(dartType, "List<"), ">")
			return fmt.Sprintf("const <%s>[]", inner)
		}
	}
	return ""
}

// constSafeCtorDefaultFromYaml emits const-constructor-safe defaults from YAML `default`
// (int/double/bool/string literals only). Skips DateTime/Map/List — those use listCtorDefaultConst or required.
func constSafeCtorDefaultFromYaml(f projectionFieldDef, dt string) string {
	d := strings.TrimSpace(f.Default)
	if d == "" {
		return ""
	}
	switch dt {
	case "int":
		for _, r := range d {
			if r < '0' || r > '9' {
				return ""
			}
		}
		return d
	case "double":
		ok := true
		dot := false
		for i, r := range d {
			if i == 0 && r == '-' {
				continue
			}
			if r == '.' {
				if dot {
					ok = false
					break
				}
				dot = true
				continue
			}
			if r < '0' || r > '9' {
				ok = false
				break
			}
		}
		if !ok || d == "." || d == "-" {
			return ""
		}
		return d
	case "bool":
		if d == "true" || d == "false" {
			return d
		}
		return ""
	case "String":
		return d
	default:
		return ""
	}
}

