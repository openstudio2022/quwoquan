package main

import (
	"fmt"
	"sort"
	"strings"
)

var telemetryCommonFields = []string{
	"logType",
	"eventType",
	"sessionId",
	"pageName",
	"occurredAt",
	"deviceManufacturer",
	"deviceModel",
	"appVersion",
	"networkClass",
}

func validateTelemetryMetadata(
	catalog *telemetryEventCatalogFile,
	pages *appPagesFile,
	routes *appRoutesFile,
) error {
	if catalog == nil || pages == nil || routes == nil {
		return fmt.Errorf("telemetry metadata requires event_catalog.yaml, app_pages.yaml and app_routes.yaml")
	}
	if strings.Join(catalog.CommonFields, ",") != strings.Join(telemetryCommonFields, ",") {
		return fmt.Errorf("telemetry common_fields must be the frozen nine-field envelope in canonical order")
	}
	if strings.Join(catalog.ContextExtensions, ",") != "devicePlatform" {
		return fmt.Errorf("telemetry context_extensions must be [devicePlatform]")
	}
	if strings.Join(catalog.LogTypes, ",") != "event,error" {
		return fmt.Errorf("telemetry log_types must be [event, error]")
	}
	if strings.Join(catalog.NetworkClasses, ",") != "wifi,ethernet,5g,4g,mobile,other,none" {
		return fmt.Errorf("telemetry network_classes must be [wifi, ethernet, 5g, 4g, mobile, other, none]")
	}
	allowedExtensionTypes := map[string]bool{
		"string": true, "int": true, "double": true, "bool": true, "string_list": true,
	}
	for name, extension := range catalog.ExtensionFields {
		if strings.TrimSpace(name) == "" || !allowedExtensionTypes[extension.Type] {
			return fmt.Errorf("invalid telemetry extension %q type %q", name, extension.Type)
		}
	}
	for _, field := range catalog.ContextExtensions {
		if _, ok := catalog.ExtensionFields[field]; !ok {
			return fmt.Errorf("telemetry context extension references unknown extension %s", field)
		}
	}
	seenEvents := map[string]bool{}
	for _, event := range catalog.Events {
		if event.EventType == "" || seenEvents[event.EventType] {
			return fmt.Errorf("telemetry event_type must be non-empty and unique: %q", event.EventType)
		}
		seenEvents[event.EventType] = true
		if event.LogType != "event" && event.LogType != "error" {
			return fmt.Errorf("telemetry event %s has invalid log_type %q", event.EventType, event.LogType)
		}
		if event.NormalSampleRate < 0 || event.NormalSampleRate > 1 {
			return fmt.Errorf("telemetry event %s has invalid sample rate", event.EventType)
		}
		seenExtensions := map[string]bool{}
		for _, field := range append(append([]string{}, event.RequiredExtensions...), event.OptionalExtensions...) {
			if _, ok := catalog.ExtensionFields[field]; !ok {
				return fmt.Errorf("telemetry event %s references unknown extension %s", event.EventType, field)
			}
			if seenExtensions[field] {
				return fmt.Errorf("telemetry event %s repeats extension %s", event.EventType, field)
			}
			seenExtensions[field] = true
		}
		if event.LogType == "error" && !seenExtensions["errorCode"] {
			return fmt.Errorf("telemetry error event %s must declare errorCode", event.EventType)
		}
	}

	routeIDs := map[string]bool{}
	for _, route := range routes.Routes {
		routeIDs[route.ID] = true
	}
	pageRouteIDs := map[string]bool{}
	pageNames := map[string]bool{}
	for _, page := range pages.Pages {
		if page.PageName == "" || page.RouteID == "" || !routeIDs[page.RouteID] {
			return fmt.Errorf("invalid app page mapping page=%q route_id=%q", page.PageName, page.RouteID)
		}
		if pageRouteIDs[page.RouteID] {
			return fmt.Errorf("duplicate app page route_id %s", page.RouteID)
		}
		pageRouteIDs[page.RouteID] = true
		pageNames[page.PageName] = true
	}
	for routeID := range routeIDs {
		if !pageRouteIDs[routeID] {
			return fmt.Errorf("app_pages.yaml does not classify route_id %s", routeID)
		}
	}
	seenInternalIDs := map[string]bool{}
	seenInternalLocations := map[string]bool{}
	for _, page := range pages.InternalPages {
		if page.PageName == "" || page.InternalID == "" || page.Location == "" {
			return fmt.Errorf("invalid internal app page mapping: %+v", page)
		}
		if seenInternalIDs[page.InternalID] || seenInternalLocations[page.Location] {
			return fmt.Errorf("duplicate internal app page id/location: %s %s", page.InternalID, page.Location)
		}
		seenInternalIDs[page.InternalID] = true
		seenInternalLocations[page.Location] = true
		pageNames[page.PageName] = true
	}
	for _, context := range pages.FallbackContexts {
		if context == "" || pageNames[context] {
			return fmt.Errorf("invalid or colliding app page fallback context %q", context)
		}
		pageNames[context] = true
	}
	return nil
}

func renderAppTelemetryCatalogDart(catalog *telemetryEventCatalogFile) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from ops/event_record/event_catalog.yaml. DO NOT EDIT.\n// ignore_for_file: use_null_aware_elements\n\n")
	b.WriteString("class AppTelemetryEventDefinition {\n")
	b.WriteString("  const AppTelemetryEventDefinition({required this.eventType, required this.logType, required this.requiredExtensions, required this.optionalExtensions, required this.normalSampleRate, required this.slowThresholdMs, required this.internalPriority});\n")
	b.WriteString("  final String eventType;\n  final String logType;\n  final Set<String> requiredExtensions;\n  final Set<String> optionalExtensions;\n  final double normalSampleRate;\n  final int slowThresholdMs;\n  final String internalPriority;\n")
	b.WriteString("  Set<String> get allowedExtensions => <String>{...requiredExtensions, ...optionalExtensions};\n}\n\n")
	b.WriteString("class AppTelemetryPayload {\n")
	b.WriteString("  const AppTelemetryPayload._(this.eventType, this.logType, this.extensions);\n")
	b.WriteString("  final String eventType;\n  final String logType;\n  final Map<String, Object?> extensions;\n\n")
	for _, event := range catalog.Events {
		method := toDartValueName(event.EventType)
		args := []string{}
		entries := []string{}
		for _, name := range event.RequiredExtensions {
			args = append(args, fmt.Sprintf("required %s %s", dartTelemetryType(catalog.ExtensionFields[name].Type, false), name))
			entries = append(entries, fmt.Sprintf("      '%s': %s,", name, name))
		}
		for _, name := range event.OptionalExtensions {
			args = append(args, fmt.Sprintf("%s %s", dartTelemetryType(catalog.ExtensionFields[name].Type, true), name))
			entries = append(entries, fmt.Sprintf("      if (%s != null) '%s': %s,", name, name, name))
		}
		parameterList := ""
		if len(args) > 0 {
			parameterList = "{" + strings.Join(args, ", ") + "}"
		}
		b.WriteString(fmt.Sprintf("  factory AppTelemetryPayload.%s(%s) {\n", method, parameterList))
		b.WriteString(fmt.Sprintf("    return AppTelemetryPayload._('%s', '%s', <String, Object?>{\n", event.EventType, event.LogType))
		for _, entry := range entries {
			b.WriteString(entry + "\n")
		}
		b.WriteString("    });\n  }\n\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("abstract final class AppTelemetryCatalog {\n")
	b.WriteString("  static const List<String> commonFields = <String>[")
	for i, field := range catalog.CommonFields {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("'%s'", field))
	}
	b.WriteString("];\n")
	b.WriteString("  static const Set<String> contextExtensions = <String>{")
	for i, field := range catalog.ContextExtensions {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("'%s'", field))
	}
	b.WriteString("};\n")
	b.WriteString("  static const Set<String> networkClasses = <String>{")
	for i, value := range catalog.NetworkClasses {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("'%s'", value))
	}
	b.WriteString("};\n")
	b.WriteString("  static const Map<String, AppTelemetryEventDefinition> events = <String, AppTelemetryEventDefinition>{\n")
	for _, event := range catalog.Events {
		b.WriteString(fmt.Sprintf("    '%s': AppTelemetryEventDefinition(eventType: '%s', logType: '%s', requiredExtensions: <String>{", event.EventType, event.EventType, event.LogType))
		for i, field := range event.RequiredExtensions {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(fmt.Sprintf("'%s'", field))
		}
		b.WriteString("}, optionalExtensions: <String>{")
		for i, field := range event.OptionalExtensions {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(fmt.Sprintf("'%s'", field))
		}
		b.WriteString(fmt.Sprintf("}, normalSampleRate: %g, slowThresholdMs: %d, internalPriority: '%s'),\n", event.NormalSampleRate, event.SlowThresholdMS, event.InternalPriority))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  static String? validate(AppTelemetryPayload payload) {\n")
	b.WriteString("    final definition = events[payload.eventType];\n")
	b.WriteString("    if (definition == null || definition.logType != payload.logType) return 'unknown_event';\n")
	b.WriteString("    if (!payload.extensions.keys.every(definition.allowedExtensions.contains)) return 'unknown_extension';\n")
	b.WriteString("    if (!definition.requiredExtensions.every(payload.extensions.containsKey)) return 'missing_extension';\n")
	b.WriteString("    return null;\n  }\n")
	b.WriteString("}\n")
	return b.String()
}

func dartTelemetryType(kind string, nullable bool) string {
	base := map[string]string{
		"string": "String", "int": "int", "double": "double", "bool": "bool", "string_list": "List<String>",
	}[kind]
	if nullable {
		return base + "?"
	}
	return base
}

func renderAppPagesDart(pages *appPagesFile, routes *appRoutesFile) string {
	routesByID := map[string]appRouteDef{}
	for _, route := range routes.Routes {
		routesByID[route.ID] = route
	}
	ordered := append([]appPageDef{}, pages.Pages...)
	sort.SliceStable(ordered, func(i, j int) bool {
		left := routesByID[ordered[i].RouteID].Path
		right := routesByID[ordered[j].RouteID].Path
		leftDynamic := strings.Contains(left, "{")
		rightDynamic := strings.Contains(right, "{")
		if leftDynamic != rightDynamic {
			return !leftDynamic
		}
		if len(left) != len(right) {
			return len(left) > len(right)
		}
		return left < right
	})

	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from _shared/app_pages.yaml. DO NOT EDIT.\n\n")
	b.WriteString("class AppPageDefinition {\n")
	b.WriteString("  const AppPageDefinition({required this.pageName, required this.routeId, required this.pathTemplate, required this.collectPageAccess});\n")
	b.WriteString("  final String pageName;\n  final String routeId;\n  final String pathTemplate;\n  final bool collectPageAccess;\n}\n\n")
	b.WriteString("abstract final class PageNames {\n")
	uniquePageNames := map[string]bool{}
	for _, page := range append(append([]appPageDef{}, pages.Pages...), pages.InternalPages...) {
		uniquePageNames[page.PageName] = true
	}
	for _, context := range pages.FallbackContexts {
		uniquePageNames[context] = true
	}
	names := make([]string, 0, len(uniquePageNames))
	for name := range uniquePageNames {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		b.WriteString(fmt.Sprintf("  static const String %s = '%s';\n", toDartValueName(name), name))
	}
	b.WriteString("}\n\n")
	b.WriteString("abstract final class AppPages {\n")
	b.WriteString("  static const List<AppPageDefinition> routes = <AppPageDefinition>[\n")
	for _, page := range ordered {
		route := routesByID[page.RouteID]
		b.WriteString(fmt.Sprintf("    AppPageDefinition(pageName: '%s', routeId: '%s', pathTemplate: '%s', collectPageAccess: %t),\n", page.PageName, page.RouteID, route.Path, page.CollectPageAccess))
	}
	b.WriteString("  ];\n")
	b.WriteString("  static const Map<String, String> internalLocations = <String, String>{\n")
	for _, page := range pages.InternalPages {
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", page.Location, page.PageName))
	}
	b.WriteString("  };\n")
	b.WriteString("  static const Set<String> fallbackContexts = <String>{")
	for i, value := range pages.FallbackContexts {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("'%s'", value))
	}
	b.WriteString("};\n\n")
	b.WriteString("  static String? pageNameFromLocation(String location) {\n")
	b.WriteString("    var path = location.split('?').first;\n")
	b.WriteString("    if (path.length > 1 && path.endsWith('/')) path = path.substring(0, path.length - 1);\n")
	b.WriteString("    final internal = internalLocations[path];\n    if (internal != null) return internal;\n")
	b.WriteString("    for (final page in routes) { if (_matches(page.pathTemplate, path)) return page.pageName; }\n")
	b.WriteString("    return null;\n  }\n\n")
	b.WriteString("  static bool _matches(String template, String path) {\n")
	b.WriteString("    if (template == path) return true;\n")
	b.WriteString("    final expected = template.split('/');\n    final actual = path.split('/');\n")
	b.WriteString("    if (expected.length != actual.length) return false;\n")
	b.WriteString("    for (var i = 0; i < expected.length; i++) { final segment = expected[i]; if (segment.startsWith('{') && segment.endsWith('}')) { if (actual[i].isEmpty) return false; continue; } if (segment != actual[i]) return false; }\n")
	b.WriteString("    return true;\n  }\n}\n")
	return b.String()
}

func renderPageAccessInternalRoutesDart(pages *appPagesFile) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from _shared/app_pages.yaml. DO NOT EDIT.\n\n")
	b.WriteString("abstract final class PageAccessInternalRoutes {\n")
	for _, page := range pages.InternalPages {
		b.WriteString(fmt.Sprintf("  static const String %s = '%s';\n", page.InternalID, page.Location))
	}
	b.WriteString("}\n")
	return b.String()
}
