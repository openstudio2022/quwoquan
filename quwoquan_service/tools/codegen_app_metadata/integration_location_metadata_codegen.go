package main

import (
	"fmt"
	"sort"
	"strings"
)

func feedQueryDartLiteral(m map[string]string) string {
	if len(m) == 0 {
		return "<String, String>{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%s: %s", dartStringLiteral(k), dartStringLiteral(m[k])))
	}
	return "<String, String>{" + strings.Join(parts, ", ") + "}"
}

// 路径与 response key 来自 services/integration-service/contracts/external_integration/location/operations.yaml，
// 禁止在业务/测试中硬编码。
func renderIntegrationLocationMetadataDart(svc *integrationLocationServiceFile) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from integration/external_integration/location/operations.yaml. DO NOT EDIT.\n")
	b.WriteString("// ignore_for_file: prefer_const_constructors\n\n")
	b.WriteString("/// integration/external_integration/location API 元数据，与 contracts/metadata 同步。\n")
	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString("class IntegrationLocationMetadata {\n")
	b.WriteString("  const IntegrationLocationMetadata._();\n\n")

	responseKey := strings.TrimSpace(svc.ResponseListKey)
	if responseKey == "" {
		responseKey = "items"
	}
	b.WriteString(fmt.Sprintf("  /// 列表响应根 key（与 integration-service handler 一致）\n"))
	b.WriteString(fmt.Sprintf("  static const String responseItemsKey = '%s';\n\n", responseKey))

	nearbyPath := ""
	searchPath := ""
	for _, r := range svc.APIRoutes {
		switch r.Operation {
		case "GetNearbyLocations":
			nearbyPath = r.Path
		case "SearchLocations":
			searchPath = r.Path
		}
	}
	if nearbyPath == "" {
		nearbyPath = "/integration/external_integration/location/nearby"
	}
	if searchPath == "" {
		searchPath = "/integration/external_integration/location/search"
	}
	b.WriteString("  /// API 路径（来自 api_routes）\n")
	b.WriteString(fmt.Sprintf("  static const String nearbyPath = '%s';\n", nearbyPath))
	b.WriteString(fmt.Sprintf("  static const String searchPath = '%s';\n", searchPath))

	b.WriteString("}\n")
	return b.String()
}
