// renderSimpleErrorsDart 生成一个 *ErrorCode Dart enum + *ErrorMessages 文案表，
// 模式与 renderChatErrorsDart 完全一致，抽成通用渲染以避免每个客户端域复制一份
// （军规 R25：横切关注提取统一抽象）。enumName 形如 "AssistantErrorCode"，
// unknownMessage 是 unknown 兜底的 zh 文案。
func renderSimpleErrorsDart(enumName, sourcePath, unknownMessage string, ef *errorsFile) string {
	var b strings.Builder
	messagesClass := strings.TrimSuffix(enumName, "Code") + "Messages"
	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from %s. DO NOT EDIT.\n", sourcePath))
	b.WriteString("// ignore_for_file: constant_identifier_names\n\n")

	b.WriteString(fmt.Sprintf("enum %s {\n", enumName))
	for _, e := range ef.Errors {
		if e.DartConst == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("  %s('%s', '%s', %d),\n", e.DartConst, e.Code, strings.ReplaceAll(e.UserMessage["zh"], "'", "\\'"), e.HTTPStatus))
	}
	b.WriteString(fmt.Sprintf("  unknown('', '%s', 500);\n\n", strings.ReplaceAll(unknownMessage, "'", "\\'")))

	b.WriteString("  final String code;\n")
	b.WriteString("  final String defaultMessage;\n")
	b.WriteString("  final int httpStatus;\n\n")
	b.WriteString(fmt.Sprintf("  const %s(this.code, this.defaultMessage, this.httpStatus);\n\n", enumName))
	b.WriteString(fmt.Sprintf("  static %s fromCode(String code) {\n", enumName))
	b.WriteString("    for (final value in values) {\n")
	b.WriteString("      if (value.code == code) return value;\n")
	b.WriteString("    }\n")
	b.WriteString(fmt.Sprintf("    return %s.unknown;\n", enumName))
	b.WriteString("  }\n")
	b.WriteString("}\n\n")

	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString(fmt.Sprintf("class %s {\n", messagesClass))
	b.WriteString(fmt.Sprintf("  const %s._();\n\n", messagesClass))
	b.WriteString(fmt.Sprintf("  static const Map<%s, String> zh = <%s, String>{\n", enumName, enumName))
	for _, e := range ef.Errors {
		if e.DartConst == "" {
			continue
		}
		if msg, ok := e.UserMessage["zh"]; ok {
			b.WriteString(fmt.Sprintf("    %s.%s: '%s',\n", enumName, e.DartConst, strings.ReplaceAll(msg, "'", "\\'")))
		}
	}
	b.WriteString("  };\n\n")
	b.WriteString(fmt.Sprintf("  static const Map<%s, String> en = <%s, String>{\n", enumName, enumName))
	for _, e := range ef.Errors {
		if e.DartConst == "" {
			continue
		}
		if msg, ok := e.UserMessage["en"]; ok {
			b.WriteString(fmt.Sprintf("    %s.%s: '%s',\n", enumName, e.DartConst, strings.ReplaceAll(msg, "'", "\\'")))
		}
	}
	b.WriteString("  };\n")
	b.WriteString("}\n")

	return b.String()
}

func renderUserErrorsDart(ef *errorsFile) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from user/**/errors.yaml. DO NOT EDIT.\n")
	b.WriteString("// ignore_for_file: constant_identifier_names\n\n")
	b.WriteString("enum UserErrorCode {\n")
	for _, e := range ef.Errors {
		if e.DartConst == "" {
			continue
		}
		zh := escapeDartString(e.UserMessage["zh"])
		en := escapeDartString(e.UserMessage["en"])
		if zh == "" {
			zh = escapeDartString(goErrorUserMessage(e))
		}
		if en == "" {
			en = zh
		}
		b.WriteString(fmt.Sprintf(
			"  %s('%s', '%s', '%s', %d, '%s', '%s', %d, '%s'),\n",
			e.DartConst,
			e.Code,
			zh,
			en,
			e.HTTPStatus,
			effectiveRecoveryAction(e),
			effectiveRecoveryDisruptionLevel(e),
			effectiveRecoveryAfterSeconds(e),
			escapeDartString(e.L10nKey),
		))
	}
	b.WriteString(";\n\n")
	b.WriteString("  final String code;\n")
	b.WriteString("  final String defaultMessageZh;\n")
	b.WriteString("  final String defaultMessageEn;\n")
	b.WriteString("  final int httpStatus;\n\n")
	b.WriteString("  final String recoveryAction;\n")
	b.WriteString("  final String disruptionLevel;\n")
	b.WriteString("  final int recoveryAfterSeconds;\n")
	b.WriteString("  final String l10nKey;\n\n")
	b.WriteString("  const UserErrorCode(this.code, this.defaultMessageZh, this.defaultMessageEn, this.httpStatus, this.recoveryAction, this.disruptionLevel, this.recoveryAfterSeconds, this.l10nKey);\n\n")
	b.WriteString("  String get defaultMessage => defaultMessageZh;\n\n")
	b.WriteString("  String messageForLocale(String locale) => locale.toLowerCase().startsWith('en') ? defaultMessageEn : defaultMessageZh;\n\n")
	b.WriteString("  static UserErrorCode? fromCode(String code) {\n")
	b.WriteString("    for (final e in values) {\n")
	b.WriteString("      if (e.code == code) return e;\n")
	b.WriteString("    }\n")
	b.WriteString("    return null;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

func goErrorUserMessage(e errorDef) string {
	msg := e.UserMessage["zh"]
	if msg == "" {
		msg = e.UserMessage["en"]
	}
	if msg == "" {
		msg = "请稍后重试"
	}
	return msg
}

func effectiveRecoveryAction(e errorDef) string {
	if action := strings.TrimSpace(e.Recovery.Action); action != "" {
		return action
	}
	return strings.TrimSpace(e.RecoveryAction)
}

func effectiveRecoveryDisruptionLevel(e errorDef) string {
	return strings.TrimSpace(e.Recovery.DisruptionLevel)
}

func effectiveRecoveryAfterSeconds(e errorDef) int {
	if e.Recovery.AfterSeconds > 0 {
		return e.Recovery.AfterSeconds
	}
	return e.RecoveryAfterSecs
}

