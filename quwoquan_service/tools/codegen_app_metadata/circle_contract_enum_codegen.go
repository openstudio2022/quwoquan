package main

import (
	"fmt"
	"strings"
)

func personaCircleSliceEnumRefs(
	circleFields *fieldsFile,
	membershipFields *fieldsFile,
) ([]string, error) {
	circle, exists := circleFields.Entities["Circle"]
	if !exists {
		return nil, fmt.Errorf("Circle is absent from circle/fields.yaml")
	}
	projection, exists := membershipFields.Entities["PersonaCircleSlice"]
	if !exists {
		return nil, fmt.Errorf("PersonaCircleSlice is absent from circle_membership/fields.yaml")
	}
	canonicalByName := make(map[string]fieldDef, len(circle.Fields))
	for _, field := range circle.Fields {
		canonicalByName[field.Name] = field
	}
	seen := map[string]struct{}{}
	refs := make([]string, 0)
	for _, field := range projection.Fields {
		if canonical, matchesCanonical := canonicalByName[field.Name]; matchesCanonical &&
			strings.TrimSpace(canonical.Type) == "enum" {
			if strings.TrimSpace(field.Type) != "enum" ||
				strings.TrimSpace(field.EnumRef) != strings.TrimSpace(canonical.EnumRef) {
				return nil, fmt.Errorf(
					"PersonaCircleSlice.%s must preserve canonical Circle enum_ref %s",
					field.Name,
					canonical.EnumRef,
				)
			}
		}
		if strings.TrimSpace(field.Type) != "enum" {
			continue
		}
		ref := strings.TrimSpace(field.EnumRef)
		if ref == "" {
			return nil, fmt.Errorf("PersonaCircleSlice.%s enum requires enum_ref", field.Name)
		}
		if _, exists := seen[ref]; exists {
			continue
		}
		seen[ref] = struct{}{}
		refs = append(refs, ref)
	}
	if len(refs) == 0 {
		return nil, fmt.Errorf("PersonaCircleSlice has no canonical enum_ref fields")
	}
	return refs, nil
}

func renderCircleContractEnumsDart(
	enums map[string][]string,
	enumNames []string,
) (string, error) {
	return renderSharedContractEnumsDart(enums, enumNames)
}

// renderSharedContractEnumsDart is the single Dart representation for enums
// owned by contracts/metadata/_shared/types.yaml. Domain-specific generators
// select which canonical enum refs their public client package consumes; they
// must not restate wire values in handwritten Dart.
func renderSharedContractEnumsDart(
	enums map[string][]string,
	enumNames []string,
) (string, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from _shared/types.yaml. DO NOT EDIT.\n\n")
	for _, enumName := range enumNames {
		values := enums[enumName]
		if len(values) == 0 {
			return "", fmt.Errorf("client enum %s is absent from _shared/types.yaml", enumName)
		}
		b.WriteString("enum " + enumName + " {\n")
		for _, value := range values {
			b.WriteString(fmt.Sprintf("  %s(%q),\n", toDartValueName(value), value))
		}
		b.WriteString("  ;\n\n")
		b.WriteString("  const " + enumName + "(this.wireValue);\n\n")
		b.WriteString("  final String wireValue;\n\n")
		b.WriteString("  static " + enumName + " fromWire(Object? raw) {\n")
		b.WriteString("    switch (raw) {\n")
		for _, value := range values {
			b.WriteString(fmt.Sprintf("      case %q:\n", value))
			b.WriteString(fmt.Sprintf("        return %s.%s;\n", enumName, toDartValueName(value)))
		}
		b.WriteString("      default:\n")
		b.WriteString(fmt.Sprintf("        throw FormatException('invalid %s: $raw');\n", enumName))
		b.WriteString("    }\n")
		b.WriteString("  }\n")
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}
