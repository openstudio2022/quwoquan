package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/santhosh-tekuri/jsonschema/v6"
	"gopkg.in/yaml.v3"
)

const nativeOrientationMetadataPath = "content/media/media_asset/native_orientation_contract.yaml"
const nativeOrientationDartOutput = "lib/runtime/platform/media/generated/native_orientation_contract.g.dart"
const nativeOrientationJavaOutput = "android/app/src/main/java/com/quwoquan/quwoquan_app/NativeOrientationContract.java"
const nativeOrientationSwiftOutput = "ios/Runner/NativeOrientationContract.generated.swift"
const nativeOrientationManifestOutput = "tool/native_orientation_codegen/generated_manifest.json"

type nativeOrientationContract struct {
	Schema   string         `yaml:"schema"`
	Channel  string         `yaml:"channel"`
	Method   string         `yaml:"method"`
	Response map[string]any `yaml:"response_schema"`
}

// 只读当前 canonical view 中的两个专用输入，不消费或改写共享 Graph/App lock。
func runNativeOrientationMode(metadataDir, appDir string, check bool) error {
	sourcePath := filepath.Join(metadataDir, nativeOrientationMetadataPath)
	payload, err := os.ReadFile(sourcePath)
	if err != nil {
		return err
	}
	schemaPath := filepath.Join(metadataDir, "_schemas/native_orientation_contract.schema.json")
	schemaPayload, err := os.ReadFile(schemaPath)
	if err != nil {
		return err
	}
	var source nativeOrientationContract
	decoder := yaml.NewDecoder(bytes.NewReader(payload))
	decoder.KnownFields(true)
	if err := decoder.Decode(&source); err != nil {
		return err
	}
	var raw map[string]any
	if err := yaml.Unmarshal(payload, &raw); err != nil {
		return err
	}
	rawBytes, err := json.Marshal(raw)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(rawBytes, &raw); err != nil {
		return err
	}
	schema, err := jsonschema.NewCompiler().Compile(schemaPath)
	if err != nil {
		return err
	}
	if err := schema.Validate(raw); err != nil {
		return err
	}
	response := raw["response_schema"].(map[string]any)
	variants, ok := response["oneOf"].([]any)
	if !ok || len(variants) != 3 {
		return fmt.Errorf("orientation response must have three platform/status variants")
	}
	// 专用 emitter 只接受现役完整形状；schema 改变时必须显式更新 typed 模型。
	expected := []string{"platform,status", "axis,binding,platform,rotation,status", "binding,orientation,platform,status"}
	for index, value := range variants {
		variant, ok := value.(map[string]any)
		if !ok {
			return fmt.Errorf("orientation variant must be object")
		}
		required, ok := variant["required"].([]any)
		if !ok {
			return fmt.Errorf("orientation variant requires explicit fields")
		}
		keys := make([]string, 0, len(required))
		for _, key := range required {
			name, ok := key.(string)
			if !ok {
				return fmt.Errorf("invalid required field")
			}
			keys = append(keys, name)
		}
		sort.Strings(keys)
		properties, ok := variant["properties"].(map[string]any)
		if !ok || len(properties) != len(keys) || strings.Join(keys, ",") != expected[index] || variant["additionalProperties"] != false {
			return fmt.Errorf("unsupported orientation variant shape %d", index)
		}
	}
	dart, err := renderNativeOrientationDart(source, variants)
	if err != nil {
		return err
	}
	values := map[string]string{"channel": source.Channel, "method": source.Method}
	for _, value := range variants {
		for key, definition := range value.(map[string]any)["properties"].(map[string]any) {
			values["field_"+key] = key
			property := definition.(map[string]any)
			if constant, ok := property["const"].(string); ok {
				values["value_"+constant] = constant
			}
			if enums, ok := property["enum"].([]any); ok {
				for _, enum := range enums {
					if text, ok := enum.(string); ok {
						values["value_"+text] = text
					}
				}
			}
		}
	}
	names := make([]string, 0, len(values))
	for name := range values {
		names = append(names, name)
	}
	sort.Strings(names)
	const banner = "// Code generated by tools/codegen_app_metadata --native-orientation-only. DO NOT EDIT.\n"
	var java, swift strings.Builder
	java.WriteString(banner + "package com.quwoquan.quwoquan_app;\n\npublic final class NativeOrientationContract {\n  private NativeOrientationContract() {}\n")
	swift.WriteString(banner + "import Foundation\n\nenum NativeOrientationContract {\n")
	for _, name := range names {
		java.WriteString("  public static final String " + name + " = " + strconv.Quote(values[name]) + ";\n")
		swift.WriteString("  static let " + name + " = " + strconv.Quote(values[name]) + "\n")
	}
	java.WriteString("}\n")
	swift.WriteString("}\n")
	artifacts := map[string][]byte{nativeOrientationDartOutput: []byte(dart), nativeOrientationJavaOutput: []byte(java.String()), nativeOrientationSwiftOutput: []byte(swift.String())}
	digest := func(data []byte) string { sum := sha256.Sum256(data); return "sha256:" + hex.EncodeToString(sum[:]) }
	inputs := []map[string]any{
		{"path": "quwoquan_service/services/content-service/contracts/media/media_asset/native_orientation_contract.yaml", "sha256": digest(payload)},
		{"path": "quwoquan_service/contracts/metadata/_schemas/native_orientation_contract.schema.json", "sha256": digest(schemaPayload)},
	}
	outputPaths := make([]string, 0, len(artifacts))
	for path := range artifacts {
		outputPaths = append(outputPaths, path)
	}
	sort.Strings(outputPaths)
	outputs := make([]map[string]any, 0, len(artifacts))
	for _, path := range outputPaths {
		data := artifacts[path]
		outputs = append(outputs, map[string]any{"path": "quwoquan_app/" + path, "sha256": digest(data), "bytes": len(data)})
	}
	inputBytes, _ := json.Marshal(inputs)
	manifest, err := json.MarshalIndent(map[string]any{"schema": "qwq.native-orientation-codegen-manifest", "generator": "tools/codegen_app_metadata --native-orientation-only", "sourceDigest": digest(inputBytes), "inputs": inputs, "outputs": outputs}, "", "  ")
	if err != nil {
		return err
	}
	artifacts[nativeOrientationManifestOutput] = append(manifest, '\n')
	outputPaths = append(outputPaths, nativeOrientationManifestOutput)
	for _, relative := range outputPaths {
		target := filepath.Join(appDir, relative)
		if check {
			actual, err := os.ReadFile(target)
			if err != nil {
				return err
			}
			if !bytes.Equal(actual, artifacts[relative]) {
				return fmt.Errorf("native orientation generated output stale: %s", target)
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(target, artifacts[relative], 0644); err != nil {
				return err
			}
		}
	}
	return nil
}
