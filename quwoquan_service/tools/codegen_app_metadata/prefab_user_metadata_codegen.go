package main

import (
	"fmt"
	"strings"
)

type prefabUserProvenance struct {
	CurrentUser prefabCurrentUser `yaml:"currentUser"`
}

type prefabCurrentUser struct {
	UserID       string `yaml:"userId"`
	SubAccountID string `yaml:"subAccountId"`
}

func readPrefabUserProvenance(path string) (*prefabUserProvenance, error) {
	var parsed prefabUserProvenance
	if err := decodeMetadataDocument(path, &parsed); err != nil {
		return nil, err
	}
	if strings.TrimSpace(parsed.CurrentUser.UserID) == "" {
		return nil, fmt.Errorf("prefab provenance currentUser.userId is required")
	}
	if strings.TrimSpace(parsed.CurrentUser.SubAccountID) == "" {
		return nil, fmt.Errorf("prefab provenance currentUser.subAccountId is required")
	}
	return &parsed, nil
}

func renderPrefabUserMetadataDart(def *prefabUserProvenance) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from _shared/prefab_user_provenance.yaml. DO NOT EDIT.\n\n")
	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString("class PrefabUserMetadata {\n")
	b.WriteString("  const PrefabUserMetadata._();\n\n")
	b.WriteString(fmt.Sprintf(
		"  static const String currentUserId = %s;\n",
		dartStringLiteral(strings.TrimSpace(def.CurrentUser.UserID)),
	))
	b.WriteString(fmt.Sprintf(
		"  static const String currentSubAccountId = %s;\n",
		dartStringLiteral(strings.TrimSpace(def.CurrentUser.SubAccountID)),
	))
	b.WriteString("}\n")
	return b.String()
}
