package main

import (
	"fmt"
	"sort"
	"strings"
)

func renderContentMediaUploadPolicyDart(
	policy *contentMediaUploadPolicyFile,
) string {
	if policy == nil {
		return ""
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from content/media/media_upload_session/upload_policy.yaml. DO NOT EDIT.\n\n")
	b.WriteString("final class ContentMediaUploadTypePolicy {\n")
	b.WriteString("  const ContentMediaUploadTypePolicy({\n")
	b.WriteString("    required this.maxFileSizeBytes,\n")
	b.WriteString("    required this.allowedContentTypes,\n")
	b.WriteString("  });\n\n")
	b.WriteString("  final int maxFileSizeBytes;\n")
	b.WriteString("  final Set<String> allowedContentTypes;\n")
	b.WriteString("}\n\n")
	b.WriteString("abstract final class ContentMediaUploadPolicy {\n")
	fmt.Fprintf(&b, "  static const bool streamingRequired = %t;\n", policy.StreamingRequired)
	fmt.Fprintf(&b, "  static const String fileTooLargeErrorCode = %q;\n", policy.Errors.FileTooLarge)
	fmt.Fprintf(&b, "  static const String unsupportedTypeErrorCode = %q;\n", policy.Errors.UnsupportedType)
	mediaTypes := make([]string, 0, len(policy.MediaTypes))
	for mediaType := range policy.MediaTypes {
		mediaTypes = append(mediaTypes, mediaType)
	}
	sort.Strings(mediaTypes)
	b.WriteString("  static const Map<String, ContentMediaUploadTypePolicy> mediaTypes = {\n")
	for _, mediaType := range mediaTypes {
		definition := policy.MediaTypes[mediaType]
		fmt.Fprintf(&b, "    %q: ContentMediaUploadTypePolicy(\n", mediaType)
		fmt.Fprintf(&b, "      maxFileSizeBytes: %d,\n", definition.MaxFileSizeBytes)
		b.WriteString("      allowedContentTypes: {\n")
		for _, contentType := range definition.AllowedContentTypes {
			fmt.Fprintf(&b, "        %q,\n", contentType)
		}
		b.WriteString("      },\n")
		b.WriteString("    ),\n")
	}
	b.WriteString("  };\n")
	b.WriteString("}\n")
	return b.String()
}
