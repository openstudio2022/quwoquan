package main

import (
	"fmt"
	"path/filepath"
	"strings"

	"quwoquan_service/tools/recimpactmeta"
)

// 影响力 helpType 注册表 → 端可消费 impact iconKey/tone 闭集（§23 去桥接，对齐交集）。
// registry 解析/校验层统一在 tools/recimpactmeta（服务端 Go codegen 同源复用），
// 本文件只负责把注册表渲染为客户端 Dart；端 IntersectionIconResolver 查本表，
// 不再硬编码 impact iconKey→tone switch。

// writeImpactHelpTypeMetadata generates the App-consumable impact iconKey→tone table
// + helpType/iconKey closed sets from impact_help_type_registry.yaml.
func writeImpactHelpTypeMetadata(appDir, metadataDir string) error {
	contractPath := filepath.Join(metadataDir, "recommendation", "rec_model", "impact_help_type_registry.yaml")
	raw, err := readMetadataDocument(contractPath)
	if err != nil {
		return fmt.Errorf("impact help type registry: %w", err)
	}
	registry, err := recimpactmeta.Parse(raw)
	if err != nil {
		return fmt.Errorf("read impact help type registry: %w", err)
	}
	if err := recimpactmeta.Validate(registry); err != nil {
		return fmt.Errorf("impact help type registry: %w", err)
	}
	out := renderImpactHelpTypeMetadataDart(contractPath, registry)
	outPath := filepath.Join(appDir, "lib", "cloud", "runtime", "generated", "recommendation", "impact_help_type_metadata.g.dart")
	writeFile(outPath, out)
	return nil
}

func renderImpactHelpTypeMetadataDart(sourcePath string, r *recimpactmeta.Registry) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from recommendation/rec_model/impact_help_type_registry.yaml. DO NOT EDIT.\n")
	b.WriteString("// Source: ")
	b.WriteString(filepath.ToSlash(sourcePath))
	b.WriteString("\n\n")

	// helpType 闭集（registry 顺序）。
	helpTypes := make([]string, 0, len(r.HelpTypes))
	for _, h := range r.HelpTypes {
		helpTypes = append(helpTypes, h.HelpType)
	}
	b.WriteString("/// §23 影响力 helpType 闭集（registry.helpTypes[].helpType，端归一/校验唯一真相源）。\n")
	b.WriteString(fmt.Sprintf("const List<String> impactHelpTypeKeys = %s;\n\n", dartStringListLiteral(helpTypes)))

	// helpType → iconKey。
	b.WriteString("/// helpType → 端图标语义键（registry.helpTypes[].iconKey）。\n")
	b.WriteString("const Map<String, String> impactIconKeyByHelpType = <String, String>{\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("  %s: %s,\n", dartStringLiteral(h.HelpType), dartStringLiteral(h.IconKey)))
	}
	b.WriteString("};\n\n")

	// iconKey → tone（端 IntersectionIconResolver._toneKey 影响段唯一真相源）。
	b.WriteString("/// 影响 iconKey → 低饱和语义 tone（registry.toneByIconKey）。\n")
	b.WriteString("/// 端 IntersectionIconResolver 查本表，不再硬编码 impact 色调 switch。\n")
	b.WriteString("const Map<String, String> impactToneByIconKey = <String, String>{\n")
	writeSortedStringMap(&b, r.ToneByIcon)
	b.WriteString("};\n\n")

	// 防御默认（未登记 helpType / iconKey 兜底，对齐 registry.defaults）。
	b.WriteString("/// 未登记 iconKey 的兜底 tone（registry.defaults.tone）。\n")
	b.WriteString(fmt.Sprintf("const String impactDefaultTone = %s;\n\n", dartStringLiteral(r.Defaults.Tone)))
	b.WriteString("/// 未登记 helpType 的兜底 iconKey（registry.defaults.iconKey）。\n")
	b.WriteString(fmt.Sprintf("const String impactDefaultIconKey = %s;\n", dartStringLiteral(r.Defaults.IconKey)))

	return b.String()
}
