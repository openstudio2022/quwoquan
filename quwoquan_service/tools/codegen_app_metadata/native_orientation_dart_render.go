package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

func renderNativeOrientationDart(source nativeOrientationContract, variants []any) (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by tools/codegen_app_metadata --native-orientation-only. DO NOT EDIT.\n\n")
	out.WriteString("const nativeOrientationChannel = " + strconv.Quote(source.Channel) + ";\n")
	out.WriteString("const nativeOrientationMethod = " + strconv.Quote(source.Method) + ";\n\n")
	enums := map[string][]string{}
	for _, item := range variants {
		for field, value := range item.(map[string]any)["properties"].(map[string]any) {
			if field == "rotation" || field == "binding" {
				continue
			}
			property := value.(map[string]any)
			values := []any{}
			if valuesRaw, ok := property["enum"].([]any); ok {
				values = valuesRaw
			}
			if constant, ok := property["const"]; ok {
				values = append(values, constant)
			}
			for _, raw := range values {
				text, ok := raw.(string)
				if !ok {
					return "", fmt.Errorf("non-string orientation enum")
				}
				exists := false
				for _, old := range enums[field] {
					if old == text {
						exists = true
					}
				}
				if !exists {
					enums[field] = append(enums[field], text)
				}
			}
		}
	}
	names := []string{"status", "platform", "axis", "orientation"}
	types := map[string]string{"status": "NativeOrientationStatus", "platform": "NativeOrientationPlatform", "axis": "NativeOrientationAxis", "orientation": "NativeInterfaceOrientation"}
	for _, name := range names {
		if len(enums[name]) == 0 {
			return "", fmt.Errorf("missing orientation enum %s", name)
		}
		out.WriteString("enum " + types[name] + " { " + strings.Join(enums[name], ", ") + " }\n")
	}
	out.WriteString(`
final class NativeOrientationObservation {
  const NativeOrientationObservation._({required this.status, required this.platform,
    this.binding, this.axis, this.rotation, this.orientation});
  final NativeOrientationStatus status;
  final NativeOrientationPlatform platform;
  final String? binding;
  final NativeOrientationAxis? axis;
  final int? rotation;
  final NativeInterfaceOrientation? orientation;

  factory NativeOrientationObservation.decode(Object? payload) {
    if (payload is! Map) throw const FormatException('Orientation response must be an object');
    final matches = <bool>[
`)
	for _, item := range variants {
		variant := item.(map[string]any)
		properties := variant["properties"].(map[string]any)
		keys := make([]string, 0, len(properties))
		for key := range properties {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		keyBytes, _ := json.Marshal(keys)
		guards := []string{fmt.Sprintf("payload.length == %d", len(keys)), fmt.Sprintf("payload.keys.every(%s.contains)", string(keyBytes))}
		for _, key := range keys {
			property := properties[key].(map[string]any)
			access := "payload[" + strconv.Quote(key) + "]"
			if constant, ok := property["const"]; ok {
				encoded, _ := json.Marshal(constant)
				guards = append(guards, access+" == "+string(encoded))
			}
			if values, ok := property["enum"].([]any); ok {
				encoded, _ := json.Marshal(values)
				guards = append(guards, string(encoded)+".contains("+access+")")
			}
			if property["type"] == "integer" {
				guards = append(guards, access+" is int")
			}
			if property["type"] == "string" {
				guards = append(guards, access+" is String")
				if _, ok := property["minLength"]; ok {
					guards = append(guards, "("+access+" as String).trim().isNotEmpty")
				}
			}
		}
		out.WriteString("      " + strings.Join(guards, " && ") + ",\n")
	}
	out.WriteString("    ];\n    if (matches.where((value) => value).length != 1) {\n      throw const FormatException('Invalid or mismatched orientation response');\n    }\n    return NativeOrientationObservation._(\n")
	for _, name := range names {
		access := "payload[" + strconv.Quote(name) + "]"
		expression := types[name] + ".values.byName(" + access + " as String)"
		if name == "axis" || name == "orientation" {
			expression = access + " == null ? null : " + expression
		}
		out.WriteString("      " + name + ": " + expression + ",\n")
	}
	out.WriteString("      binding: payload[\"binding\"] as String?,\n      rotation: payload[\"rotation\"] as int?,\n    );\n  }\n}\n")
	return out.String(), nil
}
