package main

import (
	"fmt"
	"strings"
)

func renderContentPublicationPolicyDart(
	policy *contentPublicationPolicyFile,
) string {
	if policy == nil {
		return ""
	}
	limits := policy.TextLimits
	format := policy.FormatRecommendation
	rate := policy.RateLimit
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from content/post/publication_policy.yaml. DO NOT EDIT.\n\n")
	b.WriteString("enum ContentPublicationSafetyDecision { allow, review, reject, unavailable }\n\n")
	b.WriteString("abstract final class ContentPublicationPolicy {\n")
	fmt.Fprintf(&b, "  static const int titleMaxRunes = %d;\n", limits.TitleMaxRunes)
	fmt.Fprintf(&b, "  static const int microBodyMaxRunes = %d;\n", limits.MicroBodyMaxRunes)
	fmt.Fprintf(&b, "  static const int articleMarkdownMaxRunes = %d;\n", limits.ArticleMarkdownMaxRunes)
	fmt.Fprintf(&b, "  static const int summaryMaxRunes = %d;\n", limits.SummaryMaxRunes)
	fmt.Fprintf(&b, "  static const int semanticMentionsMaxItems = %d;\n", limits.SemanticMentionsMaxItems)
	fmt.Fprintf(&b, "  static const int articleBodyMinRunes = %d;\n", format.ArticleBodyMinRunes)
	fmt.Fprintf(&b, "  static const int articleParagraphMinCount = %d;\n", format.ArticleParagraphMinCount)
	fmt.Fprintf(&b, "  static const bool articleWhenTitlePresent = %t;\n", format.ArticleWhenTitlePresent)
	fmt.Fprintf(&b, "  static const bool articleWhenMediaPresent = %t;\n", format.ArticleWhenMediaPresent)
	fmt.Fprintf(&b, "  static const bool userConfirmationRequired = %t;\n", format.UserConfirmationRequired)
	fmt.Fprintf(&b, "  static const Duration personaRateWindow = Duration(seconds: %d);\n", rate.PersonaWindowSeconds)
	fmt.Fprintf(&b, "  static const int personaMaxPublications = %d;\n", rate.PersonaMaxPublications)
	fmt.Fprintf(&b, "  static const String rejectErrorCode = %q;\n", policy.Safety.RejectErrorCode)
	fmt.Fprintf(&b, "  static const String unavailableErrorCode = %q;\n", policy.Safety.UnavailableErrorCode)
	b.WriteString("}\n")
	return b.String()
}
