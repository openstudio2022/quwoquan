package main

import (
	"fmt"
	"sort"
	"strings"
)

func renderContentImageVariantPolicyDart(
	policy *contentImageVariantPolicyFile,
) string {
	if policy == nil {
		return ""
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from content/media/media_asset/image_variant_policy.yaml. DO NOT EDIT.\n\n")
	b.WriteString("final class ContentImageVariantProfile {\n")
	b.WriteString("  const ContentImageVariantProfile({\n")
	b.WriteString("    required this.width,\n")
	b.WriteString("    required this.format,\n")
	b.WriteString("    required this.quality,\n")
	b.WriteString("    required this.scene,\n")
	b.WriteString("    required this.processing,\n")
	b.WriteString("  });\n\n")
	b.WriteString("  final int width;\n")
	b.WriteString("  final String format;\n")
	b.WriteString("  final int quality;\n")
	b.WriteString("  final String scene;\n")
	b.WriteString("  final String processing;\n")
	b.WriteString("}\n\n")
	b.WriteString("abstract final class ContentImageVariantPolicy {\n")
	fmt.Fprintf(
		&b,
		"  static const int derivativePolicyVersion = %d;\n",
		policy.DerivativePolicyVersion,
	)
	b.WriteString("  static const Map<String, ContentImageVariantProfile> profiles = {\n")
	names := make([]string, 0, len(policy.Profiles))
	for name := range policy.Profiles {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		profile := policy.Profiles[name]
		fmt.Fprintf(&b, "    %q: ContentImageVariantProfile(\n", name)
		fmt.Fprintf(&b, "      width: %d,\n", profile.Width)
		fmt.Fprintf(&b, "      format: %q,\n", profile.Format)
		fmt.Fprintf(&b, "      quality: %d,\n", profile.Quality)
		fmt.Fprintf(&b, "      scene: %q,\n", profile.Scene)
		fmt.Fprintf(&b, "      processing: %q,\n", profile.Processing)
		b.WriteString("    ),\n")
	}
	b.WriteString("  };\n\n")
	b.WriteString("  static ContentImageVariantProfile profile(String name) {\n")
	b.WriteString("    final profile = profiles[name];\n")
	b.WriteString("    if (profile == null) {\n")
	b.WriteString("      throw ArgumentError.value(name, 'name', 'unknown image variant profile');\n")
	b.WriteString("    }\n")
	b.WriteString("    return profile;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}
