func renderDomainAPIMetadataDart(domain string, routes []routeDef, responseModelByReadModel map[string]string) string {
	var b strings.Builder
	className := toDartExportedName(domain) + "ApiMetadata"
	hasPathParams := false
	b.WriteString(fmt.Sprintf("// Code generated by tools/codegen_app_metadata from %s domain operations.yaml files. DO NOT EDIT.\n\n", domain))
	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString("import 'dart:core';\n\n")
	b.WriteString(fmt.Sprintf("class %s {\n", className))
	b.WriteString(fmt.Sprintf("  const %s._();\n\n", className))
	b.WriteString(fmt.Sprintf("  static const String domain = '%s';\n", domain))
	prefixes := collectRoutePrefixes(routes)
	b.WriteString("  static const List<String> apiPrefixes = <String>[\n")
	for _, prefix := range prefixes {
		b.WriteString(fmt.Sprintf("    '%s',\n", prefix))
	}
	b.WriteString("  ];\n\n")
	b.WriteString("  static const Map<String, String> operationToPathTemplate = <String, String>{\n")
	for _, route := range routes {
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", route.Operation, route.Path))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  static const Map<String, String> operationToMethod = <String, String>{\n")
	for _, route := range routes {
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", route.Operation, strings.ToUpper(route.Method)))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  /// 鉴权模式：public | optional | required（security.auth_mode 真相源）。\n")
	b.WriteString("  static const Map<String, String> operationToAuthMode = <String, String>{\n")
	for _, route := range routes {
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", route.Operation, route.resolveAuthMode()))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  /// 已绑定端侧强类型的响应读模型：operation -> Dart 契约类名。\n")
	b.WriteString("  static const Map<String, String> operationToResponseModel = <String, String>{\n")
	for _, route := range routes {
		body := strings.TrimSpace(route.ResponseBody)
		if body == "" {
			continue
		}
		dartClass := responseModelByReadModel[body]
		if dartClass == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", route.Operation, dartClass))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  /// 响应体形态：object 单对象 | page 分页列表（items） | ack 仅状态确认（无读模型）。\n")
	b.WriteString("  static const Map<String, String> operationToResponseKind = <String, String>{\n")
	for _, route := range routes {
		kind := strings.TrimSpace(route.ResponseBodyKind)
		if kind == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", route.Operation, kind))
	}
	b.WriteString("  };\n\n")
	for _, route := range routes {
		identifier := lowerCamel(route.Operation)
		b.WriteString(fmt.Sprintf("  static const String %sOperation = '%s';\n", identifier, route.Operation))
	}
	b.WriteString("\n")
	for _, route := range routes {
		identifier := lowerCamel(route.Operation)
		params := extractPathParams(route.Path)
		if len(params) == 0 {
			b.WriteString(fmt.Sprintf("  static const String %sPath = '%s';\n", identifier, route.Path))
			continue
		}
		hasPathParams = true
		b.WriteString(fmt.Sprintf("  static const String %sPathTemplate = '%s';\n", identifier, route.Path))
		b.WriteString(fmt.Sprintf("  static String %sPath({", identifier))
		for idx, param := range params {
			if idx > 0 {
				b.WriteString(", ")
			}
			b.WriteString(fmt.Sprintf("required String %s", param))
		}
		b.WriteString("}) {\n")
		b.WriteString(fmt.Sprintf("    return _fillPath(%sPathTemplate, <String, String>{\n", identifier))
		for _, param := range params {
			b.WriteString(fmt.Sprintf("      '%s': %s,\n", param, param))
		}
		b.WriteString("    });\n")
		b.WriteString("  }\n")
	}
	if hasPathParams {
		b.WriteString("\n  static String _fillPath(String template, Map<String, String> params) {\n")
		b.WriteString("    var path = template;\n")
		b.WriteString("    params.forEach((key, value) {\n")
		b.WriteString("      path = path.replaceAll('{$key}', Uri.encodeComponent(value));\n")
		b.WriteString("    });\n")
		b.WriteString("    return path;\n")
		b.WriteString("  }\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// renderAuthPolicyDart 聚合所有域的 operation -> auth_mode，作为端侧鉴权快照的单一来源，
// 供 AuthGate 矩阵交叉校验与 Remote token 使用测试消费。
func renderAuthPolicyDart(domainRoutes map[string][]routeDef) string {
	type opMode struct {
		op   string
		mode string
	}
	var entries []opMode
	seen := map[string]bool{}
	domains := make([]string, 0, len(domainRoutes))
	for d := range domainRoutes {
		domains = append(domains, d)
	}
	sort.Strings(domains)
	for _, d := range domains {
		for _, route := range domainRoutes[d] {
			if route.Operation == "" {
				continue
			}
			if seen[route.Operation] {
				panic(fmt.Sprintf(
					"duplicate short operation id %q; generate auth policy from canonical ContractGraph operation ids",
					route.Operation,
				))
			}
			seen[route.Operation] = true
			entries = append(entries, opMode{op: route.Operation, mode: route.resolveAuthMode()})
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].op < entries[j].op })

	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_app_metadata from all domain operations.yaml security blocks. DO NOT EDIT.\n\n")
	b.WriteString("import 'dart:core';\n\n")
	b.WriteString("/// 端侧 API 鉴权快照：operation -> 鉴权模式（public | optional | required）。\n")
	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString("class AuthApiPolicy {\n")
	b.WriteString("  const AuthApiPolicy._();\n\n")
	b.WriteString("  static const Map<String, String> operationToAuthMode = <String, String>{\n")
	for _, e := range entries {
		b.WriteString(fmt.Sprintf("    '%s': '%s',\n", e.op, e.mode))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  static bool isRequired(String operation) =>\n")
	b.WriteString("      operationToAuthMode[operation] == 'required';\n\n")
	b.WriteString("  static bool isPublic(String operation) =>\n")
	b.WriteString("      operationToAuthMode[operation] == 'public';\n\n")
	b.WriteString("  static bool isOptional(String operation) =>\n")
	b.WriteString("      operationToAuthMode[operation] == 'optional';\n")
	b.WriteString("}\n")
	return b.String()
}

// renderCanonicalAuthPolicyDart 只消费 App 已接收的 canonical operation，
// 避免不同领域的本地短名互相覆盖。
func renderCanonicalAuthPolicyDart(lock appContractLock) string {
	entries := append(
		[]appExposedOperation(nil),
		lock.AppExposedOperations...,
	)
	sort.Slice(entries, func(i, j int) bool {
		return entries[i].CanonicalOperationID <
			entries[j].CanonicalOperationID
	})

	var b strings.Builder
	b.WriteString("// Code generated by app-only-emitter from the accepted ContractGraph. DO NOT EDIT.\n\n")
	b.WriteString("import 'dart:core';\n\n")
	b.WriteString("/// 端侧 API 鉴权快照：canonical operation -> 鉴权模式。\n")
	b.WriteString("// ignore: avoid_classes_with_only_static_members\n")
	b.WriteString("class AuthApiPolicy {\n")
	b.WriteString("  const AuthApiPolicy._();\n\n")
	b.WriteString("  static const Map<String, String> operationToAuthMode = <String, String>{\n")
	for _, entry := range entries {
		b.WriteString(fmt.Sprintf(
			"    '%s': '%s',\n",
			entry.CanonicalOperationID,
			entry.AuthMode,
		))
	}
	b.WriteString("  };\n\n")
	b.WriteString("  static bool isRequired(String canonicalOperationId) =>\n")
	b.WriteString("      operationToAuthMode[canonicalOperationId] == 'required';\n\n")
	b.WriteString("  static bool isPublic(String canonicalOperationId) =>\n")
	b.WriteString("      operationToAuthMode[canonicalOperationId] == 'public';\n\n")
	b.WriteString("  static bool isOptional(String canonicalOperationId) =>\n")
	b.WriteString("      operationToAuthMode[canonicalOperationId] == 'optional';\n")
	b.WriteString("}\n")
	return b.String()
}

