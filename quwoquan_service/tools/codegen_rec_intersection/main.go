// Command codegen_rec_intersection 从交集 kind 注册表
// (services/recommendation-service/contracts/recommendation/recommendation_model_release/intersection_kind_registry.yaml)
// 生成服务端 Go 查表 (content-service/internal/generated/intersection_kind_table.go)，
// 取代 intersection_service.go / intersection_hydration.go 中手写的
// evidenceRank / iconKey / route / asset / actionKeys / actionLabel switch（§23 去桥接）。
//
// 与端侧 Dart codegen (tools/codegen_app_metadata) 共用 tools/recintersectionmeta 解析层，
// registry 是唯一真相源；门禁 scripts/recommendation/verify_intersection_kind_registry.py
// 校验本产物逐字段 == registry，禁止手改生成文件。
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
	"quwoquan_service/tools/recintersectionmeta"
)

func main() {
	metadataDir := flag.String("metadata-dir", "contracts/metadata", "contracts/metadata 根目录")
	outputDir := flag.String("output-dir", "services/content-service/generated/content/post", "生成 Go 表的输出目录")
	flag.Parse()

	source, err := contractcodegen.NewSource(*metadataDir, validate.ProfileBaseline)
	if err != nil {
		fail(fmt.Errorf("compile ContractGraph: %w", err))
	}
	const contractPath = "recommendation/recommendation/recommendation_model_release/intersection_kind_registry.yaml"
	raw, err := source.Content(contractPath)
	if err != nil {
		fail(fmt.Errorf("read intersection kind registry: %w", err))
	}
	registry, err := recintersectionmeta.Parse(raw)
	if err != nil {
		fail(fmt.Errorf("read intersection kind registry: %w", err))
	}
	if err := recintersectionmeta.Validate(registry); err != nil {
		fail(fmt.Errorf("validate intersection kind registry: %w", err))
	}

	out := renderGoTable(contractPath, registry)
	formatted, err := format.Source([]byte(out))
	if err != nil {
		fail(fmt.Errorf("gofmt generated table: %w", err))
	}
	outPath := filepath.Join(*outputDir, "intersection_kind_table.go")
	if err := os.MkdirAll(*outputDir, 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("[codegen_rec_intersection] wrote %s (%d kinds)\n", outPath, len(registry.Kinds))
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "[codegen_rec_intersection] FAIL: %v\n", err)
	os.Exit(1)
}

func renderGoTable(sourcePath string, r *recintersectionmeta.Registry) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_rec_intersection from recommendation/recommendation/recommendation_model_release/intersection_kind_registry.yaml. DO NOT EDIT.\n")
	b.WriteString("// Source: ")
	b.WriteString(filepath.ToSlash(sourcePath))
	b.WriteString("\n//\n")
	b.WriteString("// 交集 kind → 语义查表（云侧水合唯一真相源）。intersection_service.go /\n")
	b.WriteString("// intersection_hydration.go 一律查本表，禁止手写 kind/objectKind switch 第二份。\n")
	b.WriteString("package generated\n\n")

	// ── evidenceRank：kind → 证据组挖掘强度排序键（越小越靠前） ──
	b.WriteString("// IntersectionEvidenceRank: kind → evidenceKindRank（registry.kinds[].evidenceRank）。\n")
	b.WriteString("// pointClass==\"recommended\" 固定 900、未登记 kind 落 500 由消费方兜底，不入本表。\n")
	b.WriteString("var IntersectionEvidenceRank = map[string]int{\n")
	for _, k := range r.Kinds {
		b.WriteString(fmt.Sprintf("\t%q: %d,\n", k.Kind, k.EvidenceRank))
	}
	b.WriteString("}\n\n")

	// ── iconKey by kind ──
	b.WriteString("// IntersectionIconKeyByKind: kind → 端侧类型图标语义键（registry.kinds[].iconKey）。\n")
	b.WriteString("// 未登记 kind 返回零值（\"\"），消费方再走 dimension 末级回退。\n")
	b.WriteString("var IntersectionIconKeyByKind = map[string]string{\n")
	for _, k := range r.Kinds {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", k.Kind, k.IconKey))
	}
	b.WriteString("}\n\n")

	// ── iconKey by dimension（末级回退） ──
	b.WriteString("// IntersectionIconKeyByDimension: dimension → iconKey 末级回退（registry.iconKeyByDimension）。\n")
	b.WriteString("var IntersectionIconKeyByDimension = map[string]string{\n")
	writeSortedStringMap(&b, r.IconKeyByDimension)
	b.WriteString("}\n\n")

	// ── iconKey → tone / 远程图标资源（零发版视觉扩展位） ──
	b.WriteString("// IntersectionToneByIconKey: iconKey → 色板 token 名（registry.visualToneByIconKey）。\n")
	b.WriteString("// 云侧只下发色号名，端持 light/dark 成对调色板按主题取色；未登记 iconKey 查表落 \"\"。\n")
	b.WriteString("var IntersectionToneByIconKey = map[string]string{\n")
	writeSortedStringMap(&b, r.VisualToneByIcon)
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionIconAssetByIconKey: iconKey → 远程图标资源相对路径（registry.iconAssetByIconKey）。\n")
	b.WriteString("// 值是数据发布 media 根下的 alpha 蒙版图路径；为空表示该图标仍走端侧 glyph 兜底。\n")
	b.WriteString("// 新增交集类型图标 = 发一次数据 + 登记一行，不需要发端。\n")
	b.WriteString("var IntersectionIconAssetByIconKey = map[string]string{\n")
	writeSortedStringMap(&b, r.IconAssetByIconKey)
	b.WriteString("}\n\n")

	// ── objectKind → routeId / assetKind ──
	b.WriteString("// IntersectionRouteIDByObjectKind: objectKind → 端路由逻辑名（registry.objectKinds[].routeId）。\n")
	b.WriteString("// 仅登记非空 routeId；不可导航对象（content/tag）缺省查表落 \"\"（map 零值）。\n")
	b.WriteString("var IntersectionRouteIDByObjectKind = map[string]string{\n")
	for _, ok := range r.ObjectKinds {
		if strings.TrimSpace(ok.RouteID) == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", ok.Kind, ok.RouteID))
	}
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionAssetKindByObjectKind: objectKind → 对象视觉资产类型（registry.objectKinds[].assetKind）。\n")
	b.WriteString("// 仅登记声明了 assetKind 的主对象类型；未登记缺省由消费方兜底 \"icon\"。\n")
	b.WriteString("var IntersectionAssetKindByObjectKind = map[string]string{\n")
	for _, ok := range r.ObjectKinds {
		if strings.TrimSpace(ok.AssetKind) == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", ok.Kind, ok.AssetKind))
	}
	b.WriteString("}\n\n")

	// ── objectKind → dimension / label ──
	b.WriteString("// IntersectionDimensionByObjectKind: objectKind → 共享标签 reason 的交集维度\n")
	b.WriteString("// （registry.objectKinds[].dimension）。取代服务端手写的 objectDimension switch。\n")
	b.WriteString("var IntersectionDimensionByObjectKind = map[string]string{\n")
	for _, ok := range r.ObjectKinds {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", ok.Kind, ok.Dimension))
	}
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionLabelByObjectKind: objectKind → 展示名缺失时的兜底称谓\n")
	b.WriteString("// （registry.objectKinds[].label）。取代服务端手写的 objectLabel switch。\n")
	b.WriteString("var IntersectionLabelByObjectKind = map[string]string{\n")
	for _, ok := range r.ObjectKinds {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", ok.Kind, ok.Label))
	}
	b.WriteString("}\n\n")

	// ── objectType → objectKind ──
	b.WriteString("// IntersectionObjectKindByObjectType: 开放 objectType 词汇 → objectKind 闭集\n")
	b.WriteString("// （registry.objectTypeBindings）。HomepageType 全集逐值登记，不留 default；\n")
	b.WriteString("// 未登记 objectType 查表落 \"\"，由消费方 fail-safe，而不是静默当成人物。\n")
	b.WriteString("var IntersectionObjectKindByObjectType = map[string]string{\n")
	bindings := append([]recintersectionmeta.ObjectTypeBinding(nil), r.ObjectTypeBindings...)
	sort.Slice(bindings, func(i, j int) bool {
		return bindings[i].ObjectType < bindings[j].ObjectType
	})
	for _, binding := range bindings {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", binding.ObjectType, binding.ObjectKind))
	}
	b.WriteString("}\n\n")

	// ── actionKeys by kind ──
	b.WriteString("// IntersectionActionKeysByKind: kind → 行动建议 actionKey 有序列表（registry.actionHintsByKind）。\n")
	b.WriteString("// 未登记 kind 返回 nil，消费方兜底 [\"ask_assistant\"]。\n")
	b.WriteString("var IntersectionActionKeysByKind = map[string][]string{\n")
	actionKindKeys := make([]string, 0, len(r.ActionHintsByKind))
	for k := range r.ActionHintsByKind {
		actionKindKeys = append(actionKindKeys, k)
	}
	sort.Strings(actionKindKeys)
	for _, kind := range actionKindKeys {
		keys := r.ActionHintsByKind[kind]
		quoted := make([]string, 0, len(keys))
		for _, key := range keys {
			quoted = append(quoted, fmt.Sprintf("%q", key))
		}
		b.WriteString(fmt.Sprintf("\t%q: {%s},\n", kind, strings.Join(quoted, ", ")))
	}
	b.WriteString("}\n\n")

	// ── actionKey → 终端短标签 ──
	writeTextMap(&b, "IntersectionActionLabelByKey",
		"actionKey → 终端 UI 短标签（registry.actionLabelByKey）；未登记 key 由消费方兜底 ask_assistant 标签",
		r.ActionLabelPrefix, r.ActionLabelByKey)

	// ── moment by kind（§24 M0.2 意图时态；缺省 current） ──
	b.WriteString("// IntersectionMomentByKind: kind → 意图时态（registry.kinds[].moment，缺省 current）。\n")
	b.WriteString("// retrospective 回溯 / current 当下 / prospective 前瞻；与 lifecycleState 正交，未登记 kind 兜底 current。\n")
	b.WriteString("var IntersectionMomentByKind = map[string]string{\n")
	for _, k := range r.Kinds {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", k.Kind, k.MomentOrDefault()))
	}
	b.WriteString("}\n\n")

	// ── 意图时态 / 安全门 / 负反馈闭集（§24 M0.1/M0.2/M0.4，端云同源下发） ──
	writeStringSliceVar(&b, "IntersectionMoments",
		"意图时态闭集（registry.moments，retrospective|current|prospective）", r.Moments)
	writeStringSliceVar(&b, "IntersectionGateKeys",
		"安全门闭集（registry.gateKeys，requiredGates 取值域）", r.GateKeys)
	writeStringSliceVar(&b, "IntersectionFeedbackKinds",
		"负反馈闭集（registry.feedbackKinds，驱动降权/冷却）", r.FeedbackKinds)
	writeStringSliceVar(&b, "IntersectionActionDispatch",
		"行动路由类别闭集（registry.actionDispatch，M0.7；assistant|navigate|message|companion|connect|commerce）", r.ActionDispatch)

	// ── actionKey 行动阶梯元数据（§24 M0.1/M0.3；下发 IntersectionActionHint 时填充） ──
	akKeys := sortedActionKeyMetaKeys(r.ActionKeyMeta)
	b.WriteString("// IntersectionActionTierByKey: actionKey → tier（light|heavy，registry.actionKeyMeta）。\n")
	b.WriteString("var IntersectionActionTierByKey = map[string]string{\n")
	for _, key := range akKeys {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", key, r.ActionKeyMeta[key].Tier))
	}
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionRequiredGatesByActionKey: actionKey → 前置安全门有序列表（registry.actionKeyMeta.requiredGates ⊆ gateKeys）。\n")
	b.WriteString("var IntersectionRequiredGatesByActionKey = map[string][]string{\n")
	for _, key := range akKeys {
		gates := r.ActionKeyMeta[key].RequiredGates
		quoted := make([]string, 0, len(gates))
		for _, g := range gates {
			quoted = append(quoted, fmt.Sprintf("%q", g))
		}
		b.WriteString(fmt.Sprintf("\t%q: {%s},\n", key, strings.Join(quoted, ", ")))
	}
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionActionDispatchByKey: actionKey → 路由类别（registry.actionKeyMeta.dispatch ∈ actionDispatch，M0.7）。\n")
	b.WriteString("// 端交互 handler 路由维度，与 tier 权限成本正交；下发 IntersectionActionHint 时填充 dispatch。\n")
	b.WriteString("var IntersectionActionDispatchByKey = map[string]string{\n")
	for _, key := range akKeys {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", key, r.ActionKeyMeta[key].Dispatch))
	}
	b.WriteString("}\n\n")

	// ── 冷启动稀释闸门（P0 横切；Feed / List / ObjectIntersections 三入口共用） ──
	b.WriteString("// IntersectionColdStartSupplyKeyByKind: kind → 供给计量口径（registry.coldStartSupply.supplyKeyByKind）。\n")
	b.WriteString("// 未登记的 kind 不受冷启动闸门约束（对象池天然等于用户池等情形）。\n")
	b.WriteString("var IntersectionColdStartSupplyKeyByKind = map[string]string{\n")
	writeSortedStringMap(&b, r.ColdStartSupply.SupplyKeyByKind)
	b.WriteString("}\n\n")

	writeStatementTemplates(&b, r)

	writePresentationText(&b, r)

	b.WriteString("// IntersectionColdStartMinDistinctObjects: kind → 最小候选池规模（去重对象数）。\n")
	b.WriteString("// 语料供给低于该值时整类交集不展示：人人都命中的交集信息量为零（P0 稀释闸门）。\n")
	b.WriteString("var IntersectionColdStartMinDistinctObjects = map[string]int{\n")
	supplyKinds := make([]string, 0, len(r.ColdStartSupply.SupplyKeyByKind))
	for kind := range r.ColdStartSupply.SupplyKeyByKind {
		supplyKinds = append(supplyKinds, kind)
	}
	sort.Strings(supplyKinds)
	for _, kind := range supplyKinds {
		b.WriteString(fmt.Sprintf("\t%q: %d,\n", kind, r.ColdStartSupply.MinDistinctObjectsFor(kind)))
	}
	b.WriteString("}\n")

	return b.String()
}

// writeStatementTemplates 输出 §17.1 结论句模板表（registry.statementTemplates）。
//
// 文本与 spans 共用这一份模板：消费方按 kind 取 IntersectionStatementForm，用槽位值渲染，
// 因此 join(primarySpans.text) == primaryText 是渲染器的结构性结果，不再靠两份手写模板对齐。
func writeStatementTemplates(b *strings.Builder, r *recintersectionmeta.Registry) {
	st := r.StatementTemplates
	writeStringSliceVar(b, "IntersectionStatementSlots",
		"结论句槽位闭集（registry.statementTemplates.slots）", st.Slots)

	b.WriteString("// IntersectionStatementVariant 是一条可渲染模板：Template 带 {slot}，L10nKey 供端取译文。\n")
	b.WriteString("type IntersectionStatementVariant struct {\n")
	b.WriteString("\tTemplate string\n")
	b.WriteString("\tL10nKey  string\n")
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionStatementForm 是单个 kind 的结论句模板族。\n")
	b.WriteString("// Counted 为零值表示该 kind 无计数降级句（缺具名对象时整条隐藏，不造名）。\n")
	b.WriteString("type IntersectionStatementForm struct {\n")
	b.WriteString("\tTemplate       string\n")
	b.WriteString("\tL10nKey        string\n")
	b.WriteString("\tActionFallback string\n")
	b.WriteString("\tCounted        IntersectionStatementVariant\n")
	b.WriteString("\tVariants       map[string]IntersectionStatementVariant\n")
	b.WriteString("}\n\n")

	b.WriteString("// IntersectionStatementFormByKind: kind → 结论句模板族（registry.statementTemplates.byKind）。\n")
	b.WriteString("// 未登记 kind 查表落零值，消费方必须据此不产出结论句（§20.4 降级链末级：隐藏）。\n")
	b.WriteString("var IntersectionStatementFormByKind = map[string]IntersectionStatementForm{\n")
	kinds := make([]string, 0, len(st.ByKind))
	for kind := range st.ByKind {
		kinds = append(kinds, kind)
	}
	sort.Strings(kinds)
	for _, kind := range kinds {
		form := st.ByKind[kind]
		b.WriteString(fmt.Sprintf("\t%q: {\n", kind))
		b.WriteString(fmt.Sprintf("\t\tTemplate: %q,\n", form.Template))
		b.WriteString(fmt.Sprintf("\t\tL10nKey:  %q,\n", form.L10nKey))
		if strings.TrimSpace(form.ActionFallback) != "" {
			b.WriteString(fmt.Sprintf("\t\tActionFallback: %q,\n", form.ActionFallback))
		}
		if form.Counted != nil {
			b.WriteString(fmt.Sprintf("\t\tCounted: IntersectionStatementVariant{Template: %q, L10nKey: %q},\n",
				form.Counted.Template, form.Counted.L10nKey))
		}
		if len(form.Variants) > 0 {
			names := make([]string, 0, len(form.Variants))
			for name := range form.Variants {
				names = append(names, name)
			}
			sort.Strings(names)
			b.WriteString("\t\tVariants: map[string]IntersectionStatementVariant{\n")
			for _, name := range names {
				v := form.Variants[name]
				b.WriteString(fmt.Sprintf("\t\t\t%q: {Template: %q, L10nKey: %q},\n", name, v.Template, v.L10nKey))
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
}

// writePresentationText 输出 §17.2 展示文案层（registry.presentationText）。
//
// 每条文案生成 IntersectionText{Text, L10nKey} 对：Text 是可直接渲染的基线，
// L10nKey 供运营态覆盖与本地化按键取译文。服务端渲染层只查这些表，
// 不再持有中文字面量。
