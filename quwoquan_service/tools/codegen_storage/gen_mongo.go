package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"quwoquan_service/internal/metadata/codegen"
)

type mongoStoreData struct {
	CollName     string
	EntityName   string
	ShortName    string
	BaseName     string
	DomainPkg    string
	ModelImport  string
	HasCreatedAt bool
	Indexes      []mongoIdxData
}

type mongoIdxData struct {
	Name               string
	Keys               []mongoKeyData
	Unique             bool
	Sparse             bool
	HasExpiration      bool
	ExpireAfterSeconds int64
}

type mongoKeyData struct {
	Field     string
	ValueExpr string
}

func generateMongoStore(ctx *genContext, collName string, coll CollectionDef) error {
	dir := filepath.Join(ctx.outputDir(), ctx.source.infrastructurePath("persistence"))
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	entity := coll.Entity
	shortName := ctx.source.resolveStoreName(entity)
	snakeShort := codegen.CamelToSnake(shortName)

	data := mongoStoreData{
		CollName:     collName,
		EntityName:   entity,
		ShortName:    shortName,
		BaseName:     "Mongo" + shortName + "StoreBase",
		DomainPkg:    ctx.domainPkg(),
		ModelImport:  ctx.source.modelImport(ctx.modulePath()),
		HasCreatedAt: entityHasField(ctx, entity, "createdAt"),
	}

	for _, idx := range coll.Indexes {
		if len(idx.Keys) == 0 {
			return fmt.Errorf(
				"index %s uses a text/vector union not supported by the Mongo store generator; keep it in an object-owned implementation",
				idx.Name,
			)
		}
		if len(idx.PartialFilter) > 0 {
			return fmt.Errorf(
				"index %s uses partial_filter not supported by the Mongo store generator; keep it in an object-owned implementation",
				idx.Name,
			)
		}
		id := mongoIdxData{
			Name:   idx.Name,
			Unique: idx.Unique,
			Sparse: idx.Sparse,
		}
		if idx.ExpireAfterSeconds != nil {
			if *idx.ExpireAfterSeconds < 0 || *idx.ExpireAfterSeconds > math.MaxInt32 {
				return fmt.Errorf("index %s expire_after_seconds is outside Mongo int32 range", idx.Name)
			}
			id.HasExpiration = true
			id.ExpireAfterSeconds = *idx.ExpireAfterSeconds
		}
		keys := append([]string{}, idx.KeyOrder...)
		if len(keys) == 0 {
			keys = make([]string, 0, len(idx.Keys))
			for k := range idx.Keys {
				keys = append(keys, k)
			}
			sort.Strings(keys)
		}
		for _, k := range keys {
			if _, ok := idx.Keys[k]; !ok {
				return fmt.Errorf("index %s key_order references unknown key %s", idx.Name, k)
			}
			valueExpr, err := formatMongoIndexValue(idx.Keys[k])
			if err != nil {
				return fmt.Errorf("index %s key %s: %w", idx.Name, k, err)
			}
			id.Keys = append(id.Keys, mongoKeyData{Field: k, ValueExpr: valueExpr})
		}
		data.Indexes = append(data.Indexes, id)
	}

	tmpl, err := template.New("mongo_store").Parse(mongoStoreTemplate)
	if err != nil {
		return fmt.Errorf("parse mongo template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("execute mongo template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		formatted = buf.Bytes()
	}

	fileName := "mongo_" + snakeShort + "_store.g.go"
	path := filepath.Join(dir, fileName)
	fmt.Printf("  mongo_store: %s\n", fileName)
	return os.WriteFile(path, formatted, 0644)
}

func entityHasField(ctx *genContext, entityName, fieldName string) bool {
	entity, ok := ctx.fields.Entities[entityName]
	if !ok {
		return false
	}
	for _, field := range entity.Fields {
		if strings.EqualFold(field.Name, fieldName) {
			return true
		}
	}
	return false
}

const mongoStoreTemplate = `// Code generated by codegen_storage. DO NOT EDIT.
package persistence

import (
	"context"
	{{- if .HasCreatedAt}}
	"time"
	{{- end}}

	"go.mongodb.org/mongo-driver/v2/bson"
	"go.mongodb.org/mongo-driver/v2/mongo"
	"go.mongodb.org/mongo-driver/v2/mongo/options"

	model "{{.ModelImport}}"
)

// {{.BaseName}} provides generated MongoDB operations for {{.EntityName}}.
// Embed this in a public store type defined in _ext.go.
type {{.BaseName}} struct {
	coll *mongo.Collection
}

// New{{.BaseName}} wires the generated base to its collection.
func New{{.BaseName}}(coll *mongo.Collection) *{{.BaseName}} {
	return &{{.BaseName}}{coll: coll}
}

// EnsureIndexes creates required indexes on the {{.CollName}} collection.
func (s *{{.BaseName}}) EnsureIndexes(ctx context.Context) error {
	models := []mongo.IndexModel{
{{- range .Indexes}}
		{
			Keys: bson.D{
{{- range .Keys}}
				{Key: "{{.Field}}", Value: {{.ValueExpr}}},
{{- end}}
			},
			Options: options.Index().SetName("{{.Name}}"){{if .Unique}}.SetUnique(true){{end}}{{if .Sparse}}.SetSparse(true){{end}}{{if .HasExpiration}}.SetExpireAfterSeconds({{.ExpireAfterSeconds}}){{end}},
		},
{{- end}}
	}
	_, err := s.coll.Indexes().CreateMany(ctx, models)
	return err
}

// Create inserts a new {{.EntityName}} document. Returns false if duplicate key.
func (s *{{.BaseName}}) Create(ctx context.Context, e *model.{{.EntityName}}) (bool, error) {
	{{- if .HasCreatedAt}}
	e.CreatedAt = time.Now().UTC()
	{{- end}}
	_, err := s.coll.InsertOne(ctx, e)
	if err != nil {
		if mongo.IsDuplicateKeyError(err) {
			return false, nil
		}
		return false, err
	}
	return true, nil
}

// DeleteByFilter removes a document matching the filter.
func (s *{{.BaseName}}) DeleteByFilter(ctx context.Context, filter bson.M) (int64, error) {
	result, err := s.coll.DeleteOne(ctx, filter)
	if err != nil {
		return 0, err
	}
	return result.DeletedCount, nil
}

// ExistsByFilter checks if a document matching the filter exists.
func (s *{{.BaseName}}) ExistsByFilter(ctx context.Context, filter bson.M) (bool, error) {
	count, err := s.coll.CountDocuments(ctx, filter, options.Count().SetLimit(1))
	return count > 0, err
}

// CountByFilter returns the number of documents matching the filter.
func (s *{{.BaseName}}) CountByFilter(ctx context.Context, filter bson.M) (int64, error) {
	return s.coll.CountDocuments(ctx, filter)
}
`

func formatMongoIndexValue(value any) (string, error) {
	switch v := value.(type) {
	case int:
		return fmt.Sprintf("%d", v), nil
	case int64:
		return fmt.Sprintf("%d", v), nil
	case float64:
		if v == float64(int(v)) {
			return fmt.Sprintf("%d", int(v)), nil
		}
		return "", fmt.Errorf("unsupported non-integer numeric value %v", v)
	case string:
		return fmt.Sprintf("%q", v), nil
	default:
		return "", fmt.Errorf("unsupported mongo index value type %T", value)
	}
}
