package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"text/template"

	"quwoquan_service/internal/metadata/graph"
)

type eventsYAML struct {
	Events []eventDef `yaml:"events"`
}

type eventDef struct {
	Name string `yaml:"name"`
}

// generateMergedEventConstants merges events.yaml from all sources sharing the same
// domain_pkg and writes a single events.g.go per package. This prevents overwriting
// when multiple metadata sources map to the same Go package.
func generateMergedEventConstants(
	manifest *Manifest,
	contractGraph *graph.ContractGraph,
) error {
	// Group events by physical object and Go package. Generated code must remain
	// underneath generated/<context>/<object>; sharing a package name never grants
	// permission to merge two business objects into one output directory.
	pkgEvents := make(map[string][]eventDef)
	pkgOutputDir := make(map[string]string)
	pkgNames := make(map[string]string)

	for _, src := range manifest.Sources {
		eventsPath := filepath.ToSlash(filepath.Join(src.Metadata, "events.yaml"))
		if !contractGraph.HasDocument(eventsPath) {
			continue
		}
		var ev eventsYAML
		if err := contractGraph.DecodeDocumentYAML(eventsPath, &ev); err != nil {
			return fmt.Errorf("parse %s: %w", eventsPath, err)
		}
		pkg := filepath.ToSlash(filepath.Join(src.ObjectPath, src.domainPath()))
		pkgEvents[pkg] = appendUniqueEvents(pkgEvents[pkg], ev.Events)
		if _, exists := pkgNames[pkg]; !exists {
			pkgNames[pkg] = src.DomainPkg
		}
		// Record output dir (same for all sources with same domain_pkg + manifest)
		if _, exists := pkgOutputDir[pkg]; !exists {
			pkgOutputDir[pkg] = filepath.Join(
				manifest.OutputDir,
				src.ObjectPath,
				"contract",
				src.domainPath(),
				"event",
			)
		}
	}

	for pkg, events := range pkgEvents {
		if len(events) == 0 {
			continue
		}
		dir := pkgOutputDir[pkg]
		if err := os.MkdirAll(dir, 0755); err != nil {
			return err
		}

		tmpl, err := template.New("events").Parse(eventsTemplate)
		if err != nil {
			return fmt.Errorf("parse events template: %w", err)
		}

		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, struct {
			Package string
			Events  []eventDef
		}{Package: pkgNames[pkg], Events: events}); err != nil {
			return fmt.Errorf("execute events template for %s: %w", pkg, err)
		}

		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			formatted = buf.Bytes()
		}

		path := filepath.Join(dir, "events.g.go")
		fmt.Printf("  events: %s/events.g.go\n", pkg)
		if err := os.WriteFile(path, formatted, 0644); err != nil {
			return err
		}
	}
	return nil
}

func appendUniqueEvents(existing, incoming []eventDef) []eventDef {
	seen := make(map[string]bool, len(existing))
	for _, e := range existing {
		seen[e.Name] = true
	}
	for _, e := range incoming {
		if !seen[e.Name] {
			existing = append(existing, e)
			seen[e.Name] = true
		}
	}
	return existing
}

const eventsTemplate = `// Code generated by codegen_storage. DO NOT EDIT.
package event

const (
{{- range .Events}}
	{{.Name}} = "{{.Name}}"
{{- end}}
)
`
