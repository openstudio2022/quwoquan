// Command codegen_impact 从影响力 helpType 注册表
// (services/recommendation-service/contracts/recommendation/recommendation_model_release/impact_help_type_registry.yaml)
// 生成服务端 Go 查表 (runtime/impact/help_type_table.go, package impact)：
// Help* 常量 + helpType 闭集 + iconKey/summaryAction/evidenceAction 查表 + behaviorAction→helpType 反查表，
// 取代散落在 explain.go / author_impact_store.go / author_impact_language.go /
// author_impact_evidence_view.go / behavior_service.go / circle_service.go 的手写常量与 switch（§23 去桥接）。
//
// 与端侧 Dart codegen (tools/codegen_app_metadata) 共用 tools/recimpactmeta 解析层，registry 是唯一真相源。
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
	"quwoquan_service/tools/recimpactmeta"
)

func main() {
	metadataDir := flag.String("metadata-dir", "contracts/metadata", "contracts/metadata 根目录")
	outputDir := flag.String("output-dir", "runtime/impact", "生成 Go 表的输出目录 (package impact)")
	flag.Parse()

	source, err := contractcodegen.NewSource(*metadataDir, validate.ProfileBaseline)
	if err != nil {
		fail(fmt.Errorf("compile ContractGraph: %w", err))
	}
	const contractPath = "recommendation/recommendation/recommendation_model_release/impact_help_type_registry.yaml"
	raw, err := source.Content(contractPath)
	if err != nil {
		fail(fmt.Errorf("read impact help type registry: %w", err))
	}
	registry, err := recimpactmeta.Parse(raw)
	if err != nil {
		fail(fmt.Errorf("read impact help type registry: %w", err))
	}
	if err := recimpactmeta.Validate(registry); err != nil {
		fail(fmt.Errorf("validate impact help type registry: %w", err))
	}

	out := renderGoTable(contractPath, registry)
	formatted, err := format.Source([]byte(out))
	if err != nil {
		fail(fmt.Errorf("gofmt generated table: %w", err))
	}
	outPath := filepath.Join(*outputDir, "help_type_table.go")
	if err := os.MkdirAll(*outputDir, 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("[codegen_impact] wrote %s (%d helpTypes)\n", outPath, len(registry.HelpTypes))
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "[codegen_impact] FAIL: %v\n", err)
	os.Exit(1)
}

func goConstName(helpType string) string {
	h := strings.TrimSpace(helpType)
	if h == "" {
		return "Help"
	}
	return "Help" + strings.ToUpper(h[:1]) + h[1:]
}

func renderGoTable(sourcePath string, r *recimpactmeta.Registry) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen_impact from recommendation/recommendation/recommendation_model_release/impact_help_type_registry.yaml. DO NOT EDIT.\n")
	b.WriteString("// Source: ")
	b.WriteString(filepath.ToSlash(sourcePath))
	b.WriteString("\n//\n")
	b.WriteString("// 影响力 helpType → 语义查表（云侧唯一真相源）。explain.go / author_impact_language.go /\n")
	b.WriteString("// author_impact_evidence_view.go / behavior_service.go 一律查本表，禁止手写 helpType switch 第二份。\n")
	b.WriteString("package impact\n\n")

	// ── helpType 标准名常量 ──
	b.WriteString("// helpType 标准名（registry.helpTypes[].helpType）。\n")
	b.WriteString("const (\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("\t%s = %q\n", goConstName(h.HelpType), h.HelpType))
	}
	b.WriteString(")\n\n")

	// ── helpType 闭集 ──
	b.WriteString("// HelpTypes 是 helpType 闭集（registry 顺序）。\n")
	b.WriteString("var HelpTypes = []string{\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("\t%s,\n", goConstName(h.HelpType)))
	}
	b.WriteString("}\n\n")

	// ── ImpactAction DTO ──
	b.WriteString("// ImpactAction 是影响力行动建议 {key,label}（summary / evidence / default 共用）。\n")
	b.WriteString("type ImpactAction struct {\n")
	b.WriteString("\tKey   string\n")
	b.WriteString("\tLabel string\n")
	b.WriteString("}\n\n")

	// ── iconKey by helpType ──
	b.WriteString("// IconKeyByHelpType: helpType → 端设计系统图标语义键（registry.helpTypes[].iconKey）。\n")
	b.WriteString("// 未登记 helpType 由消费方兜底 DefaultIconKey。\n")
	b.WriteString("var IconKeyByHelpType = map[string]string{\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("\t%s: %q,\n", goConstName(h.HelpType), h.IconKey))
	}
	b.WriteString("}\n\n")
	b.WriteString(fmt.Sprintf("// DefaultIconKey 是未登记 helpType 的防御默认 iconKey（registry.defaults.iconKey）。\n"))
	b.WriteString(fmt.Sprintf("const DefaultIconKey = %q\n\n", r.Defaults.IconKey))

	// ── summaryAction / evidenceAction by helpType ──
	b.WriteString("// SummaryActionByHelpType: helpType → 影响力卡主行动 {key,label}（registry.helpTypes[].summaryAction）。\n")
	b.WriteString("var SummaryActionByHelpType = map[string]ImpactAction{\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("\t%s: {Key: %q, Label: %q},\n", goConstName(h.HelpType), h.SummaryAction.Key, h.SummaryAction.Label))
	}
	b.WriteString("}\n\n")
	b.WriteString(fmt.Sprintf("// DefaultSummaryAction 未登记 helpType 兜底（registry.defaults.summaryAction）。\n"))
	b.WriteString(fmt.Sprintf("var DefaultSummaryAction = ImpactAction{Key: %q, Label: %q}\n\n", r.Defaults.SummaryAction.Key, r.Defaults.SummaryAction.Label))

	b.WriteString("// EvidenceActionByHelpType: helpType → 影响力证据明细行主行动 {key,label}（registry.helpTypes[].evidenceAction）。\n")
	b.WriteString("var EvidenceActionByHelpType = map[string]ImpactAction{\n")
	for _, h := range r.HelpTypes {
		b.WriteString(fmt.Sprintf("\t%s: {Key: %q, Label: %q},\n", goConstName(h.HelpType), h.EvidenceAction.Key, h.EvidenceAction.Label))
	}
	b.WriteString("}\n\n")
	b.WriteString(fmt.Sprintf("// DefaultEvidenceAction 未登记 helpType 兜底（registry.defaults.evidenceAction）。\n"))
	b.WriteString(fmt.Sprintf("var DefaultEvidenceAction = ImpactAction{Key: %q, Label: %q}\n\n", r.Defaults.EvidenceAction.Key, r.Defaults.EvidenceAction.Label))

	// ── behaviorAction → helpType 反查 ──
	b.WriteString("// BehaviorActionToHelpType: 行为信号 action → helpType（registry.helpTypes[].behaviorActions 反查）。\n")
	b.WriteString("// 未命中 action 不产出影响力事件；behaviorActions 为空的 helpType（如 audience）仅 seed/投影产出。\n")
	b.WriteString("var BehaviorActionToHelpType = map[string]string{\n")
	type pair struct{ action, helpType string }
	pairs := make([]pair, 0)
	for _, h := range r.HelpTypes {
		for _, a := range h.BehaviorActions {
			pairs = append(pairs, pair{a, goConstName(h.HelpType)})
		}
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].action < pairs[j].action })
	for _, p := range pairs {
		b.WriteString(fmt.Sprintf("\t%q: %s,\n", p.action, p.helpType))
	}
	b.WriteString("}\n")

	return b.String()
}
