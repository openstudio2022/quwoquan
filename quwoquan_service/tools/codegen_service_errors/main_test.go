package main

import (
	"strings"
	"testing"
)

func TestRenderErrorsUsesMetadataMessageAndRecovery(t *testing.T) {
	generated, err := renderErrors("assistant", []errorEntry{
		{
			Code:                 "ASSISTANT.SYSTEM.preference_storage_unavailable",
			Reason:               "unavailable",
			HTTPStatus:           503,
			GoConst:              "ErrPreferenceStorageUnavailable",
			RecoveryAction:       "retry",
			RecoveryAfterSeconds: 3,
			UserMessage: map[string]string{
				"zh": "偏好服务暂不可用，请稍后重试",
			},
		},
	})
	if err != nil {
		t.Fatalf("renderErrors() error = %v", err)
	}
	text := string(generated)
	for _, expected := range []string{
		"Code generated by tools/codegen_service_errors. DO NOT EDIT.",
		"func AppErrorFromPreferenceStorageUnavailable",
		"偏好服务暂不可用，请稍后重试",
		`.WithMetadata("unavailable", 503).WithRecovery("retry", 3)`,
	} {
		if !strings.Contains(text, expected) {
			t.Fatalf("generated output missing %q:\n%s", expected, text)
		}
	}
}

func TestRenderErrorsRejectsMissingMetadataMessage(t *testing.T) {
	_, err := renderErrors("assistant", []errorEntry{
		{
			Code:           "ASSISTANT.USER.preference_not_found",
			Reason:         "not_found",
			HTTPStatus:     404,
			GoConst:        "ErrPreferenceNotFound",
			RecoveryAction: "refresh",
		},
	})
	if err == nil {
		t.Fatal("renderErrors() must reject missing user_message.zh")
	}
}
