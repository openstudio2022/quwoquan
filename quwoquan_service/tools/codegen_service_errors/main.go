package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

type errorEntry struct {
	Code                 string            `yaml:"code"`
	Reason               string            `yaml:"reason"`
	HTTPStatus           int               `yaml:"http_status"`
	GoConst              string            `yaml:"go_const"`
	RecoveryAction       string            `yaml:"recovery_action"`
	RecoveryAfterSeconds int               `yaml:"recovery_after_seconds"`
	UserMessage          map[string]string `yaml:"user_message"`
}

type errorsDocument struct {
	Domain string       `yaml:"domain"`
	Errors []errorEntry `yaml:"errors"`
}

func main() {
	var metadataDir string
	var domain string
	var output string
	var check bool
	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&domain, "domain", "", "metadata domain to generate")
	flag.StringVar(&output, "output", "", "generated Go file")
	flag.BoolVar(&check, "check", false, "fail when generated output is stale")
	flag.Parse()

	if strings.TrimSpace(domain) == "" || strings.TrimSpace(output) == "" {
		exitErr(fmt.Errorf("--domain and --output are required"))
	}
	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		exitErr(fmt.Errorf("compile ContractGraph: %w", err))
	}
	entries, err := collectErrors(source, domain)
	if err != nil {
		exitErr(err)
	}
	generated, err := renderErrors(domain, entries)
	if err != nil {
		exitErr(err)
	}
	if check {
		current, readErr := os.ReadFile(output)
		if readErr != nil {
			exitErr(fmt.Errorf("read generated output: %w", readErr))
		}
		if !bytes.Equal(current, generated) {
			exitErr(fmt.Errorf("generated %s errors are stale: %s", domain, output))
		}
		fmt.Printf("verified %s errors at %s\n", domain, output)
		return
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		exitErr(err)
	}
	if err := os.WriteFile(output, generated, 0o644); err != nil {
		exitErr(err)
	}
	fmt.Printf("generated %s errors at %s\n", domain, output)
}

func collectErrors(
	source *contractcodegen.Source,
	domain string,
) ([]errorEntry, error) {
	paths := source.Paths(strings.TrimSpace(domain)+"/", "errors.yaml")
	if len(paths) == 0 {
		return nil, fmt.Errorf("no errors.yaml found for domain %s", domain)
	}
	seenCodes := map[string]string{}
	seenConstants := map[string]string{}
	entries := []errorEntry{}
	for _, path := range paths {
		var document errorsDocument
		if err := source.Decode(path, &document); err != nil {
			return nil, fmt.Errorf("decode %s: %w", path, err)
		}
		if !strings.EqualFold(strings.TrimSpace(document.Domain), domain) {
			return nil, fmt.Errorf(
				"%s domain %q does not match %q",
				path,
				document.Domain,
				domain,
			)
		}
		for _, entry := range document.Errors {
			if strings.TrimSpace(entry.GoConst) == "" {
				continue
			}
			if previous := seenCodes[entry.Code]; previous != "" {
				return nil, fmt.Errorf(
					"duplicate error code %s in %s and %s",
					entry.Code,
					previous,
					path,
				)
			}
			if previous := seenConstants[entry.GoConst]; previous != "" {
				return nil, fmt.Errorf(
					"duplicate Go constant %s in %s and %s",
					entry.GoConst,
					previous,
					path,
				)
			}
			seenCodes[entry.Code] = path
			seenConstants[entry.GoConst] = path
			entries = append(entries, entry)
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		return entries[i].GoConst < entries[j].GoConst
	})
	return entries, nil
}

func renderErrors(domain string, entries []errorEntry) ([]byte, error) {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by tools/codegen_service_errors. DO NOT EDIT.\n")
	buffer.WriteString("package generated\n\n")
	buffer.WriteString("import (\n")
	buffer.WriteString("\t\"errors\"\n\n")
	buffer.WriteString("\trterr \"quwoquan_service/runtime/errors\"\n")
	buffer.WriteString(")\n\n")
	buffer.WriteString("//nolint:gochecknoglobals\n")
	buffer.WriteString("var (\n")
	for _, entry := range entries {
		if err := validateEntry(entry); err != nil {
			return nil, err
		}
		fmt.Fprintf(
			&buffer,
			"\t%s = errors.New(%q)\n",
			entry.GoConst,
			entry.Code,
		)
	}
	buffer.WriteString(")\n")
	for _, entry := range entries {
		functionName := "AppErrorFrom" + strings.TrimPrefix(entry.GoConst, "Err")
		fmt.Fprintf(
			&buffer,
			"\n// %s returns *AppError for %s (user_message from errors.yaml).\n",
			functionName,
			entry.Code,
		)
		fmt.Fprintf(
			&buffer,
			"func %s(debugMessage string) *rterr.AppError {\n",
			functionName,
		)
		fmt.Fprintf(&buffer, "\tcode, _ := rterr.ParseCode(%q)\n", entry.Code)
		fmt.Fprintf(
			&buffer,
			"\treturn rterr.NewAppError(code, %q, debugMessage).WithMetadata(%q, %d).WithRecovery(%q, %d)\n",
			strings.TrimSpace(entry.UserMessage["zh"]),
			strings.TrimSpace(entry.Reason),
			entry.HTTPStatus,
			strings.TrimSpace(entry.RecoveryAction),
			entry.RecoveryAfterSeconds,
		)
		buffer.WriteString("}\n")
	}
	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated %s errors: %w", domain, err)
	}
	return formatted, nil
}

func validateEntry(entry errorEntry) error {
	switch {
	case strings.TrimSpace(entry.Code) == "":
		return fmt.Errorf("error code is required")
	case strings.TrimSpace(entry.GoConst) == "":
		return fmt.Errorf("%s go_const is required", entry.Code)
	case strings.TrimSpace(entry.Reason) == "":
		return fmt.Errorf("%s reason is required", entry.Code)
	case entry.HTTPStatus < 400:
		return fmt.Errorf("%s http_status must be >= 400", entry.Code)
	case strings.TrimSpace(entry.RecoveryAction) == "":
		return fmt.Errorf("%s recovery_action is required", entry.Code)
	case strings.TrimSpace(entry.UserMessage["zh"]) == "":
		return fmt.Errorf("%s user_message.zh is required", entry.Code)
	default:
		return nil
	}
}

func exitErr(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
