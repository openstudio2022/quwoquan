// codegen_rtc_service 从 rtc metadata 生成 rtc-service 的服务端产物：
// generated/rtc/call_session 下的错误和 transport 路由契约。
// 唯一真相源：services/rtc-service/contracts/rtc/call_session/{errors,service}.yaml。
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	"quwoquan_service/internal/metadata/validate"
)

type serviceRoutesFile struct {
	APIRoutes []struct {
		Method    string `yaml:"method"`
		Path      string `yaml:"path"`
		Operation string `yaml:"operation"`
	} `yaml:"api_routes"`
}

type realtimeEventsFile struct {
	Events []struct {
		Name          string   `yaml:"name"`
		ClientWsType  string   `yaml:"client_ws_type"`
		PayloadFields []string `yaml:"payload_fields"`
	} `yaml:"events"`
}

func main() {
	var metadataDir string
	var outputDir string
	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&outputDir, "output-dir", "services/rtc-service/generated/rtc/call_session", "rtc-service generated object output directory")
	flag.Parse()

	source, err := contractcodegen.NewSource(metadataDir, validate.ProfileBaseline)
	if err != nil {
		exitErr(fmt.Errorf("compile ContractGraph: %w", err))
	}

	var errorsFile contractcodegen.ErrorsFile
	const errorsSource = "rtc/rtc/call_session/errors.yaml"
	if err := source.Decode(errorsSource, &errorsFile); err != nil {
		exitErr(fmt.Errorf("load %s: %w", errorsSource, err))
	}
	writeGoFile(
		filepath.Join(outputDir, "errors.go"),
		contractcodegen.RenderGoErrorsFile(&errorsFile, contractcodegen.GoErrorsFileOptions{
			Generator:    "tools/codegen_rtc_service",
			SourcePath:   errorsSource,
			CommentLines: []string{"RTC error sentinels and helpers. user_message from errors.yaml user_message.zh."},
		}),
	)

	var routes serviceRoutesFile
	const routesSource = "rtc/rtc/call_session/operations.yaml"
	if err := source.Decode(routesSource, &routes); err != nil {
		exitErr(fmt.Errorf("load %s: %w", routesSource, err))
	}
	if len(routes.APIRoutes) == 0 {
		exitErr(fmt.Errorf("%s: api_routes must not be empty", routesSource))
	}
	var table strings.Builder
	table.WriteString("// Code generated by tools/codegen_rtc_service from contracts/metadata/" + routesSource + ". DO NOT EDIT.\n")
	table.WriteString("package transport\n\n")
	table.WriteString("type RouteEntry struct {\n")
	table.WriteString("\tMethod    string\n")
	table.WriteString("\tTemplate  string\n")
	table.WriteString("\tOperation string\n")
	table.WriteString("}\n\n")
	table.WriteString("var RouteTable = []RouteEntry{\n")
	for _, route := range routes.APIRoutes {
		method := strings.TrimSpace(route.Method)
		path := strings.TrimSpace(route.Path)
		operation := strings.TrimSpace(route.Operation)
		if method == "" || path == "" || operation == "" {
			exitErr(fmt.Errorf("%s: route requires method, path and operation", routesSource))
		}
		table.WriteString(fmt.Sprintf("\t{%q, %q, %q},\n", method, path, operation))
	}
	table.WriteString("}\n")
	writeGoFile(filepath.Join(outputDir, "transport", "routes.g.go"), table.String())

	var realtimeEvents realtimeEventsFile
	const realtimeEventsSource = "rtc/rtc/call_session/events.yaml"
	if err := source.Decode(realtimeEventsSource, &realtimeEvents); err != nil {
		exitErr(fmt.Errorf("load %s: %w", realtimeEventsSource, err))
	}
	realtimeFields, err := renderRealtimePayloadFields(
		realtimeEventsSource,
		realtimeEvents,
	)
	if err != nil {
		exitErr(err)
	}
	writeGoFile(
		filepath.Join(outputDir, "realtime_payload_fields.g.go"),
		realtimeFields,
	)
}

func renderRealtimePayloadFields(
	sourcePath string,
	document realtimeEventsFile,
) (string, error) {
	seen := map[string]string{}
	var output strings.Builder
	output.WriteString("// Code generated by tools/codegen_rtc_service from contracts/metadata/" + sourcePath + ". DO NOT EDIT.\n")
	output.WriteString("package generated\n\n")
	output.WriteString("var clientRealtimePayloadFieldsByWireType = map[string][]string{\n")
	for _, item := range document.Events {
		name := strings.TrimSpace(item.Name)
		wireType := strings.TrimSpace(item.ClientWsType)
		if wireType == "" {
			continue
		}
		if previous, exists := seen[wireType]; exists {
			return "", fmt.Errorf("%s client_ws_type %q is owned by both %s and %s", sourcePath, wireType, previous, name)
		}
		if len(item.PayloadFields) == 0 {
			return "", fmt.Errorf("%s realtime event %s has no payload_fields", sourcePath, name)
		}
		seen[wireType] = name
		output.WriteString(fmt.Sprintf("\t%q: {\n", wireType))
		fieldSeen := map[string]struct{}{}
		for _, rawField := range item.PayloadFields {
			field := strings.TrimSpace(rawField)
			if field == "" {
				return "", fmt.Errorf("%s realtime event %s has an empty payload field", sourcePath, name)
			}
			if _, duplicate := fieldSeen[field]; duplicate {
				return "", fmt.Errorf("%s realtime event %s duplicates payload field %s", sourcePath, name, field)
			}
			fieldSeen[field] = struct{}{}
			output.WriteString(fmt.Sprintf("\t\t%q,\n", field))
		}
		output.WriteString("\t},\n")
	}
	if len(seen) == 0 {
		return "", fmt.Errorf("%s declares no client realtime events", sourcePath)
	}
	output.WriteString("}\n\n")
	output.WriteString("func ClientRealtimePayloadFieldNames(wireType string) ([]string, bool) {\n")
	output.WriteString("\tfields, exists := clientRealtimePayloadFieldsByWireType[wireType]\n")
	output.WriteString("\tif !exists { return nil, false }\n")
	output.WriteString("\treturn append([]string(nil), fields...), true\n")
	output.WriteString("}\n")
	return output.String(), nil
}

func writeGoFile(path string, contents string) {
	formatted, err := format.Source([]byte(contents))
	if err != nil {
		exitErr(fmt.Errorf("gofmt %s: %w", path, err))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		exitErr(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		exitErr(err)
	}
	fmt.Printf("codegen_rtc_service: wrote %s\n", path)
}

func exitErr(err error) {
	fmt.Fprintf(os.Stderr, "codegen_rtc_service error: %v\n", err)
	os.Exit(1)
}
