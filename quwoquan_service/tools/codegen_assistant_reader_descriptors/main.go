// codegen_assistant_reader_descriptors 从对象契约的
// assistant_access.read.reader 声明生成 DomainReaderDescriptor 目录数据表。
//
// 生成物是纯数据（不 import internal），由 assistant_run 的 skillcontext
// 组合层映射为 domain model；目录的唯一真相源是各对象契约。
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	contractvalidate "quwoquan_service/internal/metadata/validate"
)

type readerDeclaration struct {
	DescriptorID        string   `yaml:"descriptor_id"`
	ResolverRef         string   `yaml:"resolver_ref"`
	OwnerService        string   `yaml:"owner_service"`
	OwnerOperationRef   string   `yaml:"owner_operation_ref"`
	InputSchemaRef      string   `yaml:"input_schema_ref"`
	OutputSchemaRef     string   `yaml:"output_schema_ref"`
	ObjectTypeRef       string   `yaml:"object_type_ref"`
	Authority           string   `yaml:"authority"`
	Sensitivity         string   `yaml:"sensitivity"`
	AcceptedSourceKinds []string `yaml:"accepted_source_kinds"`
	SurfaceKinds        []string `yaml:"surface_kinds"`
	MaxFreshnessSeconds int      `yaml:"max_freshness_seconds"`
	CacheTTLSeconds     int      `yaml:"cache_ttl_seconds"`
	ArtifactPolicy      string   `yaml:"artifact_policy"`
	CitationPolicy      string   `yaml:"citation_policy"`
}

type objectDocument struct {
	AssistantAccess struct {
		Read struct {
			Mode   string             `yaml:"mode"`
			Reader *readerDeclaration `yaml:"reader"`
		} `yaml:"read"`
	} `yaml:"assistant_access"`
}

func main() {
	metadataDir := flag.String("metadata-dir", "", "contract view root (<domain>/<context>/<object>)")
	output := flag.String("output", "", "generated Go file path")
	flag.Parse()
	if *metadataDir == "" || *output == "" {
		fmt.Fprintln(os.Stderr, "usage: codegen_assistant_reader_descriptors --metadata-dir <dir> --output <file>")
		os.Exit(2)
	}
	declarations, err := collect(*metadataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "codegen_assistant_reader_descriptors: %v\n", err)
		os.Exit(1)
	}
	if len(declarations) == 0 {
		fmt.Fprintln(os.Stderr, "codegen_assistant_reader_descriptors: 0 reader declarations; an empty catalogue is never emitted silently")
		os.Exit(1)
	}
	if err := os.WriteFile(*output, []byte(render(declarations)), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "codegen_assistant_reader_descriptors: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("codegen_assistant_reader_descriptors: %d descriptor(s) -> %s\n", len(declarations), *output)
}

func collect(metadataDir string) ([]readerDeclaration, error) {
	// 治理约束：generator 只允许经统一 ContractGraph Source 读取契约，
	// 禁止自行扫 metadata 文件系统（verify_codegen_contract_graph_source.py）。
	source, err := contractcodegen.NewSource(
		metadataDir,
		contractvalidate.ProfileBaseline,
	)
	if err != nil {
		return nil, fmt.Errorf("compile ContractGraph: %w", err)
	}
	var objectPaths []string
	for _, path := range source.Paths("", "object.yaml") {
		// 与既有目录轴一致：只认 <domain>/<context>/<object>/object.yaml。
		if strings.Count(path, "/") == 3 {
			objectPaths = append(objectPaths, path)
		}
	}
	if len(objectPaths) == 0 {
		return nil, fmt.Errorf("scanned 0 object.yaml under %s", metadataDir)
	}
	seen := map[string]string{}
	var declarations []readerDeclaration
	for _, path := range objectPaths {
		var document objectDocument
		if err := source.Decode(path, &document); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		reader := document.AssistantAccess.Read.Reader
		if reader == nil {
			continue
		}
		if document.AssistantAccess.Read.Mode == "none" {
			return nil, fmt.Errorf("%s: reader declared while read.mode=none", path)
		}
		if previous, duplicate := seen[reader.DescriptorID]; duplicate {
			return nil, fmt.Errorf(
				"duplicate descriptor_id %q declared by %s and %s",
				reader.DescriptorID, previous, path,
			)
		}
		seen[reader.DescriptorID] = path
		declarations = append(declarations, *reader)
	}
	sort.Slice(declarations, func(left, right int) bool {
		return declarations[left].DescriptorID < declarations[right].DescriptorID
	})
	return declarations, nil
}

func render(declarations []readerDeclaration) string {
	var builder strings.Builder
	builder.WriteString(
		"// Code generated by tools/codegen_assistant_reader_descriptors from\n" +
			"// object contract assistant_access.read.reader declarations. DO NOT EDIT.\n" +
			"package generated\n\n" +
			"// ContractReaderDescriptor mirrors one object contract reader declaration.\n" +
			"type ContractReaderDescriptor struct {\n" +
			"\tDescriptorID        string\n" +
			"\tResolverRef         string\n" +
			"\tOwnerService        string\n" +
			"\tOwnerOperationRef   string\n" +
			"\tInputSchemaRef      string\n" +
			"\tOutputSchemaRef     string\n" +
			"\tObjectTypeRef       string\n" +
			"\tAuthority           string\n" +
			"\tSensitivity         string\n" +
			"\tAcceptedSourceKinds []string\n" +
			"\tSurfaceKinds        []string\n" +
			"\tMaxFreshnessSeconds int\n" +
			"\tCacheTTLSeconds     int\n" +
			"\tArtifactPolicy      string\n" +
			"\tCitationPolicy      string\n" +
			"}\n\n" +
			"// ContractReaderDescriptors returns the contract-derived Reader catalogue.\n" +
			"func ContractReaderDescriptors() []ContractReaderDescriptor {\n" +
			"\treturn []ContractReaderDescriptor{\n",
	)
	for _, declaration := range declarations {
		builder.WriteString("\t\t{\n")
		builder.WriteString(fmt.Sprintf("\t\t\tDescriptorID:        %q,\n", declaration.DescriptorID))
		builder.WriteString(fmt.Sprintf("\t\t\tResolverRef:         %q,\n", declaration.ResolverRef))
		builder.WriteString(fmt.Sprintf("\t\t\tOwnerService:        %q,\n", declaration.OwnerService))
		builder.WriteString(fmt.Sprintf("\t\t\tOwnerOperationRef:   %q,\n", declaration.OwnerOperationRef))
		builder.WriteString(fmt.Sprintf("\t\t\tInputSchemaRef:      %q,\n", declaration.InputSchemaRef))
		builder.WriteString(fmt.Sprintf("\t\t\tOutputSchemaRef:     %q,\n", declaration.OutputSchemaRef))
		builder.WriteString(fmt.Sprintf("\t\t\tObjectTypeRef:       %q,\n", declaration.ObjectTypeRef))
		builder.WriteString(fmt.Sprintf("\t\t\tAuthority:           %q,\n", declaration.Authority))
		builder.WriteString(fmt.Sprintf("\t\t\tSensitivity:         %q,\n", declaration.Sensitivity))
		builder.WriteString(fmt.Sprintf("\t\t\tAcceptedSourceKinds: %s,\n", goStringSlice(declaration.AcceptedSourceKinds)))
		builder.WriteString(fmt.Sprintf("\t\t\tSurfaceKinds:        %s,\n", goStringSlice(declaration.SurfaceKinds)))
		builder.WriteString(fmt.Sprintf("\t\t\tMaxFreshnessSeconds: %d,\n", declaration.MaxFreshnessSeconds))
		builder.WriteString(fmt.Sprintf("\t\t\tCacheTTLSeconds:     %d,\n", declaration.CacheTTLSeconds))
		builder.WriteString(fmt.Sprintf("\t\t\tArtifactPolicy:      %q,\n", declaration.ArtifactPolicy))
		builder.WriteString(fmt.Sprintf("\t\t\tCitationPolicy:      %q,\n", declaration.CitationPolicy))
		builder.WriteString("\t\t},\n")
	}
	builder.WriteString("\t}\n}\n")
	return builder.String()
}

func goStringSlice(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}
