package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	contractvalidate "quwoquan_service/internal/metadata/validate"
)

type catalogDocument struct {
	Catalog string           `yaml:"catalog"`
	Tools   []map[string]any `yaml:"tools"`
}

func main() {
	var metadataDir string
	var output string
	var check bool
	flag.StringVar(&metadataDir, "metadata-dir", "", "compiled service contract view")
	flag.StringVar(&output, "output", "", "generated Go catalog output")
	flag.BoolVar(&check, "check", false, "fail when generated output is stale")
	flag.Parse()
	if strings.TrimSpace(metadataDir) == "" || strings.TrimSpace(output) == "" {
		fail("--metadata-dir and --output are required")
	}
	content, err := generate(metadataDir)
	if err != nil {
		fail(err.Error())
	}
	if check {
		existing, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(existing, content) {
			fail("generated assistant tool catalog is stale; run make codegen-assistant-tool-catalog")
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		fail(err.Error())
	}
	if err := os.WriteFile(output, content, 0o644); err != nil {
		fail(err.Error())
	}
}

func generate(metadataDir string) ([]byte, error) {
	source, err := contractcodegen.NewSource(metadataDir, contractvalidate.ProfileBaseline)
	if err != nil {
		return nil, fmt.Errorf("compile ContractGraph: %w", err)
	}
	var document catalogDocument
	const sourcePath = "assistant/assistant_tool_metadata/catalog.yaml"
	if err := source.Decode(sourcePath, &document); err != nil {
		return nil, fmt.Errorf("decode assistant tool catalog: %w", err)
	}
	if document.Catalog != "assistant_tool_metadata" {
		return nil, fmt.Errorf("unexpected assistant tool catalog %q", document.Catalog)
	}
	if err := validateTools(document.Tools); err != nil {
		return nil, err
	}
	sort.Slice(document.Tools, func(i, j int) bool {
		return stringValue(document.Tools[i], "toolName") < stringValue(document.Tools[j], "toolName")
	})
	payload, err := json.MarshalIndent(document.Tools, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode assistant tool catalog: %w", err)
	}
	payload = append(payload, '\n')
	digest := sha256.Sum256(payload)
	rendered := fmt.Sprintf(`// Code generated by codegen_assistant_tool_catalog. DO NOT EDIT.

package generated

const AssistantToolCatalogDigest = %s

const AssistantToolCatalogJSON = %s
`, strconv.Quote("sha256:"+hex.EncodeToString(digest[:])), strconv.Quote(string(payload)))
	formatted, err := format.Source([]byte(rendered))
	if err != nil {
		return nil, fmt.Errorf("format generated assistant tool catalog: %w", err)
	}
	return formatted, nil
}

func validateTools(tools []map[string]any) error {
	if len(tools) == 0 {
		return fmt.Errorf("assistant tool catalog is empty")
	}
	seen := map[string]bool{}
	namespaceCounts := map[string]int{}
	for index, tool := range tools {
		name := stringValue(tool, "toolName")
		namespace := stringValue(tool, "namespace")
		placement := stringValue(tool, "placement")
		if name == "" || namespace == "" || placement == "" {
			return fmt.Errorf("tool[%d] requires toolName, namespace and placement", index)
		}
		if seen[name] {
			return fmt.Errorf("duplicate assistant tool %q", name)
		}
		seen[name] = true
		namespaceCounts[namespace]++
		for _, key := range []string{"inputSchema", "outputSchema"} {
			schema, ok := tool[key].(map[string]any)
			if !ok || schema["type"] != "object" || schema["additionalProperties"] != false {
				return fmt.Errorf("tool %q %s must be a closed object schema", name, key)
			}
		}
		scopes, ok := tool["environmentScopes"].([]any)
		if !ok || len(scopes) == 0 {
			return fmt.Errorf("tool %q requires environmentScopes", name)
		}
		readOnly, ok := tool["readOnly"].(bool)
		if !ok {
			return fmt.Errorf("tool %q requires readOnly", name)
		}
		if !readOnly {
			requiresConfirmation, _ := tool["requiresConfirmation"].(bool)
			if placement != "device_action" || !requiresConfirmation {
				return fmt.Errorf(
					"mutating tool %q must be a confirmed device_action",
					name,
				)
			}
			if err := validateMutatingCapabilityPolicy(name, tool); err != nil {
				return err
			}
		}
		if err := validateServerInjectedInputs(name, tool); err != nil {
			return err
		}
	}
	for namespace, count := range namespaceCounts {
		if count >= 10 {
			return fmt.Errorf("tool namespace %q has %d tools; limit is 9", namespace, count)
		}
	}
	return nil
}

func validateMutatingCapabilityPolicy(name string, tool map[string]any) error {
	policy, ok := tool["capability"].(map[string]any)
	if !ok {
		return fmt.Errorf("mutating tool %q requires capability policy", name)
	}
	capabilityKey := stringValue(policy, "capabilityKey")
	connectorRequirement := stringValue(policy, "connectorRequirement")
	if capabilityKey == "" || !strings.Contains(capabilityKey, ".") {
		return fmt.Errorf("mutating tool %q requires canonical capabilityKey", name)
	}
	if connectorRequirement != "required" && connectorRequirement != "none" {
		return fmt.Errorf(
			"mutating tool %q has unsupported connectorRequirement %q",
			name,
			connectorRequirement,
		)
	}
	consentScopes, consentOK := policy["consentScopes"].([]any)
	surfaces, surfacesOK := policy["allowedSurfaceKinds"].([]any)
	recheck, recheckOK := policy["recheckAtExecution"].(bool)
	if !consentOK || len(consentScopes) == 0 || !surfacesOK || len(surfaces) == 0 ||
		!recheckOK || !recheck {
		return fmt.Errorf(
			"mutating tool %q requires consent scopes, surface policy and execution recheck",
			name,
		)
	}
	return nil
}

func validateServerInjectedInputs(name string, tool map[string]any) error {
	values, ok := tool["serverInjectedInputs"].([]any)
	if !ok {
		return fmt.Errorf("tool %q requires serverInjectedInputs", name)
	}
	schema, _ := tool["inputSchema"].(map[string]any)
	properties, _ := schema["properties"].(map[string]any)
	for _, value := range values {
		field := strings.TrimSpace(fmt.Sprint(value))
		if field != "runId" && field != "skillId" {
			return fmt.Errorf("tool %q has unsupported server injected input %q", name, field)
		}
		if _, exists := properties[field]; !exists {
			return fmt.Errorf("tool %q injected input %q has no schema property", name, field)
		}
	}
	return nil
}

func stringValue(value map[string]any, key string) string {
	return strings.TrimSpace(fmt.Sprint(value[key]))
}

func fail(message string) {
	fmt.Fprintln(os.Stderr, "codegen_assistant_tool_catalog:", message)
	os.Exit(1)
}
