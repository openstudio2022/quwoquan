package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
)

type searchRegistryDocument struct {
	ObjectTypes []searchObjectType `yaml:"object_types"`
}

type searchObjectType struct {
	ID                string `yaml:"id"`
	Domain            string `yaml:"domain"`
	OwnerObject       string `yaml:"owner_object"`
	ExecutionStrategy string `yaml:"execution_strategy"`
}

type assistantAccessMode struct {
	Mode string `yaml:"mode"`
}

type assistantAccessDocument struct {
	Read assistantAccessMode `yaml:"read"`
	Cite assistantAccessMode `yaml:"cite"`
}

type searchPolicyDocument struct {
	Exposed string `yaml:"exposed"`
}

type assistantSearchObjectDocument struct {
	AssistantAccess assistantAccessDocument `yaml:"assistant_access"`
	SearchPolicy    searchPolicyDocument    `yaml:"search_policy"`
}

func generateAssistantSearchAccess(
	source *contractcodegen.Source,
) ([]byte, error) {
	var registry searchRegistryDocument
	if err := source.Decode("_shared/search_objects.yaml", &registry); err != nil {
		return nil, fmt.Errorf("decode search object registry: %w", err)
	}
	objects := map[string]assistantSearchObjectDocument{}
	for _, relative := range source.Paths("", "/object.yaml") {
		parts := strings.Split(relative, "/")
		if len(parts) < 3 || parts[0] == "_shared" {
			return nil, fmt.Errorf("object contract has no canonical domain/object path: %s", relative)
		}
		objectID := strings.ReplaceAll(parts[0], "-", "_") + "." +
			strings.ReplaceAll(parts[len(parts)-2], "-", "_")
		if _, duplicated := objects[objectID]; duplicated {
			return nil, fmt.Errorf("duplicate assistant object identity %q", objectID)
		}
		var document assistantSearchObjectDocument
		if err := source.Decode(relative, &document); err != nil {
			return nil, fmt.Errorf("decode %s: %w", relative, err)
		}
		objects[objectID] = document
	}
	return renderAssistantSearchAccess(registry, objects)
}

func renderAssistantSearchAccess(
	registry searchRegistryDocument,
	objects map[string]assistantSearchObjectDocument,
) ([]byte, error) {
	if len(registry.ObjectTypes) == 0 {
		return nil, fmt.Errorf("search object registry is empty")
	}
	readable := make([]string, 0, len(registry.ObjectTypes))
	citable := make([]string, 0, len(registry.ObjectTypes))
	seen := map[string]struct{}{}
	for _, entry := range registry.ObjectTypes {
		entry.ID = strings.TrimSpace(entry.ID)
		entry.Domain = strings.TrimSpace(entry.Domain)
		entry.OwnerObject = strings.TrimSpace(entry.OwnerObject)
		entry.ExecutionStrategy = strings.TrimSpace(entry.ExecutionStrategy)
		if entry.ID == "" || entry.OwnerObject == "" {
			return nil, fmt.Errorf("search object entry requires id and owner_object")
		}
		if _, duplicated := seen[entry.ID]; duplicated {
			return nil, fmt.Errorf("duplicate search object type %q", entry.ID)
		}
		seen[entry.ID] = struct{}{}
		owner, found := objects[entry.OwnerObject]
		if !found {
			return nil, fmt.Errorf("search object %q has unknown owner %q", entry.ID, entry.OwnerObject)
		}
		if entry.ExecutionStrategy == "filter_only" {
			continue
		}
		if entry.Domain == "external" {
			if strings.TrimSpace(owner.SearchPolicy.Exposed) == "remote_provider" {
				readable = append(readable, entry.ID)
				citable = append(citable, entry.ID)
			}
			continue
		}
		if strings.TrimSpace(owner.AssistantAccess.Read.Mode) != "public" {
			continue
		}
		readable = append(readable, entry.ID)
		if mode := strings.TrimSpace(owner.AssistantAccess.Cite.Mode); mode != "" && mode != "none" {
			citable = append(citable, entry.ID)
		}
	}
	sort.Strings(readable)
	sort.Strings(citable)
	if len(readable) == 0 {
		return nil, fmt.Errorf("assistant search readable projection is empty")
	}
	payload, err := json.Marshal(struct {
		Readable []string `json:"readable"`
		Citable  []string `json:"citable"`
	}{Readable: readable, Citable: citable})
	if err != nil {
		return nil, fmt.Errorf("encode assistant search access: %w", err)
	}
	digest := sha256.Sum256(append([]byte("assistant-search-access-v1\x00"), payload...))
	rendered := "// Code generated by codegen_assistant_tool_catalog. DO NOT EDIT.\n\n" +
		"package generated\n\n" +
		"const AssistantSearchAccessPolicyDigest = " + strconv.Quote("sha256:"+hex.EncodeToString(digest[:])) + "\n\n" +
		"var AssistantSearchReadableObjectTypes = []string{" + quotedList(readable) + "}\n\n" +
		"var AssistantSearchCitableObjectTypes = []string{" + quotedList(citable) + "}\n"
	formatted, err := format.Source([]byte(rendered))
	if err != nil {
		return nil, fmt.Errorf("format generated assistant search access: %w", err)
	}
	return formatted, nil
}

func quotedList(values []string) string {
	parts := make([]string, 0, len(values))
	for _, value := range values {
		parts = append(parts, strconv.Quote(value))
	}
	return strings.Join(parts, ",")
}
