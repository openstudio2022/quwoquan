func pythonEnumTuple(prefix string, values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = prefix + "." + screaming(v)
	}
	if len(parts) == 1 {
		return "(" + parts[0] + ",)"
	}
	return "(" + strings.Join(parts, ", ") + ")"
}
func pythonTuple(values []string) string {
	if len(values) == 1 {
		return "(" + strconv.Quote(values[0]) + ",)"
	}
	return "(" + quotedCSV(values) + ")"
}
func pythonEnums(c contract) string {
	sets := []struct {
		name   string
		values []string
	}{{"ProcessingDisposition", c.ClosedSets.ProcessingDispositions}, {"PublicationDecision", c.ClosedSets.PublicationDecisions}, {"CompatibilityDecision", c.ClosedSets.CompatibilityDecisions}, {"NodeKind", sortedKeys(c.NodeRegistry)}, {"InlineKind", c.InlineRegistry.Kinds}}
	var b strings.Builder
	for _, set := range sets {
		fmt.Fprintf(&b, "class %s(str, Enum):\n", set.name)
		for _, v := range set.values {
			fmt.Fprintf(&b, "    %s = %s\n", screaming(v), strconv.Quote(v))
		}
		b.WriteString("\n")
	}
	return b.String()
}
func screaming(v string) string {
	words := regexp.MustCompile(`([a-z0-9])([A-Z])`).ReplaceAllString(v, `${1}_${2}`)
	words = regexp.MustCompile(`[^A-Za-z0-9]+`).ReplaceAllString(words, "_")
	return strings.ToUpper(words)
}
