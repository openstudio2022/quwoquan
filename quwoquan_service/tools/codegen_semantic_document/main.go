func formatDart(data []byte) ([]byte, error) {
	cmd := exec.Command("dart", "format")
	cmd.Stdin = bytes.NewReader(data)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("dart format: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	return stdout.Bytes(), nil
}

func checkOutputs(outputs []output) error {
	expected := map[string]bool{}
	for _, out := range outputs {
		path, _ := filepath.Abs(out.path)
		expected[path] = true
		actual, err := os.ReadFile(out.path)
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return fmt.Errorf("generated output missing: %s", out.path)
			}
			return err
		}
		if !bytes.Equal(actual, out.data) {
			return fmt.Errorf("generated output stale: %s", out.path)
		}
	}
	parents := map[string]bool{}
	for _, out := range outputs {
		parents[filepath.Dir(out.path)] = true
	}
	for parent := range parents {
		entries, err := os.ReadDir(parent)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if entry.IsDir() {
				continue
			}
			path := filepath.Join(parent, entry.Name())
			abs, _ := filepath.Abs(path)
			if expected[abs] {
				continue
			}
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if bytes.Contains(data, []byte(generatedMarker)) {
				return fmt.Errorf("unexpected semantic document generated output: %s", path)
			}
		}
	}
	return nil
}

