type output struct {
	path string
	data []byte
}

func main() {
	var source, repoRoot string
	var check bool
	flag.StringVar(&source, "source", "contracts/metadata/_shared/semantic_document.yaml", "canonical semantic document YAML")
	flag.StringVar(&repoRoot, "repo-root", "..", "repository root")
	flag.BoolVar(&check, "check", false, "fail when generated outputs drift")
	flag.Parse()

	c, err := loadContract(source)
	if err != nil {
		fatal(err)
	}
	outputs, err := renderAll(c, repoRoot)
	if err != nil {
		fatal(err)
	}
	if check {
		if err := checkOutputs(outputs); err != nil {
			fatal(err)
		}
		return
	}
	for _, out := range outputs {
		if err := writeOutputAtomically(out); err != nil {
			fatal(err)
		}
	}
}

func writeOutputAtomically(out output) error {
	parent := filepath.Dir(out.path)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return err
	}
	temporary, err := os.CreateTemp(parent, ".semantic-document-*.tmp")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	committed := false
	defer func() {
		_ = temporary.Close()
		if !committed {
			_ = os.Remove(temporaryPath)
		}
	}()
	if err := temporary.Chmod(0o644); err != nil {
		return err
	}
	if _, err := temporary.Write(out.data); err != nil {
		return err
	}
	if err := temporary.Sync(); err != nil {
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	if err := os.Rename(temporaryPath, out.path); err != nil {
		return err
	}
	committed = true
	return nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "semantic document codegen:", err)
	os.Exit(1)
}

func loadContract(path string) (contract, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return contract{}, err
	}
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	var c contract
	if err := dec.Decode(&c); err != nil {
		return contract{}, fmt.Errorf("strict YAML decode: %w", err)
	}
	if err := validateContract(c); err != nil {
		return contract{}, err
	}
	return c, nil
}

func validateContract(c contract) error {
	if c.Schema != "semantic_document.authoring" || c.Dialect == "" || c.OffsetEncoding == "" || c.RawHTMLPolicy == "" || c.UnknownValuePolicy != "reject" {
		return errors.New("schema, dialect, offsetEncoding, rawHtmlPolicy, and reject unknownValuePolicy must be declared")
	}
	if c.ImplementationStatus.Role != "authoring_contract" || c.ImplementationStatus.MetadataValidator == "" || c.ImplementationStatus.CrossLanguageCodegen == "" || c.ImplementationStatus.CanonicalMarkdownCodec == "" || c.ImplementationStatus.ConformanceCorpus == "" || c.ImplementationStatus.CodegenGap == "" {
		return errors.New("implementationStatus fields must be declared")
	}
	for name, node := range map[string]yaml.Node{"identityAndCanonicalization": c.IdentityAndCanonicalization, "canonicalMarkdown": c.CanonicalMarkdown, "nodeCommon": c.Model.NodeCommon, "inlineCommon": c.Model.InlineCommon, "nodeRegistryPolicy": c.NodeRegistryPolicy, "markdownToSemantic": c.MarkdownToSemantic, "htmlToSemantic": c.HTMLToSemantic, "safeProjection": c.SafeProjection, "semanticToSafeHtml": c.SemanticToSafeHTML, "structureContracts": c.StructureContracts, "compatibility": c.Compatibility, "diagnostics": c.Diagnostics} {
		if node.Kind == 0 {
			return fmt.Errorf("required section %s is missing", name)
		}
	}
	for name, value := range map[string]string{"schemaVersion": c.SchemaVersion, "dialectVersion": c.DialectVersion, "canonicalizationVersion": c.CanonicalizationVersion} {
		if !semverPattern.MatchString(value) {
			return fmt.Errorf("%s must be an exact major.minor.patch triplet", name)
		}
	}
	if err := exactSet("processingDispositions", c.ClosedSets.ProcessingDispositions, []string{"preserved", "normalized", "degraded", "metadata_only", "dropped_noise", "unsupported_opaque", "blocked_unsafe"}); err != nil {
		return err
	}
	if err := exactSet("publicationDecisions", c.ClosedSets.PublicationDecisions, []string{"publish", "publish_with_losses", "block"}); err != nil {
		return err
	}
	if err := exactSet("compatibilityDecisions", c.ClosedSets.CompatibilityDecisions, []string{"compatible", "migrate_explicitly", "incompatible"}); err != nil {
		return err
	}
	if err := exactSet("nodeStatuses", c.ClosedSets.NodeStatuses, []string{"formal", "experimental"}); err != nil {
		return err
	}
	if len(c.Model.DocumentEnvelope.Required) == 0 || c.Model.DocumentEnvelope.AdditionalProperties {
		return errors.New("documentEnvelope must be closed and declare required fields")
	}
	if len(c.CapabilityCatalog.IDs) == 0 || len(c.NodeRegistry) == 0 || len(c.InlineRegistry.Kinds) == 0 {
		return errors.New("capability, node, and inline registries must be non-empty")
	}
	if err := exactSet("capabilityRequiredFields", c.CapabilityCatalog.CapabilityRequiredFields, []string{"id", "allowedOrigins", "fallbackPolicy"}); err != nil {
		return err
	}
	if len(c.CapabilityCatalog.AllowedOrigins) == 0 || len(c.CapabilityCatalog.FallbackPolicies) == 0 || c.CapabilityCatalog.FormalNodeRule == "" || c.CapabilityCatalog.OpaqueMutationRule == "" {
		return errors.New("capability policy fields must be declared")
	}
	capabilities := stringSet(c.CapabilityCatalog.IDs)
	statuses := stringSet(c.ClosedSets.NodeStatuses)
	publication := stringSet(c.ClosedSets.PublicationDecisions)
	fallback := stringSet(c.CapabilityCatalog.FallbackPolicies)
	for kind, spec := range c.NodeRegistry {
		if kind == "" || !statuses[spec.Status] {
			return fmt.Errorf("node %q has invalid status %q", kind, spec.Status)
		}
		if spec.Status == "formal" && len(spec.RequiredCapabilities) == 0 {
			return fmt.Errorf("formal node %q has no required capabilities", kind)
		}
		for _, id := range spec.RequiredCapabilities {
			if !capabilities[id] {
				return fmt.Errorf("node %q references unknown capability %q", kind, id)
			}
		}
		if spec.FallbackPolicy != "" && !fallback[spec.FallbackPolicy] {
			return fmt.Errorf("node %q has unknown fallback policy %q", kind, spec.FallbackPolicy)
		}
		if spec.PublicationDecision != "" && !publication[spec.PublicationDecision] {
			return fmt.Errorf("node %q has unknown publication decision %q", kind, spec.PublicationDecision)
		}
	}
	for _, id := range c.CapabilityCatalog.IDs {
		parts := strings.Split(id, ".")
		if len(parts) != 2 || !contains(c.CapabilityCatalog.Dimensions[parts[0]], parts[1]) {
			return fmt.Errorf("capability id %q is absent from dimensions", id)
		}
	}
	return nil
}

func exactSet(name string, got, want []string) error {
	if len(got) != len(want) {
		return fmt.Errorf("%s must contain exactly %d values", name, len(want))
	}
	gs, ws := stringSet(got), stringSet(want)
	if len(gs) != len(got) {
		return fmt.Errorf("%s contains duplicates", name)
	}
	for value := range ws {
		if !gs[value] {
			return fmt.Errorf("%s missing required value %q", name, value)
		}
	}
	for value := range gs {
		if !ws[value] {
			return fmt.Errorf("%s contains unknown value %q", name, value)
		}
	}
	return nil
}

