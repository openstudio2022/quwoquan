package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"
	"path/filepath"
	codegen "quwoquan_service/internal/metadata/codegen"
	validate "quwoquan_service/internal/metadata/validate"
	"sort"
	"strings"
)

const collectionClientPath = "lib/runtime/transport/graphql_read/generated/post_collection.g.dart"
const collectionManifestPath = "tool/graphql_read_codegen/collection_generated_manifest.json"

func GenerateCollection(options Options) ([]byte, []byte, error) {
	source, err := codegen.NewSource(options.MetadataDir, validate.ProfileBaseline)
	if err != nil {
		return nil, nil, err
	}
	graphRaw, err := readRegularFile(options.ContractGraphPath, "graph")
	if err != nil {
		return nil, nil, err
	}
	lockRaw, err := readRegularFile(options.AppLockPath, "lock")
	if err != nil {
		return nil, nil, err
	}
	registryRaw, err := readRegularFile(options.RegistryPath, "registry")
	if err != nil {
		return nil, nil, err
	}
	schemaRaw, err := readRegularFile(options.SchemaPath, "schema")
	if err != nil {
		return nil, nil, err
	}
	var lock appLockDocument
	var registry registryDocument
	if json.Unmarshal(lockRaw, &lock) != nil || json.Unmarshal(registryRaw, &registry) != nil {
		return nil, nil, errors.New("collection generator malformed input")
	}
	if lock.ContractGraph.SHA256 != sha256Hex(graphRaw) || registry.SchemaDigest != "sha256:"+sha256Hex(schemaRaw) {
		return nil, nil, errors.New("collection generator graph/schema drift")
	}
	schema, gerr := gqlparser.LoadSchema(&ast.Source{Input: string(schemaRaw)})
	if gerr != nil {
		return nil, nil, gerr
	}
	var gateway graphOperation
	var graph contractGraphDocument
	if json.Unmarshal(graphRaw, &graph) != nil {
		return nil, nil, errors.New("graph decode")
	}
	for _, op := range graph.Operations {
		if op.ID == "gateway.persisted_query_execution.ExecutePersistedGraphQLQuery" {
			gateway = op
		}
	}
	if gateway.ID == "" {
		return nil, nil, errors.New("canonical GraphQL transport missing")
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by codegen_graphql_app_client from PostCollection persisted contracts. DO NOT EDIT.\n// ContractGraph SHA256: %s\nimport 'package:quwoquan_cloud_contracts/quwoquan_cloud_contracts.dart';\n", sha256Hex(graphRaw))
	out.WriteString("final class GeneratedPostCollectionGraphQLClient {\n const GeneratedPostCollectionGraphQLClient(this.executor);\n final CloudOperationExecutor executor;\n")
	for _, item := range []struct{ Name, Operation, Document, Method, Request, Response, Root string }{{"PostCollection", "GetPostCollection", "post_collection.graphql", "get", "GetPostCollectionQuery", "PostCollectionPage", "postCollection"}, {"PostCollectionManagement", "GetPostCollectionManagement", "post_collection_management.graphql", "management", "GetPostCollectionManagementQuery", "PostCollectionManagementView", "postCollectionManagement"}} {
		id := "content.post_collection." + item.Operation
		var entry registryEntry
		found := false
		for _, candidate := range registry.Entries {
			if candidate.CanonicalOperationID == id {
				if found {
					return nil, nil, errors.New("duplicate collection registry entry")
				}
				entry = candidate
				found = true
			}
		}
		if !found || entry.OperationName != item.Name || entry.ExecutorKey != "content.postCollection.query" {
			return nil, nil, errors.New("exact collection registry binding missing")
		}
		document, err := readRegularFile(filepath.Join(filepath.Dir(options.MetadataPath), "persisted_queries", item.Document), "collection persisted document")
		if err != nil {
			return nil, nil, err
		}
		if sha256Hex(document) != entry.SHA256Hash {
			return nil, nil, errors.New("collection document hash drift")
		}
		var ownerBinding struct {
			OperationID string `yaml:"canonicalOperationId"`
			Name        string `yaml:"operationName"`
			Hash        string `yaml:"sha256Hash"`
			Variables   struct {
				Bindings  map[string]string `yaml:"bindings"`
				Constants map[string]any    `yaml:"constants"`
			} `yaml:"variables"`
			Response struct {
				Root string `yaml:"rootField"`
			} `yaml:"response"`
		}
		if err := source.Decode("content/content/post_collection/persisted_queries/"+strings.TrimSuffix(item.Document, ".graphql")+".yaml", &ownerBinding); err != nil {
			return nil, nil, err
		}
		if ownerBinding.OperationID != id || ownerBinding.Name != item.Name || ownerBinding.Hash != entry.SHA256Hash || ownerBinding.Response.Root != item.Root {
			return nil, nil, errors.New("collection owner persisted binding drift")
		}
		operationFound := false
		for _, op := range graph.Operations {
			if op.ID == id {
				if operationFound || op.ResponseEntity != item.Response {
					return nil, nil, errors.New("collection canonical response entity drift")
				}
				operationFound = true
			}
		}
		if !operationFound {
			return nil, nil, errors.New("collection response operation missing")
		}
		selection, queryErrors := gqlparser.LoadQuery(schema, string(document))
		if queryErrors != nil {
			return nil, nil, queryErrors
		}
		projection := "post_collection_page.yaml"
		if item.Method == "management" {
			projection = "post_collection_management_view.yaml"
		}
		if err := validateCollectionSelection(source, schema, selection, item.Response, projection); err != nil {
			return nil, nil, err
		}
		var appOp appLockOperation
		for _, candidate := range lock.AppExposedOperations {
			if candidate.CanonicalOperationID == id {
				appOp = candidate
			}
		}
		if appOp.ClientContract.ResponseType != item.Response || appOp.ClientContract.ResponseDecoder != "decode"+item.Response {
			return nil, nil, errors.New("collection App response owner drift")
		}
		rootField := selection.Operations[0].SelectionSet[0].(*ast.Field)
		shape, _ := json.Marshal(collectionSelectionShape(rootField.SelectionSet))
		shapeDart := strings.ReplaceAll(string(shape), "\"", "'")
		fmt.Fprintf(&out, " static const Map<String,Object?> _%sShape = %s;\n", item.Method, shapeDart)
		names := make([]string, 0, len(ownerBinding.Variables.Bindings))
		for name := range ownerBinding.Variables.Bindings {
			names = append(names, name)
		}
		sort.Strings(names)
		variableParts := []string{}
		for _, name := range names {
			field := ownerBinding.Variables.Bindings[name]
			definition := selection.Operations[0].VariableDefinitions.ForName(name)
			if definition == nil {
				return nil, nil, errors.New("unknown persisted variable binding")
			}
			part := fmt.Sprintf("%s: request.%s", dartString(name), field)
			if !definition.Type.NonNull {
				part = fmt.Sprintf("if (request.%s != null) %s", field, part)
			}
			variableParts = append(variableParts, part)
		}
		names = nil
		for name := range ownerBinding.Variables.Constants {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			encoded, err := json.Marshal(ownerBinding.Variables.Constants[name])
			if err != nil {
				return nil, nil, err
			}
			variableParts = append(variableParts, fmt.Sprintf("%s: %s", dartString(name), encoded))
		}
		if len(variableParts) != len(selection.Operations[0].VariableDefinitions) {
			return nil, nil, errors.New("persisted variables not fully bound")
		}
		vars := strings.Join(variableParts, ", ")
		fmt.Fprintf(&out, " Future<%s> %s(%s request, {required CloudOperationInvocationContext context}) => executor.send<%s>(_persistedGraphQLTransportOperation, context: context, responseDecoder: (value) => decode%s(_root(value, '%s', _%sShape)), requestEncoder: () => CloudOperationRequestPayload(body: <String,Object?>{'operationName':'%s','variables':<String,Object?>{%s},'extensions':<String,Object?>{'persistedQuery':<String,Object?>{'version':1,'sha256Hash':'%s'}}}));\n", item.Response, item.Method, item.Request, item.Response, item.Response, item.Root, item.Method, item.Name, vars, entry.SHA256Hash)
	}
	out.WriteString("}\nMap<String,Object?> _root(Object? value,String root,Map<String,Object?> shape){if(value is! Map || value.length!=1 || value['data'] is! Map)throw const FormatException('invalid GraphQL envelope');final data=value['data'] as Map;if(data.length!=1||data[root] is! Map)throw const FormatException('invalid GraphQL root');_validateSelection(data[root],shape);return Map<String,Object?>.from(data[root] as Map);}\n")
	out.WriteString(`void _validateSelection(Object? value, Map<String,Object?> shape) {
 if(value==null){if(shape['nullable']==true)return;throw const FormatException('non-null selection');}
 switch(shape['kind']) {
 case 'object':
 if(value is! Map)throw const FormatException('object selection');
 final fields=shape['fields'] as Map<String,Object?>;
 if(value.length!=fields.length || !fields.keys.every(value.containsKey))throw const FormatException('exact selection fields');
 for(final field in fields.entries){_validateSelection(value[field.key],field.value as Map<String,Object?>);} return;
 case 'list': if(value is! List)throw const FormatException('list selection');for(final item in value){_validateSelection(item,shape['item'] as Map<String,Object?>);}return;
 case 'string':if(value is String)return;break;
 case 'int':if(value is int)return;break;
 case 'bool':if(value is bool)return;break;
 }
 throw const FormatException('selection value type');
}
`)
	renderGatewayContract(&out, gateway, appLockOperation{SurfaceIDs: []string{"postCollection"}})
	generated := []byte(out.String())
	manifest := generatedManifest{Generator: "codegen_graphql_app_collection_client", RegistrySHA256: sha256Hex(registryRaw), ContractGraphSHA256: sha256Hex(graphRaw), AppLockSHA256: sha256Hex(lockRaw), Outputs: []generatedOutput{{Path: filepath.ToSlash(collectionClientPath), SHA256: sha256Hex(generated), Bytes: len(generated)}}}
	encoded, err := json.MarshalIndent(manifest, "", "  ")
	return generated, append(encoded, '\n'), err
}
