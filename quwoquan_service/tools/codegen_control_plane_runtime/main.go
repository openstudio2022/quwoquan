package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	contractcodegen "quwoquan_service/internal/metadata/codegen"
	metacontrolplane "quwoquan_service/internal/metadata/controlplane"
	"quwoquan_service/internal/metadata/validate"
)

type artifact struct {
	fileName  string
	constName string
	data      any
}

type generatedOperationSecurity struct {
	domain              string
	contractOperationID string
}

var compileContractSource = contractcodegen.NewSource

func main() {
	var metadataDir string
	var goOutDir string
	var pythonOutDir string

	flag.StringVar(&metadataDir, "metadata-dir", "contracts/metadata", "metadata root directory")
	flag.StringVar(&goOutDir, "go-out-dir", "generated/control_plane", "Go output directory")
	flag.StringVar(&pythonOutDir, "python-out-dir", "services/recommendation-service/internal/recommendation/recommendation_model_release/generated/python/control_plane", "Python output directory")
	flag.Parse()

	source, err := compileContractSource(metadataDir, validate.ProfileBaseline)
	must(err)
	artifacts := collectArtifacts(source)

	must(os.MkdirAll(goOutDir, 0o755))
	must(os.MkdirAll(pythonOutDir, 0o755))

	for _, item := range artifacts {
		writeGoArtifact(filepath.Join(goOutDir, item.fileName+".go"), item.constName, item.data)
		writePythonArtifact(filepath.Join(pythonOutDir, item.fileName+".py"), strings.ToUpper(item.fileName), item.data)
	}
	writeGoOperationSecurity(
		filepath.Join(goOutDir, "operation_security.go"),
		collectOperationSecurity(artifacts),
	)
	writePythonIndex(filepath.Join(pythonOutDir, "__init__.py"), artifacts)
}

func collectArtifacts(source *contractcodegen.Source) []artifact {
	const sharedRoot = "_shared"
	const controlRoot = "_control_plane"

	items := []artifact{
		{
			fileName:  "shared_control_plane",
			constName: "SharedControlPlane",
			data:      readYAMLAny(source, filepath.Join(sharedRoot, "control_plane.yaml")),
		},
		{
			fileName:  "portal_shell",
			constName: "PortalShell",
			data:      readYAMLAny(source, filepath.Join(controlRoot, "portal_shell.yaml")),
		},
		{
			fileName:  "portal_menu",
			constName: "PortalMenu",
			data:      readYAMLAny(source, filepath.Join(controlRoot, "portal_menu.yaml")),
		},
	}
	for _, domain := range []string{"platform", "product"} {
		baseDir := filepath.Join(controlRoot, domain)
		if len(source.Paths(baseDir, ".yaml")) == 0 {
			continue
		}

		configPath := filepath.Join(baseDir, "config.yaml")
		if domain == "platform" {
			configPath = filepath.Join("platform", "config.yaml")
		}
		for _, def := range []struct {
			fileName  string
			constName string
			path      string
		}{
			{fileName: domain + "_control_plane", constName: toPascalCase(domain) + "ControlPlane", path: filepath.Join(baseDir, "control_plane.yaml")},
			{fileName: domain + "_config", constName: toPascalCase(domain) + "Config", path: configPath},
			{fileName: domain + "_workflow", constName: toPascalCase(domain) + "Workflow", path: filepath.Join(baseDir, "workflow.yaml")},
			{fileName: domain + "_audit_schema", constName: toPascalCase(domain) + "AuditSchema", path: filepath.Join(baseDir, "audit_schema.yaml")},
		} {
			if !source.Has(def.path) {
				continue
			}
			data := readYAMLAny(source, def.path)
			if strings.HasSuffix(def.path, "control_plane.yaml") {
				document, ok := data.(map[string]any)
				if !ok {
					must(fmt.Errorf("%s must decode to an object", def.path))
				}
				must(metacontrolplane.HydrateOperationReferences(document, source.Graph()))
				data = document
			}
			items = append(items, artifact{
				fileName:  def.fileName,
				constName: def.constName,
				data:      data,
			})
		}
	}

	sort.Slice(items, func(i, j int) bool {
		return items[i].fileName < items[j].fileName
	})
	return items
}

func readYAMLAny(source *contractcodegen.Source, path string) any {
	var out any
	must(source.Decode(path, &out))
	return normalizeYAML(out)
}

func normalizeYAML(value any) any {
	switch typed := value.(type) {
	case map[string]any:
		normalized := make(map[string]any, len(typed))
		for key, inner := range typed {
			normalized[key] = normalizeYAML(inner)
		}
		return normalized
	case map[any]any:
		normalized := make(map[string]any, len(typed))
		for key, inner := range typed {
			normalized[fmt.Sprint(key)] = normalizeYAML(inner)
		}
		return normalized
	case []any:
		normalized := make([]any, 0, len(typed))
		for _, inner := range typed {
			normalized = append(normalized, normalizeYAML(inner))
		}
		return normalized
	default:
		return typed
	}
}

func writeGoArtifact(path, constName string, data any) {
	payload, err := json.MarshalIndent(data, "", "  ")
	must(err)

	content := fmt.Sprintf(`// Code generated by codegen_control_plane_runtime. DO NOT EDIT.

package control_plane

import "encoding/json"

var %sRaw = []byte(%q)

func MustLoad%s() map[string]any {
	var out map[string]any
	if err := json.Unmarshal(%sRaw, &out); err != nil {
		panic(err)
	}
	return out
}
`, constName, string(payload), constName, constName)
	writeFile(path, content)
}

func collectOperationSecurity(artifacts []artifact) []generatedOperationSecurity {
	out := make([]generatedOperationSecurity, 0)
	for _, item := range artifacts {
		if item.fileName != "platform_control_plane" &&
			item.fileName != "product_control_plane" {
			continue
		}
		document, ok := item.data.(map[string]any)
		if !ok {
			continue
		}
		domain := textValue(document["domain"])
		objectTypes, _ := document["object_types"].([]any)
		for _, rawObject := range objectTypes {
			object, _ := rawObject.(map[string]any)
			operations, _ := object["operations"].([]any)
			for _, rawOperation := range operations {
				operation, _ := rawOperation.(map[string]any)
				contractOperationID := textValue(operation["contract_operation_id"])
				if contractOperationID == "" {
					continue
				}
				out = append(out, generatedOperationSecurity{
					domain:              domain,
					contractOperationID: contractOperationID,
				})
			}
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].domain == out[j].domain {
			return out[i].contractOperationID < out[j].contractOperationID
		}
		return out[i].domain < out[j].domain
	})
	return out
}

func writeGoOperationSecurity(path string, operations []generatedOperationSecurity) {
	byDomain := map[string][]generatedOperationSecurity{}
	for _, operation := range operations {
		byDomain[operation.domain] = append(byDomain[operation.domain], operation)
	}
	domains := make([]string, 0, len(byDomain))
	for domain := range byDomain {
		domains = append(domains, domain)
	}
	sort.Strings(domains)

	var content strings.Builder
	content.WriteString("// Code generated by codegen_control_plane_runtime. DO NOT EDIT.\n\n")
	content.WriteString("package control_plane\n\n")
	content.WriteString("import (\n")
	content.WriteString("\toperationsecurity \"quwoquan_service/generated/operationsecurity\"\n")
	content.WriteString("\trtauth \"quwoquan_service/runtime/auth\"\n")
	content.WriteString(")\n\n")
	content.WriteString("func mustSelectOperationSecurityDescriptors(operationIDs []string) []rtauth.OperationSecurityDescriptor {\n")
	content.WriteString("\tavailable := make(map[string]rtauth.OperationSecurityDescriptor, len(operationIDs))\n")
	content.WriteString("\tdomains := make(map[string]struct{}, len(operationIDs))\n")
	content.WriteString("\tfor _, operationID := range operationIDs {\n")
	content.WriteString("\t\tdomain := operationID\n")
	content.WriteString("\t\tfor index, character := range operationID {\n")
	content.WriteString("\t\t\tif character == '.' {\n")
	content.WriteString("\t\t\t\tdomain = operationID[:index]\n")
	content.WriteString("\t\t\t\tbreak\n")
	content.WriteString("\t\t\t}\n")
	content.WriteString("\t\t}\n")
	content.WriteString("\t\tdomains[domain] = struct{}{}\n")
	content.WriteString("\t}\n")
	content.WriteString("\tfor domain := range domains {\n")
	content.WriteString("\t\tfor _, descriptor := range operationsecurity.ForDomain(domain) {\n")
	content.WriteString("\t\t\tavailable[descriptor.CanonicalOperationID] = descriptor\n")
	content.WriteString("\t\t}\n")
	content.WriteString("\t}\n")
	content.WriteString("\tselected := make([]rtauth.OperationSecurityDescriptor, 0, len(operationIDs))\n")
	content.WriteString("\tseen := make(map[string]struct{}, len(operationIDs))\n")
	content.WriteString("\tfor _, operationID := range operationIDs {\n")
	content.WriteString("\t\tif _, duplicated := seen[operationID]; duplicated {\n")
	content.WriteString("\t\t\tpanic(\"duplicate control-plane operation reference: \" + operationID)\n")
	content.WriteString("\t\t}\n")
	content.WriteString("\t\tdescriptor, found := available[operationID]\n")
	content.WriteString("\t\tif !found {\n")
	content.WriteString("\t\t\tpanic(\"control-plane operation reference missing generated security descriptor: \" + operationID)\n")
	content.WriteString("\t\t}\n")
	content.WriteString("\t\tseen[operationID] = struct{}{}\n")
	content.WriteString("\t\tselected = append(selected, descriptor)\n")
	content.WriteString("\t}\n")
	content.WriteString("\treturn selected\n")
	content.WriteString("}\n\n")
	for _, domain := range domains {
		fmt.Fprintf(
			&content,
			"var %sOperationSecurityDescriptors = mustSelectOperationSecurityDescriptors([]string{\n",
			toPascalCase(domain),
		)
		for _, operation := range byDomain[domain] {
			fmt.Fprintf(&content, "\t%q,\n", operation.contractOperationID)
		}
		content.WriteString("})\n\n")
	}
	formatted, err := format.Source([]byte(content.String()))
	must(err)
	writeFile(path, string(formatted))
}

func textValue(value any) string {
	if value == nil {
		return ""
	}
	return strings.TrimSpace(fmt.Sprint(value))
}

func writePythonArtifact(path, constName string, data any) {
	payload, err := json.MarshalIndent(data, "", "  ")
	must(err)

	content := fmt.Sprintf(`# Code generated by codegen_control_plane_runtime. DO NOT EDIT.

import json

_%s_JSON = r'''%s'''
%s = json.loads(_%s_JSON)
`, constName, string(payload), constName, constName)
	writeFile(path, content)
}

func writePythonIndex(path string, items []artifact) {
	lines := []string{"# Code generated by codegen_control_plane_runtime. DO NOT EDIT.", ""}
	for _, item := range items {
		lines = append(lines, fmt.Sprintf("from .%s import %s", item.fileName, strings.ToUpper(item.fileName)))
	}
	lines = append(lines, "")
	writeFile(path, strings.Join(lines, "\n"))
}

func writeFile(path, content string) {
	must(os.MkdirAll(filepath.Dir(path), 0o755))
	must(os.WriteFile(path, []byte(content), 0o644))
	fmt.Printf("generated: %s\n", path)
}

func toPascalCase(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '-' || r == '_' || r == '.'
	})
	if len(parts) == 0 {
		parts = []string{s}
	}
	var out strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]))
		if len(part) > 1 {
			out.WriteString(part[1:])
		}
	}
	return out.String()
}

func must(err error) {
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}
