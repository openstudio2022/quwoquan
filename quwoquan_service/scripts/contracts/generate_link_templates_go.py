#!/usr/bin/env python3
"""从 link_templates metadata 生成 Service 端 typed Web path builders。"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import yaml


PLACEHOLDER = re.compile(r"\{([A-Za-z][A-Za-z0-9_]*)\}")


def _go_identifier(raw: str, *, exported: bool) -> str:
    parts = [part for part in re.split(r"[^A-Za-z0-9]+", raw) if part]
    if not parts:
        raise ValueError(f"invalid Go identifier source: {raw!r}")
    identifier = "".join(part[:1].upper() + part[1:] for part in parts)
    if not exported:
        identifier = identifier[:1].lower() + identifier[1:]
    return identifier


def render(metadata_path: Path) -> str:
    document = yaml.safe_load(metadata_path.read_text(encoding="utf-8"))
    entities = document.get("entities") if isinstance(document, dict) else None
    if not isinstance(entities, dict) or not entities:
        raise ValueError("link_templates.entities must be a non-empty mapping")

    functions: list[str] = []
    for entity_name, raw_entity in sorted(entities.items()):
        if not isinstance(raw_entity, dict):
            raise ValueError(f"entities.{entity_name} must be a mapping")
        web = raw_entity.get("web")
        primary_params = raw_entity.get("primary_params")
        if not isinstance(web, dict) or not isinstance(web.get("path_template"), str):
            raise ValueError(f"entities.{entity_name}.web.path_template is required")
        if not isinstance(primary_params, list) or not all(
            isinstance(item, str) and item for item in primary_params
        ):
            raise ValueError(f"entities.{entity_name}.primary_params is required")

        template = str(web["path_template"]).strip().strip("/")
        placeholders = PLACEHOLDER.findall(template)
        if placeholders != primary_params:
            raise ValueError(
                f"entities.{entity_name}: primary_params {primary_params!r} "
                f"must match path placeholders {placeholders!r}"
            )

        function_name = f"{_go_identifier(str(entity_name), exported=True)}WebPath"
        arguments = ", ".join(
            f"{_go_identifier(parameter, exported=False)} string"
            for parameter in primary_params
        )
        replacements = ",\n\t\t".join(
            (
                f"{json.dumps('{' + parameter + '}')}, "
                f"escapePathSegment({_go_identifier(parameter, exported=False)})"
            )
            for parameter in primary_params
        )
        functions.append(
            f"""// {function_name} 构造 metadata-owned {entity_name} Web path。
func {function_name}({arguments}) string {{
\treturn strings.NewReplacer(
\t\t{replacements},
\t).Replace({json.dumps('/' + template)})
}}"""
        )

    return (
        "// Code generated by scripts/contracts/generate_link_templates_go.py; "
        "DO NOT EDIT.\n\n"
        "package linktemplates\n\n"
        "import (\n"
        '\t"net/url"\n'
        '\t"strings"\n'
        ")\n\n"
        "func escapePathSegment(raw string) string {\n"
        "\treturn url.PathEscape(strings.TrimSpace(raw))\n"
        "}\n\n"
        + "\n\n".join(functions)
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--metadata-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    metadata_path = args.metadata_dir / "_shared/link_templates.yaml"
    rendered = render(metadata_path)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"stale generated link templates: {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
