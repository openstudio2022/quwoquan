#!/usr/bin/env python3
"""Generate static Go facts from the canonical Human delivery contract."""
from __future__ import annotations
import argparse, hashlib, subprocess, tempfile
from pathlib import Path
import yaml

HEADER = "// Code generated by contracts/platform_ops/human_authority/generate_binding.py; DO NOT EDIT.\n"

def quote(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'

def render(source: Path, fields_source: Path) -> str:
    raw = source.read_bytes()
    fields_raw = fields_source.read_bytes()
    doc = yaml.safe_load(raw)
    fields_doc = yaml.safe_load(fields_raw)
    roles = doc["namespaces"]["human_authority_role"]["values"]
    kinds = doc["closed_sets"]["decision_kind"]
    sod = doc["closed_sets"]["sod_policy"]
    router = doc["router"]
    risk = doc["risk_sod_policy"]
    responsibilities = doc["closed_sets"]["decision_unit_responsibility"]
    sod_policies = doc["sod_policies"]
    source_name = str(source).replace('\\', '/')
    marker = "quwoquan_ops/"
    if marker not in source_name:
        raise SystemExit("canonical Human contract must be under quwoquan_ops/")
    source_name = marker + source_name.split(marker, 1)[1]
    claim_fields = [str(field["name"]) for field in fields_doc["types"]["AuthorityReceiptClaims"]["fields"]]
    attestation_fields = [str(field["name"]) for field in fields_doc["types"]["AuthorityStateAttestation"]["fields"]]
    wrapper_fields = [str(field["name"]) for field in fields_doc["types"]["AuthorizationReceipt"]["fields"]]
    fields_name = str(fields_source).replace('\\', '/')
    marker = "quwoquan_service/"
    if marker in fields_name:
        fields_name = marker + fields_name.split(marker, 1)[1]
    elif fields_name.startswith("control-plane/"):
        fields_name = marker + fields_name
    else:
        raise SystemExit("hosted authority fields source must be under quwoquan_service/")
    lines = [HEADER.rstrip(), "package model", "", "const CanonicalHumanContractSource = " + quote(source_name), "const CanonicalHumanContractSHA256 = " + quote("sha256:" + hashlib.sha256(raw).hexdigest()), "const CanonicalAuthorityFieldsSource = " + quote(fields_name), "const CanonicalAuthorityFieldsSHA256 = " + quote("sha256:" + hashlib.sha256(fields_raw).hexdigest()), ""]
    generated_fields = (("GeneratedAuthorityReceiptClaimFields", claim_fields), ("GeneratedAuthorityStateAttestationFields", attestation_fields), ("GeneratedAuthorizationReceiptWrapperFields", wrapper_fields))
    for name, values in generated_fields:
        lines.append(f"var {name} = []string{{")
        lines.extend("\t" + quote(value) + "," for value in values)
        lines.extend(["}", ""])
    import json
    lines.extend([
        "const GeneratedAuthorityReceiptClaimFieldsJSON = " + quote(json.dumps(claim_fields, separators=(",", ":"))),
        "const GeneratedAuthorityStateAttestationFieldsJSON = " + quote(json.dumps(attestation_fields, separators=(",", ":"))),
        "const GeneratedAuthorizationReceiptWrapperFieldsJSON = " + quote(json.dumps(wrapper_fields, separators=(",", ":"))),
        "",
    ])
    for name, values in (("GeneratedHumanAuthorityRoles", roles), ("GeneratedDecisionKinds", kinds), ("GeneratedSoDPolicies", sod), ("GeneratedDecisionUnitResponsibilities", responsibilities)):
        lines.append(f"var {name} = []string{{")
        lines.extend("\t" + quote(str(v)) + "," for v in values)
        lines.extend(["}", ""])
    lines.extend(["type GeneratedRouterRule struct {", "\tStage string", "\tDecisionKind string", "\tAccountableRole string", "\tHardVetoRoles []string", "}", "", "var GeneratedRouterRules = []GeneratedRouterRule{"])
    for row in router:
        veto = ", ".join(quote(str(v)) for v in row.get("hard_veto_roles", []))
        lines.append("\t{Stage: %s, DecisionKind: %s, AccountableRole: %s, HardVetoRoles: []string{%s}}," % (quote(str(row["stage"])), quote(str(row["decision_kind"])), quote(str(row.get("accountable_role") or "")), veto))
    lines.extend(["}", "", "type GeneratedSoDPolicy struct {", "\tSeparateRoleRecordsRequired bool", "\tDistinctAuthenticatedActorsRequired bool", "}", "", "var GeneratedSoDPolicyRules = map[string]GeneratedSoDPolicy{"])
    for key, value in sorted(sod_policies.items()):
        lines.append("\t%s: {SeparateRoleRecordsRequired: %s, DistinctAuthenticatedActorsRequired: %s}," % (quote(str(key)), str(bool(value.get("separate_role_records_required"))).lower(), str(bool(value.get("distinct_authenticated_actors_required"))).lower()))
    lines.extend(["}", "", "const GeneratedDefaultSoDPolicy = " + quote(str(risk["default"])), "", "var GeneratedRiskSoDPolicies = map[string]string{"])
    for key, value in sorted(risk["classifications"].items()):
        lines.append("\t%s: %s," % (quote(str(key)), quote(str(value))))
    lines.extend(["}", ""])
    text = "\n".join(lines).replace(HEADER.rstrip() + "\npackage", HEADER.rstrip() + "\n\npackage", 1)
    with tempfile.NamedTemporaryFile(mode="w+", suffix=".go") as generated:
        generated.write(text)
        generated.flush()
        subprocess.run(["gofmt", "-w", generated.name], check=True)
        generated.seek(0)
        return generated.read()

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True)
    parser.add_argument("--fields-source", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, fields_source, output = Path(args.source), Path(args.fields_source), Path(args.output)
    expected = render(source, fields_source)
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit("generated Human contract binding drifted; rerun generator")
    else:
        output.write_text(expected)
    return 0
if __name__ == "__main__":
    raise SystemExit(main())
