package openapi

import (
	"fmt"
	"path"
	"regexp"
	"sort"
	"strings"

	"quwoquan_service/internal/metadata/ast"
	"quwoquan_service/internal/metadata/graph"

	"gopkg.in/yaml.v3"
)

const (
	openAPIVersion          = "3.0.3"
	generatedHeader         = "# Code generated by qwq-contract generate-openapi. DO NOT EDIT.\n"
	commonErrorResponseRef  = "../_shared/openapi_common.yaml#/components/schemas/ErrorResponse"
	commonBearerSecurityRef = "../_shared/openapi_common.yaml#/components/securitySchemes/bearerAuth"
)

var pathParameterPattern = regexp.MustCompile(`\{([^{}]+)\}`)

// Snapshot 是从 ContractGraph 确定性派生出的单域 OpenAPI 快照。
type Snapshot struct {
	Domain         string
	RelativePath   string
	Content        []byte
	OperationCount int
}

// Generate 为所有版本化 HTTP operation 生成按域拆分的 OpenAPI 3.0.3 快照。
func Generate(contractGraph *graph.ContractGraph) ([]Snapshot, error) {
	if contractGraph == nil {
		return nil, fmt.Errorf("ContractGraph is required")
	}

	operationsByDomain := map[string][]ast.Operation{}
	transportOwners := map[string]string{}
	for _, operation := range contractGraph.Operations {
		if operation.Transport == "graphql" {
			continue
		}
		if !isVersionedTransport(operation.PathTemplate) {
			continue
		}
		if strings.TrimSpace(operation.Domain) == "" {
			return nil, fmt.Errorf("operation %q has no domain", operation.ID)
		}
		transportKey := strings.ToUpper(operation.Method) + " " + operation.PathTemplate
		if previous, exists := transportOwners[transportKey]; exists {
			return nil, fmt.Errorf(
				"transport %s is owned by both %s and %s",
				transportKey,
				previous,
				operation.ID,
			)
		}
		transportOwners[transportKey] = operation.ID
		operationsByDomain[operation.Domain] = append(
			operationsByDomain[operation.Domain],
			operation,
		)
	}

	domains := make([]string, 0, len(operationsByDomain))
	for domain := range operationsByDomain {
		domains = append(domains, domain)
	}
	sort.Strings(domains)

	snapshots := make([]Snapshot, 0, len(domains))
	for _, domain := range domains {
		operations := append([]ast.Operation(nil), operationsByDomain[domain]...)
		sort.Slice(operations, func(left, right int) bool {
			leftKey := operations[left].PathTemplate + "\x00" +
				methodSortKey(operations[left].Method) + "\x00" +
				operations[left].ID
			rightKey := operations[right].PathTemplate + "\x00" +
				methodSortKey(operations[right].Method) + "\x00" +
				operations[right].ID
			return leftKey < rightKey
		})
		content, err := renderDomain(domain, operations)
		if err != nil {
			return nil, err
		}
		snapshots = append(snapshots, Snapshot{
			Domain:         domain,
			RelativePath:   path.Join(domain, "openapi.yaml"),
			Content:        content,
			OperationCount: len(operations),
		})
	}
	return snapshots, nil
}

func renderDomain(domain string, operations []ast.Operation) ([]byte, error) {
	document := openAPIDocument{
		OpenAPI: openAPIVersion,
		Info: openAPIInfo{
			Title:   "quwoquan " + domain + " API",
			Version: "canonical",
		},
		Paths: map[string]openAPIPathItem{},
		Components: openAPIComponents{
			SecuritySchemes: map[string]openAPISchema{
				"bearerAuth": {Ref: commonBearerSecurityRef},
			},
			Schemas: map[string]openAPISchema{},
		},
	}
	registry := newSchemaRegistry(document.Components.Schemas)
	localOperationIDs := map[string]string{}

	for _, operation := range operations {
		if strings.TrimSpace(operation.LocalID) == "" {
			return nil, fmt.Errorf("operation %q has no stable local ID", operation.ID)
		}
		if previous, exists := localOperationIDs[operation.LocalID]; exists {
			return nil, fmt.Errorf(
				"domain %s has duplicate local operationId %q from %s and %s",
				domain,
				operation.LocalID,
				previous,
				operation.ID,
			)
		}
		localOperationIDs[operation.LocalID] = operation.ID

		rendered, err := renderOperation(operation, registry)
		if err != nil {
			return nil, err
		}
		item := document.Paths[operation.PathTemplate]
		if err := item.set(strings.ToUpper(operation.Method), rendered); err != nil {
			return nil, fmt.Errorf("operation %q: %w", operation.ID, err)
		}
		document.Paths[operation.PathTemplate] = item
	}

	raw, err := yaml.Marshal(document)
	if err != nil {
		return nil, fmt.Errorf("marshal %s OpenAPI: %w", domain, err)
	}
	return append([]byte(generatedHeader), raw...), nil
}

func renderOperation(
	operation ast.Operation,
	registry *schemaRegistry,
) (*openAPIOperation, error) {
	rendered := &openAPIOperation{
		OperationID:          operation.LocalID,
		XContractOperationID: operation.ID,
		XObjectID:            operation.ObjectID,
		XActor:               operation.ActorRequirement,
		XApplication: openAPIApplicationBinding{
			Kind:           string(operation.Kind),
			Facet:          operation.Facet,
			Method:         operation.FacadeMethod,
			AggregateOwner: operation.AggregateOwner,
			AppendSink:     operation.AppendSink,
			LifecycleOwner: operation.LifecycleOwner,
			SessionOwner:   operation.SessionOwner,
			Reader:         operation.Reader,
			Slice:          operation.Slice,
		},
		Parameters: operationParameters(operation),
		Responses: map[string]openAPIResponse{
			"default": errorResponse(),
		},
		Security: operationSecurity(operation),
	}

	requestBody, err := buildRequestBody(operation, registry)
	if err != nil {
		return nil, fmt.Errorf("operation %q request: %w", operation.ID, err)
	}
	rendered.RequestBody = requestBody

	status, response, err := buildSuccessResponse(operation, registry)
	if err != nil {
		return nil, fmt.Errorf("operation %q response: %w", operation.ID, err)
	}
	rendered.Responses[status] = response
	return rendered, nil
}

func buildRequestBody(
	operation ast.Operation,
	registry *schemaRegistry,
) (*openAPIRequestBody, error) {
	entity := strings.TrimSpace(operation.RequestEntity)
	requestKind := strings.TrimSpace(operation.RequestBodyKind)
	switch requestKind {
	case "none":
		// request_entity is the complete typed invocation model. For a bodyless
		// operation all of its fields are bound to path/query/header/injected
		// positions, so it remains useful to generators but emits no OpenAPI
		// requestBody.
		return nil, nil
	case "object":
		if entity == "" {
			return nil, fmt.Errorf("request_body_kind=object requires request_entity")
		}
	case "":
	default:
		return nil, fmt.Errorf("unsupported request_body_kind %q", requestKind)
	}
	required := true
	if entity == "" {
		if operation.Kind != ast.OperationKindCommand ||
			!methodMayCarryBody(operation.Method) {
			return nil, nil
		}
		entity = operation.LocalID + "Request"
		required = false
	}
	component, err := registry.addPlaceholder(entity)
	if err != nil {
		return nil, err
	}
	return &openAPIRequestBody{
		Required: required,
		Content: jsonContent(openAPISchema{
			Ref: componentRef(component),
		}),
	}, nil
}

func buildSuccessResponse(
	operation ast.Operation,
	registry *schemaRegistry,
) (string, openAPIResponse, error) {
	responseKind := strings.TrimSpace(operation.ResponseBodyKind)
	responseEntity := strings.TrimSpace(operation.ResponseEntity)
	legacyResponseBody := strings.TrimSpace(operation.ResponseBody)
	entity := firstNonEmpty(responseEntity, legacyResponseBody)

	switch responseKind {
	case "upgrade":
		return "101", openAPIResponse{Description: "Switching Protocols"}, nil
	case "ack":
		return "204", openAPIResponse{Description: "No Content"}, nil
	case "page":
		// response_entity is the exact canonical response wire (normally a
		// bounded *Slice). response_body was the retired item-type track; only
		// use its page-wrapper fallback for operations not yet declaring the
		// canonical response entity.
		if responseEntity != "" {
			component, err := registry.addPlaceholder(responseEntity)
			if err != nil {
				return "", openAPIResponse{}, err
			}
			status, description := successResponseStatus(operation, "200")
			return jsonResponse(status, description, componentRef(component))
		}
		if entity == "" {
			entity = operation.LocalID + "Item"
		}
		itemComponent, err := registry.addPlaceholder(entity)
		if err != nil {
			return "", openAPIResponse{}, err
		}
		pageComponent, err := registry.addPage(
			operation.LocalID+"Page",
			entity,
			itemComponent,
		)
		if err != nil {
			return "", openAPIResponse{}, err
		}
		status, description := successResponseStatus(operation, "200")
		return jsonResponse(status, description, componentRef(pageComponent))
	case "", "object":
		if entity == "" {
			if operation.Kind == ast.OperationKindCommand {
				return "204", openAPIResponse{Description: "No Content"}, nil
			}
			entity = operation.LocalID + "Response"
		}
		component, err := registry.addPlaceholder(entity)
		if err != nil {
			return "", openAPIResponse{}, err
		}
		status, description := successResponseStatus(operation, "200")
		return jsonResponse(status, description, componentRef(component))
	default:
		return "", openAPIResponse{}, fmt.Errorf(
			"unsupported response_body_kind %q",
			responseKind,
		)
	}
}

func successResponseStatus(operation ast.Operation, fallback string) (string, string) {
	status := operation.SuccessStatus
	if status == 0 {
		switch fallback {
		case "201":
			return fallback, "Created"
		case "202":
			return fallback, "Accepted"
		case "204":
			return fallback, "No Content"
		default:
			return fallback, "OK"
		}
	}
	switch status {
	case 201:
		return "201", "Created"
	case 202:
		return "202", "Accepted"
	case 204:
		return "204", "No Content"
	default:
		return "200", "OK"
	}
}

func jsonResponse(
	status string,
	description string,
	ref string,
) (string, openAPIResponse, error) {
	return status, openAPIResponse{
		Description: description,
		Content: jsonContent(openAPISchema{
			Ref: ref,
		}),
	}, nil
}

func errorResponse() openAPIResponse {
	return openAPIResponse{
		Description: "Runtime failure",
		Content: jsonContent(openAPISchema{
			Ref: commonErrorResponseRef,
		}),
	}
}

func jsonContent(schema openAPISchema) map[string]openAPIMediaType {
	return map[string]openAPIMediaType{
		"application/json": {Schema: schema},
	}
}

func operationSecurity(operation ast.Operation) []map[string][]string {
	// AuthMode is the normalized ContractGraph truth produced by the metadata
	// loader. OpenAPI 只消费该 canonical 字段，避免从原始 security map 再次派生。
	authMode := strings.TrimSpace(operation.AuthMode)
	switch authMode {
	case "required":
		return []map[string][]string{{"bearerAuth": {}}}
	case "optional":
		return []map[string][]string{
			{"bearerAuth": {}},
			{},
		}
	}
	switch operation.ActorRequirement {
	case "account", "persona":
		return []map[string][]string{{"bearerAuth": {}}}
	case "persona_or_device":
		return []map[string][]string{
			{"bearerAuth": {}},
			{},
		}
	default:
		return nil
	}
}

func pathParameters(pathTemplate string) []openAPIParameter {
	matches := pathParameterPattern.FindAllStringSubmatch(pathTemplate, -1)
	if len(matches) == 0 {
		return nil
	}
	seen := map[string]struct{}{}
	parameters := make([]openAPIParameter, 0, len(matches))
	for _, match := range matches {
		name := strings.TrimSpace(match[1])
		if name == "" {
			continue
		}
		if _, exists := seen[name]; exists {
			continue
		}
		seen[name] = struct{}{}
		parameters = append(parameters, openAPIParameter{
			Name:     name,
			In:       "path",
			Required: true,
			Schema:   openAPISchema{Type: "string"},
		})
	}
	return parameters
}

func operationParameters(operation ast.Operation) []openAPIParameter {
	parameters := requestBindingParameters(operation)
	if operation.Reliability.Idempotency == "required" ||
		operation.Reliability.Idempotency == "optional" {
		parameters = append(parameters, openAPIParameter{
			Name:        "Idempotency-Key",
			In:          "header",
			Required:    operation.Reliability.Idempotency == "required",
			Description: "Stable business replay identity; distinct from X-Request-Id.",
			Schema:      openAPISchema{Type: "string"},
		})
	}
	if operation.Concurrency.VersionPrecondition == ast.VersionPreconditionIfMatch &&
		!hasRequestHeaderBinding(operation, "If-Match") {
		parameters = append(parameters, openAPIParameter{
			Name:        "If-Match",
			In:          "header",
			Required:    true,
			Description: "Quoted positive aggregate version for a snapshot overwrite.",
			Schema:      openAPISchema{Type: "string"},
		})
	}
	return parameters
}

func hasRequestHeaderBinding(operation ast.Operation, expected string) bool {
	if operation.RequestBindings == nil {
		return false
	}
	for _, binding := range operation.RequestBindings.Header {
		if strings.EqualFold(strings.TrimSpace(binding.Name), expected) {
			return true
		}
	}
	return false
}

func requestBindingParameters(operation ast.Operation) []openAPIParameter {
	if operation.RequestBindings == nil {
		return pathParameters(operation.PathTemplate)
	}
	bindings := operation.RequestBindings
	parameters := make(
		[]openAPIParameter,
		0,
		len(bindings.Path)+len(bindings.Query)+len(bindings.Header),
	)
	for _, binding := range bindings.Path {
		parameters = append(parameters, openAPIParameter{
			Name:     binding.Name,
			In:       "path",
			Required: true,
			Schema:   openAPISchema{Type: "string"},
		})
	}
	for _, binding := range bindings.Query {
		required := false
		if binding.Required != nil {
			required = *binding.Required
		}
		parameters = append(parameters, openAPIParameter{
			Name:     binding.Name,
			In:       "query",
			Required: required,
			Schema:   openAPISchema{Type: "string"},
		})
	}
	for _, binding := range bindings.Header {
		required := false
		if binding.Required != nil {
			required = *binding.Required
		}
		parameters = append(parameters, openAPIParameter{
			Name:     binding.Name,
			In:       "header",
			Required: required,
			Schema:   openAPISchema{Type: "string"},
		})
	}
	return parameters
}

func isVersionedTransport(pathTemplate string) bool {
	// Historical name: eligible current HTTP transport path (unversioned only).
	switch pathTemplate {
	case "/health", "/healthz", "/metrics", "/livez", "/startupz":
		return false
	}
	if pathTemplate == "" || !strings.HasPrefix(pathTemplate, "/") {
		return false
	}
	for _, segment := range strings.Split(strings.Trim(pathTemplate, "/"), "/") {
		if len(segment) >= 2 && segment[0] == 'v' {
			digitsOnly := true
			for i := 1; i < len(segment); i++ {
				if segment[i] < '0' || segment[i] > '9' {
					digitsOnly = false
					break
				}
			}
			if digitsOnly {
				return false
			}
		}
	}
	if strings.HasPrefix(pathTemplate, "/internal/") || strings.HasPrefix(pathTemplate, "/callbacks/") {
		return true
	}
	second := pathTemplate[1]
	return (second >= 'a' && second <= 'z') || (second >= 'A' && second <= 'Z')
}

func methodMayCarryBody(method string) bool {
	switch strings.ToUpper(strings.TrimSpace(method)) {
	case "POST", "PUT", "PATCH":
		return true
	default:
		return false
	}
}

func methodSortKey(method string) string {
	switch strings.ToUpper(strings.TrimSpace(method)) {
	case "GET":
		return "1"
	case "POST":
		return "2"
	case "PUT":
		return "3"
	case "PATCH":
		return "4"
	case "DELETE":
		return "5"
	default:
		return "9" + method
	}
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if strings.TrimSpace(value) != "" {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

func componentRef(name string) string {
	return "#/components/schemas/" + name
}
