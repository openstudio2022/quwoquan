package codegen

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"quwoquan_service/internal/metadata/ast"
	"quwoquan_service/internal/metadata/graph"
)

// RenderOperationSecurityGo emits the only route-security descriptor table
// accepted by runtime/auth. Missing commercial bindings remain in the table as
// blocked entries so registration stays fail-closed during object migration.
func RenderOperationSecurityGo(
	contractGraph *graph.ContractGraph,
	graphSHA256 string,
) []byte {
	operations := append([]ast.Operation(nil), contractGraph.Operations...)
	sort.Slice(operations, func(i, j int) bool {
		return operations[i].ID < operations[j].ID
	})
	byDomain := map[string][]ast.Operation{}
	for _, operation := range operations {
		byDomain[operation.Domain] = append(
			byDomain[operation.Domain],
			operation,
		)
	}
	domains := make([]string, 0, len(byDomain))
	for domain := range byDomain {
		domains = append(domains, domain)
	}
	sort.Strings(domains)

	var output strings.Builder
	output.WriteString("// Code generated by qwq-contract. DO NOT EDIT.\n")
	fmt.Fprintf(&output, "// ContractGraph SHA256: %s\n\n", graphSHA256)
	output.WriteString("package operationsecurity\n\n")
	output.WriteString("import \"quwoquan_service/runtime/auth\"\n\n")
	fmt.Fprintf(
		&output,
		"const ContractGraphSHA256 = %s\n\n",
		strconv.Quote(graphSHA256),
	)
	output.WriteString(
		"func ForDomain(domain string) []auth.OperationSecurityDescriptor {\n",
	)
	output.WriteString(
		"\tvar source []auth.OperationSecurityDescriptor\n\t" +
			"switch domain {\n",
	)
	for _, domain := range domains {
		fmt.Fprintf(&output, "\tcase %s:\n", strconv.Quote(domain))
		fmt.Fprintf(
			&output,
			"\t\tsource = %sDescriptors\n",
			goPrivateIdentifier(domain),
		)
	}
	output.WriteString("\tdefault:\n\t\treturn nil\n\t}\n")
	output.WriteString(
		"\treturn append([]auth.OperationSecurityDescriptor(nil), source...)\n",
	)
	output.WriteString("}\n\n")

	for _, domain := range domains {
		fmt.Fprintf(
			&output,
			"var %sDescriptors = []auth.OperationSecurityDescriptor{\n",
			goPrivateIdentifier(domain),
		)
		for _, operation := range byDomain[domain] {
			output.WriteString("\t{\n")
			writeGoStringField(
				&output,
				"CanonicalOperationID",
				operation.ID,
			)
			writeGoStringField(
				&output,
				"ContractGraphSHA256",
				graphSHA256,
			)
			writeGoStringField(&output, "Method", operation.Method)
			writeGoStringField(
				&output,
				"OperationKind",
				string(operation.Kind),
			)
			writeGoStringField(
				&output,
				"MutationTarget",
				operation.MutationTarget,
			)
			writeGoStringField(
				&output,
				"InvariantTarget",
				operation.InvariantTarget,
			)
			writeGoStringField(
				&output,
				"PathTemplate",
				operation.PathTemplate,
			)
			writeGoStringField(&output, "AuthMode", operation.AuthMode)
			writeGoStringField(
				&output,
				"ActorRequirement",
				operation.ActorRequirement,
			)
			writeGoStringField(&output, "Principal", operation.Principal)
			writeGoStringSliceField(&output, "Scopes", operation.Scopes)
			writeGoStringSliceField(
				&output,
				"Permissions",
				operation.Permissions,
			)
			writeGoStringField(
				&output,
				"OwnershipPolicy",
				operation.OwnershipPolicy,
			)
			fmt.Fprintf(
				&output,
				"\t\tTimeoutMilliseconds: %d,\n",
				operation.Reliability.TimeoutMilliseconds,
			)
			writeGoStringField(
				&output,
				"Idempotency",
				operation.Reliability.Idempotency,
			)
			writeGoStringField(
				&output,
				"VersionPrecondition",
				string(operation.Concurrency.VersionPrecondition),
			)
			writeGoStringField(
				&output,
				"CommercialStatus",
				operation.Commercial.Status,
			)
			output.WriteString("\t},\n")
		}
		output.WriteString("}\n\n")
	}
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		panic(fmt.Sprintf("format generated operation security: %v", err))
	}
	return formatted
}

func writeGoStringField(output *strings.Builder, name, value string) {
	fmt.Fprintf(output, "\t\t%s: %s,\n", name, strconv.Quote(value))
}

func writeGoStringSliceField(
	output *strings.Builder,
	name string,
	values []string,
) {
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(output, "\t\t%s: []string{", name)
	for index, value := range values {
		if index > 0 {
			output.WriteString(", ")
		}
		output.WriteString(strconv.Quote(value))
	}
	output.WriteString("},\n")
}

func goIdentifier(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool {
		return r == '-' || r == '_' || r == '.'
	})
	var output strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		output.WriteString(strings.ToUpper(part[:1]))
		output.WriteString(part[1:])
	}
	if output.Len() == 0 {
		return "Unknown"
	}
	return output.String()
}

func goPrivateIdentifier(value string) string {
	identifier := goIdentifier(value)
	return strings.ToLower(identifier[:1]) + identifier[1:]
}
