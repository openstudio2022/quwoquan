package codegen

import (
	"fmt"
	"strings"
)

// ErrorDefinition 是稳定端云错误的 ContractGraph 视图。恢复语义只有扁平一轨:
// recovery_action / recovery_after_seconds / disruption_level。
type ErrorDefinition struct {
	Code              string            `yaml:"code"`
	Reason            string            `yaml:"reason"`
	HTTPStatus        int               `yaml:"http_status"`
	RecoveryAction    string            `yaml:"recovery_action"`
	RecoveryAfterSecs int               `yaml:"recovery_after_seconds"`
	DisruptionLevel   string            `yaml:"disruption_level"`
	DartConst         string            `yaml:"dart_const"`
	GoConst           string            `yaml:"go_const"`
	L10nKey           string            `yaml:"l10n_key"`
	UserMessage       map[string]string `yaml:"user_message"`
}

// ErrorsFile 是领域 errors.yaml 的 ContractGraph 视图。
type ErrorsFile struct {
	Domain string            `yaml:"domain"`
	Errors []ErrorDefinition `yaml:"errors"`
}

// GoErrorsFileOptions 声明领域 Service 错误生成物的所有权和可选扩展。
type GoErrorsFileOptions struct {
	Generator    string
	SourcePath   string
	CommentLines []string
	ExtraImports []string
	Trailer      string
}

// RenderGoErrorsFile 从 ContractGraph errors.yaml 生成 Service 端稳定错误 helper。
func RenderGoErrorsFile(file *ErrorsFile, opts GoErrorsFileOptions) string {
	var b strings.Builder
	hasGeneratedErrors := false
	for _, definition := range file.Errors {
		if definition.GoConst != "" {
			hasGeneratedErrors = true
			break
		}
	}
	generator := strings.TrimSpace(opts.Generator)
	if generator == "" {
		generator = "metadata domain codegen"
	}
	b.WriteString(fmt.Sprintf("// Code generated by %s from %s. DO NOT EDIT.\n", generator, opts.SourcePath))
	b.WriteString("package generated\n\n")
	imports := append([]string(nil), opts.ExtraImports...)
	if hasGeneratedErrors || strings.Contains(opts.Trailer, "errors.") {
		imports = append(imports, "errors")
	}
	if hasGeneratedErrors || strings.Contains(opts.Trailer, "rerrors.") {
		imports = append(imports, "quwoquan_service/runtime/errors")
	}
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range imports {
			if imp == "quwoquan_service/runtime/errors" {
				b.WriteString("\trerrors \"quwoquan_service/runtime/errors\"\n")
				continue
			}
			b.WriteString(fmt.Sprintf("\t%q\n", imp))
		}
		b.WriteString(")\n\n")
	}
	for _, line := range opts.CommentLines {
		b.WriteString("// " + line + "\n")
	}
	if hasGeneratedErrors {
		b.WriteString("//\n//nolint:gochecknoglobals\n")
		b.WriteString("var (\n")
		for _, definition := range file.Errors {
			if definition.GoConst == "" {
				continue
			}
			b.WriteString(fmt.Sprintf("\t%s = errors.New(%q)\n", definition.GoConst, definition.Code))
		}
		b.WriteString(")\n\n")
	}
	for _, definition := range file.Errors {
		if definition.GoConst == "" {
			continue
		}
		funcName := goErrorHelperName(definition.GoConst)
		b.WriteString(fmt.Sprintf("// %s returns *AppError for %s (user_message from errors.yaml).\n", funcName, definition.Code))
		b.WriteString(fmt.Sprintf("func %s(debugMessage string) *rerrors.AppError {\n", funcName))
		b.WriteString(fmt.Sprintf("\tcode, _ := rerrors.ParseCode(string(%s.Error()))\n", definition.GoConst))
		b.WriteString(fmt.Sprintf(
			"\treturn rerrors.NewAppError(code, %q, debugMessage).WithMetadata(%q, %d)%s\n",
			errorUserMessage(definition),
			definition.Reason,
			definition.HTTPStatus,
			errorRecoveryCall(definition),
		))
		b.WriteString("}\n\n")
	}
	if opts.Trailer != "" {
		b.WriteString(opts.Trailer)
		if !strings.HasSuffix(opts.Trailer, "\n") {
			b.WriteString("\n")
		}
	}
	return b.String()
}

func goErrorHelperName(goConst string) string {
	if strings.HasPrefix(goConst, "Err") {
		return "AppErrorFrom" + goConst[3:]
	}
	return "AppErrorFrom" + goConst
}

func errorUserMessage(definition ErrorDefinition) string {
	message := definition.UserMessage["zh"]
	if message == "" {
		message = definition.UserMessage["en"]
	}
	if message == "" {
		message = "请稍后重试"
	}
	return message
}

func errorRecoveryCall(definition ErrorDefinition) string {
	action := strings.TrimSpace(definition.RecoveryAction)
	if action == "" {
		return ""
	}
	afterSeconds := definition.RecoveryAfterSecs
	if disruption := strings.TrimSpace(definition.DisruptionLevel); disruption != "" {
		return fmt.Sprintf(".WithRecoveryDirective(%q, %q, %d)", action, disruption, afterSeconds)
	}
	return fmt.Sprintf(".WithRecovery(%q, %d)", action, afterSeconds)
}
