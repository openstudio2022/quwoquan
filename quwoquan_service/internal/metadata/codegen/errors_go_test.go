package codegen

import (
	"strings"
	"testing"
)

func TestRenderGoErrorsFile_emitsStableHelperFromContractGraph(t *testing.T) {
	file := &ErrorsFile{Errors: []ErrorDefinition{{
		Code:           "CHAT.USER.message_not_found",
		Reason:         "not_found",
		HTTPStatus:     404,
		RecoveryAction: "surface",
		GoConst:        "ErrMessageNotFound",
		UserMessage:    map[string]string{"zh": "消息不存在"},
	}}}

	output := RenderGoErrorsFile(file, GoErrorsFileOptions{
		Generator:  "tools/codegen_chat_service",
		SourcePath: "chat/chat/conversation/errors.yaml",
	})

	for _, expected := range []string{
		"Code generated by tools/codegen_chat_service from chat/chat/conversation/errors.yaml",
		`ErrMessageNotFound = errors.New("CHAT.USER.message_not_found")`,
		"func AppErrorFromMessageNotFound(debugMessage string) *rerrors.AppError",
		`WithMetadata("not_found", 404).WithRecovery("surface", 0)`,
	} {
		if !strings.Contains(output, expected) {
			t.Fatalf("generated Go errors missing %q:\n%s", expected, output)
		}
	}
}

func TestRenderGoErrorsFile_omitsUnusedImportsForEmptyContract(t *testing.T) {
	output := RenderGoErrorsFile(&ErrorsFile{}, GoErrorsFileOptions{
		Generator:    "tools/codegen_product_ops_service",
		SourcePath:   "ops/product_ops/app_release/errors.yaml",
		CommentLines: []string{"Object-owned ProductOps errors."},
	})

	for _, unexpected := range []string{"import (", `"errors"`, "rerrors", "var ("} {
		if strings.Contains(output, unexpected) {
			t.Fatalf("empty generated Go errors contains %q:\n%s", unexpected, output)
		}
	}
	if !strings.Contains(output, "// Object-owned ProductOps errors.") {
		t.Fatalf("empty generated Go errors lost ownership comment:\n%s", output)
	}
}
